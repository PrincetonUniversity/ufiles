!------------------------------------------------------------------
!  SPLICE3.BLK - COMMON BLOCKS FOR 3d UFILES SPLICE2 UTILITY
!
module splice3_blk
  integer, PARAMETER :: MAXNI=65536  ! MAX NUMBER OF PTS IN IND. COORDS
  integer, PARAMETER :: MAXN=524288  ! MAX TOT NO. OF PTS IN 2D DEP. DATA
  integer, PARAMETER :: MAXFI=6      ! MAX NUMBER OF INPUT 3D UFILES
  integer, PARAMETER :: MAXG=100   ! MAX NUMBER OF TIME INTERVAL ENDPTS
  integer, PARAMETER :: MAXSC=100  ! MAX NUMBER OF SCALARS/INPUT FILE
  !
  ! INPUT DATA BLOCK
  !
  INTEGER LUNI(MAXFI),NSHOTI(MAXFI) ! UFILES LUNS; INPUT SHOT NOS.
  CHARACTER*4 IDEV(MAXFI)           ! DATA DEVICE LABELS
  CHARACTER*10 SDATE(MAXFI)         ! DATA DATE LABELS
  REAL XIN(MAXNI,3,MAXFI)		  ! INDEPENDENT COORDINATES
  REAL FIN(MAXN,MAXFI)  		  ! DEPENDENT DATA SETS
  INTEGER NIN(3,MAXFI),IPROC(MAXFI)   ! DATA COUNTS, PROC CODE
  !
  ! LABELS
  !
  CHARACTER*10 XLAB(3,3,MAXFI)      ! LABELS
  CHARACTER*10 FLAB(3,MAXFI),SCLAB(3,MAXSC,MAXFI)  ! LABELS
  INTEGER NUMSC(MAXFI)              ! SCALAR COUNTS
  REAL SCVAL(MAXSC,MAXFI)           ! SCALAR DATA
  !
  INTEGER NDSPLICE			! CHOSEN "SPLICE" DIMENSION
  INTEGER NFILEI                    ! NUMBER OF INPUT FILES READ
  !
  !COMMON/SPLCIN/ XIN,FIN,SCVAL,NUMSC,NFILEI,LUNI,NSHOTI,NIN,IPROC,NDSPLICE
  !COMMON/CSPLCIN/ IDEV,SDATE,XLAB,FLAB,SCLAB
  !
  ! OUTPUT DATA BLOCK
  !
  REAL XBDY(MAXG),XWK(MAXG)     ! BDYS OF X INTERVALS
  REAL XBDYS(2,MAXFI) ! splice coord ranges of input files
  INTEGER IWK(MAXG)   ! WK SPACE
  INTEGER NBDY        ! NO. OF BDYS = NO. OF INTERVALS + 1
  INTEGER IFILE(MAXG) ! WHICH FILE DATA TO USE FOR EACH INTERVAL
  INTEGER LFILE       ! WHICH INPUT FILE LABELS AND SCALARS TO USE
  INTEGER INUMI(MAXG) ! NUMBER OF PTS TRANSFERRED TO OUTPUT, EACH GRP
  !
  INTEGER LUNOUT              ! LUN FOR OUTPUT FILE
  REAL XOUT(MAXNI,3),FOUT(MAXN)  ! ASSEMBLED OUTPUT DATA
  INTEGER NOUT                ! NO. OF PTS, SPLICE DIMENSION, OUTPUT DATA
  !
  CHARACTER*10 XLABO(3,3),FLABO(3)
  !
  !COMMON/SPLCOUT/ XOUT,FOUT,XBDY,XWK,XBDYS,INUMI,IFILE,LFILE,IWK,LUNOUT,NOUT,NBDY
  !COMMON/CSPLCOUT/ XLABO,FLABO
  !
end module splice3_blk
