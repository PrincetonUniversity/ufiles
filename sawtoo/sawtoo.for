C******************** START FILE SAWTOO.FOR ; GROUP SAWTOO *************
C-----------------------------------------------------------
C  SAWTOO
C  PROGRAM TO PICK OUT SAWTOOTH TIMES FROM INPUT TIMETRACE DATA
C
C  BASED ON OLD VSN GSMOO1.FOR - DMC NOV 1985
C
C
      PROGRAM SAWTOO
C
C MAX NUMBER OF SCALARS
      PARAMETER (MAXSC=100)
C
C  MAX SIZE OF DATA ARRAYS
C
      PARAMETER (JDSIZ=102400)
C
C  DATA BUFFERS AND LABELS
      REAL X(JDSIZ),Y(JDSIZ),YF(JDSIZ),WK1(JDSIZ),WK2(JDSIZ),
     >       YSAW(JDSIZ),XSAW(JDSIZ),SSAW(JDSIZ),
     >       EPS(JDSIZ),DEL(JDSIZ),XTRVAL(MAXSC),XTEVAL(MAXSC)
C
      CHARACTER*10 ZSDATE,XLAB(3),YLAB(3),XTRLAB(3,MAXSC),ZSHID,ZDATE
      CHARACTER*10 SLAB(3),ZPROG
      INTEGER IORDER(MAXSC)
      CHARACTER*40 ZFILE
      CHARACTER*4 IDEV
C
      CHARACTER*60 ZNAME
C
C  PROGRAM MOD APR 1984 DMC-- DEAL WITH VAX COMPRESSED UFILES DATA
C   FORMATTED COMMENTS FOR THE OUTPUT FILE ARE PUT IN A TEMPORARY FILE
C   WHICH IS SPOOLED TO THE PERMANENT FILE WHICH IS OPTIONALLY BINARY-
C   COMPRESSED.
C  USER MAY SELECT COMPRESSED OR UNCOMPRESSED DATA OUTPUT
C
      CHARACTER*7 CMPSTA(0:4)
C
      logical lxout
C
      DATA SLAB/'SAWTOOTH C','ORRELATION',' FRACTION '/
C
      DATA CMPSTA/'ascii','????','binary','HDF','NetCDF'/
C
C  COMPRESSED DATA OUTPUT DEFAULT FLAG, =1 FOR COMPRESSION ON
      DATA ICOMPR/2/  ! loss free portable compressed binary
C
C
C-------------------------------
C
C  L.U.N FOR DATA INPUT
C
      DATA ILUNI/21/
C  L.U.N FOR DATA OUPUT
      DATA ILUNO/22/
C  L.U.N. FOR ERROR BAR FILES
      DATA ILUNE/23/
C  L.U.N. FOR TEMPORARY COMMENTS FILE
      DATA ILUNT/24/
C  L.U.N. FOR 2NDARY FCN
      DATA ILUN2/25/
C  L.U.N. FOR 2NDARY COMMENTS FILE
      DATA ILUNT2/26/
C
C----------------------------------
C
      itoggl=icompr
C
      MAXD=JDSIZ
C
      CALL C9DATE(ZDATE)
      CALL UINITG("SAWTOO")
C
      CALL UREADL('SAWTOO: PLEASE TYPE IN YOUR NAME:$$',ZNAME)
C
      call urdext('ifi')
      luntrm=lnout(0)
C
 10   CONTINUE
      CALL UFNTER(ILUNI,'1D U.F(T) W/SAWTEETH')
      CALL UFNTER(ILUNO,'OUTPUT SAWTOOTH FILE')
      IFLAGE=0
C
 20   CONTINUE
      CALL NEUPAG
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'               INPUT',ILUNI)
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'              OUTPUT',ILUNO)
 21   CONTINUE
      CALL UREAD(
     >'SAWTOO: ENTER 5 DIGIT SHOT #, "0" TO QUIT, "D" TO CHANGE NAMES$')
      IANS=IXUOPC('QD$')
C
      IF(IANS.EQ.1) GO TO 900
      IF(IANS.EQ.2) GO TO 10
C
      ISHOT=IDCOD(IERT)
C
      IF(IERT.NE.0) GO TO 21
      IF(ISHOT.EQ.0) GO TO 900
C---
C  CREATE TEMPORARY FILE TO RECORD SCALARS MODIFICATIONS, OTHER REMARKS
      ISMOO=0
      IDCUT=0
      CALL UFOPCF(ILUNT,IER)
      WRITE(ILUNT,7001)
 7001 FORMAT('  ')
C---
C
      CALL UFOPRD(ILUNI,ISHOT,IER)
      IF(IER.NE.0) THEN
        CALL UCLEAR
        GO TO 21
      ENDIF
C
      NSAW=0
C
      CALL UF1DRD(ILUNI,IDEV,ZSDATE,
     >   X,Y,JDSIZ,NRET,IPROC,
     >   XLAB,YLAB,MAXSC,NUMSC,XTRVAL,XTRLAB,IER)
C
      IF(IER.NE.0) THEN
        CALL UCLEAR
        GO TO 290
      ENDIF
C
 50   CONTINUE
C-------------------------------------------
C  SAWTOOTH PICKER CONTROL NODE
C
      CALL NEUPAG
 51   IF(LXOUT(0)) WRITE(LUNTRM,2000) NSAW,CMPSTA(ICOMPR)
 2000 FORMAT(' SAWTOO OPTIONS (',I5,' SAWTEETH FOUND):'/
     >'  G - GRAPH THE *INPUT* DATA WITH MARKED SAWTEETH IF AVAILABLE'/
     >'  H - GRAPH THE *OUTPUT* SAWTOOTH DATA'/
     >'  Q - QUIT (GET NEW SHOT WITHOUT WRITING OUTPUT FILE)'/
     >'  S - SMOOTH INPUT DATA AND EVALUATE SAWTOOTH TIMES'/
     >'      FROM "RESIDUE" R(T)= F(T) - F:SMOOTHED(T)'/
     >'  W - WRITE SAWTOOTH DATA TO OUTPUT FILE'/
     >'  P - COMPRESS- TOGGLE OUTPUT DATA FORMAT FLAG, NOW "',A,'"'/
     >'  4 - FORMAT  - *new* Ufile output format control menu'/
     >'  X - EXIT (STOP PROGRAM NOW)')
      CALL UREAD('SAWTOO:  ENTER OPTION CODE:$')
      IANS=IXUOPC('GHQSWP4X$')
      CALL UCHKOP(IANS,0,1,100,-1,*51)
      GO TO (180,190,290,70,125,55,56,900) IANS
C
 55   CONTINUE
      ICOMPR=ITOGGL-ICOMPR
      GO TO 50
C
 56   CONTINUE
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      GO TO 50
C
C  EVALUATE THE SAWTEETH
C
C 70	ENCODE(10,3001,ZSHID) IDEV,ISHOT
 70   write(ZSHID,3001) IDEV,ISHOT
 3001 FORMAT(A4,I6)
      CALL SAWCOR(X,Y,NRET,YF,DEL,EPS,
     >     WK1,WK2,XSAW,YSAW,SSAW,NSAW,
     >     XLAB,YLAB,XLAB(3),YLAB(3),ZSHID,ZPROG,ISHOT,IDEV,ZSDATE)
      GO TO 50
C  GRAPH THE UNSMOOTHED DATA
 180  CONTINUE
      IF(NSAW.GT.0) THEN
        CALL GRFFIT(X,Y,NRET,IPROCP,YLAB,XLAB,ISHOT,IDEV,ZSDATE,
     >              NUMSC,XTRVAL,XTRLAB,NSAW,XSAW,YSAW)
      ELSE
        CALL GRFUF1(X,Y,NRET,IPROCP,YLAB,XLAB,ISHOT,IDEV,ZSDATE,
     >              NUMSC,XTRVAL,XTRLAB)
      ENDIF
      GO TO 50
C  GRAPH SAWTOOTH TRACE (IF ANY)
 190  CONTINUE
      IF(NSAW.LE.0) THEN
        CALL UERMSG(' % SAWTEETH NOT (YET) FOUND',' ',1)
      ELSE
        CALL GRFFIT(XSAW,SSAW,NSAW,4,SLAB,XLAB,ISHOT,IDEV,ZSDATE,
     >               0,XTRVAL,XTRLAB,NSAW,XSAW,SSAW)
      ENDIF
      GO TO 50
C *** WRITE THE FILE
 125  CONTINUE
      IF(NSAW.LE.0) THEN
        CALL UERMSG(' % SAWTEETH NOT (YET) FOUND',' ',1)
        GO TO 50
      ENDIF
C
C  SET COMPRESSION OPTION
      CALL UFCMPR(ILUNO,ICOMPR)
      CALL UFOPWR(ILUNO,ISHOT,IER)
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 290
C
      IPROC=4
      ISMOO=0
C
      CALL UF1DWR(ILUNO,IDEV,
     >     ZSDATE,XSAW,SSAW,NSAW,IPROC,XLAB,SLAB,0,XTRVAL,XTRLAB,IER)
C
C  APPEND COMMENTS TO FILE
C
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 200
C
      CALL UFSNAM(ISHOT,ZFILE,IER,ILUNI)
      WRITE(ILUNT,4001) ZFILE,ZNAME
 4001 FORMAT('    PRODUCED BY PROGRAM SAWTOO [TRANSP] '/
     >         '    FROM INPUT DATA FILE:  "',A,'"'//
     >         ' OPERATED BY ',A/)
C
C  GET USER COMMENTS TO APPEND TO END OF OUTPUT FILE
      CALL UFACOM(ILUNT)
C
      WRITE(ILUNT,4007) IPROCP,ZDATE
 4007 FORMAT(
     > /' =========================================================='/
     >  ' COMMENTS SPOOLED FROM FILE INPUT TO SAWTOO [IPROC=',I1,']:'/
     >  ' ON VAX-11 ON DATE:  ',A10/)
C  SPOOL COMMENTS FROM INPUT FILE, SCALARS MODIFICATIONS RECORD FILE
C
      CALL UCSEND(ILUNT,ILUNO)
C
      CALL USPOOL(ILUNI,ILUNO)
C
 200  CONTINUE
      CALL UFCLOS(ILUNO)
 290  CONTINUE
      CALL UFCLOS(ILUNI)
      GO TO 20
C-------------------------------------------------------
C  EXIT PROGRAM
C
 900  CONTINUE
      CALL UEXITA
      STOP
      	END
C******************** END FILE SAWTOO.FOR ; GROUP SAWTOO ******************
