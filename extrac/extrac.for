C******************** START FILE EXTRAC.FOR ; GROUP EXTRAC *************
C--------------------------------------------------------------
C  EXTRAC
C
C  EXTRACT SLICES OF A 2D UFILES FOR OUTPUT TO 1D UFILES
C  GRAPHICS AND DATA AVERAGING OPTIONS
C
C  SEE ALSO THE SUBROUTINES IN EXSUBS.FOR
C
C  **MODIF DMC OCT 1984--
C
C  OPTION FOR EXTRACTED PROFILES OR TRACES TO BE INTERPOLATED
C  OR EXTRAPOLATED TO A DATA GRID FROM A SECONDARY UFILE
C
      PROGRAM EXTRAC
C
      USE EXTRAC_MOD
C
      LOGICAL LYES,lxout
C
      CALL UFHEADER("extrac")
C
      LYABL(1)='          '
      LYABL(2)=' AVERAGED.'
      LYABL(3)=' SMOOTHED.'
      LYABL(4)=' AVG+SM''D.'
      LYABL(5)=' SPECIAL. '
C
C  L.U.N FOR DATA INPUT
C
      ILUNI=21
C
C  L.U.N FOR DATA OUTPUT
C
      ILUNO=22
C
C  L.U.N FOR TEMPORARY FILE (SPOOLED DATA COMMENTS)
C
      ILUNT=23
C
C  L.U.N FOR TEMPORARY FILE (LOCALLY GENERATED DATA COMMENTS)
C
      ILUNC=24
C
C  L.U.N. FOR X OR Y TARGET DATA
C
      ILUNX=25
      ILUNY=26
C
C  COMPRESSED OUTPUT DATA FLAG - INITIALLY SET TO 1 (ON)
C
      ICOMPR=2
      ITOGGL=ICOMPR
      CMPSTA(0)='ascii'
      CMPSTA(1)='?????'
      CMPSTA(2)='binary'
      CMPSTA(3)='HDF'
      CMPSTA(4)='NetCDF'
C
      CALL UINITG("EXTRAC")
CC	CALL USINIT
CC	CALL UAHEAD
      luntrm=lnout(0)
      call urdext('ifi')
 10   CONTINUE
      CALL UFNTER(ILUNI,'2D INPUT FILES      ')
C
 20   CONTINUE
      CALL NEUPAG
C
 21   CONTINUE
      CALL URSHOT('EXTRAC',', "Q" TO QUIT, "D" TO CHANGE NAMES','QD',
     >	  ISHOT,IANS)
      IF(IANS.EQ.1) GO TO 900
      IF(IANS.EQ.2) GO TO 10
      IF(ISHOT.EQ.0) GO TO 900
      JSHOT=ISHOT
C
      CALL UFOPRD(ILUNI,ISHOT,IER)
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 21
C
      IX1MAX=MAXTOT/MAXIND
C  IN THIS READ THE FIRST SCALAR POSITION IS RESERVED FOR THE OUTPUT
C  FILE
      CALL UF2DRD(ILUNI,IDEV,ZSDATE,
     >   F,IX1MAX,X,MAXIND,Y,MAXIND,IPROC,
     >   NXACT,NYACT,1,
     >   FLAB,XLAB,YLAB,MAXSC,NUMSC,SCV(2),SCLAB(1,2),IER)
C
      ZTITLE(1)='DATA FROM '
      ZTITLE(2)=ZSDATE
      IND=MIN0(5,(IPROC+1))
      ZTITLE(3)=LYABL(IND)
C
C  SPOOL COMMENTS TO TEMPORARY FILE
C
C  DELETE OLD COPY OF FILE IF IT EXISTS
      OPEN(UNIT=ILUNT,status='OLD',FILE='ZEXTRC.MMT',IOSTAT=IOS)
      IF(IOS.EQ.0) CLOSE(UNIT=ILUNT,STATUS='DELETE')
      OPEN(UNIT=ILUNT,status='NEW',FILE='ZEXTRC.MMT')
C
      CALL EXCHED(ILUNI,ILUNT)
      CALL USPOOL(ILUNI,ILUNT)
C
      CLOSE(UNIT=ILUNT)
C
      CALL UFCLOS(ILUNI)
C
C  INITIAL ASSUMPTION WILL BE NO INTERPOLATION OR EXTRAPOLATION ON
C   OUTPUT--
C
      LXTRAP=0
      LYTRAP=0
C
      NXTARG=NXACT
      DO 22 IX=1,NXTARG
        XTARG(IX)=X(IX)
 22   CONTINUE
C
      NYTARG=NYACT
      DO 24 IY=1,NYTARG
        YTARG(IY)=Y(IY)
 24   CONTINUE
C
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 20
C
C  EXAMINE SCALARS
      IF(NUMSC.LE.0) THEN
        WRITE(LUNTRM,3001) NUMSC
        CALL UPAUST(1)
                     ELSE
        WRITE(LUNTRM,3001) NUMSC
        CALL UREAD('UGRAF1:  DO YOU WANT TO EXAMINE SCALARS? (Y/N)$')
        IF(LYES(0))
     >	    CALL UFSCLK(ILUNI,ISHOT,NUMSC,SCV(2),SCLAB(1,2),IORDSC,0,0)
      ENDIF
 3001 FORMAT(' NUMBER OF ASSOCIATED SCALARS IN FILE:  ',I3)
C
      ISMOO=0
CXX	IF((IPROC.GE.2).AND.(IPROC.LE.3)) ISMOO=1
C
C  EXTRACTION OPTIONS
C
 30   CONTINUE
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,3002) CMPSTA(ICOMPR)
 3002 FORMAT(/' EXTRAC OPTIONS:'/
     >'  G - GRAPH THE 2D INPUT DATA'/
     >'  1 - EXTRACT A SINGLE SLICE (AVERAGING OPTION AVAILABLE)'/
     >'  2 - EXTRACT "ALL" SLICES (NO AVERAGING)'/
     >'  B - EXTRACT A 2D "BLOCK" OF THE 2D INPUT DATA'/
     >'  C - COMPRESS- TOGGLE OUTPUT DATA FORMAT FLAG, NOW "',A,'"'/
     >'  4 - FORMAT  - *new* Ufile output format control menu'/
     >'  Q - QUIT (GET NEW SHOT)'/)
C
      CALL UREAD('EXTRAC: ENTER OPTION G/1/2/B/Q:$')
      IANS=IXUOPC('G12BC4Q$')
      CALL UCHKOP(IANS,0,1,100,-1,*30)
C
      GO TO (100,200,300,400,60,58,20) IANS
C
 58   CONTINUE
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      GO TO 30
C
 60   CONTINUE
      ICOMPR=ITOGGL-ICOMPR
      GO TO 30
C
 100  CONTINUE
C
      CALL GRF3(X,F,Y,ZWK,NXACT,NYACT,NXACT,
     >   XLAB,YLAB,FLAB,XLAB(3),YLAB(3),FLAB(3),
     >   ZTITLE,1,0,0,IDEV,ISHOT,0,JSHOT,1,ISMOO)
C
      GO TO 30
C
 200  CONTINUE
      CALL EXTRK1
      GO TO 30
C
 300  CONTINUE
      CALL EXTRK2
      GO TO 30
C
 400  CONTINUE
      CALL EXBLOK
      GO TO 30
C  EXIT
 900  CONTINUE
C
C  CLEANUP ARTIFACT
      OPEN(UNIT=ILUNT,status='OLD',FILE='ZEXTRC.MMT',IOSTAT=IOS)
      IF(IOS.EQ.0) CLOSE(UNIT=ILUNT,STATUS='DELETE')
      CALL NEUPAG
      CALL UEXITA(0)
C
      STOP
C
      END
C******************** END FILE EXTRAC.FOR ; GROUP EXTRAC ***************
