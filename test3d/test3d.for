C-------------------------------------------------------------
C
      SUBROUTINE FDEFIN(X,NX,Y,NY,Z,NZ,F,PI)
C
      REAL X(NX),Y(NY),Z(NZ),F(NX,NY,NZ)
C
      REAL ZZ(2,7)
C
      ZZ(1,1)=1.0
      ZZ(2,1)=0.0
C
      ZZ(1,2)=SQRT(3.0)/2.0
      ZZ(2,2)=0.5
C
      ZZ(1,3)=ZZ(2,2)
      ZZ(2,3)=ZZ(1,2)
C
      ZZ(1,4)=0.0
      ZZ(2,4)=1.0
C
      ZZ(1,5)=-0.5
      ZZ(2,5)=SQRT(3.0)/2.0
C
      ZZ(1,6)=-ZZ(2,5)
      ZZ(2,6)=-ZZ(1,5)
C
      ZZ(1,7)=-1.0
      ZZ(2,7)=0.0
C
      DO 10 IZ=1,NZ
        Z(IZ)=FLOAT(IZ)
 10   CONTINUE
C
      DO 20 IX=1,NX
        X(IX)=-1.0+2.0*(IX-1)/FLOAT(NX-1)
 20   CONTINUE
C
      DO 30 IY=1,NY
        Y(IY)=-1.0+2.0*(IY-1)/FLOAT(NY-1)
 30   CONTINUE
C
      DO 100 IZ=1,7
        ZC=ZZ(1,IZ)
        ZD=ZZ(2,IZ)
        DO 90 IY=1,NY
          ZB=Y(IY)
          DO 80 IX=1,NX
            ZA=X(IX)
C
            ZAA=ZA*ZC-ZB*ZD
            ZAB=ZB*ZC+ZA*ZD
C
C	      F(IX,IY,IZ)=EXP(ZAA)*COS(PI*ZAB)
            F(IX,IY,IZ)=Iz   ! tbt
C
 80       CONTINUE
 90     CONTINUE
 100  CONTINUE
C
      RETURN
      END
