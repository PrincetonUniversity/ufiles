C******************** START FILE USMOO2.FOR ; GROUP USMOO2 *************
C===========================================================
C  USMOO2
C
C  INTERACTIVE USER INTERFACE FOR SMOOTHING 2-D DATA FCNS
C    EMPLOYS SMOOTHING ALGORITHM "FILTR6"
C    D. MC CUNE 17 JULY 1980 @PPPL
C
C Modified:
C  20020225 - tbt - added ismtyp as an argument to the call to
C                   GRF3F2 - prevent seg fault.
c
C  PROGRAM PRESENTS OPTIONS TO USER IN "MENU" FORMAT, AND
C    ALLOWS INTERACTIVE DEFINITION OF SMOOTHING CONTROL
C    PARAMETERS THRU PIECEWISE LINEAR DEFINITION ROUTINE
C    "PCIDEF.FOR"
C
C  ACCESS TO ROUTINES TO GRAPH THE DATA, SMOOTHED AND
C    UNSMOOTHED, IS PROVIDED, SO THAT REFERENCE TO THE
C    DATA ITSELF MAY BE MADE IN THE INTERACTIVE PROCESS
C    OF DEFINING SMOOTHING CONTROLS
C
C  PROGRAM ARCHITECTURE ALLOWS USER TO MAKE AN ATTEMPT AT
C  SMOOTHING THE DATA, DECIDE ITS NO GOOD, AND TRY TO SMOOTH
C  THE DATA AGAIN; I.E. THE ORIGINAL UNSMOOTHED DATA IS NOT
C  DESTROYED IN THE PROCESS
C
C-------------------------
C  SUBROUTINE ARGUMENTS:
C   X(NX),Z(NZ1,NY),Y(NY)    ARRAYS CONTAINING THE ORDINATES AND
C            ABSCISSAE OF THE ORIGINAL (UNSMOOTHED) DATA.
C            GENERALLY THESE ARRAYS ARE NOT MODIFIED BY THIS
C            SUBROUTINE, EXCEPT POSSIBLY BY THE FILTR6
C            SPIKE-DROP FEATURE (SEE FILTR6.FOR)
C            THESE ARE INPUT ARRAYS
C
C   ZS(NZ1,NY)        OUTPUT ARRAY CONTAINING THE SMOOTHED DATA
C            INITIALLY DEFAULTS TO THE UNSMOOTHED DATA IF THE
C            USER DOES NOT DIRECT THE PROGRAM TO CARRY OUT A
C            SMOOTHING OPERATION
C
C   DELF(NZ1,NY)       OUTPUT ARRAY CONTAINING THE FINAL 'DELTA',
C            OR WEIGHTED AVERAGE SMOOTHING RADIUS, AS A FUNCTION
C            OF X AND Y, USED TO CALCULATE ZS.  EACH ZS(I,J) IS
C            CALCULATED BY A SYMMETRIC WEIGHTED AVERAGE INTEGRAL
C            ALONG EITHER X OR Y (DEPENDING ON THE VALUE OF ISEL),
C            FROM X(I)-DELF(I,J) TO X(I)+DELF(I,J), Y(J) FIXED
C            (OR FROM Y(J)-DELF(I,J) TO Y(J)+DELF(I,J), X(I) FIXED)
C            OF THE UNSMOOTHED DATA.  DELF IS ITERATIVELY LOCALLY
C            REDUCED AS NECESSARY TO MAKE THE SMOOTHED DATA FALL
C            WITHIN THE USER SPECIFIED ERROR BARS ON THE RAW DATA.
C            ON EXIT DELF(I,J) IS THE DELTA ACTUALLY USED TO
C            CALCULATE ZS(I,J).  **OUTPUT ARRAY**
C
C   ZWK(NWK,4)   WORKSPACE FOR CARRYING OUT SMOOTHING OPERATION;
C            NWK SHOULD BE AT LEAST AS BIG AS THE MAX OF NX AND
C            NY TO AVOID ARRAY SPACE PROBLEMS. NWK X 4 ARRAY
C
C   ISEL     *** SELECT DIMENSION ***  ISEL=1 MEANS SMOOTHING
C            WILL BE CARRIED OUT BY AVERAGING ALONG THE DATA'S
C            FIRST DIMENSION IDEPENDANT VARIABLE; ISEL=2 MEANS
C            THE SMOOTHING WILL BE DONE BY AVERAGING ALONG
C            THE DATA'S SECOND DIMENSION INDEPENDANT VARIABLE.
C            **INPUT PARAMETER**
C
C
C   ZEND1    LEFT END-CONDITION PARAMETER USED IN LAST SMOOTHING
C            OPERATION CARRIED OUT (DEFAULT 0.5)
C               LOCATION OF "LEFT END" DEPENDS ON ISEL
C   ZEND2    RIGHT END CONDITION PARAMETER USED IN SMOOTHING
C            ZEND1 AND ZEND2 ARE OUTPUT
C               LOCATION OF "RIGHT END" DEPENDS ON ISEL
C
C   ZBASE    BASELINE VALUE IMPOSED DURING SMOOTHING
C            (MINIMUM ALLOWED VALUE FOR FUNCTION)
C   NBASE    # OF POINTS OF FUNCTION RESET TO BASELINE; BASELINE
C            RESET AFFECTS THE *UNSMOOTHED* DATA; ZBASE,NBASE ARE
C            OUTPUTS  OF THIS SUBROUTINE
C
C   ZDROP    SPIKE DROP HEIGHT (SEE OPTON #6 BELOW) USED
C   NDROP    # OF DATA SPIKE POINTS DROPPED; THIS AFFECTS
C            THE UNSMOOTHED DATA; ZDROP, NDROP ARE OUTPUTS
C
C   XLAB     10 CHARACTER LABEL FOR X, E.G. "TIME      "
C   YLAB     10 CHARACTER LABEL FOR Y, E.G. "RADIUS    "
C   ZLAB     20 CHARACTER LABEL FOR Z, E.G. "ELECTRON TEMPERATURE"
C   XUN      10 CHAR UNITS FOR X TERMINATED BY "$", E.G. "SECONDS  $"
C   YUN      10 CHAR UNITS FOR Y TERMINATED BY "$", E.G. "CM       $"
C   ZUN      10 CHAR UNITS FOR Z TERMINATED BY "$", E.G. "EV       $"
C
C   ISF,IDEV,NSHOT,IAVTYP,NSHOT2,NS2-- SPECIFICATION OF DATA TYPE,
C       I.E. DERIVED FROM SINGLE SHOT OR AVERAGED/CONSTRUCTED
C       FROM SEVERAL SHOTS, AND LISTS OF SHOTS IN A5 OR I5
C       FORMAT, FOR LABELING OF GRAPHS;  SEE "GRF3SG.FOR"
C       SUBROUTINE "GRF3" -- ALSO 4 CHARACTER DEVICE CODE (E.G. "PDX ")
C
C   PROGID   10 CHAR ID OF PROGRAM CARRYING OUT SMOOTHING
C            CALCULATION, FOR INFORMATION OF CALLER
C            (OUTPUT)
C
C-------------------------
      SUBROUTINE USMOO2(X,Y,Z,ISEL,NX,NY,NZ1,ZS,DELF,
     >     ZWK,NWK,ZEND1,ZEND2,ZBASE,NBASE,ZDROP,NDROP,
     >     XLAB,YLAB,ZLAB,XUN,YUN,ZUN,PROGID,
     >     ISF,IDEV,NSHOT,IAVTYP,NSHOT2,NS2)
      USE USMOO
C  COMMON:
      use plot1mmx
C  PASSED ARGS:
      DIMENSION X(NX),Y(NY),Z(NZ1,NY),ZS(NZ1,NY),DELF(NZ1,NY),
     >     ZWK(NWK,4),NSHOT2(NS2)
      CHARACTER*10 XLAB,YLAB,ZLAB(2),XUN,YUN,ZUN,DATID,PROGID
      character*4 idev
C  LOCAL:
      LOGICAL ILSMOO
      CHARACTER*10 ZEPS(2),ZDEL(2),ZEUN,ZDUN,ULAB,
     >     WLAB,VUN,ZDELF(2)
      CHARACTER*3 ZONOFF(2)
      CHARACTER*1 VLAB
      character*12 zslbl
C
C DMC MAY 85 - INTERIOR ENDPTS OPTION
      PARAMETER (NXEND=1028)
      REAL XENDI(NXEND),XYENDI(NXEND)
      INTEGER ISTRTI(NXEND+1),INUMI(NXEND+1)
C
C
C  INITIALIZE
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
      LOGICAL LXOUT
      LOGICAL LYES
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => USMOO2               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA ZDEL/'AVERAGING ','WIDTH     '/
      DATA ZDELF/'AVGING WID','TH (FINAL)'/
      DATA ZEPS/'ERROR TOLE','RANCE     '/
      DATA ZONOFF/'ON ','OFF'/
      DATA EPSINV/1.E38/
C => END DATA BLOCK
C ====================
C
      luntrm=lnout(0)
C
      PROGID='FILTR6.FOR'
 
      IDIR=0
      IF(ISEL.LT.1) ISEL=1
      IF(ISEL.GT.2) ISEL=2
      IF(ISEL.EQ.1) ZDUN=XUN
      IF(ISEL.EQ.2) ZDUN=YUN
      ILSMOO=.FALSE.
      NPCD=0
      NPCE=0
      ISELD=ISEL
      ISELE=ISEL
      KBASL=0
      KDROP=0
      KIXTRP=0
      KSAWCK=0
      XEND1=0.5
      XEND2=0.5
      NEPS2=0
      DO 5 I=1,NX
      DO 5 J=1,NY
      ZS(I,J)=Z(I,J)
      DELF(I,J)=0.0
 5    CONTINUE
C
      NUMIX=0
C
C---
C TOP MENU
C
      IF(ISEL.EQ.1) VLAB='X'
      IF(ISEL.EQ.2) VLAB='Y'
      IF(ISEL.EQ.1) ULAB=XLAB
      IF(ISEL.EQ.2) ULAB=YLAB
 10   CONTINUE
      CALL NEUPAG
      JBASL=2-KBASL
      JDROP=2-KDROP
      JIXTRP=2-KIXTRP
      JSAWCK=2-MIN0(1,KSAWCK)
 11   IF(LXOUT(0)) WRITE(LUNTRM,1001) ZLAB(1),ZLAB(2),ZUN,
     >     XLAB,XUN,YLAB,YUN,VLAB,
     >     ZONOFF(JBASL),ZONOFF(JDROP),XEND1,XEND2,NEPS2,NUMIX,
     >     ZONOFF(JIXTRP),ZONOFF(JSAWCK)
 
 1001 FORMAT(//'      DATA: Z= ',2A10,' (',A9,')'/
     >           '        VS. X= ',A10,10X,' (',A9,')   AND'/
     >           '            Y= ',A10,10X,' (',A9,')'//
     >  ' >>> CURRENTLY SMOOTHING IN "',A1,'" DIRECTION <<<'//
     >  ' CURRENT SETTINGS ENCLOSED IN BRACKETS "[ ]"'//
     >  ' OPTIONS:'/
     >  ' (1) GRAPH THE UNSMOOTHED DATA'/
     >  ' (2) GRAPH THE SMOOTHED DATA'/
     >  ' "K" to graph both data sets (via GRF3F2)'/
     >  ' (3) DEFINE (REDEFINE) DELTA ARRAY (WGHTD AVG WIDTH)'/
     >  ' (4) DEFINE (REDEFINE) EPSILON ARRAY (ERROR BAR)'/
     >  '     DEFAULT -- EPSILON = INFINITY'/
     >  ' (5) SET BASELINE    ["',A3,'"]'/
     >  ' (6) SET SPIKE DROP CONDITION    ["',A3,'"]'/
     >  ' (7) SET END CONDITIONS  [LH=',1PE10.3,' RH=',1PE10.3,']'/
     >  ' (8) SET LOW-N RELAXATION OF ERROR BAR (EPSILON)  [N=',I2,']'/
     >  ' (9) TYPE HELP MESSAGE ***'/
     >  ' (10) >>>>> SMOOTH THE DATA USING CURRENT PARAMETERS'/
     >  ' (11) QUIT'/
     >' ** TYPE "I" FOR INTERIOR ENDPTS OPTION (',I4,' NOW DEFINED)'/
     >' ** TYPE "X" FOR DELTA EXTRAPOLATIONS AT INT. ENDPTS, NOW "',
     >A,'"'/
     >' ** TYPE "S" FOR SAWTOOTH BREAK/SEARCH AT EACH ENDPT, NOW "',
     >A,'"')
      CALL UREAD(' SUB:USMOO2 >> ENTER OPTION #:$')
      IF(LCHAR('Q')) GOTO 2000
      IF(LCHAR('I')) THEN
        CALL INORDU(XENDI,XYENDI,NXEND,NUMIX,
     >     'INTERIOR SMOOTHING ENDPTS',0)
        GO TO 10
      ELSE IF(LCHAR('X')) THEN
        KIXTRP=1-KIXTRP
        GO TO 10
      ELSE IF(LCHAR('S')) THEN
        IF(LXOUT(0)) WRITE(LUNTRM,1070) KSAWCK
 1070   FORMAT(/' CURRENT SETTING:  ',I6/
     >' AT EACH INTERIOR BREAK PT SCAN THIS NO. OF NEIGHBOURING'/
     >' INTERVALS FOR THE ACTUAL SAWTOOTH EVENT, DEFINED AS THE'/
     >' LARGEST DISCONTINUITY (F(J+1)-F(J))**2; SCAN BOTH WAYS')
        CALL UREADI('USMOO1:  ENTER NO. OF INTERVALS TO SCAN:$',
     >	    KSAWCK)
        KSAWCK=MAX0(0,KSAWCK)
        GO TO 10
 
      else if(lchar('K')) then
 
C        tbt - I do not know what smoothing has been done.
C        Arbitrarily chose 0 just to have an argument.
         ismtyp = 0
         write(zslbl,'(a4,1x,i6)') idev,nshot
 
C  20020225 - tbt - added ismtyp as an argument - prevent seg fault.
 
         call grf3f2(x,zs,z,y,zwk,nx,ny,nz1,
     1	xlab,zlab(1)//zlab(2)//' smoothed',zlab(1)//zlab(2),
     2	ylab,xun,zun,yun,'USMOO2 data comparison',
     3	zslbl//' '//progid,
     4               ismtyp)
 
         go to 10
      ENDIF
      IANS=IDCOD(IERT)
      IF((IERT.NE.0).OR.(IANS.LT.1).OR.(IANS.GT.11)) THEN
        CALL UERMSG('ILLEGAL INTEGER OPCODE',' ',0)
        GO TO 11
      ENDIF
C  BRANCH
      GO TO (100,200,300,400,500,600,700,800,900,1000,2000) IANS
C-------------
C  GRAPH THE DATA
C
 100  CONTINUE
      ISMTYP=0
      CALL GRF3(X,Z,Y,ZWK,NX,NY,NZ1,XLAB,YLAB,ZLAB,
     >         XUN,YUN,ZUN,ZWK,0,IDIR,
     >         ISF,IDEV,NSHOT,IAVTYP,NSHOT2,NS2,ISMTYP)
      GO TO 10
C--------
C  GRAPH THE SMOOTHED DATA
C
 200  CONTINUE
      ISMTYP=0
      IF(ILSMOO) ISMTYP=1
      CALL GRF3(X,ZS,Y,ZWK,NX,NY,NZ1,XLAB,YLAB,ZLAB,
     >         XUN,YUN,ZUN,ZWK,0,IDIR,
     >         ISF,IDEV,NSHOT,IAVTYP,NSHOT2,NS2,ISMTYP)
      GO TO 10
C-------------
C  DEFINE DELTA ARRAY
C
 300  CONTINUE
      CALL NEUPAG
      WLAB=XLAB
      IF(ISELD.EQ.2) WLAB=YLAB
      IF(LXOUT(0)) WRITE(LUNTRM,3001) ZLAB(1),ZLAB(2),
     >     ULAB,ZDEL(1),ZDEL(2),XLAB,YLAB,WLAB
 3001 FORMAT(/' SMOOTHING:  ',2A10,' IN ',A10/1X,' THE ',2A10/
     >  ' MAY BE DEFINED AS A FUNCTION OF EITHER INDEPENDANT'/
     >  ' COORDINATE, ',A10,' OR ',A10,', BUT *NOT* BOTH;'//
     >  ' CURRENTLY THIS PARAMETER IS DEFINED AS A FUNCTION'/
     >  ' OF ',A10,' ... NOTE CHANGING THE INDEPENDANT VARIABLE'/
     >  ' DESTROYS THE OLD DEFINITION (IF ANY)'/)
      CALL UREAD(
     >  ' USMOO2:  INTERCHANGE INDEPENDANT VARIABLE? (Y/N):$')
      IF(LCHAR('Q')) GOTO 2000
      IF(LYES(0)) THEN
        ISELD=3-ISELD
        NPCD=0
      ENDIF
      IF(ISELD.EQ.1) CALL PCIDEF(X,ZWK,NX,XPCD,DELPC,NPCD,JPCMAX,
     >         XLAB,ZDEL,XUN,ZDUN)
      IF(ISELD.EQ.2) CALL PCIDEF(Y,ZWK,NY,XPCD,DELPC,NPCD,JPCMAX,
     >         YLAB,ZDEL,YUN,ZDUN)
      GO TO 10
C---------
C  DEFINE EPSILON ARRAY
C
 400  CONTINUE
      CALL NEUPAG
      WLAB=XLAB
      IF(ISELE.EQ.2) WLAB=YLAB
      IF(LXOUT(0)) WRITE(LUNTRM,3001) ZLAB(1),ZLAB(2),
     >     ULAB,ZEPS(1),ZEPS(2),XLAB,YLAB,WLAB
      CALL UREAD(
     >  ' USMOO2: INTERCHANGE INDEPENDANT VARIABLE? (Y/N):$')
      IF(LYES(0)) THEN
        ISELE=3-ISELE
        NPCE=0
      ENDIF
C  OPTION-- ABSOLUTE OR PER-CENT ERROR BAR
 404  IF(LXOUT(0)) WRITE(LUNTRM,4001)
 4001 FORMAT(/' OPTION:  ENTER:'/
     >  ' "1" IF ERROR BAR IS TO BE EXPRESSED AS PER-CENT OF'/
     >  '     FUNCTION BEING SMOOTHED;'/
     >  ' "2" IF ERROR BAR IS TO BE EXPRESSED IN ABSOLUTE UNITS'/
     >  '     OF FUNCTION BEING SMOOTHED:'/
     >  )
 405  CALL UREAD(' SUB:USMOO2 >> ENTER "1" OR "2":$')
      IEPST=IXUOPC('12$')
      IF(LCHAR('Q')) GOTO 2000
      IF(IEPST.EQ.0) THEN
        CALL UERMSG('INVALID OPTION CODE',' ',0)
        GO TO 404
      ENDIF
      ZEUN=ZUN
      IF(IEPST.EQ.1) ZEUN='PER-CENT $'
C
      IF(ISELE.EQ.1) CALL PCIDEF(X,ZWK,NX,XPCE,EPSPC,NPCE,JPCMAX,
     >         XLAB,ZEPS,XUN,ZEUN)
      IF(ISELE.EQ.2) CALL PCIDEF(Y,ZWK,NY,XPCE,EPSPC,NPCE,JPCMAX,
     >         YLAB,ZEPS,YUN,ZEUN)
C
      GO TO 10
C-------------
C  SET BASELINE
C
 500  CONTINUE
 505  CALL UREAD(
     >  ' SUB:USMOO2 >> DO YOU WANT A BASELINE? (Y/N):$$')
      IBASL=1
      IF(LCHAR('Q')) GOTO 2000
      IF(LYES(0)) IBASL=2
      KBASL=IBASL-1
      IF(KBASL.EQ.0) GO TO 10
 506  CALL UREAD(' SUB:USMOO2 >> ENTER BASELINE VALUE:$')
      ZBASL=FDCOD(IERT)
      IF(IERT.NE.0) GO TO 506
      BASL=ZBASL
      GO TO 10
C-------------
C  SPIKE DROP
C
 600  CONTINUE
 605  CALL UREAD(
     >   ' SUB:USMOO2 >> DO YOU WANT SPIKE DROP OPTION? (Y/N):$$')
      IDROP=1
      IF(LCHAR('Q')) GOTO 2000
      IF(LYES(0)) IDROP=2
      KDROP=IDROP-1
      IF(KDROP.EQ.0) GO TO 10
      IF(LXOUT(0)) WRITE(LUNTRM,6002)
 6002 FORMAT(' THE HEIGHT OF A SPIKE AT DATA POINT J IS DEFINED'/
     >  ' AS THE HEIGHT OF THE TRIANGLE FORMED BY THE THREE PTS'/
     >  ' (X(I-1),Z(I-1,J)),(X(I),Z(I,J)),(X(I+1),Z(I+1,J)).'/
     >  ' [ IF SMOOTHING IS VS. X; ANALOGOUS DEFN. APPLIES IF VS. Y]'/
     >  ' SPIKES OF GREATER THAN THE SPECIFIED HEIGHT ARE'/
     >  ' REMOVED IF THEY ARE ISOLATED FROM OTHER SPIKES'/)
 606  CALL UREAD(' SUB: USMOO2 >> ENTER SPIKE HEIGHT:$$')
      ZDROP=FDCOD(IERT)
      IF(IERT.NE.0) GO TO 606
      DROP=ZDROP
      GO TO 10
C-------------
C  END CONDITIONS:
C
 700  CONTINUE
      VUN=XUN
      IF(ISEL.EQ.2) VUN=YUN
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,7001)
 7001 FORMAT(/
     >  '  END CONDITION PARAMETERS DETERMINE HANDLING OF THE'/
     >  ' SMOOTHING OPERATION AT THE LEFT AND RIGHT ENDPOINTS '/
     >  ' OF THE DATA.  A PARAMETER VALUE OF 1.0 RESULTS IN'/
     >  ' MAXIMUM SMOOTHING:  THE SLOPE OF THE DATA FUNCTION'/
     >  ' WILL TEND TO ZERO AT THE ENDPOINT; A PARAMETER VALUE'/
     >  ' OF 0.0 RESULTS IN MINIMAL SMOOTHING:  THE ENDPOINT IS'/
     >  ' FIXED.  INTERMEDIATE VALUES RESULT IN A "MIXTURE" OF'/
     >  ' THESE EXTREMES; PARAMETER VALUES NOT BETWEEN 0 AND 1'/
     >  ' ARE NOT ALLOWED.'/)
      Z1=X(1)
      Z2=X(NX)
      IF(ISEL.EQ.2) Z1=Y(1)
      IF(ISEL.EQ.2) Z2=Y(NY)
      IF(LXOUT(0)) WRITE(LUNTRM,7002) VLAB,Z1,VUN,VLAB,Z2,VUN
 7002 FORMAT(1X,
     >  ' 2D SMOOTHING-- LEFT "END" IS LINE ',A1,'=',1PE10.3,1X,A9/
     >  1X,'               RIGHT "END" IS LINE ',A1,'=',1PE10.3,
     >  1X,A9/)
 705  CALL UREAD(
     >  ' USMOO2:  ENTER END PARAMETER FOR *LEFT* ENDPOINT:$')
      ZEND=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 2000
      IF(IERT.NE.0) GO TO 705
      IF((ZEND.LT.0.0).OR.(ZEND.GT.1.0)) GO TO 700
      XEND1=ZEND
 706  CALL UREAD(
     >  ' USMOO2:  ENTER END PARAMETER FOR *RIGHT* ENDPOINT:$')
      ZEND=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 2000
      IF(IERT.NE.0) GO TO 706
      IF((ZEND.LT.0.0).OR.(ZEND.GT.1.0)) GO TO 700
      XEND2=ZEND
      GO TO 10
C-------------
C  LOW-N RELAXATION OF ERROR BAR
C
 800  CONTINUE
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,8001)
 8001 FORMAT(//
     >  '  THIS OPTION ALLOWS THE RELAXATION OF STRICT'/
     >  ' IMPLIMENTATION OF THE ERROR BAR FEATURE IN THE CASE'/
     >  ' OF THE SMOOTHED DATA VIOLATING THE ERROR BAR ON'/
     >  ' THE RAW DATA FOR A "SMALL" NUMBER OF CONSECUTIVE'/
     >  ' DATA POINTS ONLY.  TWO INPUTS ARE REQUIRED:  THE'/
     >  ' MAXIMUM NUMBER N CONSTITUTING A "SMALL" NUMBER OF DATA'/
     >  ' POINTS (THE DEFAULT, N=0, TURNS OFF THIS FEATURE),'/
     >  ' AND THE *MAXIMUM* RELAXATION FACTOR TO APPLY, IN THE'/
     >  ' CASE OF A VERY SHORT VIOLATION CONSISTING OF BUT'/
     >  ' ONE DATA POINT.  THE RELAXATION FACTOR IS MULTIPLIED'/
     >  ' WITH THE ORIGINAL ERROR BAR TO GET THE EFFECTIVE ERROR'/
     >  ' BAR; LESSER RELAXATION FACTORS ARE APPLIED IN THE'/
     >  ' CASE OF A VIOLATION OF LENGTH M POINTS, 1 < M <= N.'/
     >  ' THE RELAXATION FACTOR MUST BE GREATER THAN 1.0;'/
     >  ' THE MAXIMUM VALUE OF N IS 50.'//)
 805  CALL UREAD(' USMOO2: ENTER N FOR ERROR BAR RELAXATION:$')
      IEPS2=IDCOD(IERT)
      IF(IERT.NE.0) GO TO 805
      IF((IEPS2.GT.50).OR.(IEPS2.LT.0)) GO TO 805
      NEPS2=IEPS2
      IF(NEPS2.EQ.0) GO TO 10
 807  CALL UREAD(' USMOO2: ENTER MAXIMAL RELAXATION FACTOR:$')
      ZEPS2=FDCOD(IERT)
      IF(IERT.NE.0) GO TO 807
      IF(ZEPS2.LE.1.0) GO TO 800
C  CALCULATE RELAXATION FACTOR AS A FUNCTION OF M LINEARLY
      EPS2(1)=ZEPS2
      IF(NEPS2.EQ.1) GO TO 10
C
      DO 820 J=2,NEPS2
      EPS2(J)=ZEPS2+(J-1)*(1.0-ZEPS2)/NEPS2
 820  CONTINUE
C
      GO TO 10
C-------------
C  TYPE HELP MESSAGE
C
 900  CONTINUE
C
      CALL NEUPAG
      WRITE(LUNTRM,9001)
 9001 FORMAT(/
     >  ' THIS IS AN ALGORITHM FOR NUMERICALLY SMOOTHING DATA.'/
     >  ' THE SMOOTHED DATA FUNCTION IS CALCULATED FROM THE'/
     >  ' UNSMOOTHED FUNCTION BY THE CALCULATION OF "LOCAL'/
     >  ' WEIGHTED AVERAGES", SO THAT THE SMOOTHED FUNCTION'/
     >  ' ZSM(X,Y) IS AN AVERAGE OF THE ORIGINAL FUNCTION'/
     >  ' Z(X,Y) FROM X-DELTA TO X+DELTA (Y FIXED), OR, FROM'/
     >  ' Y-DELTA TO Y+DELTA (X FIXED), DEPENDING UPON WHICH'/
     >  ' DIMENSION THE DATA IS BEING SMOOTHED AGAINST.'/
     >  ' THE (HALF-) WIDTH OF THE WEIGHTED AVERAGE, "DELTA",'/
     >  ' IS USER DEFINED AND MAY BE A FUNCTION OF X OR A '/
     >  ' FUNCTION OF Y, BUT IN THIS IMPLIMENTATION NOT A '/
     >  ' FUNCTION OF BOTH X AND Y.'/
     >  '     AN ADDITIONAL FEATURE OF THIS SMOOTHING ALGORITHM'/
     >  ' IS TO ALLOW THE DEFINITION OF AN ERROR BAR ( EPS(X)'/
     >  ' OR EPS(Y) BUT NOT EPS(X,Y) ) SUCH THAT FOR ANY'/
     >  ' (X,Y), ABS(ZSM(X,Y)-Z(X,Y)) < EPS WILL BE MAINTAINED'/
     >  ' THE ERROR BAR "EPSILON" PROVIDES A MEANS OF PREVENTING'/
     >  ' THE DATA FROM BEING OVERSMOOTHED.  THE ERROR BAR IS'/
     >  ' STRICTLY ADHERED TO EXCEPT AS PROVIDED FOR UNDER '/
     >  ' OPTION #8 ABOVE.'/
     >  '    IF PROBLEMS ARISE, CONTACT D. MC CUNE  X2731')
      CALL UPAUST(1)
      GO TO 10
C-------------
C  *** SMOOTH THE DATA
C
 1000 CONTINUE
      IEPCLR=0
      IF((NPCD.GT.0).AND.(NPCE.GT.0)) GO TO 1100
      IF(NPCD.LE.0) THEN
        CALL UERMSG('? "DELTA" PARAMETER NOT DEFINED',' ',-1)
        GO TO 11
      ENDIF
      IF(NPCE.LE.0) THEN
        IEPCLR=1
        NPCE=1
        IEPST=0
        XPCE(1)=0.0
        EPSPC(1)=EPSINV
      ENDIF
C
C  SET PARAMETERS TO CARRY OUT SUCCESSIVE SMOOTHS ALONG
C  LINES OF CONST X (Y) DEPENDING ON SETTING OF ISEL
C
 1100 CONTINUE
      CALL CPU_TIME(ZTIM1)
C  END CONDITIONS
      ZEND1=XEND1
      ZEND2=XEND2
C  DEFN # OF LINES ALONG WHICH TO SMOOTH, # OF PTS PER LINE
      GO TO (1102,1103) ISEL
 1102 CONTINUE
      IOPS=NY
      IPTS=NX
      GO TO 1105
 1103 CONTINUE
      IOPS=NX
      IPTS=NY
      GO TO 1105
 1105 CONTINUE
C  CLEAR COUNTERS
      NDROP=0
      NBASE=0
C  LOOP THRU EACH LINE
      DO 1200 I=1,IOPS
C  DEFINE DELTA-INITIAL FOR THIS LINE
      GO TO (1201,1202) ISELD
 1201 CONTINUE
      CALL PCTRAN(X,ZWK(1,1),NX,XPCD,DELPC,JPCMAX,NPCD)
      GO TO 1205
 1202 CONTINUE
      CALL PCTRAN(Y,ZWK(1,1),NY,XPCD,DELPC,JPCMAX,NPCD)
      GO TO 1205
 1205 CONTINUE
      IF(ISEL.EQ.ISELD) GO TO 1210
      ZDELT=ZWK(I,1)
      DO 1208 J=1,IPTS
      ZWK(J,1)=ZDELT
 1208 CONTINUE
 1210 CONTINUE
C  DEFINE EPSILON FOR THIS LINE
      GO TO (1211,1212) ISELE
 1211 CONTINUE
      CALL PCTRAN(X,ZWK(1,2),NX,XPCE,EPSPC,JPCMAX,NPCE)
      GO TO 1215
 1212 CONTINUE
      CALL PCTRAN(Y,ZWK(1,2),NY,XPCE,EPSPC,JPCMAX,NPCE)
      GO TO 1215
 1215 CONTINUE
      IF(ISEL.EQ.ISELE) GO TO 1220
      ZEPSL=ZWK(I,2)
      DO 1218 J=1,IPTS
      ZWK(J,2)=ZEPSL
 1218 CONTINUE
 1220 CONTINUE
C  GET Z ALONG THIS LINE
      DO 1230 J=1,IPTS
      GO TO (1225,1226) ISEL
 1225 CONTINUE
      KI=J
      KJ=I
      GO TO 1228
 1226 CONTINUE
      KI=I
      KJ=J
      GO TO 1228
 1228 CONTINUE
      ZWK(J,3)=Z(KI,KJ)
 1230 CONTINUE
C  CONVERT PER-CENT EPSILON TO ABSOLUTE UNITS IF NECESSARY
      IF(IEPST.NE.1) GO TO 1250
      ZMAX=0
      DO 1235 J=1,IPTS
      ZMAX=AMAX1(ZMAX,ABS(ZWK(J,3)))
 1235 CONTINUE
      DO 1237 J=1,IPTS
      IF(ZWK(J,3).EQ.0.0) ZWK(J,2)=.01*ZMAX*ZWK(J,2)
      IF(ZWK(J,3).NE.0.0) ZWK(J,2)=.01*ZWK(J,2)*ABS(ZWK(J,3))
 1237 CONTINUE
 1250 CONTINUE
CXC  TEMP-- PRINT PARAMETERS:
CX	CALL NEUPAG
CX	WRITE(LUNTRM,12501)
CX12501	FORMAT(' J   DELTA    EPSILON   Z')
CX	DO 12502 J=1,IPTS
CX	WRITE(LUNTRM,12503) J,ZWK(J,1),ZWK(J,2),ZWK(J,3)
CX12502	CONTINUE
CX12503	FORMAT(2X,I3,3(1X,1PE10.3))
CX	PAUSE 'DIAGNOSE'
C---
C  SMOOTH THE DATA ALONG LINE
C
C  ** DMC MAY 1985 - IMPLIMENT INTERIOR END PTS
      IF(NUMIX.EQ.0) THEN
        GO TO (1260,1270) ISEL
 1260   CALL FILTR6(X,ZWK(1,3),ZWK(1,4),NX,ZWK(1,2),NX,
     >       EPS2,NEPS2,ZWK(1,1),KDROP,DROP,KBASL,BASL,
     >       ZEND1,ZEND2,ZSM,ICDROP,ICBASE)
        GO TO 1275
 1270   CALL FILTR6(Y,ZWK(1,3),ZWK(1,4),NY,ZWK(1,2),NY,
     >       EPS2,NEPS2,ZWK(1,1),KDROP,DROP,KBASL,BASL,
     >       ZEND1,ZEND2,ZSM,ICDROP,ICBASE)
        GO TO 1275
      ELSE
C  EVALUATE SMOOTHING GRPS (1ST PASS ONLY)
       IF(I.EQ.1) THEN
        ISIZF=NZ1*NY
        IF(ISEL.EQ.1) THEN
          CALL INCORL(X,NX,XENDI,NUMIX,ISTRTI,INUMI,NXEND,IGRP)
          IF(KSAWCK.GT.0) CALL INCORS(Z,ISIZF,ISTRTI,INUMI,IGRP,
     >		NY,NZ1,1,KSAWCK)
        ELSE IF(ISEL.EQ.2) THEN
          CALL INCORL(Y,NY,XENDI,NUMIX,ISTRTI,INUMI,NXEND,IGRP)
          IF(KSAWCK.GT.0) CALL INCORS(Z,ISIZF,ISTRTI,INUMI,IGRP,
     >		NX,1,NZ1,KSAWCK)
        ENDIF
       ENDIF
C  SMOOTH EACH GRP SEPERATELY
        DO IG=1,IGRP
          I1=ISTRTI(IG)
          IN=INUMI(IG)
          IF(IN.EQ.1) THEN
            ZWK(I1,4)=ZWK(I1,3)
          ELSE IF(IN.GT.1) THEN
            IF(ISEL.EQ.1) THEN
      	CALL FILTR6(X(I1),ZWK(I1,3),ZWK(I1,4),IN,ZWK(I1,2),IN,
     >            EPS2,NEPS2,ZWK(I1,1),KDROP,DROP,KBASL,BASL,
     >            ZEND1,ZEND2,ZSM,NDROP,NBASE)
C  DMC NOV 1985 - EXTRAPOLATION TO INTERIOR ENDPTS OPTION
              IF(KIXTRP.EQ.1)
     >                   CALL FIXTRP(X,ZWK(1,4),ZWK(1,1),NX,I1,IN)
            ELSE IF(ISEL.EQ.2) THEN
      	CALL FILTR6(Y(I1),ZWK(I1,3),ZWK(I1,4),IN,ZWK(I1,2),IN,
     >            EPS2,NEPS2,ZWK(I1,1),KDROP,DROP,KBASL,BASL,
     >            ZEND1,ZEND2,ZSM,NDROP,NBASE)
C  DMC NOV 1985 - EXTRAPOLATION TO INTERIOR ENDPTS OPTION
              IF(KIXTRP.EQ.1)
     >                   CALL FIXTRP(Y,ZWK(1,4),ZWK(1,1),NY,I1,IN)
            ENDIF
          ENDIF
        ENDDO
      ENDIF
C  SAVE RESULTS
 1275 CONTINUE
      NBASE=NBASE+ICBASE
      NDROP=NDROP+ICDROP
      DO 1280 J=1,IPTS
      GO TO (1281,1282) ISEL
 1281 CONTINUE
      KI=J
      KJ=I
      GO TO 1285
 1282 CONTINUE
      KI=I
      KJ=J
      GO TO 1285
 1285 CONTINUE
      ZS(KI,KJ)=ZWK(J,4)
      DELF(KI,KJ)=ZWK(J,1)
 1280 CONTINUE
C==> END OF LOOP FOR SMOOTHING
 1200 CONTINUE
      ILSMOO=.TRUE.
C====
C
C
C
C
      ZBASE=0.0
      IF(NBASE.NE.0) ZBASE=BASL
      ZDROP=0.0
      IF(NDROP.NE.0) ZDROP=DROP
C  DISPLAY SUMMARY:
      IF(IEPCLR.EQ.1) NPCE=0
      CALL CPU_TIME(ZTIM2)
      ZCTIM=ZTIM2-ZTIM1
      CALL NEUPAG
      INPTS=NX*NY
      WRITE(LUNTRM,10001) PROGID,ZCTIM,INPTS,NBASE,NDROP
10001 FORMAT(//'  SMOOTHING COMPLETED.  ALGORITHM: "',A10,'"'/
     >  '  CPU TIME = ',1PE10.3,' SECONDS; ',I6,' DATA PTS.'/
     >  '  ',I6,' POINTS RESET TO BASELINE'/
     >  '  ',I6,' POINTS DROPPED AS DATA SPIKES'/
     >  )
      CALL UPAUST(1)
      CALL UREAD(' USMOO2: ENTER "Y" TO PLOT DELTA (FINAL):$')
      IF(LCHAR('Q')) GOTO 2000
      IF(.NOT.LYES(0)) GO TO 10
      ISMTYP=0
      CALL GRF3(X,DELF,Y,ZWK,NX,NY,NZ1,XLAB,YLAB,ZDELF,
     >         XUN,YUN,ZDUN,ZWK,0,IDIR,ISF,IDEV,NSHOT,
     >         IAVTYP,NSHOT2,NS2,ISMTYP)
C
      GO TO 10
C
C
C-----------------
C  EXIT
C
 2000 CONTINUE
C
      IF(ILSMOO) GO TO 2100
      DO 2010 I=1,NX
      DO 2010 J=1,NY
      DELF(I,J)=0.0
      ZS(I,J)=Z(I,J)
 2010 CONTINUE
C
      ZEND1=0.0
      ZEND2=0.0
C
 2100 CONTINUE
      RETURN
      	END
