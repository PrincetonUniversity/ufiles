C******************** START FILE INCORL.FOR ; GROUP INORD ******************
C-----------------------------------------------------------------------
C  INCORL
C
      SUBROUTINE INCORL(XIN,NIN,XBRK,NBRK,ISTART,INUM,NDIM,NGRP)
C
C  CORRELATE INPUT ORDERED LIST (XBRK...) WITH INPUT ORDERED
C  COORDINATE (XIN...)
C
C  EXPECT XIN(NIN) TO INDEP COORD OF ARBITRARY NUMERIC DATA FCN
C  XBRK TO BE A LIST OF "EVENT BDY'S" E.G. INPUT BY INORD ABOVE
C
      REAL XIN(NIN)
      REAL XBRK(NBRK)
C
      INTEGER ISTART(NDIM)
      INTEGER INUM(NDIM)
C
C
C  XIN(NIN) ORDERED ARRAY OF X (INPUT)
C  XBRK(NBRK)  ORDERED ARRAY OF X "BREAKS" (INPUT)
C
C  NDIM - INPUT MAX NO. OF OUTPUT GROUPS DEFINED BY X "BREAKS"
C
C  ISTART(J) - INDEX (TO XIN) OF START OF JTH GROUP (DETERMINED
C                 BY XBRK AND ENDPTS OF XIN) (OUTPUT)
C  INUM(J)   - NUMBER OF XIN PTS IN JTH GRP (OUTPUT)
C
C  NGRP - NUMBER OF GROUPS (OUTPUT)
C
C-----------------------
C
C START - 1ST GROUP
C
      NGRP=1
      ISTART(NGRP)=1
C
      DO IBRK=1,NBRK
        IF(XBRK(IBRK).GT.XIN(1)) GO TO 10
      ENDDO
C
C  NO RELEVENT BREAKS (ALL .LE. XIN(1))
      INUM(NGRP)=NIN
      RETURN
C
 10   CONTINUE
      IBRK1=IBRK
C
      DO IBRK=NBRK,IBRK1,-1
        IF(XBRK(IBRK).LT.XIN(NIN)) GO TO 20
      ENDDO
C
C  NO RELEVENT BREAKS (ALL .LE. XIN(1) .OR. .GE. XIN(NIN))
      INUM(NGRP)=NIN
      RETURN
C
 20   CONTINUE
      IBRKND=IBRK
C
      IBRK=IBRK1
      IST=1
 50   CONTINUE
      XB=XBRK(IBRK)
C  FIND END OF CURRENT GROUP
      DO IX=IST,NIN
        IF(XIN(IX).GT.XB) GO TO 60
      ENDDO
C  NO EXIT
      IARGH=1/IARGH
 60   CONTINUE
C  OK, START NEXT GROUP IF SPACE AVAIL.
      IF(NGRP.EQ.NDIM) THEN
        CALL UERMSI('INCORL:  GROUP NO. DIMENSION EXCEEDED',NDIM,1)
        INUM(NGRP)=NIN-IST+1
        RETURN
      ENDIF
      INUM(NGRP)=IX-IST
      NGRP=NGRP+1
      IST=IX
      ISTART(NGRP)=IST
C  FIND NEXT PROPER X BREAK (IF ANY)
      IF(IBRK.EQ.IBRKND) GO TO 100
      IBP1=IBRK+1
      DO IBRK=IBP1,IBRKND
        IF(XBRK(IBRK).GT.XIN(IST)) GO TO 50
      ENDDO
C  NO MORE BREAKS - EXIT
 100  CONTINUE
      INUM(NGRP)=NIN+1-IST
      RETURN
      END
C******************** END FILE INCORL.FOR ; GROUP INORD ******************
