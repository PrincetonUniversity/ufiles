C******************** START FILE INDUFI.FOR ; GROUP INORD ******************
C---------------------------------------------------------------
C INDUFI - READ INDORD LIST FROM UFILE
C  OPTION TO DEFINE INTERVAL ABOUT EACH POINT
C
      SUBROUTINE INDUFI(LUN,X,WK,NDIM,NUM,LABEL,IFLAG)
C
      CHARACTER*(*) LABEL   ! LABEL FOR USER PROMPTING
C
      REAL X(NDIM),WK(NDIM) ! DATA TO BE READ IN
C
C  LUN - I/O CHANNEL NO. FOR UFILE
C  IFLAG - REQUIRE OUTPUT X ARRAY IN ASCENDING ORDER IF .NE.1
C
C  OUTPUT X,WK, NUM= NUMBER OF X PTS RETURNED
C
C  NAME AND OPEN FILE
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LXOUT
      LOGICAL LYES
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      CALL UFNTER(LUN,LABEL)
C
      CALL UREADI('INDUFI:  ENTER UFILE SHOT NO.:$$',ISHOT)
C
      CALL UFOPRD(LUN,ISHOT,IER)
C
      IF(IER.NE.0) GO TO 900
C
      NUM=0
C
C  READ FILE
C
      CALL UF1DRE(LUN,X,WK,NDIM,INUM,IER,0)
      CALL UFCLOS(LUN)
C
      IF(IER.NE.0) GO TO 900
C
C  CHECK ORDER
C
      IF(IFLAG.NE.1) THEN
        INM1=INUM-1
        DO 10 I=1,INM1
          IP1=I+1
          IF(X(IP1).LE.X(I)) THEN
            CALL UERMSG('?INDUFI:  UFILE X AXIS OUT OF ORDER',' ',1)
            GO TO 900
          ENDIF
 10     CONTINUE
      ENDIF
      IF(LXOUT(0)) WRITE(LNOUT(0),1001) INUM,X(1),X(INUM)
 1001 FORMAT(' INDUFI:  ',I4,' X POINTS READ, RANGE ',
     >1PE11.4,' TO ',1PE11.4)
C
C  OPTION TO DEFINE INTERVAL AROUND EACH PT READ IN
C
      CALL UREAD(
     >'INDUFI: DEFINE 2 PT INTERVAL ABOUT EACH PT READ IN? (Y/N):$$')
        IF(.NOT.LYES(0)) THEN
C  ALL DONE
          NUM=INUM
          GO TO 100
        ELSE
C  DEFINE INTERVAL
          CALL UREADF('  SPECIFY INTERVAL HALF WIDTH, X UNITS:$$',ZW)
C
          Z=X(1)-ZW
          CALL INDUAD(WK,NDIM,NUM,Z,IER)
          IF(IER.NE.0) GO TO 900
C
          INM1=INUM-1
          DO 20 I=1,INM1
            IP1=I+1
            ZWX=X(IP1)-X(I)
            IF((ZWX.GT.3.0*ZW).OR.(IFLAG.EQ.1)) THEN
              ZZW=ZW
            ELSE
              ZZW=0.333333*ZWX
            ENDIF
C
            Z=X(I)+ZZW
            CALL INDUAD(WK,NDIM,NUM,Z,IER)
            IF(IER.NE.0) GO TO 900
            Z=X(IP1)-ZZW
            CALL INDUAD(WK,NDIM,NUM,Z,IER)
            IF(IER.NE.0) GO TO 900
C
 20       CONTINUE
C
          Z=X(INUM)+ZW
          CALL INDUAD(WK,NDIM,NUM,Z,IER)
          IF(IER.NE.0) GO TO 900
C
        DO 30 I=1,NUM
          X(I)=WK(I)
 30     CONTINUE
      ENDIF
C
 100  CONTINUE
      RETURN
C
 900  CONTINUE
      CALL UERMSI('?INDUFI:  RAN OUT OF SPACE, LIMIT',NDIM,1)
      NUM=0
      RETURN
      END
C******************** END FILE INDUFI.FOR ; GROUP INORD ******************
