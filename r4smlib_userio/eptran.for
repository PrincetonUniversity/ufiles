C******************** START FILE EPTRAN.FOR ; GROUP USMOO1 ******************
C=============================================================
C  EPTRAN
C  TRANSLATE USER ARRAY TO ERROR BARS FOR SMOOTHING OR PLOTTING
C    IEPST=1 ==> USER ARRAY IN PER-CENTS OF DATA
C
      SUBROUTINE EPTRAN(X,Y,EPS,N,XPCE,EPSPC,NPCE,
     >               JPCMAX,IEPST)
C
      DIMENSION X(N),Y(N),EPS(N),XPCE(NPCE),EPSPC(NPCE)
C
      CALL PCTRAN(X,EPS,N,XPCE,EPSPC,JPCMAX,NPCE)
C  TRANSFORM PER-CENT EPSILON TO ABSOLUTE UNITS IF NECESSARY
      IF(IEPST.NE.1) GO TO 1110
      ZMAX=0.0
      DO 1105 IJ=1,N
      ZMAX=AMAX1(ZMAX,ABS(Y(IJ)))
 1105 CONTINUE
C
      DO 1107 IJ=1,N
      IF(Y(IJ).EQ.0.0) EPS(IJ)=.01*EPS(IJ)*ZMAX
      IF(Y(IJ).NE.0.0) EPS(IJ)=.01*EPS(IJ)*ABS(Y(IJ))
 1107 CONTINUE
C
 1110 CONTINUE
      RETURN
      	END
C******************** END FILE EPTRAN.FOR ; GROUP USMOO1 ******************
