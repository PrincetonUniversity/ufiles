C******************** START FILE GRFWEB.FOR ; GROUP GRFWEB ******************
C----------------------GRFWEB-SUBMODULE-----------------------
C  D. MC CUNE  JULY 16 1980
C   >>> THIS VERSION DOES NOT HAVE SMOOTHING <<<
c
c dmc Aug 2004 -- this routine does not appear to be in use.
c
C
C  GRFADH    ASKS QUESTIONS AND PLOTS 1 CURVE WITH OR WITHOUT
C            ERROR BARS
C
C  CREATED 10-AUG-78  D. MCCUNE TO TAKE REPITITIOUS CODE
C                     OUT OF MAIN
C
      SUBROUTINE GRFWEB(TIME,Y1,YERR,NSCANS,IC1,IC2,IC3,LBL1,
     1                 LBL2,LBL3)
C
      use plot1mmx
C
C  IC1-- CONTROLS TYPE OF AXES FOR PLOT OF Y1(TIME)
C  IC2-- =1 TO PLOT ERROR BARS YERR(T)
C        =2 NOT TO PLOT ERROR BARS
C  IC3-- =0==> ERROR BARS USER DEFINED; =1==> ERROR BARS READ FROM
C               DATA FILE (FOR LABELING PURPOSES
C
      DIMENSION TIME(NSCANS),Y1(NSCANS),YERR(NSCANS)
      character*80 ZBUFF
      CHARACTER*10 LBL1(3),LBL2(3),LBL3
      CHARACTER*10 ZLBL(2)
      character*1  yesno
      REAL XPERR(2),YPERR(2)
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
      LOGICAL LYES
      LOGICAL LYESC
      logical lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => GRFWEB               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA IOFFL/30/
C => END DATA BLOCK
C ====================
C
      luntrm=lnout(0)
C
      ZLBL(1)=LBL3
      ZLBL(2)='          '
      YESNO='Y'
      IF(IC2.NE.1) GO TO 99
      ZFAC=1.0
      IF((TIME(NSCANS).GT.TIME(1)).AND.(XMAX.GT.XMIN))
     >     ZFAC=(XMAX-XMIN)/(TIME(NSCANS)-TIME(1))
      IF((ZFAC*NSCANS).LE.100.0) GO TO 99
 10   CONTINUE
      CALL NEUPAG
      WRITE(LUNTRM,9901) NSCANS
 9901 FORMAT(//3X,I5,' ERROR BARS IS A LOT TO PLOT'/
     >  '   YOU MAY WANT TO CHANGE THE SCALE OR TURN OFF ERROR BARS:'/)
      GO TO 704
 99   CONTINUE
      IF(YESNO.NE.'N') GO TO 705
C
C	SET SCALE
C
704   CONTINUE
      CALL UREAD(
     >  ' SUB:GRFWEB >> ENTER "1" TO TURN ON ERROR BAR PLOTTING:$')
      IC2=2
      IF(LYESC('1')) IC2=1
      IF(LCHAR('Q')) RETURN
      CALL UREAD(' SUB:GRFWEB >> CHANGE THE SCALE ? (Y/N)$')
      IF(.NOT.LYES(0)) GO TO 801
      IF(LXOUT(0)) WRITE(LUNTRM,7059)
 7059 FORMAT(/
     >  ' ENTER "X" NOT TO CHANGE A LIMIT ON THE GRAPH'/)
 71   CONTINUE
      IF(LXOUT(0)) WRITE(LUNTRM,7101) XMIN
 7101 FORMAT('  OLD XMIN=',1PE10.3)
      CALL UREAD(' SUB:GRFWEB >> ENTER NEW XMIN (E10.3)$')
      IF(LCHAR('X')) GO TO 72
      IF(LCHAR('Q')) GO TO 704
      XMIN=FDCOD(IERT)
      IF(IERT.NE.0) GO TO 71
 72   IF(LXOUT(0)) WRITE(LUNTRM,7201) XMAX
 7201 FORMAT('  OLD XMAX=',1PE10.3)
      CALL UREAD(' SUB:GRFWEB >> ENTER NEW XMAX$')
      IF(LCHAR('Q')) GO TO 704
      IF(LCHAR('X')) GO TO 73
      XMAX=FDCOD(IERT)
      IF(IERT.NE.0) GO TO 72
 73   IF(LXOUT(0)) WRITE(LUNTRM,7301) YMIN
 7301 FORMAT('  OLD YMIN=',1PE10.3)
      CALL UREAD(' SUB:GRFWEB >> ENTER NEW YMIN$')
      IF(LCHAR('Q')) GO TO 704
      IF(LCHAR('X')) GO TO 74
      YMIN=FDCOD(IERT)
      IF(IERT.NE.0) GO TO 73
 74   IF(LXOUT(0)) WRITE(LUNTRM,7401) YMAX
 7401 FORMAT('  OLD YMAX=',1PE10.3)
      CALL UREAD(' SUB:GRFWEB >> ENTER NEW YMAX$')
      IF(LCHAR('Q')) GO TO 704
      IF(LCHAR('X')) GO TO 801
      YMAX=FDCOD(IERT)
      IF(IERT.NE.0) GO TO 74
 801  CONTINUE
C
C  MAKE GRAPH
C
705   IF(IC1.NE.0) CALL DPLOT1(TIME,Y1,NSCANS,IC1)
C
C   D. MC CUNE  APR 21 1980--- MAKE A.G. CALLS FOR GRAPH LABELS
C
C    THIS ENABLES USE OF VERSATEC AS OUTPUT DEVICE
C
c !*** jpj@JET Apr-1995
c ***	ENCODE(66,1000,ZBUFF)
        write (ZBUFF,1000)
     >             (LBL1(IJ),IJ=1,2),(LBL2(IJ),IJ=1,2)
 1000 FORMAT(20X,2A10,' VS. ',2A10,'$')
      CALL AGXMHS(IOFFL,20,ZBUFF)
C
C    *** UNITS ***
      write(zbuff,1007) LBL2(3)
 1007 FORMAT(A9,'$')
      CALL AGXMHS(800,50,ZBUFF)
      write(zbuff,1007) LBL1(3)
      CALL AGXMVS(30,680,ZBUFF)
C
      write(zbuff,1002) (ZLBL(IJ),IJ=1,2)
 1002 FORMAT(30X,2A10,'     $')
      CALL AGXMHS(0,750,ZBUFF)
C
      IF(IC2.EQ.2) GO TO 1009
      IF(IC3.NE.1) write(zbuff,1003)
      IF(IC3.EQ.1) write(zbuff,10031)
 1003 FORMAT(30X,'USER SUPPLIED ERROR BARS           $')
10031 FORMAT(30X,'FILE SUPPLIED ERROR BARS           $')
      CALL AGXMHS(0,727,ZBUFF)
 1009 CONTINUE
C
      IF(IC2.EQ.2) GO TO 900
C  PLOT ERROR BARS
      ZDX=0.25*(TIME(NSCANS)-TIME(1))/(NSCANS-1)
      ILINE=2
      DO 850 I=1,NSCANS
      IF((TIME(I).LT.XMIN).OR.(TIME(I).GT.XMAX)) GO TO 850
      XPERR(1)=TIME(I)
      XPERR(2)=TIME(I)
      YPERR(1)=Y1(I)-YERR(I)
      YPERR(2)=Y1(I)+YERR(I)
      CALL DPLOT1(XPERR,YPERR,2,ILINE)
C
      XPERR(1)=TIME(I)-ZDX
      XPERR(2)=TIME(I)+ZDX
      YPERR(1)=Y1(I)+YERR(I)
      YPERR(2)=YPERR(1)
      CALL DPLOT1(XPERR,YPERR,2,ILINE)
C
      YPERR(1)=Y1(I)-YERR(I)
      YPERR(2)=YPERR(1)
      CALL DPLOT1(XPERR,YPERR,2,ILINE)
C
 850  CONTINUE
C
 900  CONTINUE
      CALL UPAUST(2)
      CALL UREAD(' SUB:GRFWEB >> PLOT CURVE AGAIN ? (Y/N)$')
      IF(LYES(0)) GO TO 704
C
      RETURN
      	END
C******************** END FILE GRFWEB.FOR ; GROUP GRFWEB ******************
