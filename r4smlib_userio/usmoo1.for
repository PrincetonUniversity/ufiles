C******************** START FILE USMOO1.FOR ; GROUP USMOO1 *************
C===========================================================
C  USMOO1
C
C  INTERACTIVE USER INTERFACE FOR SMOOTHING 1-D DATA FCNS
C    EMPLOYS SMOOTHING ALGORITHM "FILTR6"
C    D. MC CUNE 17 JULY 1980 @PPPL
C
C  PROGRAM PRESENTS OPTIONS TO USER IN "MENU" FORMAT, AND
C    ALLOWS INTERACTIVE DEFINITION OF SMOOTHING CONTROL
C    PARAMETERS THRU PIECEWISE LINEAR DEFINITION ROUTINE
C    "PCIDEF.FOR"
C
C  ACCESS TO ROUTINES TO GRAPH THE DATA, SMOOTHED AND
C    UNSMOOTHED, IS PROVIDED, SO THAT REFERENCE TO THE
C    DATA ITSELF MAY BE MADE IN THE INTERACTIVE PROCESS
C    OF DEFINING SMOOTHING CONTROLS
C
C  PROGRAM ARCHITECTURE ALLOWS USER TO MAKE AN ATTEMPT AT
C  SMOOTHING THE DATA, DECIDE ITS NO GOOD, AND TRY TO SMOOTH
C  THE DATA AGAIN; I.E. THE ORIGINAL UNSMOOTHED DATA IS NOT
C  DESTROYED IN THE PROCESS
C
C-------------------------
C  REV. D. MC CUNE 13 MARCH 1981
C    USMOO.BLK COMMON SWITCH "KTPPCE" ADDED; KTPPCE=0 MEANS
C  USER SUPPLIED ERROR BARS VIA PCIDEF (AS BEFORE); KTPPCE=1
C  MEANS ERROR BARS HAVE BEEN SUPPLIED VIA FILE INPUT
C  OUTSIDE OF THIS SUBROUTINE***.  CODE REVISED SO AS TO CHECK
C  THIS SWITCH AND NOT DESTROY FILE-SUPPLIED ERROR BARS IF
C  AVAILABLE.
C      PLOTTING OF ERROR BARS WITH RAW DATA IS ALSO NOW
C  SUPPORTED, USING SUBROUTINE "GRFWEB"
C     ***>> ERROR BARS GO INTO USMOO.BLK COMMON ARRAY EPSPC;
C       THE X VALUES WITH RESPECT TO WHICH THESE ARE DEFINED GO INTO
C       ARRAY XPCE; VARIABLE NPCE= # DEFINED; NOTE MAXIMUM=100 ***
C
C-------------------------
C  SUBROUTINE ARGUMENTS:
C   X(N),Y(N)    ARRAYS CONTAINING THE ORDINATES AND
C            ABSCISSAE OF THE ORIGINAL (UNSMOOTHED) DATA.
C            GENERALLY THESE ARRAYS ARE NOT MODIFIED BY THIS
C            SUBROUTINE, EXCEPT POSSIBLY BY THE FILTR6
C            SPIKE-DROP FEATURE (SEE FILTR6.FOR)
C            THESE ARE INPUT ARRAYS
C
C   YS(N)        OUTPUT ARRAY CONTAINING THE SMOTHED DATA
C            INITIALLY DEFAULTS TO THE UNSMOOTHED DATA IF THE
C            USER DOES NOT DIRECT THE PROGRAM TO CARRY OUT A
C            SMOOTHING OPERATION
C
C   DEL(N)       OUTPUT ARRAY CONTAINING THE *FINAL* 'DELTA',
C            OR WEIGHTED AVERAGE SMOOTHING RADIUS, AS A FUNCTION
C            OF X, USED TO CALCULATE YS.  EACH YS(J) IS CALCULATED
C            BY A SYMMETRIC WEIGHTED AVERAGE INTEGRAL ON Y OVER
C            RANGE X(J)-DEL(J) TO X(J)+DEL(J); FILTR6 LOCALLY AND
C            ITERATIVELY REDUCES THE VALUE OF DEL(J) AS REQUIRED
C            TO CONFORM TO ERROR BARS ON THE ORIGINAL UNSMOOTHED
C            DATA DEFINED INTERACTIVELY BY THE USER IN THIS ROUTINE
C
C   EPS(N)       WORKSPACE FOR USER DEFINITION OF ERROR BARS ON
C            THE ORIGINAL DATA.  ON EXIT THIS ARRAY DOES *NOT*
C            NECESSARILY CONTAIN THE ERROR BARS USED WHEN THE
C            LAST SMOOTHING OPERATION WAS CARRIED OUT.  BOTH EPS(J)
C            AND DEL(J) DEFAULT TO 0.0 FOR ALL J IF NO SMOOTHING
C            OPERATION IS CARRIED OUT.
C
C   ZEND1    LEFT END-CONDITION PARAMETER USED IN LAST SMOOTHING
C            OPERATION CARRIED OUT (DEFAULT 0.5)
C   ZEND2    RIGHT END CONDITION PARAMETER USED IN SMOOTHING
C            ZEND1 AND ZEND2 ARE OUTPUT
C
C   ZBASE    BASELINE VALUE IMPOSED DURING SMOOTHING
C            (MINIMUM ALLOWED VALUE FOR FUNCTION)
C   NBASE    # OF POINTS OF FUNCTION RESET TO BASELINE; BASELINE
C            RESET AFFECTS THE SMOOTHED DATA ONLY; ZBASE,NBASE ARE
C            OUTPUTS  OF THIS SUBROUTINE
C
C   ZDROP    SPIKE DROP HEIGHT (SEE OPTON #6 BELOW) USED
C   NDROP    # OF DATA SPIKE POINTS DROPPED; THIS AFFECTS
C            THE *UNSMOOTHED* DATA; ZDROP, NDROP ARE OUTPUTS
C
C   XLAB     10 CHARACTER LABEL FOR X, E.G. "TIME      "
C   YLAB     20 CHARACTER LABEL FOR Y, E.G. "ELECTRON TEMPERATURE"
C   XUN      10 CHAR UNITS FOR X TERMINATED BY "$", E.G. "SECONDS  $"
C   YUN      10 CHAR UNITS FOR Y TERMINATED BY "$", E.G. "EV       $"
C
C   DATID    10 CHAR ID FOR DATA, E.G. "SHOT 13800", TO BE
C            DISPLAYED ON GRAPHS. (INPUT)
C
C   PROGID   10 CHAR ID OF PROGRAM CARRYING OUT SMOOTHING
C            CALCULATION, FOR INFORMATION OF CALLER
C            (OUTPUT)
C
C-------------------------
      SUBROUTINE USMOO1(
     >     X,Y,N,YS,DEL,EPS,ZEND1,ZEND2,ZBASE,NBASE,ZDROP,NDROP,
     >     XLAB,YLAB,XUN,YUN,DATID,PROGID)
      USE USMOO
C  COMMON:
      use plot1mmx
C  PASSED ARGS:
      DIMENSION X(N),Y(N),YS(N),DEL(N),EPS(N)
      CHARACTER*10 XLAB,YLAB(2),XUN,YUN,DATID,PROGID
C  LOCAL:
      LOGICAL ILSMOO
      CHARACTER*10 ZL1(3),ZL2(3),ZEPS(2),ZDEL(2),ZEUN,ZDUN
      CHARACTER*3 ZONOFF(2)
C
C DMC MAY 85 - INTERIOR ENDPTS OPTION
C
C *LISMAK* 11-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
      LOGICAL LXOUT
      LOGICAL LYES
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      PARAMETER (NXEND=1028)
      REAL XENDI(NXEND),XYENDI(NXEND)
      INTEGER ISTRTI(NXEND+1),INUMI(NXEND+1)
C
C  INITIALIZE
C
      DATA ZDEL/'AVERAGING ','RADIUS    '/
      DATA ZEPS/'ERROR TOLE','RANCE     '/
      DATA ZONOFF/'ON ','OFF'/
C  A VERY LARGE NUMBER...
      DATA EPSINV/1.E38/
C
      PROGID='FILTR6.FOR'
C
      ZDUN=XUN
      ILSMOO=.FALSE.
      NPCD=0
      IF(KTPPCE.EQ.0) NPCE=0
C
      luntrm=lnout(0)
C
C  SET DEFAULTS - PLOTS WITH "ERROR BARS"
C
      IF(N.LT.100) THEN
        INWEB=N
      ELSE
        INWEB=40
      ENDIF
      IWEBFX=0
C
      IF((KTPPCE.EQ.1).AND.(NPCE.GT.0)) THEN
        IWEBF=1
      ELSE
        IWEBF=0
      ENDIF
C
      KSAWCK=0
      KIXTRP=0
      KBASL=0
      KDROP=0
      XEND1=0.5
      XEND2=0.5
      NEPS2=0
      DO 5 I=1,N
        YS(I)=Y(I)
        DEL(I)=0.0
        EPS(I)=0.0
 5    CONTINUE
C
      ZL1(1)=YLAB(1)
      ZL1(2)=YLAB(2)
      ZL1(3)=YUN
      ZL2(1)=XLAB
      ZL2(3)=XUN
C
      XMIN=X(1)
      XMAX=X(N)
      ZYMIN=Y(1)
      ZYMAX=Y(1)
      DO 7 I=1,N
        ZYMIN=AMIN1(ZYMIN,Y(I))
        ZYMAX=AMAX1(ZYMAX,Y(I))
 7    CONTINUE
      ZXMIN2=X(1)
      ZXMAX2=X(N)
      ZYMIN2=ZYMIN
      ZYMAX2=ZYMAX
C
      NUMIX=0
C
C---
C TOP MENU
C
 10   CONTINUE
      CALL NEUPAG
      JBASL=2-KBASL
      JDROP=2-KDROP
      JIXTRP=2-KIXTRP
      JSAWCK=2-MIN0(1,KSAWCK)
 11   CONTINUE
      IF(LXOUT(0)) WRITE(LUNTRM,1001) YLAB(1),YLAB(2),YUN,
     >     XLAB,XUN,ZONOFF(JBASL),ZONOFF(JDROP),XEND1,XEND2,NEPS2
     >     ,ZONOFF(2-IWEBF),NUMIX,ZONOFF(JIXTRP),ZONOFF(JSAWCK)
 1001 FORMAT(//' SMOOTHING: Y= ',2A10,' (',A9,')'/
     >           '        VS. X= ',A10,10X,' (',A9,')'//
     >  ' CURRENT SETTINGS ENCLOSED IN BRACKETS "[ ]"'//
     >  ' OPTIONS:'/
     >  ' (1) GRAPH THE UNSMOOTHED DATA'/
     >  ' (2) GRAPH THE SMOOTHED DATA'/
     >  ' "K" for both smoothed and unsmoothed data on same axes'/
     >  ' (3) DEFINE (REDEFINE) DELTA ARRAY (WGHTD AVG WIDTH)'/
     >  ' (4) DEFINE (REDEFINE) EPSILON ARRAY (ERROR BAR)'/
     >  '      DEFAULT - EPSILON=INFINITY'/
     >  ' (5) SET BASELINE    ["',A3,'"]'/
     >  ' (6) SET SPIKE DROP CONDITION    ["',A3,'"]'/
     >  ' (7) SET END CONDITIONS  [LH=',1PE10.3,' RH=',1PE10.3,']'/
     >  ' (8) SET LOW-N RELAXATION OF ERROR BAR (EPSILON)  [N=',I2,']'/
     >  ' (9) TYPE HELP MESSAGE ***'/
     >  ' (10) >>>>> SMOOTH THE DATA USING CURRENT PARAMETERS'/
     >  ' (11) QUIT'/
     >  ' (12) SET CONTROLS FOR PLOTTING "ERROR BARS" ["',A3,'"]'/
     >  ' (13) RESTORE ORIGINAL (MIN & MAX OF F,X) SCALE TO 2D GRAPHS'/
     >' ... EVENT SMOOTHING FEATURES ...'/
     >' ** TYPE "I" FOR INTERIOR ENDPTS OPTION (',I4,' NOW DEFINED)'/
     >' ** TYPE "X" FOR DELTA-WIDTH EXTRAPOLATION AT INT.ENDPTS, NOW "',
     >A,'"'/
     >' ** TYPE "S" FOR SAWTOOTH BREAK/SEARCH AT EACH ENDPT, NOW "',
     >A,'"')
 15   CALL UREAD(' SUB:USMOO1 >> ENTER OPTION #:$')
      IF(LCHAR('Q')) GOTO 2000
      IF(LCHAR('I')) THEN
        CALL INORDU(XENDI,XYENDI,NXEND,NUMIX,
     >     'INTERIOR SMOOTHING ENDPTS',0)
        GO TO 10
      ELSE IF(LCHAR('X')) THEN
        KIXTRP=1-KIXTRP
        GO TO 10
      ELSE IF(LCHAR('S')) THEN
        IF(LXOUT(0)) WRITE(LUNTRM,1070) KSAWCK
 1070   FORMAT(/' CURRENT SETTING:  ',I6/
     >' AT EACH INTERIOR BREAK PT SCAN THIS NO. OF NEIGHBOURING'/
     >' INTERVALS FOR THE ACTUAL SAWTOOTH EVENT, DEFINED AS THE'/
     >' LARGEST DISCONTINUITY (F(J+1)-F(J))**2; SCAN BOTH WAYS')
        CALL UREADI('USMOO1:  ENTER NO. OF INTERVALS TO SCAN:$',
     >	    KSAWCK)
        KSAWCK=MAX0(0,KSAWCK)
        GO TO 10
      else if(lchar('K')) then
         call grafx2(x,ys,y,n,xun,yun,datid//' '//progid,
     1	ylab(1)//ylab(2)//' vs. '//xlab,
     2	'smoothed and unsmoothed data.')
         go to 10
      ENDIF
      IANS=IDCOD(IERT)
      IF((IERT.NE.0).OR.(IANS.LT.1).OR.(IANS.GT.13)) THEN
        CALL UERMSG('% ILLEGAL INTEGER OPCODE',' ',0)
        GO TO 11
      ENDIF
C  BRANCH
      GO TO (100,200,300,400,500,600,700,800,900,
     >         1000,2000,1200,1300) IANS
C-------------
C  GRAPH THE DATA
C
 100  CONTINUE
      ZL2(2)='          '
      IF(IWEBF.EQ.0) THEN
        CALL GRFAH0(X,Y,N,ZL2,ZL1,DATID,0,ZL1)
      ELSE
C
        IF(NPCE.GT.0) THEN
          DO 104 I=1,N
            EPS(I)=0.0
 104      CONTINUE
          CALL EPTRAN(X,Y,EPS,N,
     >		 XPCE,EPSPC,NPCE,JPCMAX,IEPST)
        ENDIF
C
        IF(NPCD.GT.0) THEN
          DO 105 I=1,N
            DEL(I)=0.0
 105      CONTINUE
          CALL PCTRAN(X,DEL,N,XPCD,DELPC,JPCMAX,NPCD)
        ENDIF
C
        CALL GRAFXE(X,Y,N,X,Y,N,IWEBFX,DEL,INWEB,EPS,
     >       ZL2(3),ZL1(3),DATID,' ',
     >       ZL1(1)//ZL1(2)//' VS. '//ZL2(1)//ZL2(2) )
C
      ENDIF
C
      GO TO 10
C--------
C  GRAPH THE SMOOTHED DATA
C
 200  CONTINUE
C
      IF(.NOT.ILSMOO) GO TO 100
      ZL2(2)='(SMOOTHED)'
C
      IF(IWEBF.EQ.0) THEN
        CALL GRFAH0(X,YS,N,ZL2,ZL1,DATID,0,ZL1)
      ELSE
C
        IF(NPCE.GT.0) THEN
          DO 204 I=1,N
            EPS(I)=0.0
 204      CONTINUE
          CALL EPTRAN(X,Y,EPS,N,
     >		 XPCE,EPSPC,NPCE,JPCMAX,IEPST)
        ENDIF
C
        IF(NPCD.GT.0) THEN
          DO 205 I=1,N
            DEL(I)=0.0
 205      CONTINUE
          CALL PCTRAN(X,DEL,N,XPCD,DELPC,JPCMAX,NPCD)
        ENDIF
C
        CALL GRAFXE(X,YS,N,X,Y,N,IWEBFX,DEL,INWEB,EPS,
     >       ZL2(3),ZL1(3),DATID,' ',
     >       ZL1(1)//ZL1(2)//' VS. '//ZL2(1)//ZL2(2) )
      ENDIF
C
      GO TO 10
C-------------
C  DEFINE DELTA ARRAY
C
 300  CONTINUE
      CALL PCIDEF(X,EPS,N,XPCD,DELPC,NPCD,JPCMAX,
     >         XLAB,ZDEL,XUN,ZDUN)
      GO TO 10
C---------
C  DEFINE EPSILON ARRAY
C
 400  CONTINUE
C  CLEAR FILE-SUPPLIED ERROR BAR FLAG
C
      KTPPCE=0
C
      CALL NEUPAG
C  OPTION-- ABSOLUTE OR PER-CENT ERROR BAR
 402  IF(LXOUT(0)) WRITE(LUNTRM,4001)
 4001 FORMAT(/' OPTION:  ENTER:'/
     >  ' "1" IF ERROR BAR IS TO BE EXPRESSED AS PER-CENT OF'/
     >  '     FUNCTION BEING SMOOTHED;'/
     >  ' "2" IF ERROR BAR IS TO BE EXPRESSED IN ABSOLUTE UNITS'/
     >  '     OF FUNCTION BEING SMOOTHED:'/
     >  )
 405  CALL UREAD(' SUB:USMOO1 >> ENTER "1" OR "2":$')
      IEPST=IDCOD(IERT)
      IF(LCHAR('Q')) GOTO 2000
      IF((IERT.NE.0).OR.(IEPST.LT.1).OR.(IEPST.GT.2)) THEN
        CALL UERMSG('NOT A 1 OR 2',' ',0)
        GO TO 402
      ENDIF
      ZEUN=YUN
      IF(IEPST.EQ.1) ZEUN='PER-CENT $'
C
      CALL PCIDEF(X,EPS,N,XPCE,EPSPC,NPCE,JPCMAX,
     >         XLAB,ZEPS,XUN,ZEUN)
C
      GO TO 10
C-------------
C  SET BASELINE
C
 500  CONTINUE
 505  CALL UREAD(
     >  ' SUB:USMOO1 >> DO YOU WANT A BASELINE? (Y/N):$$')
      IF(LCHAR('Q')) GOTO 2000
      IBASL=1
      IF(LYES(0)) IBASL=2
      KBASL=IBASL-1
      IF(KBASL.EQ.0) GO TO 10
 506  CALL UREAD(' SUB:USMOO1 >> ENTER BASELINE VALUE:$$')
      ZBASL=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 2000
      IF(IERT.NE.0) GO TO 506
      BASL=ZBASL
      GO TO 10
C-------------
C  SPIKE DROP
C
 600  CONTINUE
 605  CALL UREAD(
     >   ' SUB:USMOO1 >> DO YOU WANT SPIKE DROP OPTION? (Y/N):$$')
      IDROP=1
      IF(LYES(0)) IDROP=2
      KDROP=IDROP-1
      IF(KDROP.EQ.0) GO TO 10
      IF(LXOUT(0)) WRITE(LUNTRM,6002)
 6002 FORMAT(' THE HEIGHT OF A SPIKE AT DATA POINT J IS DEFINED'/
     >  ' AS THE HEIGHT OF THE TRIANGLE FORMED BY THE THREE PTS'/
     >  ' (X(J-1),Y(J-1)),(X(J),Y(J)),(X(J+1),Y(J+1)).'/
     >  ' SPIKES OF GREATER THAN THE SPECIFIED HEIGHT ARE'/
     >  ' REMOVED IF THEY ARE ISOLATED FROM OTHER SPIKES'/)
 606  CALL UREAD(' SUB: USMOO1 >> ENTER SPIKE HEIGHT:$$')
      ZDROP=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 2000
      IF(IERT.NE.0) GO TO 606
      DROP=ZDROP
      GO TO 10
C-------------
C  END CONDITIONS:
C
 700  CONTINUE
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,7001)
 7001 FORMAT(/
     >  '  END CONDITION PARAMETERS DETERMINE HANDLING OF THE'/
     >  ' SMOOTHING OPERATION AT THE LEFT AND RIGHT ENDPOINTS '/
     >  ' OF THE DATA.  A PARAMETER VALUE OF 1.0 RESULTS IN'/
     >  ' MAXIMUM SMOOTHING:  THE SLOPE OF THE DATA FUNCTION'/
     >  ' WILL TEND TO ZERO AT THE ENDPOINT; A PARAMETER VALUE'/
     >  ' OF 0.0 RESULTS IN MINIMAL SMOOTHING:  THE ENDPOINT IS'/
     >  ' FIXED.  INTERMEDIATE VALUES RESULT IN A "MIXTURE" OF'/
     >  ' THESE EXTREMES; PARAMETER VALUES NOT BETWEEN 0 AND 1'/
     >  ' ARE NOT ALLOWED.'/)
 705  CALL UREAD(
     >  ' USMOO1:  ENTER END PARAMETER FOR *LEFT* ENDPOINT:$')
      ZEND=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 2000
      IF(IERT.NE.0) GO TO 705
      IF((ZEND.LT.0.0).OR.(ZEND.GT.1.0)) GO TO 700
      XEND1=ZEND
 706  CALL UREAD(
     >  ' USMOO1:  ENTER END PARAMETER FOR *RIGHT* ENDPOINT:$')
      ZEND=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 2000
      IF(IERT.NE.0) GO TO 706
      IF((ZEND.LT.0.0).OR.(ZEND.GT.1.0)) GO TO 700
      XEND2=ZEND
      GO TO 10
C-------------
C  LOW-N RELAXATION OF ERROR BAR
C
 800  CONTINUE
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,8001)
 8001 FORMAT(//
     >  '  THIS OPTION ALLOWS THE RELAXATION OF STRICT'/
     >  ' IMPLIMENTATION OF THE ERROR BAR FEATURE IN THE CASE'/
     >  ' OF THE SMOOTHED DATA VIOLATING THE ERROR BAR ON'/
     >  ' THE RAW DATA FOR A "SMALL" NUMBER OF CONSECUTIVE'/
     >  ' DATA POINTS ONLY.  TWO INPUTS ARE REQUIRED:  THE'/
     >  ' MAXIMUM NUMBER N CONSTITUTING A "SMALL" NUMBER OF DATA'/
     >  ' POINTS (THE DEFAULT, N=0, TURNS OFF THIS FEATURE),'/
     >  ' AND THE *MAXIMUM* RELAXATION FACTOR TO APPLY, IN THE'/
     >  ' CASE OF A VERY SHORT VIOLATION CONSISTING OF BUT'/
     >  ' ONE DATA POINT.  THE RELAXATION FACTOR IS MULTIPLIED'/
     >  ' WITH THE ORIGINAL ERROR BAR TO GET THE EFFECTIVE ERROR'/
     >  ' BAR; LESSER RELAXATION FACTORS ARE APPLIED IN THE'/
     >  ' CASE OF A VIOLATION OF LENGTH M POINTS, 1 < M <= N.'/
     >  ' THE RELAXATION FACTOR MUST BE GREATER THAN 1.0;'/
     >  ' THE MAXIMUM VALUE OF N IS 50.'//)
 805  CALL UREAD(' USMOO1: ENTER N FOR ERROR BAR RELAXATION:$')
      IEPS2=IDCOD(IERT)
      IF(LCHAR('Q')) GOTO 2000
      IF(IERT.NE.0) GO TO 805
      IF((IEPS2.GT.50).OR.(IEPS2.LT.0)) GO TO 805
      NEPS2=IEPS2
      IF(NEPS2.EQ.0) GO TO 10
 807  CALL UREAD(' USMOO1: ENTER MAXIMAL RELAXATION FACTOR:$')
      ZEPS2=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 2000
      IF(IERT.NE.0) GO TO 807
      IF(ZEPS2.LE.1.0) GO TO 800
C  CALCULATE RELAXATION FACTOR AS A FUNCTION OF M LINEARLY
      EPS2(1)=ZEPS2
      IF(NEPS2.EQ.1) GO TO 10
C
      DO 820 J=2,NEPS2
      EPS2(J)=ZEPS2+(J-1)*(1.0-ZEPS2)/NEPS2
 820  CONTINUE
C
      GO TO 10
C-------------
C  TYPE HELP MESSAGE
C
 900  CONTINUE
C
      CALL NEUPAG
      WRITE(LUNTRM,9001)
 9001 FORMAT(/
     >  ' THIS IS AN ALGORITHM FOR NUMERICALLY SMOOTHING DATA.'/
     >  ' THE SMOOTHED DATA FUNCTION IS CALCULATED FROM THE'/
     >  ' UNSMOOTHED FUNCTION BY THE CALCULATION OF "LOCAL'/
     >  ' WEIGHTED AVERAGES", SO THAT THE SMOOTHED FUNCTION'/
     >  ' YSM(X) IS AN AVERAGE OF THE ORIGINAL FUNCTION Y(X)'/
     >  ' FROM X-DELTA TO X+DELTA.  THE WIDTH OF THE'/
     >  ' WEIGHTED AVERAGE, DELTA, IS A USER DEFINED PARAMETER'/
     >  ' WHICH MAY BE A FUNCTION OF THE DATA''S INDEPENDANT'/
     >  ' COORDINATE X.  '/
     >  '    AN ADDITIONAL FEATURE OF THIS SMOOTHING ALGORITHM'/
     >  ' IS TO ALLOW THE DEFINITION OF AN ERROR BAR EPS(X) (WHICH '/
     >  ' MAY ALSO BE A FUNCTION OF THE INDEPENDANT COORDINATE),'/
     >  ' SUCH THAT FOR ANY X, ABS(YSM(X)-Y(X)) < EPS(X) WILL BE'/
     >  ' MAINTAINED.  THE ERROR BAR "EPSILON" PROVIDES'/
     >  ' A MEANS OF PREVENTING THE DATA FROM BEING OVERSMOOTHED.'/
     >  ' THE ERROR BAR IS STRICTLY ADHERED TO EXCEPT AS PROVIDED'/
     >  ' FOR IN OPTION (8) ABOVE.'/
     >  '    IF PROBLEMS ARISE, CONTACT D. MC CUNE  X2731')
      CALL UPAUST(1)
      GO TO 10
C-------------
C  *** SMOOTH THE DATA
C
 1000 CONTINUE
      IEPCLR=0
C  CHECK THAT PARAMETERS HAVE BEEN DEFINED
      IF((NPCD.GT.0).AND.(NPCE.GT.0)) GO TO 1100
      IF(NPCD.LE.0) THEN
        CALL UERMSG('? "DELTA" ARRAY HAS NOT BEEN DEFINED',' ',-1)
        GO TO 11
      ENDIF
      IF(NPCE.LE.0) THEN
C  DEFAULT = INFINITE ERROR BAR
        IEPST=0
        IEPCLR=1
        NPCE=1
        XPCE(1)=0.0
        EPSPC(1)=EPSINV
      ENDIF
C
 1100 CONTINUE
C  TIME THE SMOOTH
      CALL CPU_TIME(ZTIM1)
      ZEND1=XEND1
      ZEND2=XEND2
      CALL PCTRAN(X,DEL,N,XPCD,DELPC,JPCMAX,NPCD)
      CALL EPTRAN(X,Y,EPS,N,XPCE,EPSPC,NPCE,JPCMAX,IEPST)
      IF(IEPCLR.EQ.1) THEN
         NPCE=0
         epspc(1)=0.0
      endif
C
C ***
C
C  DMC MAY 85 - IMPLIMENT INTERIOR ENDPTS OPTION
      IF(NUMIX.EQ.0) THEN
        CALL FILTR6(X,Y,YS,N,EPS,N,EPS2,NEPS2,DEL,
     >         KDROP,DROP,KBASL,BASL,ZEND1,ZEND2,ZSM,NDROP,NBASE)
      ELSE
        CALL INCORL(X,N,XENDI,NUMIX,ISTRTI,INUMI,NXEND,IGRP)
        IF(KSAWCK.GT.0) CALL INCORS(Y,N,ISTRTI,INUMI,IGRP,
     >	      1,1,1,KSAWCK)
        DO I=1,IGRP
          I1=ISTRTI(I)
          IN=INUMI(I)
          IF(IN.EQ.1) THEN
            YS(I1)=Y(I1)
          ELSE IF(IN.GT.1) THEN
            CALL FILTR6(X(I1),Y(I1),YS(I1),IN,EPS(I1),IN,EPS2,NEPS2,
     >          DEL(I1),KDROP,DROP,KBASL,BASL,
     >          ZEND1,ZEND2,ZSM,NDROP,NBASE)
C  DMC NOV 1985 - EXTRAPOLATION TO INTERIOR ENDPTS OPTION
            IF(KIXTRP.EQ.1) CALL FIXTRP(X,YS,DEL,N,I1,IN)
          ENDIF
        ENDDO
      ENDIF
C
      ILSMOO=.TRUE.
      ZBASE=0.0
      IF(NBASE.NE.0) ZBASE=BASL
      ZDROP=0.0
      IF(NDROP.NE.0) ZDROP=DROP
C  DISPLAY SUMMARY, OPTION TO GRAPH DELTA
      CALL CPU_TIME(ZTIM2)
      ZCTIM=ZTIM2-ZTIM1
C
      CALL NEUPAG
      ZS1=SCURVF(X,Y,N)
      ZS2=SCURVF(X,YS,N)
      IF(ZS1.EQ.0.0) ZS1=1.0
      ZSRAT=ZS2/ZS1
      WRITE(LUNTRM,10001) PROGID,ZCTIM,N,ZSRAT,NBASE,NDROP
10001 FORMAT(//'  SMOOTHING COMPLETED.  ALGORITHM: "',A10,'"'/
     >  '  CP TIME = ',1PE10.3,' SECONDS; ',I5,' DATA POINTS.'/
     >  '  CURVATURE RATIO = ',1PE10.3,', SMOOTHED / UNSMOOTHED'/
     >  '  ',I5,' POINTS RESET TO BASELINE'/
     >  '  ',I5,' POINTS DROPPED AS DATA SPIKES'/
     >  )
      CALL UPAUST(1)
      ZL1(1)=ZDEL(1)
      ZL1(2)=ZDEL(2)
      ZL1(3)=ZDUN
      ZL2(2)=' (FINAL)  '
      CALL UREAD(' USMOO1:  ENTER "Y" TO PLOT DELTA(FINAL):$')
      XMIN=X(1)
      XMAX=X(N)
      YMIN=DEL(1)
      YMAX=DEL(1)
      DO 1190 I=1,N
        YMIN=AMIN1(YMIN,DEL(I))
        YMAX=AMAX1(YMAX,DEL(I))
 1190 CONTINUE
      IF(LYES(0)) CALL GRFAH0(X,DEL,N,ZL2,ZL1,DATID,0,ZL1)
      ZL1(1)=YLAB(1)
      ZL1(2)=YLAB(2)
      ZL1(3)=YUN
      GO TO 10
C--------------
C  TOGGLE ERROR-BAR PLOTTING SWITCH
C
 1200 CONTINUE
      CALL UREAD(
     >'USMOO1:  ENTER "Y" TO PLOT EPSILON AS VERT. ERROR BARS:$$')
      IF(LYES(0)) THEN
        IWEBF=1
        CALL UREAD(
     >'USMOO1:  ENTER "Y" TO PLOT DELTA AS HORIZ. ERROR BARS:$$')
        IF(LYES(0)) THEN
          IWEBFX=1
        ELSE
          IWEBFX=0
        ENDIF
        CALL UREADI(
     >'USMOO1:  ENTER MAXIMUM NUMBER OF ERROR BARS TO PLOT:$$',INWEB)
      ELSE
        IWEBF=0
      ENDIF
C
      GO TO 10
C  RESTORE ORIGINAL SCALE
 1300 CONTINUE
      ZXMIN2=X(1)
      ZXMAX2=X(N)
      ZYMIN2=ZYMIN
      ZYMAX2=ZYMAX
      IF(LXOUT(0)) WRITE(LUNTRM,1301)
 1301 FORMAT(' DONE.')
      GO TO 15
C
C-----------------
C  EXIT
C
 2000 CONTINUE
C
      IF(ILSMOO) GO TO 2100
      DO 2010 I=1,N
        DEL(I)=0.0
        EPS(I)=0.0
        YS(I)=Y(I)
 2010 CONTINUE
C
      ZEND1=0.0
      ZEND2=0.0
C
 2100 CONTINUE
C
      RETURN
