C-----------------------------------------------------------------------
C  DCUTA1 -- AUTOMATIC DEGLITCHING INTERACTIVE CONTROL ROUTINE
C
      SUBROUTINE DCUTA1(X,Y,WK,N,LABY,LABX,LSHOT,IALGOR)
C
      LOGICAL, EXTERNAL :: LCHAR,LXOUT,LYES,LYESC
C
      REAL X(N),Y(N),WK(N)
C
      CHARACTER*30 LABX,LABY
      CHARACTER*(*) LSHOT
C
      REAL XL(5)
C
C  INPUT DATA X(N) (ORDERED) AND Y(N)
C  WORKSPACE WK(N)
C
C  LABELS LABY,LABX,LSHOT
C
C  IALGOR=1:  REPLACE GLITCHES WITH WEIGHTED-REFLECTED INTERPOLANT
C  IALGOR=2:  REPLACE GLITCHES WITH LINEAR SEGMENT
C
C-----------------------------------------------------------------------
      LUNTRM=LNOUT(0)
      ICALC=0
C
      ZXMIN=-1.0E38
      ZXMAX=-ZXMIN
C
      GO TO 10
C
  9   CONTINUE
      CALL UERMSG(' %DCUTA1 -- DEGLITCHED FUNCTION NOT YET COMPUTED',
     >    ' ',0)
      GO TO 11
C
 10   CONTINUE
      CALL NEUPAG
C
 11   CONTINUE
C
      IF(LXOUT(0)) WRITE(LUNTRM,1001) ZXMIN,ZXMAX,IALGOR
 1001 FORMAT(//'  AUTOMATIC DEGLITCHING ROUTINE -- 1D INPUT DATA'/
     >     '  % MAY NOT BE GOOD FOR UNEVENLY SPACED DATA'//
     >     '  USER OPTIONS:'/
     >     '  "D"  DEGLITCH DATA'/
     >     '  "G"  GRAPH UN-DEGLITCHED DATA'/
     >     '  "L"  LIST LOCATION OF GLITCHES FOUND'/
     >     '  "P"  PLOT RESULTS OF DEGLITCHING'/
     >     '  "X"  TO RESTRICT X RANGE OF DEGLITCHING OPERATION'/
     >     '       CURRENT X RANGE:  (',1PE11.4,',',1PE11.4,')'/
     >     '  "S"  SAVE RESULTS AND EXIT'/
     >     '  "Q"  QUIT WITHOUT SAVING RESULTS'//
     >'  "A" TO TOGGLE INTERPOLANT CHOICE (CURRENT VALUE=',I1,'):'/
     >'    INTERPOLANT 1:  WEIGHTED REFLECTION OF NEIGHBOURING POINTS'/
     >'    INTERPOLANT 2:  LINEAR SEGMENT CONNECTING THE END POINTS'/)
C
      CALL UREAD(' DCUTA1: ENTER OPTION CODE:$$')
C
      IF(LCHAR('A')) THEN
        IALGOR=3-IALGOR
        GO TO 10
      ENDIF
C
      IF(LCHAR('Q')) THEN
        CALL DCUTCP(Y,WK,N)
        RETURN
      ENDIF
C
      IF(LCHAR('X')) THEN
        ZZXMIN=ZXMIN
        ZZXMAX=ZXMAX
        CALL UREADF('DCUTA1:  ENTER NEW XMIN FOR DEGLITCHING:$$',
     >	    ZZXMIN)
        CALL UREADF('DCUTA1:  ENTER NEW XMAX FOR DEGLITCHING:$$',
     >	    ZZXMAX)
        ZXMIN=AMIN1(ZZXMIN,ZZXMAX)
        ZXMAX=AMAX1(ZZXMIN,ZZXMAX)
        GO TO 10
      ENDIF
C
      IF(LCHAR('S')) THEN
        IF(ICALC.EQ.0) GO TO 9
        CALL DCUTCP(WK,Y,N)
        ISAVED=1
        RETURN
      ENDIF
C
      IF(LCHAR('G')) THEN
        CALL GRFAH0(X,Y,N,LABX,LABY,LSHOT,0,LABX)
        GO TO 10
      ENDIF
C
      IF(LCHAR('P')) THEN
        IF(ICALC.EQ.0) GO TO 9
        CALL GRAFX2(X,WK,Y,N,LABX(21:30),LABY(21:30),
     >      LSHOT,'SOLID CURVE:  DEGLITCHED',
     >      LABY(1:20)//' VS '//LABX(1:20))
        GO TO 10
      ENDIF
C
      IF(LCHAR('D')) THEN
 20     CONTINUE
C
C  GET MAX GLITCH WIDTH
C
        IMIN=1
        IMAX=MIN(20,(N/5))
        IF(LXOUT(0)) WRITE(LUNTRM,1002) LABX,N,X(1),X(N),IMIN,IMAX
 1002   FORMAT(/' %DCUTA1 -- X AXIS HAS LABEL:  ',A/
     >' NX=',I5,' XMIN=',1PE11.4,' XMAX=',1PE11.4//
     >' SPECIFY THE MAXIMUM WIDTH OF A GLITCH IN NO. OF X PTS'/
     >' I.E. "3" IF A GLITCH TO BE REMOVED MAY SPAN 3 CONSECUTIVE'/
     >' X DATA POINTS.  ENTER "Q" TO QUIT, OR AN INTEGER BETWEEN'/
     >1X,I1,' AND ',I5,' = MAXIMUM ALLOWED GLITCH WIDTH ...'/)
        CALL UREAD('DCUTA1:  SPECIFY MAX GLITCH WIDTH:$$')
        IF(LCHAR('Q')) GO TO 10
        IANS=IDCOD(IERT)
        IF(IERT.NE.0) GO TO 20
C
C  new dmc -- user requested on the fly correction
        IF(IANS.GT.IMAX) THEN
           WRITE(LUNTRM,2001) IANS,IMAX
 2001      FORMAT(
     >' %DCUTA1:  GLITCH WIDTH ',I5,' REDUCED TO MAX ALLOWED:  ',I5)
           IANS=IMAX
        ENDIF
C
        IF((IANS.LT.IMIN).OR.(IANS.GT.IMAX)) THEN
          CALL UERMSI(' ?DCUTA1:  SPECIFICATION OUT OF RANGE',IANS,0)
          GO TO 20
        ENDIF
C
        IWIDTH=IANS
C
C  GET GLITCH HEIGHT
C
 30     CONTINUE
        IF(LXOUT(0)) WRITE(LUNTRM,1003) LABY
 1003   FORMAT(/' %DCUTA1 -- ENTER SIZE OF GLITCH(ES) TO REMOVE'/
     >' IN UNITS OF THE Y AXIS:  ',A/
     >' TO REMOVE UPWARD SPIKES ENTER A POSITIVE NUMBER; TO REMOVE'/
     >' DOWNWARD SPIKES ENTER A NEGATIVE NUMBER.  SPIKES OF THE'/
     >' SPECIFIED SIZE (OR GREATER) WILL BE REMOVED.  ENTER "Q"'/
     >' TO QUIT, OR A NON-ZERO GLITCH SIZE FLOATING POINT NUMBER ...'/)
        CALL UREAD('DCUTA1:  SPECIFY (SIGNED) GLITCH SIZE:$$')
        IF(LCHAR('Q')) GO TO 10
        ZANS=FDCOD(IERT)
        IF(IERT.NE.0) GO TO 30
        IF(ZANS.EQ.0.0) THEN
          CALL UERMSG(' ?DCUTA1:  NON-ZERO SIZE MUST BE GIVEN',' ',0)
          GO TO 30
        ENDIF
C
        ZGSIZE=ZANS
C
        CALL DCUTS1(X,Y,WK,N,ZXMIN,ZXMAX,IALGOR,IWIDTH,ZGSIZE,IFOUND)
C
        IF(IFOUND.EQ.0) THEN
          WRITE(LUNTRM,'('' %NO GLITCHES FOUND'')')
        ELSE
          ISAVED=0
          ICALC=IFOUND
          WRITE(LUNTRM,'(1X,I5,'' GLITCH(ES) FOUND'')') IFOUND
        ENDIF
C
        GO TO 10
C
      ENDIF
C
      IF(LCHAR('L')) THEN
        IF(ICALC.EQ.0) GO TO 9
        IF(ISAVED.EQ.1) THEN
          CALL UERMSG(' %DCUTA1 -- DEGLITCHED FUNCTION ALREADY SAVED',
     >	    ' ',0)
          GO TO 10
        ENDIF
        WRITE(LUNTRM,1005) ICALC,LABX
 1005   FORMAT(/
     >1X,I5,' GLITCHES WERE FOUND AT THE FOLLOWING X LOCATIONS'/
     >' (WHERE X IS ',A,'):')
        IPREV=0
        IL=0
        DO 50 IX=1,N
          IF(Y(IX).NE.WK(IX)) THEN
            IF(IX.GT.(IPREV+1)) THEN
              IPREV=IX
      	IL=IL+1
      	IF(IL.GT.5) THEN
      	  WRITE(LUNTRM,'(5(1X,1PE11.4))') (XL(II),II=1,5)
      	  IL=1
      	ENDIF
      	XL(IL)=X(IX)
            ENDIF
          ENDIF
 50     CONTINUE
        IF(IL.GT.0) WRITE(LUNTRM,'(5(1X,1PE11.4))') (XL(II),II=1,IL)
C
        CALL UPAUST(0)
        GO TO 10
C
      ENDIF
C
      END
