C******************** START FILE DCUTUP.FOR ; GROUP DCUTP2 ******************
C============================================================
C  DCUTUP      D. MC CUNE  20 MAY 1980
C
C  INTERACTIVE 'CUT AND PASTE' ROUTINE TO ALLOW REMOVAL OF
C  UNWANTED FEATURES FROM DATA.  USER SPECIFIES A RANGE
C  OF DATA TO BE REPLACED BY CUBIC WHICH IS CONTINUOUS
C  AND MATCHES DATA FIRST DERIVATIVE AT END POINTS OF REPLACEMENT
C  INTERVAL
C
C  GRAPHICS PROVIDED:   GRFWCT.FOR[53,545]
C
C  ARGUMENTS:  X(N)   MONOTONIC INCREASING INDEP. VAR.
C              Y(N)   DEPENDANT VARIABLE.  REPLACED BY CUT-UP
C                     VERSION ON EXIT
C              Y0(N)  STORAGE/ WORKSPACE
C              LABY   30 CHARACTER LABEL FOR Y
C              LABX   30 CHARACTER LABEL FOR X
C              LSHOT  10 CHARACTER SHOT ID
C
C-------------
C
      SUBROUTINE DCUTUP(X,Y,Y0,N,LABY,LABX,LSHOT)
C
      DIMENSION X(N),Y(N),Y0(N)
      CHARACTER*10 LABY(3),LABX(3)
        character*(*)LSHOT                     ! tbt 2/15/91
C
C  LOCAL--
      DIMENSION XCUT(2),YCUT(2),XBOX(5),YBOX(5)
      INTEGER JCUT(2)
      DIMENSION YD1(2),YD0(2)
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR,lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      ISAVE=1
C
      luntrm=lnout(0)
C
C  USER OPTION
C
 10   CONTINUE
      CALL NEUPAG
 12   CONTINUE
      IF(LXOUT(0)) WRITE(LUNTRM,1001)
 1001 FORMAT(//' DCUTUP%: "CUT AND PASTE" ROUTINE'/
     >     '  REPLACE UNWANTED FEATURES WITH CUBIC INTERPOLANT'/
     >     '  VERSION 2.0:  IF CUT RANGE INCLUDES DATA ENDPOINT,'/
     >     '  USER MAY SPECIFY ENDPOINT VALUE AND SLOPE'/
     >     '  USER OPTIONS:'/
     >     '  (1)  CUT,PASTE, AND DISPLAY RESULTS'/
     >     '  (2)  SAVE RESULTS'/
     >     '  (3)  QUIT'/
     >     '  (4)  GRAPH DATA AS CURRENTLY SAVED'/)
 17   CALL UREAD(' DCUTP2: ENTER OPTION #:$')
      IF(LCHAR('Q')) RETURN
      NOPT=IDCOD(IERT)
      IF((IERT.NE.0).OR.(NOPT.LT.1).OR.(NOPT.GT.4)) THEN
        CALL UERMSG('% ILLEGAL INTEGER OPCODE',' ',0)
        GO TO 12
      ENDIF
      IF(NOPT.EQ.3) RETURN
      IF(NOPT.EQ.1) GO TO 100
      IF(NOPT.EQ.4) GO TO 400
C
C IF ISAVE=1, Y0=Y AND RESULTS ALREADY SAVED.
      IF(LXOUT(0).AND.(ISAVE.EQ.1)) WRITE(LUNTRM,1004)
 1004 FORMAT(' % NO CHANGES'/)
      IF(ISAVE.EQ.1) GO TO 12
      ISAVE=1
      DO 20 I=1,N
      Y(I)=Y0(I)
 20   CONTINUE
      GO TO 10
C
C
C  CUT AND PASTE
C
 100  CONTINUE
      ISAVE=0
      DO 110 I=1,N
      Y0(I)=Y(I)
 110  CONTINUE
C
      IF(LXOUT(0)) WRITE(LUNTRM,1011) LABX(1), X(1), X(N), LABX(3)
 1011 FORMAT(//' DCUTUP%: RANGE OF X (',A, ') IS ',
     1         1PE12.4, ',', 1PE12.4, 1X, A)
 
 1101 CALL UREAD('DCUTP2:  ENTER LOCATION OF FIRST CUT (X-UNITS):$')
      XCUT(1)=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
      IF(IERT.NE.0) GO TO 1101
 1102 FORMAT(G10.0)
 1103 CALL UREAD('DCUTP2:  ENTER LOCATION OF SECOND CUT (X-UNITS):$')
      XCUT(2)=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
      IF(IERT.NE.0) GO TO 1103
      IF(XCUT(2).GE.XCUT(1)) GO TO 120
      ZTEMP=XCUT(1)
      XCUT(1)=XCUT(2)
      XCUT(2)=ZTEMP
C
 120  CONTINUE
C  FIND INDEX LOCATIONS; CALCULATE AND SAVE BDY CONDS
C  ON INTERPOLANT CUBIC
      NM1=N-1
      JCUT(1)=N
      DO 130 J=1,NM1
      JP1=J+1
      IF((X(J).LE.XCUT(1)).AND.(X(JP1).GT.XCUT(1))) JCUT(1)=J
 130  CONTINUE
      IF(XCUT(1).LE.X(1)) JCUT(1)=1
      JCUT(2)=1
      DO 140 J=N,2,-1
      JM1=J-1
      IF((X(J).GE.XCUT(2)).AND.(X(JM1).LT.XCUT(2))) JCUT(2)=J
 140  CONTINUE
      IF(XCUT(2).GE.X(N)) JCUT(2)=N
C  # TO REPLACE BY CUBIC:
      NREP=JCUT(2)-JCUT(1)-1
      IF(NREP.GT.0) GO TO 150
C  TOO FEW-- IMPROPER RANGE SPECIFIED
      ISAVE=1
      WRITE(LUNTRM,1190) X(1),X(N)
 1190 FORMAT(/' ? IMPROPER RANGE SPECIFIED'/
     >  '   EITHER THE INTERVAL IS TOO SHORT OR THE INTERVAL'/
     >  '   SPECIFIED DOES NOT INTERSECT THE DOMAIN OF THE DATA:'/
     >  '   X= ',1PE10.3,' TO ',1PE10.3)
      CALL UPAUST(1)
      CALL UCLEAR
      GO TO 12
C
C  CALCULATE  COEFFICIENTS OF CUBIC
C
 150  CONTINUE
C ENDPT LOCNS
      XEL=X(1)
      XER=X(N)
      DELX=X(JCUT(2))-X(JCUT(1))
      YD0(1)=Y(JCUT(1))
      YD0(2)=Y(JCUT(2))
      JCP1=JCUT(1)+1
      YD1(1)=0.0
      IF(XCUT(1).GE.X(1)) THEN
        YD1(1)=(Y(JCP1)-Y(JCUT(1)))/(X(JCP1)-X(JCUT(1)))
         		    ELSE
 151    IF(LXOUT(0)) WRITE(LUNTRM,1501) XEL,X(JCUT(2))
 1501   FORMAT(' SPECIFIED RANGE INCLUDES *LEFT* ENDPOINT'/
     >    ' X1=ENDPT. LOCN=',1PE10.3,'; X2=CUT LOCN=',1PE10.3)
        CALL UREAD(
     >    'DCUTP2: ENTER NEW ENDPT. (BETWEEN X1 AND X2) OR "X":$')
        IF(LCHAR('X')) GO TO 152
      IF(LCHAR('Q')) GOTO 10
        ZX=FDCOD(IERT)
        IF(IERT.NE.0) GO TO 151
        IF((ZX.LT.XEL).OR.(ZX.GT.X(JCUT(2)))) GO TO 151
        XEL=ZX
        DELX=X(JCUT(2))-XEL
 152    CONTINUE
        CALL UREAD(' DCUTP2: SPECIFY NEW DATA VALUE AT ENDPOINT:$')
        YD0(1)=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
        IF(IERT.NE.0) GO TO 151
 153    CALL UREAD(' DCUTP2: SPECIFY SLOPE AT ENDPOINT (DY/DX):$')
        YD1(1)=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
        IF(IERT.NE.0) GO TO 153
        NREP=NREP+1
        JCUT(1)=0
      ENDIF
      JCM1=JCUT(2)-1
      YD1(2)=0.0
      IF(XCUT(2).LE.X(N)) THEN
        YD1(2)=(Y(JCUT(2))-Y(JCM1))/(X(JCUT(2))-X(JCM1))
         		    ELSE
 156    IF(LXOUT(0)) WRITE(LUNTRM,1506) X(JCUT(1)),XER
 1506   FORMAT(' SPECIFIED RANGE INCLUDES *RIGHT* ENDPOINT'/
     >    ' X1=CUT LOCN.=',1PE10.3,'; X2=RIGHT ENDPT LOCN=',1PE10.3)
        CALL UREAD(
     >    'DCUTP2: ENTER NEW ENDPT. (BETWEEN X1 AND X2) OR "X":$')
        IF(LCHAR('X')) GO TO 154
      IF(LCHAR('Q')) GOTO 10
        ZX=FDCOD(IERT)
        IF(IERT.NE.0) GO TO 156
        IF((ZX.GT.XER).OR.(ZX.LT.X(JCUT(1)))) GO TO 156
        XER=ZX
        DELX=XER-X(JCUT(1))
 154    CONTINUE
        CALL UREAD(' DCUTP2: SPECIFY NEW DATA VALUE AT ENDPOINT:$')
        YD0(2)=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
        IF(IERT.NE.0) GO TO 156
 157    CALL UREAD(' DCUTP2: SPECIFY SLOPE AT ENDPOINT (DY/DX):$')
        YD1(2)=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
        IF(IERT.NE.0) GO TO 157
        NREP=NREP+1
        JCUT(2)=N+1
      ENDIF
C
      DELXI=1./DELX
      A3=DELXI*DELXI*(2.0*(YD0(1)-YD0(2))*DELXI+(YD1(1)+YD1(2)))
      A2=DELXI*(3.0*(YD0(2)-YD0(1))*DELXI-(YD1(2)+2.0*YD1(1)))
C  CALCULATE NEW Y  AND SET UP TO DISPLAY
      IPY0=0
      DO 160 I=1,N
      IF(X(I).LT.XEL) Y0(I)=YD0(1)
      IF(X(I).GT.XER) Y0(I)=YD0(2)
      IF((X(I).LT.XEL).OR.(X(I).GT.XER)) GO TO 162
      Y0(I)=Y(I)
      IF(I.LE.JCUT(1)) GO TO 160
      IF(I.GE.JCUT(2)) GO TO 160
      ZX=X(I)-AMAX1(XEL,(X(MAX0(1,JCUT(1)))))
      Y0(I)=((A3*ZX+A2)*ZX+YD1(1))*ZX+YD0(1)
 162  CONTINUE
      IF(IPY0.EQ.0) YCUT(1)=Y(I)
      IF(IPY0.EQ.0) YCUT(2)=Y(I)
      IPY0=1
      YCUT(1)=AMIN1(YCUT(1),Y(I),Y0(I))
      YCUT(2)=AMAX1(YCUT(2),Y(I),Y0(I))
      IF(IGRAF.EQ.0) YMAX=AMAX1(YMAX,Y0(I))
      IF(IGRAF.EQ.0) YMIN=AMIN1(YMIN,Y0(I))
 160  CONTINUE
C  SET UP "BOX" AROUND CUT SECTION FOR DISPLAY
      XBOX(1)=AMAX1(XCUT(1),X(1))
      XBOX(2)=AMIN1(XCUT(2),X(N))
      XBOX(3)=AMIN1(XCUT(2),X(N))
      XBOX(4)=AMAX1(XCUT(1),X(1))
      XBOX(5)=AMAX1(XCUT(1),X(1))
      YBOX(1)=YCUT(1)
      YBOX(2)=YCUT(1)
      YBOX(3)=YCUT(2)
      YBOX(4)=YCUT(2)
      YBOX(5)=YCUT(1)
C
C  DISPLAY RESULTS
C
      JCUT(1)=MAX0(1,JCUT(1))
      JCUT(2)=MIN0(N,JCUT(2))
      CALL GRFWCT(X,Y,Y0,N,LABX,LABY,LSHOT,
     >        'DCUTUP - REPLACE SEGMENT WITH CUBIC INTERPOLANT',
     >        JCUT,XBOX,YBOX)
      IGRAF=1
      GO TO 10
C
 400  CONTINUE
C  GRAPH DATA AS CURRENTLY SAVED
      CALL GRFAH0(X,Y,N,LABX,LABY,LSHOT//' SAVED DATA (DCUTUP)',
     >              0,LABX)
      GO TO 10
C
      	END
C******************** END FILE DCUTUP.FOR ; GROUP DCUTP2 ******************
