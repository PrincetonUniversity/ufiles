C-----------------------------------------------------------------------
C  DCUTS1 -- SUBROUTINE TO DEGLITCH 1D DATA AUTOMATICALLY
C
      SUBROUTINE DCUTS1(X,Y,WK,N,ZXMIN,ZXMAX,
     >    IALGOR,IWIDTH,ZGSIZE,IFOUND)
C
C  INPUT X(N),Y(N)  -- FUNCTION TO BE DEGLITCHED
C   OUTPUT WK(N) -- DEGLITCHED VERSION OF THE NUMERIC DATA FUNCTION
C
C  INPUT ZXMIN,ZXMAX -- CONSTRAINTS ON X RANGE IN WHICH GLITCHES MAY
C    BE FOUND.
C
C  INPUT IALGOR -- METHOD OF GLITCH REPLACEMENT
C          =1:  WEIGHTED REFLECTION INTERPOLANT
C          =2:  LINEAR INTERPOLANT SEGMENT
C
C  INPUT IWIDTH -- MAX WIDTH OF GLITCH QUALIFYING FOR REMOVAL
C  INPUT ZGSIZE -- MINIMUM GLITCH SIZE.  IF ZGSIZE.LT.0.0,
C    DOWNWARD GLITCHES ARE TO BE REMOVED; IF ZGSIZE.GT.0.0, UPWARD
C    GLITCHES ARE TO BE REMOVED.
C
C  OUTPUT IFOUND -- NUMBER OF GLITCHES REMOVED.
C
      REAL X(N),Y(N),WK(N)
C
      REAL XCUT(2),YCUT(2)
      INTEGER JCUT(2)
C
      INTEGER INDICES(2,2)
C
C----------------------------------------------------
C
      IFOUND=0
C
C  PASS 1 -- IDENTIFY "GLITCHES" -- POINTS WHICH EXCEED THE LINEAR
C  INTERPOLANT BTW NEIGHBOURING POINTS BY MORE THAN THE INDICATED
C  AMOUNT
C
C  ENDPOINTS CANNOT BE GLITCH POINTS.
C
      DO 10 I=1,N
        WK(I)=0.0
 10   CONTINUE
C
      ILEFT=0
 20   CONTINUE
        ILEFT=ILEFT+1
        IRIGHT=ILEFT+IWIDTH+1
        IF(IRIGHT.GT.N) GO TO 50
C
        IF(X(ILEFT+1).LT.ZXMIN) GO TO 20
        IF(X(IRIGHT-1).GT.ZXMAX) GO TO 20
C
        DO 30 I=ILEFT+1,IRIGHT-1
          ZYI=Y(ILEFT)+(Y(IRIGHT)-Y(ILEFT))*
     >        (X(I)-X(ILEFT))/(X(IRIGHT)-X(ILEFT))
          ZFAC=(Y(I)-ZYI)/ZGSIZE
          WK(I)=AMAX1(ZFAC,WK(I))
 30     CONTINUE
C
        GO TO 20
C
 50   CONTINUE
C
C----------------------------------------------------
C  PASS 2 -- EXPAND GLITCH REGIONS TO ENCOMPASS NEARBY POINTS THAT ARE
C  "FRACTIONAL GLITCHES" BY AN APPRECIABLE FRACTION (.GT. 10%).
C  SUCH POINTS OR GROUPS OF POINTS MUST BE CONTIGUOUS TO A GLITCH POINT
C  OR GROUP OF POINTS.
C
      ZFMIN=0.1   ! 10% FRACTION
C
      IPREV=1
      ICUR=1
 60   CONTINUE
        ICUR=ICUR+1
        IF(ICUR.GE.N) GO TO 100
        IF(WK(ICUR).LT.1.0) GO TO 60
C
C  FOUND ONE.
C
C  EXPAND LEFT.
C
        ILEFT=ICUR-1
 65     CONTINUE
        IF(WK(ILEFT).GT.ZFMIN) THEN
          WK(ILEFT)=AMAX1(1.0,WK(ILEFT))
          ILEFT=ILEFT-1
          IF(ILEFT.GT.IPREV) GO TO 65
        ENDIF
C
C  EXPAND RIGHT.
C
        IRIGHT=ICUR+1
 68     CONTINUE
        IF(WK(IRIGHT).GT.ZFMIN) THEN
          WK(IRIGHT)=AMAX1(1.0,WK(IRIGHT))
          IRIGHT=IRIGHT+1
          GO TO 68
        ENDIF
C
        IPREV=IRIGHT
        ICUR=IRIGHT
C
        GO TO 60
C
 100  CONTINUE
C
C--------------------------------------------------------
C  PASS 3 -- COALESCE NEARBY GLITCH REGIONS -- DISQUALIFY REGION IF
C  IT GROWS BEYOND THE LIMIT IWIDTH
C
      ILEVEL=0
      ICUR=0
C
 110  CONTINUE
        ICUR=ICUR+1
        IF(ICUR.GT.N) GO TO 200
        IF(WK(ICUR).LT.1.0) GO TO 110
C
C  GOT ONE.
C
        ILEFT=ICUR
        IRIGHT=ICUR
 115    CONTINUE
        IF(WK(IRIGHT+1).GE.1.0) THEN
          IRIGHT=IRIGHT+1
          GO TO 115
        ENDIF
C
        ICUR=IRIGHT+1  !SAVED TO RESUME SEARCH LATER ...
C
        ILEVEL=ILEVEL+1
        INDICES(1,ILEVEL)=ILEFT
        INDICES(2,ILEVEL)=IRIGHT
C
        IF(ILEVEL.EQ.2) THEN
C
C  IF THE TWO GLITCH REGIONS ARE CLOSE TOGETHER, JOIN THEM AS ONE
C
          IMAXW=MAX( (INDICES(2,1)-INDICES(1,1)),
     >		       (INDICES(2,2)-INDICES(1,2)) )  + 1
          IGAP=(INDICES(1,2)-INDICES(2,1))  - 1
C
          IF(IGAP.LT.IMAXW) THEN
C  JOIN THE REGIONS -- FILL THE GAP
            DO 120 I=INDICES(2,1)+1,INDICES(1,2)-1
              WK(I)=AMAX1(1.0,WK(I))
 120        CONTINUE
            INDICES(2,1)=INDICES(2,2)
          ELSE
C
C  REGIONS ARE SEPARATE ENOUGH TO CONSIDER DISTINCT.  CHECK THE FIRST
C  REGION:  IS IT TOO BIG?
C
            IWID1=(INDICES(2,1)-INDICES(1,1)) + 1
            IF(IWID1.GT.IWIDTH) THEN
      	WRITE(LNOUT(0),1001) X(INDICES(1,1)),X(INDICES(2,1))
 1001 FORMAT(' %DCUTS1 -- INSUFFICIENT GLITCH SEPARATION, AUTOMATIC'/
     >'  GLITCH REMOVAL NOT POSSIBLE, X=(',1PE11.4,',',1PE11.4,')')
      	DO 130 I=INDICES(1,1),INDICES(2,1)
      	  WK(I)=0.0
 130  	CONTINUE
            ELSE
              INDICES(1,1)=INDICES(1,2)
              INDICES(2,1)=INDICES(2,2)
            ENDIF
          ENDIF
          ILEVEL=1
        ENDIF
C
        GO TO 110
C
 200  CONTINUE
C
C  DEAL WITH ANY REMAINING REGION
C
      IF(ILEVEL.EQ.1) THEN
        IWID1=(INDICES(2,1)-INDICES(1,1)) + 1
        IF(IWID1.GT.IWIDTH) THEN
          WRITE(LNOUT(0),1001) X(INDICES(1,1)),X(INDICES(2,1))
          DO 205 I=INDICES(1,1),INDICES(2,1)
            WK(I)=0.0
 205      CONTINUE
        ENDIF
      ENDIF
C
C------------------------------------------------------------------
C  PASS 4 -- EXECUTE THE DEGLITCHING
C
      IPREV=1
      ILEVEL=0
      ICUR=0
C
 210  CONTINUE
        ICUR=ICUR+1
        IF(ICUR.GT.N) GO TO 300
        IF(WK(ICUR).LT.1.0) GO TO 210
C
C  GOT ONE.
C
        ILEFT=ICUR
        IRIGHT=ICUR
 215    CONTINUE
        IF(WK(IRIGHT+1).GE.1.0) THEN
          IRIGHT=IRIGHT+1
          GO TO 215
        ENDIF
C
        ICUR=IRIGHT+1  !SAVED TO RESUME SEARCH LATER ...
C
        ILEVEL=ILEVEL+1
        INDICES(1,ILEVEL)=ILEFT
        INDICES(2,ILEVEL)=IRIGHT
C
        IF(ILEVEL.EQ.2) THEN
C  EXECUTE THE CUT
          ILIM=INDICES(1,2)-1
          INUM=ILIM-IPREV+1
          CALL DCUTCP(Y(IPREV),WK(IPREV),INUM)
          JCUT(1)=INDICES(1,1)-IPREV+1
          JCUT(2)=INDICES(2,1)-IPREV+1
          CALL DCUTF1(X(IPREV),Y(IPREV),WK(IPREV),INUM,
     >	      IALGOR,1,JCUT,XCUT,YCUT)
          IFOUND=IFOUND+1
C
C SET UP TO GO ON TO NEXT ONE.
C
          IPREV=INDICES(2,1)+1
          INDICES(1,1)=INDICES(1,2)
          INDICES(2,1)=INDICES(2,2)
          ILEVEL=1
        ENDIF
C
        GO TO 210
C
 300  CONTINUE
C
C  EXECUTE THE CUT ON ANY REMAINING SECTION
C
      IF(ILEVEL.EQ.1) THEN
        ILIM=N
        INUM=ILIM-IPREV+1
        CALL DCUTCP(Y(IPREV),WK(IPREV),INUM)
        JCUT(1)=INDICES(1,1)-IPREV+1
        JCUT(2)=INDICES(2,1)-IPREV+1
        CALL DCUTF1(X(IPREV),Y(IPREV),WK(IPREV),INUM,
     >	    IALGOR,1,JCUT,XCUT,YCUT)
        IFOUND=IFOUND+1
      ENDIF
C
      RETURN
      END
