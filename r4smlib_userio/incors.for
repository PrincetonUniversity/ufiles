C----------------------------------------------------------------
C  INCORS - SAWTOOTH INTERVAL SEARCHER
C   GIVEN INITIAL ESTIMATE OF SAWTOOTH LOCATION, IMPROVE GUESS
C   CRITERION:  MAX SUM**2 ACCROSS INTERVAL
C
C   SUBROUTINE OF USMOOj SMOOTHING INTERFACE ROUTINES
C
      SUBROUTINE INCORS(DATA,ISIZE,ISTART,INUM,NGRP,NROW,NINCR,NINCP,
     >	  ISCAN)
C
      REAL DATA(ISIZE)  ! INPUT DATA CONTAINING SAWTEETH
      INTEGER ISTART(NGRP),INUM(NGRP) ! INTERVAL ADDRESSES, AS OUTPUT
C                                       ! BY SUBROUTINE INCORL
      INTEGER NROW ! NUMBER OF "ROWS" OF DATA
      INTEGER NINCR ! INDEX INCREMENTS BTW. ROWS
      INTEGER NINCP ! INDEX INCREMENT BTW. ROW PTS
      INTEGER ISCAN ! NUMBER OF INTERVALS TO SCAN EACH WAY
C
      IF(NGRP.LE.1) RETURN
C
      IF(ISCAN.LE.0) RETURN
C
      ISC1=-ISCAN
      ISC2=ISCAN
C
      DO IGRP=2,NGRP
        IGRM1=IGRP-1
C
        ISCMAX=0
        ZDFMAX=-1.0
        IA0=ISTART(IGRP)-1
        IB0=IA0+1
C
        DO ISC=ISC1,ISC2
C  DMC JUN 1992 -- DO NOT PERMIT CREATION OF 0 WIDTH GROUPS!
          ITEST=MIN((INUM(IGRM1)+ISC),(INUM(IGRP)-ISC))
          IF(ITEST.GT.0) THEN
            IA=1+(IA0+ISC-1)*NINCP
            IB=1+(IB0+ISC-1)*NINCP
            IF((IA.GT.0).AND.((IB+(NROW-1)*NINCR).LT.ISIZE)) THEN
      	ZDFSUM=0.0
C
      	DO IROW=1,NROW
      	  IADRA=IA+(IROW-1)*NINCR
      	  IADRB=IB+(IROW-1)*NINCR
      	  ZDFSUM=ZDFSUM+(DATA(IADRA)-DATA(IADRB))**2
      	ENDDO
C
      	IF(ZDFSUM.GT.ZDFMAX) THEN
      	  ISCMAX=ISC
      	  ZDFMAX=ZDFSUM
      	ENDIF
            ENDIF  ! ADDRESS BOUNDS
          ENDIF  ! ITEST
C
        ENDDO  ! ISC LOOP
C
        IF(ISCMAX.NE.0) THEN
          INUM(IGRM1)=INUM(IGRM1)+ISCMAX
          ISTART(IGRP)=ISTART(IGRP)+ISCMAX
          INUM(IGRP)=INUM(IGRP)-ISCMAX
        ENDIF
C
      ENDDO  ! IGRP LOOP
C
      RETURN
      END
