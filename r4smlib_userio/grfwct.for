C******************** START FILE GRFWCT.FOR ; GROUP GRFWC2 ******************
C----------------------GRFADH-SUBMODULE-----------------------
C
C  GRFADH    ASKS QUESTIONS AND PLOTS 1 OR 2 CURVES
C
C  CREATED 10-AUG-78  D. MCCUNE TO TAKE REPITITIOUS CODE
C                     OUT OF MAIN
C
C  D. MC CUNE 20-MAY-80-- SPECIAL VERSION TO DISPLAY
C    "CUT AND PASTE" SPIKE REMOVAL... DCUTUP.FOR[53,545]
C       DRAWS BOX AROUND CORRECTION
C        ADDL ARGUMENTS IN CALLING SEQUENCE:
C         X3(5),Y3(5):  BOX COORDINATES
C         JCUT:  INDEX LOCATION OF CORRECTION IN X
C
      SUBROUTINE GRFWCT(X,Y,Y2,N,XLAB,
     1                 YLAB,LBL3,LBL4,JCUT,X3,Y3)
C
      use plot1mmx
C
      DIMENSION X(N),Y(N),Y2(N)
      DIMENSION X3(5),Y3(5)
C
      INTEGER JCUT(2)
C
      CHARACTER*30 XLAB,YLAB
C
      CHARACTER*(*) LBL3,LBL4
C
      CALL GRAFWC(X,Y,Y2,N,XLAB(21:30),YLAB(21:30),
     >                LBL3,LBL4,YLAB(1:20)//' VS. '//XLAB(1:20),
     >                JCUT,X3,Y3)
C
      RETURN
      END
