C******************** START FILE USMFA2.FOR ; GROUP USMFA2 ******************
C===========================================================
C  USMFA2
C
C  INTERACTIVE USER INTERFACE FOR SMOOTHING 2-D DATA FCNS
C    EMPLOYS SMOOTHING ALGORITHM "FILFAS"
C    D. MC CUNE MAY 1984-- BASED ON USMOO2 BUT CONSIDERABLY
C    SIMPLIFIED AND EMPLOYING THE "FAST" SMOOTHING ALGORITHM
C
C  PROGRAM PRESENTS OPTIONS TO USER IN "MENU" FORMAT
C
C  ACCESS TO ROUTINES TO GRAPH THE DATA, SMOOTHED AND
C    UNSMOOTHED, IS PROVIDED, SO THAT REFERENCE TO THE
C    DATA ITSELF MAY BE MADE IN THE INTERACTIVE PROCESS
C    OF DEFINING SMOOTHING CONTROLS
C
C  PROGRAM ARCHITECTURE ALLOWS USER TO MAKE AN ATTEMPT AT
C  SMOOTHING THE DATA, DECIDE ITS NO GOOD, AND TRY TO SMOOTH
C  THE DATA AGAIN; I.E. THE ORIGINAL UNSMOOTHED DATA IS NOT
C  DESTROYED IN THE PROCESS
C
C-------------------------
C  SUBROUTINE ARGUMENTS:
C   X(NX),Z(NZ1,NY),Y(NY)    ARRAYS CONTAINING THE ORDINATES AND
C            ABSCISSAE OF THE ORIGINAL (UNSMOOTHED) DATA.
C            GENERALLY THESE ARRAYS ARE NOT MODIFIED BY THIS
C            SUBROUTINE, EXCEPT POSSIBLY BY THE FILTR6
C            SPIKE-DROP FEATURE (SEE FILTR6.FOR)
C            THESE ARE INPUT ARRAYS
C
C   ZS(NZ1,NY)        OUTPUT ARRAY CONTAINING THE SMOOTHED DATA
C            INITIALLY DEFAULTS TO THE UNSMOOTHED DATA IF THE
C            USER DOES NOT DIRECT THE PROGRAM TO CARRY OUT A
C            SMOOTHING OPERATION
C
C   ZWK(NWK,2)   WORKSPACE FOR CARRYING OUT SMOOTHING OPERATION;
C            NWK SHOULD BE AT LEAST AS BIG AS THE MAX OF NX AND
C            NY TO AVOID ARRAY SPACE PROBLEMS.
C            **NOTE 2 ROWS IN THIS ARRAY**
C
C   ISEL     *** SELECT DIMENSION ***  ISEL=1 MEANS SMOOTHING
C            WILL BE CARRIED OUT BY AVERAGING ALONG THE DATA'S
C            FIRST DIMENSION IDEPENDANT VARIABLE; ISEL=2 MEANS
C            THE SMOOTHING WILL BE DONE BY AVERAGING ALONG
C            THE DATA'S SECOND DIMENSION INDEPENDANT VARIABLE.
C            **INPUT PARAMETER**
C
C
C   XLAB     10 CHARACTER LABEL FOR X, E.G. "TIME      "
C   YLAB     10 CHARACTER LABEL FOR Y, E.G. "RADIUS    "
C   ZLAB     20 CHARACTER LABEL FOR Z, E.G. "ELECTRON TEMPERATURE"
C   XUN      10 CHAR UNITS FOR X TERMINATED BY "$", E.G. "SECONDS  $"
C   YUN      10 CHAR UNITS FOR Y TERMINATED BY "$", E.G. "CM       $"
C   ZUN      10 CHAR UNITS FOR Z TERMINATED BY "$", E.G. "EV       $"
C
C   IDEV,NSHOT-- LABELING INFO FOR PLOTTING
C
C   PROGID   10 CHAR ID OF PROGRAM CARRYING OUT SMOOTHING
C            CALCULATION, FOR INFORMATION OF CALLER
C            (OUTPUT)
C
C-------------------------
      SUBROUTINE USMFA2(X,Y,Z,ISEL,NX,NY,NZ1,ZS,
     >     ZWK,NWK,
     >     XLAB,YLAB,ZLAB,XUN,YUN,ZUN,PROGID,
     >     IDEV,NSHOT)
C
C  PASSED ARGS:
      DIMENSION X(NX),Y(NY),Z(NZ1,NY),ZS(NZ1,NY),
     >     ZWK(NWK,2)
      CHARACTER*10 XLAB,YLAB,ZLAB(2),XUN,YUN,ZUN,PROGID
      CHARACTER*4 IDEV
C  LOCAL:
      LOGICAL ILSMOO
      CHARACTER*1 VLAB
C
C  uread fcn:
      logical lxout
C
C  INITIALIZE
C
      PROGID='FILFAS.FOR'
C
      luntrm=lnout(0)
C
      IF(ISEL.LT.1) ISEL=1
      IF(ISEL.GT.2) ISEL=2
      ILSMOO=.FALSE.
      DO 5 I=1,NX
      DO 5 J=1,NY
      ZS(I,J)=Z(I,J)
 5    CONTINUE
C
C
C---
C TOP MENU
C
      IF(ISEL.EQ.1) VLAB='X'
      IF(ISEL.EQ.2) VLAB='Y'
 10   CONTINUE
      CALL NEUPAG
 11   IF(LXOUT(0)) WRITE(LUNTRM,1001) ZLAB(1),ZLAB(2),ZUN,
     >     XLAB,XUN,YLAB,YUN,VLAB
 1001 FORMAT(//'      DATA: Z= ',2A10,' (',A9,')'/
     >           '        VS. X= ',A10,10X,' (',A9,')   AND'/
     >           '            Y= ',A10,10X,' (',A9,')'//
     >  ' >>> CURRENTLY SMOOTHING IN "',A1,'" DIRECTION <<<'//
     >  ' OPTIONS:'/
     >  '  1  GRAPH THE UNSMOOTHED DATA'/
     >  '  2  GRAPH THE SMOOTHED DATA'/
     >  '  R  >>>>> RESTORE UNSMOOTHED DATA'/
     >  '  S  >>>>> SMOOTH THE DATA '/
     >  '  Q  QUIT'/
     >  )
      CALL UREAD(' USMFA2>> ENTER OPTION #:$')
      IANS=IXUOPC('12RSQ$')
      IF(IANS.EQ.0) THEN
        CALL UERMSG('ILLEGAL INTEGER OPCODE',' ',0)
        GO TO 11
      ENDIF
C  BRANCH
      GO TO (100,200,900,1000,2000) IANS
C-------------
C  GRAPH THE DATA
C
 100  CONTINUE
      ISMTYP=0
      CALL GRF3(X,Z,Y,ZWK,NX,NY,NZ1,XLAB,YLAB,ZLAB,
     >         XUN,YUN,ZUN,ZWK,0,0,0,IDEV,NSHOT,0,NSHOT,1,ISMTYP)
      GO TO 10
C--------
C  GRAPH THE SMOOTHED DATA
C
 200  CONTINUE
      ISMTYP=0
      IF(ILSMOO) ISMTYP=1
      CALL GRF3(X,ZS,Y,ZWK,NX,NY,NZ1,XLAB,YLAB,ZLAB,
     >         XUN,YUN,ZUN,ZWK,0,0,0,IDEV,NSHOT,0,NSHOT,1,ISMTYP)
      GO TO 10
C
 900  CONTINUE
C  RESTORE UNSMOOTHED DATA FOR OUTPUT
      DO 910 IY=1,NY
      DO 910 IX=1,NX
        ZS(IX,IY)=Z(IX,IY)
 910  CONTINUE
C
      GO TO 10
C-------------
C  *** SMOOTH THE DATA
C
 1000 CONTINUE
      IF(LXOUT(0)) WRITE(LUNTRM,1005)
 1005 FORMAT(/' THE "FILFAS" FAST SMOOTHING ALGORITHM CALCULATES'/
     >' SMOOTHED DATA POINTS AS A TRIANGULAR WEIGHTED AVERAGE OF +/- N'/
     >' UNSMOOTHED DATA POINTS IN THE VICINITY, ALONG THE DIMENSION OF'/
     >' SMOOTHING.'/)
      NSMOO=0
      CALL UREADI('USMFA2:  ENTER "N" FOR FILFAS 2D FAST SMOOTHING:$',
     >     NSMOO)
      IF(NSMOO.LE.0) GO TO 10
C
C  SET PARAMETERS TO CARRY OUT SUCCESSIVE SMOOTHS ALONG
C  LINES OF CONST X (Y) DEPENDING ON SETTING OF ISEL
C
 1100 CONTINUE
      CALL CPU_TIME(ZTIM1)
C  DEFN # OF LINES ALONG WHICH TO SMOOTH, # OF PTS PER LINE
      GO TO (1102,1103) ISEL
 1102 CONTINUE
      IOPS=NY
      IPTS=NX
      GO TO 1105
 1103 CONTINUE
      IOPS=NX
      IPTS=NY
      GO TO 1105
 1105 CONTINUE
C  LOOP THRU EACH LINE
      DO 1200 I=1,IOPS
C  GET Z ALONG THIS LINE
      DO 1230 J=1,IPTS
      GO TO (1225,1226) ISEL
 1225 CONTINUE
      KI=J
      KJ=I
      GO TO 1228
 1226 CONTINUE
      KI=I
      KJ=J
      GO TO 1228
 1228 CONTINUE
      ZWK(J,1)=Z(KI,KJ)
 1230 CONTINUE
C---
C  SMOOTH THE DATA ALONG LINE
C
      CALL FILFAS(ZWK(1,1),ZWK(1,2),IPTS,NSMOO)
C
C  STORE IN OUTPUT ARRAY
C
      DO 1280 J=1,IPTS
      GO TO (1275,1276) ISEL
 1275 CONTINUE
      KI=J
      KJ=I
      GO TO 1278
 1276 CONTINUE
      KI=I
      KJ=J
      GO TO 1278
 1278 CONTINUE
      ZS(KI,KJ)=ZWK(J,2)
 1280 CONTINUE
C==> END OF LOOP FOR SMOOTHING
 1200 CONTINUE
C
      ILSMOO=.TRUE.
C====
C
C  DISPLAY SUMMARY:
      CALL CPU_TIME(ZTIM2)
      ZCTIM=ZTIM2-ZTIM1
      INPTS=NX*NY
      WRITE(LUNTRM,10001) PROGID,ZCTIM,INPTS
10001 FORMAT(//'  SMOOTHING COMPLETED.  ALGORITHM: "',A10,'"'/
     >  '  CPU TIME = ',1PE10.3,' SECONDS; ',I5,' DATA PTS.'/
     >  )
      CALL UPAUST(1)
      GO TO 10
C
C
C-----------------
C  EXIT
C
 2000 CONTINUE
C
      RETURN
      	END
C******************** END FILE USMFA2.FOR ; GROUP USMFA2 ******************
