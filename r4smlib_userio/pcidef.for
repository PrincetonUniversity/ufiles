C******************** START FILE PCIDEF.FOR ; GROUP PCIDEF ******************
C=============================================================
C
C  PCIDEF
C
C    THIS ROUTINE ALLOWS USER DEFINITION OF A FUNCTION BY
C  ENTRY OF A SUCCESION OF COORDINATE PAIRS (X,Y) WHICH
C  THE ROUTINE KEEPS IN ORDER, AND THEN DEFINES THE FUNCTION
C  BY PIECEWISE LINEAR INTERPOLATION BETWEEN THE POINTS (X,Y)
C  SPECIFIED
C
C     ARGUMENTS:
C
C  MODIF DMC-- IF N=1 ASSUME INTERPOLATED DATA IS NOT OF INTEREST--
C    PLOT THE SEQUENCE OF (X,Y) PAIRS TYPED IN
C
C  X   IN   X VALUES TO INTERPOLATE TO
C  Y   OUT  FCN TO BE DEFINED
C  N   IN   # OF PTS IN X,Y
C
C  XPC USER USER INPUT X VALUES BETWEEN WHICH TO INTERPOLATE
C  YPC USER USER INPUT Y VALUES BETWEEN WHICH TO INTERPOLATE
C  NPC USER CURRENT # OF USER X,Y PAIRS
C  MAX IN   MAX # OF USER PAIRS (DIMENSIONALITY OF XPC,YPC ARRAYS)
C
      SUBROUTINE PCIDEF(X,Y,N,XPC,YPC,NPC,MAX,XLAB,YLAB,XUN,YUN)
C
C  XUN-- 10 CHARACTER UNITS OF X ENDING IN "$"
C  YUN-- 10 CHARACTER UNITS OF Y ENDING IN "$"
C  XLAB- 10 CHARACTER LABEL FOR X ENDING IN "$"
C  YLAB- 20 CHARACTER LABEL FOR Y ENDING IN "$"
C
      use plot1mmx
      CHARACTER*(*) XUN,YUN,XLAB,YLAB
      CHARACTER*10 ZLAB1(3),ZLAB2(3),ZLAB3
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
      DIMENSION X(N),Y(N)
      DIMENSION XPC(MAX),YPC(MAX)
C
C  START OF EXECUTABLE CODE
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR,lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => PCIDEF               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA ZLAB3/'          '/
C => END DATA BLOCK
C ====================
C
      ily=len(ylab)
      ZLAB1(1)=XLAB
      ZLAB2(1)=YLAB(1:min(10,ily))
      ZLAB1(2)=ZLAB3
      ZLAB2(2)=ZLAB3
      if(ily.gt.10) ZLAB2(2)=YLAB(11:min(20,ily))
      ZLAB1(3)=XUN
      ZLAB2(3)=YUN
C
 10   CONTINUE
C  DO INTERPOLATION
      CALL PCTRAN(X,Y,N,XPC,YPC,MAX,NPC)
C  GET USER OPTION
 20   CONTINUE
      CALL NEUPAG
 21   IF(LXOUT(0))
     >  WRITE(LNOUT(0),1003) YLAB,YUN,XLAB,XUN,NPC
 1003 FORMAT(//' ENTER DEFINITION OF Y=',A,' (',A,')'/
     >  ' VS. X=',A,' (',A,') -- PIECEWISE LINEAR INTERPOLATION'//
     >  ' currently ',i2,' (x,y) points in definition'//
     >  ' OPTIONS:'/
     >  ' (1) ADD A POINT TO THE DEFINITION'/
     >  ' (2) REMOVE A POINT'/
     >  ' (3) GRAPH THE CURRENT DEFINITION'/
     >  ' (4) DELETE DEFINITION, START OVER'/
     >  ' (5) EXIT  ***'/
     >  ' (6) MULTIPLY ENTIRE DEFINITION BY A SCALAR QUANTITY'/
     >  )
      CALL UREAD(' SUB:PCIDEF >> ENTER OPTION #:$')
      IF(LCHAR('Q')) GOTO 500
      IANS=IDCOD(IERT)
      IF((IERT.NE.0).OR.(IANS.LE.0).OR.(IANS.GT.6)) THEN
        CALL UERMSG('% INVALID INTEGER OPCODE',' ',-1)
        GO TO 21
      ENDIF
      GO TO (100,200,300,400,500,600) IANS
C
C  ADD A POINT
C
 100  CONTINUE
C
      IF(NPC.LT.MAX) GO TO 110
      WRITE(LNOUT(0),9001) MAX
 9001 FORMAT(' ? TOO MANY POINTS, CANNOT ADD MORE.  MAX=',I5)
      CALL UPAUST(1)
      CALL UCLEAR
      GO TO 20
 110  CONTINUE
C
      CALL UREAD(' SUB:PCIDEF > ENTER NEW X VALUE:$')
      ZX=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
      IF(IERT.NE.0) GO TO 100
 101  CALL UREAD(' SUB:PCIDEF > ENTER NEW Y VALUE:$')
      ZY=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
      IF(IERT.NE.0) GO TO 101
C  INSERT VALUE-- DONT ALLOW DUPLICATION
      I=0
      IF(NPC.LE.0) GO TO 150
      DO 130 I=1,NPC
         IF(XPC(I).EQ.ZX) GO TO 140
         IF(I.EQ.NPC) GO TO 130
         IP1=I+1
         IF((XPC(I).LT.ZX).AND.(XPC(IP1).GT.ZX)) GO TO 150
 130  CONTINUE
      I=0
      IF(ZX.LT.XPC(1)) GO TO 150
      I=NPC
      GO TO 150
C
 140  CONTINUE
C  ERROR: DUPLICATE X
      WRITE(LNOUT(0),9002)
 9002 FORMAT(' ? ERROR: SPECIFIED X VALUE ALREADY IN USE')
      CALL UPAUST(1)
      CALL UCLEAR
      GO TO 20
C
 150  CONTINUE
C  INSERT NEW X,Y
      IPC=NPC+1
      JPC=I+1
      IF(IPC.EQ.JPC) GO TO 160
      DO 155 J=NPC,JPC,-1
         JP1=J+1
         XPC(JP1)=XPC(J)
         YPC(JP1)=YPC(J)
 155  CONTINUE
 160  CONTINUE
      XPC(JPC)=ZX
      YPC(JPC)=ZY
      NPC=IPC
C
      GO TO 10
C
C  DELETE A POINT
C
 200  CONTINUE
      IF(NPC.GT.0) GO TO 210
      WRITE(LNOUT(0),9003)
 9003 FORMAT(' ? NO POINTS LEFT TO DELETE')
      CALL UPAUST(1)
      CALL UCLEAR
      GO TO 20
 210  CONTINUE
C
      CALL UREAD(
     >  ' PCIDEF: ENTER X-VALUE; NEAREST PT WILL BE DELETED:$')
      ZX=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
      IF(IERT.NE.0) GO TO 20
C  FIND NEAREST X
      ZDIST=ABS(ZX-XPC(1))
      IDIST=1
      DO 220 I=1,NPC
         ZD=ABS(ZX-XPC(I))
         IF(ZD.GE.ZDIST) GO TO 220
         ZDIST=ZD
         IDIST=I
 220  CONTINUE
C
      IF(IDIST.EQ.NPC) GO TO 250
      IDP1=IDIST+1
      DO 230 I=IDP1,NPC
         IM1=I-1
         XPC(IM1)=XPC(I)
         YPC(IM1)=YPC(I)
 230  CONTINUE
 250  CONTINUE
      NPC=NPC-1
      GO TO 10
C
 300  CONTINUE
      IF(NPC.GT.0) GO TO 310
      WRITE(LNOUT(0),3001)
 3001 FORMAT(/' ? THE CURRENT DEFINITION CONTAINS NO POINTS'/)
      CALL UPAUST(1)
      CALL UCLEAR
C
 310  CONTINUE
      IF(N.GT.1) THEN
C-------------------------------/INTERPOLATE TO TARGET
      XMIN=X(1)
      XMAX=X(N)
      YMIN=Y(1)
      YMAX=Y(1)
      DO 315 I=1,N
         YMIN=AMIN1(YMIN,Y(I))
         YMAX=AMAX1(YMAX,Y(I))
 315  CONTINUE
      IF(YMAX.GT.YMIN) GO TO 317
      ELSE IF(NPC.GT.1) THEN
C-------------------------------/JUST PLOT THE TYPED IN SEQUENCE
      XMIN=XPC(1)
      XMAX=XPC(N)
      YMIN=YPC(1)
      YMAX=YPC(1)
      DO 316 I=1,NPC
         YMIN=AMIN1(YMIN,YPC(I))
         YMAX=AMAX1(YMAX,YPC(I))
 316  CONTINUE
      ELSE
C-------------------------------/N=1 AND TOO FEW PTS TO PLOT
      CALL UERMSI('?TOO FEW PTS TO PLOT:',NPC,2)
      GO TO 10
      ENDIF
C
      YMAX=YMAX*1.01
      YMIN=YMIN*0.99
 317  CONTINUE
C
      IF(N.GT.1) THEN
        CALL GRFAH0(X,Y,N,ZLAB1,ZLAB2,
     >     ' PIECEWISE LINEAR SPECIFICATION',0,ZLAB1)
      ELSE IF(NPC.GT.1) THEN
        CALL GRFAH0(XPC,YPC,NPC,ZLAB1,ZLAB2,
     >     ' PIECEWISE LINEAR SPECIFICATION',0,ZLAB1)
      ENDIF
      GO TO 10
C
C  START OVER
C
 400  CONTINUE
      NPC=0
      DO 410 I=1,MAX
         XPC(I)=0.0
         YPC(I)=0.0
 410  CONTINUE
      GO TO 10
C
C  EXIT
C
 500  CONTINUE
      RETURN
C  MULTIPLY DEFN. BY SCALAR
 600  CONTINUE
      CALL UREAD(' SUB:PCIDEF >> ENTER NON-ZERO SCALAR (E10.0):$')
      ZFAC=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
      IF(IERT.NE.0) GO TO 600
      IF(ZFAC.EQ.0.0) GO TO 600
      IF(NPC.LE.0) GO TO 10
      DO 610 I=1,NPC
         YPC(I)=ZFAC*YPC(I)
 610  CONTINUE
      GO TO 10
      	END
C******************** END FILE PCIDEF.FOR ; GROUP PCIDEF ******************
