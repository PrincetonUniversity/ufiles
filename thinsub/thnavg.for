C******************** START FILE THNAVG.FOR ; GROUP THNAVG ******************
C---------------------------------------------------------------
C  THNAVG   FILFAS D. Mc Cune  pppl 4 dec 1981
C  A FAST MOVING "SQUARE" (UN)WEIGHTED AVERAGE SMOOTHING ROUTINE
C  DMC OCT 1986 - SIMPLIFICATION OF FILFAS FOR USE WITH THINNING
C  UTILITY-- JUST AVG ADJACENT PTS WITH EQUAL WEIGHT
C
        SUBROUTINE THNAVG(F,FSM,N,NWA)
C
        DIMENSION F(N),FSM(N)
C
C  INPUT:
C   F(N) DATA TO BE SMOOTHED
C   NWA-- NUMBER OF POINTS ON EITHER SIDE OF F(J) TO AVERAGE
C         WITH TRIANGULAR WEIGHTING TO COMPUTE FSM(J)
C
C  OUTPUT:
C   FSM(N): SMOOTHED DATA
C
C
C  ALGORITHM:
C  FSM(J) IS A WEIGHTED AVERAGE OF F(J-NWA),F(J-NWA+1),...,
C                                  F(J),...,F(J+NWA-1),F(J+NWA)
C  THE WEIGHTING FACTOR W(K) IS **CONSTANT** FOR ALL F(K)
C   NOTE THAT SUM[K= -NWA TO +NWA]W(K) = 1.0 EXACTLY
C
C  END CONDITIONS:  IF THE INDEX (J+K) IS .LT. 1 IT IS
C   REPLACED BY 1-(J+K); IF (J+K) .GT. N IT IS REPLACED BY 2*N-(J+K)
C
C   THIS "REFLECTION ALGORITHM" TENDS TO MINIMIZE THE "SLOPE" OF THE
C   DATA AT THE END PTS
C
C  EXECUTABLE CODE
C
        IF(NWA.LE.0) GO TO 200
C
      ZWGHT=1.0/FLOAT(2*NWA+1)
C
C  START LOOP OVER DATA POINTS
        DO 100 J=1,N
C  INITIATE SUM FOR POINT J
      	  SUM=F(J)*ZWGHT
C  LOOP OVER POINTS TO AVERAGE
      	  DO 90 K=1,NWA
      	    IPT1=J-K
          IF(IPT1.LT.1) IPT1=1-IPT1
      	    IPT2=J+K
          IF(IPT2.GT.N) IPT2=1+2*N-IPT2
      	    SUM=SUM+ZWGHT*(F(IPT1)+F(IPT2))
 90   	  CONTINUE
      	  FSM(J)=SUM
 100    CONTINUE
        RETURN
C------------------------------------
C  NWA < 0: JUST COPY DATA
 200    CONTINUE
        DO 210 J=1,N
          FSM(J)=F(J)
 210    CONTINUE
        RETURN
        END
C******************** END FILE THNAVG.FOR ; GROUP FILFAS ******************
