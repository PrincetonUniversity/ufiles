C******************** START FILE THINSET.FOR ; GROUP THNVRG ******************
C
C  REWORKED DMC OCT 1986 - SUPPORT 2D INPUT ARRAYS
C
C------------------------------------------------------
C=================================
      SUBROUTINE THINSET(ISHOT,
     >	  X,XT,NX,Y,YT,NY,F,FT,NF1,WK,NWK,NXT,NYT,ICOD)
C==================================
C
C=================================
C-----WRITTEN BY A. ERLICH 4-4-85
C=================================
C
C=================================
C     COMMENTS: THINSET: THIS ROUTINE GATHERS
C     USER SUPPLIED PARAMETERS FOR THE THIN &
C     AVG. PROCEDURE. I.E. # OF REGIONS, THEN
C     LOWER BNDRY.,UPPER BNDRY.,THINNING FACTOR,
C     SPECIFIC OPERATION(THIN,AVG_THIN),FOR EACH
C     REGION; THINSET THEN CALLS THE APPORIATE
C     SUBROUTINE.
C=================================
C=================================
C-----IDENTIFICATION SECTION
C=================================
C
      PARAMETER (IDIM=3)
      INTEGER BND
      PARAMETER (BND=100)
C
      INTEGER INIT(IDIM)
      CHARACTER*1 AVG(BND,IDIM)
      INTEGER IOPT(BND,IDIM)
      INTEGER INPTS(BND,IDIM),IS3(BND),IC3(BND)
        REAL RBND(BND,IDIM)
      INTEGER INZONS(IDIM)
      REAL LBNDA(BND),UBNDA(BND)
C
      COMMON/THINSAVE/ INSHOT,INIT,AVG,IOPT,INPTS,RBND,INZONS
C
C
C  PASSED DATA ...
C
C   ISHOT IS THE SHOT NUMBER - CHECK RE. INITIALIZATION OF COMMON
C
C   X,Y,F ARRAYS ARE INDEP. AND DEP. COORDINATES OF INPUT VSN. OF F(X,Y)
C   XT,YT,FT ARRAYS ARE DITTO FOR THE OUTPUT (THINNED) VSN OF F(X,Y)
C
C   WK IS A WORK ARRAY WHOSE SIZE MUST BE .GE. THE LARGER OF X AND Y X 2
C
      REAL X(NX),XT(NX),Y(NY),YT(NY),F(NF1,NY),FT(NF1,NY),WK(NWK,2)
C
C
C  ICOD SELECTS THINNING DIMENSION
C
C  WK ARRAY IS USED TO HOLD THE SELECTED INDEPENDENT COORDINATE
C   *EXCEPT* WHEN ACTUAL THINNING COMPUTATION IS PERFORMED
C
C------------------------------------------
C
      logical ilxout
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
      LOGICAL LXOUT
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      ians=0
C
      IF(ISHOT.NE.INSHOT) THEN
        INSHOT=ISHOT
        DO ID=1,IDIM
          INIT(ID)=0
        ENDDO
      ENDIF
C
      IF(ICOD.EQ.1) THEN
        IWK=NX
        CALL COPYY(X,1.0,WK,NX)
        ICO=NY
        CALL COPYY(Y,1.0,YT,NY)
        NYT=NY
      ELSE IF(ICOD.EQ.2) THEN
        IWK=NY
        CALL COPYY(Y,1.0,WK,NY)
        ICO=NX
        CALL COPYY(X,1.0,XT,NX)
        NXT=NX
      ENDIF
C
      LUNTRM=LNOUT(0)
C
C--------------------------------
C-----DO NOT REINITIALIZE OR UNINTENTIONALY RESET
      IF(INIT(ICOD).GT.0) THEN
        I=INZONS(ICOD)
        ISHOW=0
        GO TO 3900
      ENDIF
C
C-----INITIALIZE REGION AND BOUNDRY COUNT.. OR "RESET".. MAIN OPT..
 211  CONTINUE
      INIT(ICOD)=1
      INZONS(ICOD)=1
      I=1
      RBND(I,ICOD)=WK(IWK,1)
      IOPT(I,ICOD)=1
      AVG(I,ICOD)='N'
      INPTS(I,ICOD)=1
      ISHOW=0
      GO TO 3900
C
C=================================
C-----INTERACTIVE SECTION
C=================================
C
 250  CONTINUE
      ISHOW=0
C
      IF(LXOUT(0)) WRITE(LUNTRM,275)
 275  FORMAT(' THINSET OPTIONS:'/
     >	' A - ADD A BOUNDRY:'/
     >  ' B - DELETE A BOUNDRY:'/
     >  ' C - ASSIGN A NEW SAMPLING FACTOR TO A ZONE (BTW 2 BDY''S):'/
     >  ' Y - TOGGLE SWITCH:  THIN/AVG OR JUST THIN REGIONS:'/
     >  ' R - RESET NO. OF REGIONS=1:'/
     >  ' S - SHOW THINNING PARAMETERS:'/
     >  ' D - GO AHEAD AND THIN USING CURRENT PARAMETERS:')
C
      CALL UREAD(' THINSET: ENTER OPTION CODE:$')
      IANS=IXUOPC ('ABCYRSDQ$')
      IF(IANS.EQ.0) THEN
        CALL UERMSG(' THINSET:  SAY AGAIN?',' ',0)
        GO TO 3800
      ELSE
        GO TO (30,6000,8000,50,211,3800,4000,5000 )IANS
      ENDIF
C
C
C-----ADD A BOUNDRY TO INDEX.. MAIN OPTION..
 30   CONTINUE
C
      CALL UREAD(
     >  ' THINSET: PLEASE ENTER A BOUNDRY VALUE$')
C
      IF(LCHAR('Q')) GO TO 250
C
      ZRBND=FDCOD(IERT)
      IF(IERT.NE.0) GO TO 30
C
      IF((ZRBND.LE.WK(1,1)).OR.(ZRBND.GE.WK(IWK,1)))
     >	   GO TO 75
C
      DO 33 IF1=1,I
        IF(RBND(I,ICOD).EQ.ZRBND) GO TO 76
 33   CONTINUE
C
C-----1)SORT:ROUTINE ASSUMES ARRAYS SORTED THRU (I-1)
C-----       INSERTS VALUE OF ARRAY(I)SUCH THAT
C-----       ARRAY(IA) < ARRAY(I) < ARRAY(IB)..
C-----       WHERE (IB) IS 1ST VALUE IN ARRAY
C-----       GREATER THAN ARRAY(I).............
C
C  LOCATE
      DO 100 IA=1,I
        IF(RBND(IA,ICOD).GT.ZRBND) GO TO 101
 100  CONTINUE
C  NO EXIT
      ZDEATH = SQRT(-1.0/(RBND(1,1)**2))  ! SHOULD NOT BE HERE !
C
 101  CONTINUE
C
C  COPY PARAMETERS
      DO 120 IC=I,IA,-1
        IP1=IC+1
        RBND(IP1,ICOD)=RBND(IC,ICOD)
        IOPT(IP1,ICOD)=IOPT(IC,ICOD)
        AVG(IP1,ICOD)=AVG(IC,ICOD)
        INPTS(IP1,ICOD)=INPTS(IC,ICOD)
 120  CONTINUE
C
C  INSERT BDY
      RBND(IA,ICOD)=ZRBND
C
      I=I+1
C
      GO TO 3900
C
C-----TOGGLE AVERAGING SWITCH
C
 50   CONTINUE
C
      IF(LXOUT(0)) WRITE(LUNTRM,2000)
 2000 FORMAT(' THINSET: ENTER REGION # TO TOGGLE AVERAGING SWITCH')
C
      CALL UREAD(' THINSET:ENTER REGION # OR "Q":$')
      IF(LCHAR('Q')) GO TO 250
C
      IAVGSW=IDCOD(IERT)
      IF(IERT.NE.0) GO TO 50
      IF((IAVGSW.LE.0).OR.(IAVGSW.GT.I)) THEN
        CALL UERMSI(' %INVALID REGION #:',IAVGSW,0)
        GO TO 3800
      ENDIF
C
      IF(IOPT(IAVGSW,ICOD).EQ.1) THEN
        IOPT(IAVGSW,ICOD)=2
        AVG(IAVGSW,ICOD)='Y'
      ELSE
        IOPT(IAVGSW,ICOD)=1
        AVG(IAVGSW,ICOD)='N'
      ENDIF
      GO TO 3800
C
C
C-----SHOW THINING PARAMETERS.. MAIN OPTION..
 3800 CONTINUE
      ilxout=lxout(0).or.(ians.eq.6)
      IF(ilxout) WRITE(LUNTRM,3267) IWK,WK(1,1),WK(IWK,1)
 3267 FORMAT(
     >' THINSET: INPUT COORDINATE TO BE THINNED CONTAINS NX=',I6,' PTS'/
     >'  X(1)=',1PE11.4,'  X(NX)=',1PE11.4)
      IF(.not.ilxout) GO TO 250
      WRITE(LUNTRM,38)
 38   FORMAT(/' SUB_REGION          X1        X2       SKIPFACTOR',
     >        '      AVG    #INPUT PTS')
C
      DO 3801 IXZ=1,I
        WRITE(LUNTRM,39)IXZ,LBNDA(IXZ),UBNDA(IXZ),INPTS(IXZ,ICOD),
     >	    AVG(IXZ,ICOD),IC3(IXZ)
 39     FORMAT(5X,I3,5X,1PE12.4,1X,1PE12.4,4X,I4,12X,A1,7X,I6)
 3801 CONTINUE
C
      GO TO 250
C
C-----END USER MESSAGES REGARDING REGION IDENTIFICATION
C
C-----% ERRORS IN BOUNDRY SPECS.
 75   CONTINUE
      WRITE(LUNTRM,90)RBND(I,ICOD),WK(1,1),WK(IWK,1)
 90   FORMAT(' % ILLEGAL BOUNDRY SPECIFICATION'/
     >  '  BOUNDRY @ X=',1PE12.4,' IS "NOT" WITHIN DATA BOUNDRIES'/
     >  '  DATA BOUNDRIES ARE BETWEEN X=',1PE12.4,'AND X=',1PE12.4)
      GO TO 30
C
 76   CONTINUE
      WRITE(LUNTRM,77)
 77   FORMAT(' %ILLEGAL BOUNDRY SPECIFICATION'/
     >	'  SPECIFIED BOUNDRY DUPLICATES A PREVIOUSLY'/
     >  '  DEFINED BOUNDRY. PLEASE CHECK YOUR INPUT'/
     >  '  PARAMETERS.')
      GO TO 30
C
C-----END BOUNDRY INPUT SPECIFICATION ERROR MESSAGES
C
C-----END EXTRACT RESORT
C
 3900 CONTINUE
      ISHOW=1
C
 4000 CONTINUE
C
      IC1P=1
      DO 4010 IU=1,I
        IHA=IU-1
        IF(IU.EQ.1) THEN
C
          IS3(1)=1
          LBNDA(IU)=WK(1,1)
          UBNDA(IU)=RBND(IU,ICOD)
C
        ELSE
C
          LBNDA(IU)=RBND(IHA,ICOD)
          UBNDA(IU)=RBND(IU,ICOD)
C
        ENDIF
C-----COMPUTE # OF PTS./REGION
        IC2=0
        DO 4005 IC1=IC1P,IWK
          IF((WK(IC1,1).GE.LBNDA(IU)).AND.
     >	       (WK(IC1,1).LT.UBNDA(IU))) THEN
            IC2=IC2+1
          ELSE IF(WK(IC1,1).GE.UBNDA(IU)) THEN
            IC1P=IC1
            IF(IU.LT.I) IS3(IU+1)=IC1P
            GO TO 4006
          ENDIF
 4005   CONTINUE
 4006   CONTINUE
        IF(I.EQ.IU) IC2=IC2+1
        IC3(IU)=IC2
        IF(IC2.EQ.0) THEN
          CALL UERMSF(
     >' %REGION CONTAINS NO POINTS, DELETED AT ',RBND(IU,ICOD),0)
          IDEL=MIN0((I-1),IU)
          GO TO 6250
        ENDIF
C-----END # OF PTS./REGION COMPUTE.
C
 4010 CONTINUE
C
      IF(ISHOW.EQ.1) GO TO 3800
C
C
C
C
      IREGN=I
      DO IC=ICO,1,-1
        DO IP=1,IWK
          IF(ICOD.EQ.1) THEN
            WK(IP,1)=F(IP,IC)
          ELSE
            WK(IP,1)=F(IC,IP)
          ENDIF
        ENDDO
C
        IF(ICOD.EQ.1) THEN
          CALL THINIT(X,WK(1,1),XT,WK(1,2),IS3,IC3,INPTS(1,ICOD),
     >	      IREGN,IOPT(1,ICOD),IOUT,IWK)
          NXT=IOUT
        ELSE
          CALL THINIT(Y,WK(1,1),YT,WK(1,2),IS3,IC3,INPTS(1,ICOD),
     >	      IREGN,IOPT(1,ICOD),IOUT,IWK)
          NYT=IOUT
        ENDIF
C
        DO IP=1,IOUT
          IF(ICOD.EQ.1) THEN
            FT(IP,IC)=WK(IP,2)
          ELSE
            FT(IC,IP)=WK(IP,2)
          ENDIF
        ENDDO
      ENDDO
C
      GO TO 5000
C
C-----DELETE AN EXISTING BOUNDRY .. MAIN OPTION..
 6000 CONTINUE
      IF(I.EQ.1)THEN
        CALL UCLEAR
        WRITE(LUNTRM,6001)
 6001   FORMAT(' %THERE ARE CURRENTLY NO BOUNDRIES TO DELETE')
        CALL UPAUST(1)
        GO TO 250
      ENDIF
C
      IM1=I-1
      IF(LXOUT(0)) THEN
          DO 6100 IL=1,IM1
            WRITE(LUNTRM,6010) IL,RBND(IL,ICOD)
 6010       FORMAT(' BOUNDRY #  ',I3,' = ',1PE12.4)
 6100     CONTINUE
      ENDIF
C
 7001 CONTINUE
C
      CALL UREAD('THINSET:ENTER # OF BOUNDRY TO DELETE, OR "Q"$')
      IF(LCHAR('Q')) GO TO 250
      IABC=IDCOD(IERT)
      IF(IERT.NE.0) GO TO 7001
      IF((IABC.LE.0).OR.(IABC.GT.IM1)) THEN
        CALL UERMSI('THINSET:  INVALID REGION # ',IABC,1)
        GO TO 7001
      ENDIF
C
      IDEL=IABC
C
 6250 CONTINUE
      IA=IDEL+1
      DO 6300 IB=IA,I
        IBM1=IB-1
        RBND(IBM1,ICOD)=RBND(IB,ICOD)
        IOPT(IBM1,ICOD)=IOPT(IB,ICOD)
        AVG(IBM1,ICOD)=AVG(IB,ICOD)
        INPTS(IBM1,ICOD)=INPTS(IB,ICOD)
 6300 CONTINUE
      I=I-1
      GO TO 3900
C
C-----END BOUNDRY EXTRACT RESORT
C-----%ERROR MESSAGES BOUNDRY INPUT
CX 7101	CONTINUE
CX	CALL UCLEAR
CX	WRITE(LUNTRM,7121)
CX 7121	FORMAT(' % THERE ARE NO BOUNDRIES CURRENTLY DEFINED')
CX	GO TO 250
C
CX 7102	CONTINUE
CX	CALL UCLEAR
CX	WRITE(LUNTRM,7122)IABC,I
CX 7122	FORMAT(' % BOUNDARY #',I3,'HAS NOT BEEN DEFINED'/
CX     >         '   THERE ARE CURRENTLY',I3,'REGIONS DEFINED'/
CX     >         '   USE OPTION "S" TO DISPLAY DEFINED REGIONS')
CX	GO TO 250
C-----END BOUNDRY INPUT ERROR MESSAGES
C-----END BOUNDRY DELETE
C
 8000 CONTINUE
C-----CHANGE A SKIP FACTOR.. MAIN OPTION..
C
      IF(LXOUT(0)) THEN
          WRITE(LUNTRM,8002)
 8002     FORMAT(' SUBREGION#     SKIPFACTOR ')
          DO 8010 ICH=1,I
            WRITE(LUNTRM,8005)ICH,INPTS(ICH,ICOD)
 8005       FORMAT('   ',I3,'        ',I3)
 8010     CONTINUE
      ENDIF
C
 8015 CONTINUE
      CALL UREAD('THINSET: ENTER REGION # TO CHANGE, OR "Q":$')
      IF(LCHAR('Q')) GO TO 250
      IXYZ=IDCOD(IERT)
      IF(IERT.NE.0) GO TO 8015
C
      IF((IXYZ.LE.0).OR.(IXYZ.GT.I)) THEN
        CALL UERMSI('THINSET:  INVALID REGION # ',IXYZ,1)
        GO TO 3800
      ENDIF
C
 8020 CONTINUE
      CALL UREAD('THINSET: ENTER NEW SAMPLING (THINNING) FACTOR:$')
      IF(LCHAR('Q')) GO TO 250
      IXYA=IDCOD(IERT)
      IF(IERT.NE.0) GO TO 8020
      INPTS(IXYZ,ICOD)=MAX0(1,IXYA)
C
      GO TO 3800
C-----END SKIP FACTOR CHANGE
C
 5000 CONTINUE
      INZONS(ICOD)=I
      RETURN
      END
C******************** END FILE THINSET.FOR ; GROUP THNVRG ******************
