C******************** START FILE GDIFF1.FOR ; GROUP GDIFF1 *************
C-----------------------------------------------------------
C  GDIFF1
C  PROGRAM TO DO DIFFERENTIATION AND INTEGRALS OF INPUT FROM UFILES
C   DATA FILE
C
C  CREATED BY T.B. TERPSTRA    3/24/89 FROM
C
C  REV. D. MC CUNE JAN 1983
C   ADDING SMOOTHING-AUXILLIARY OPTION CONTROL NODE AFTER SHOT DATA
C  IS SUCCESSFULLY READ IN.
C
      PROGRAM GDIFF1
      USE USMOO
C MAX NUMBER OF SCALARS
      PARAMETER (MAXSC=100)
C  MAX SIZE OF DATA ARRAYS
C
      PARAMETER (JDSIZ=102400)
C
C  DATA BUFFERS AND LABELS
      REAL X(JDSIZ),Y(JDSIZ),YF(JDSIZ),YT(JDSIZ),
     >     EPS(JDSIZ),DEL(JDSIZ),XTRVAL(MAXSC),XTEVAL(MAXSC)
      CHARACTER*10 ZSDATE,XLAB(3),YLAB(3),XTRLAB(3,MAXSC),ZSHID,ZDATE
      INTEGER IORDER(MAXSC)
      CHARACTER*40 ZFILE
      CHARACTER*10 ZZDATE,XELAB(3),YELAB(3),XTELAB(3,MAXSC)
      CHARACTER*10 ZXUNOL,ZYUNOL,ZXUN00,ZYUN00
      CHARACTER*4 IDEV,IDEV2
C  DATA BUFFERS - SECONDARY FCN - ADD OR SUBTRACT TO PRIMARY DATA
      REAL X2(JDSIZ),Y2(JDSIZ),XTRVL2(MAXSC)
      CHARACTER*10 XTRLB2(3,MAXSC)
C-----------------------------
C  PROGRAM MOD APR 1984 DMC-- DEAL WITH VAX COMPRESSED UFILES DATA
C   FORMATTED COMMENTS FOR THE OUTPUT FILE ARE PUT IN A TEMPORARY FILE
C   WHICH IS SPOOLED TO THE PERMANENT FILE WHICH IS OPTIONALLY BINARY-
C   COMPRESSED.
C  USER MAY SELECT COMPRESSED OR UNCOMPRESSED DATA OUTPUT
C
      CHARACTER*7 CMPSTA(0:4)
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  COMPRESSED DATA OUTPUT DEFAULT FLAG, =1 FOR COMPRESSION ON
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C
C-------------------------------
C
C  L.U.N FOR DATA INPUT
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  L.U.N FOR DATA OUPUT
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  L.U.N. FOR ERROR BAR FILES
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  L.U.N. FOR TEMPORARY COMMENTS FILE
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  L.U.N. FOR 2NDARY FCN
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  L.U.N. FOR 2NDARY COMMENTS FILE
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
      LOGICAL LYES
      logical lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C	VARIABLES ADDED BY T.B. TERPSTRA   4/15/89
      LOGICAL	LINTEG			! WAS INTEGRATION THE LAST OPERATION?
      LOGICAL LDIFF			! OR WAS IT DIFFERENTIATED?
      CHARACTER*10 YLABN(3)		! NEW YLABEL
      CHARACTER*20 C20		! TEMPORARY STORAGE
 
      REAL   XXTRVAL(MAXSC)		! TEMPORARY STORAGE FOR SCALAR VALUES.
      CHARACTER*10 XXTRLAB(3,MAXSC)   !                    "   LABELS.
C => GSMOO1               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA CMPSTA/'ascii','????','binary','HDF','NetCDF'/
      data icompr/2/  !  default:  portable binary
      DATA ILUNI/21/
      DATA ILUNO/22/
      DATA ILUNE/23/
      DATA ILUNT/24/
      DATA ILUN2/25/
      DATA ILUNT2/26/
C => END DATA BLOCK
C ====================
C
      itoggl=icompr
C
      MAXD=JDSIZ
      MAXE=JPCMAX
C
      call date_and_time(DATE=zdate)
      CALL UINITG("GDIFF1")
C  ENABLE INLINE TYPE-AHEAD
      call urdext('ifi')
      luntrm=lnout(0)
C
 10   CONTINUE
      CALL UFNTER(ILUNI,'1D INPUT FILES - RAW')
      CALL UFNTER(ILUNO,'OUTPUT FILES- DIFFERENTIATED')
      IFLAGE=0
      GO TO 20
C
 14   CONTINUE
C
 20   CONTINUE
C  INITIALIZE UNITS CONVERSION INFO
      IXUNOL=0
      ZXCONA=1.0
      ZXCONB=0.0
      IYUNOL=0
      ZYCONA=1.0
      ZYCONB=0.0
C
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,5555)
 5555 FORMAT(//' THIS IS VERSION 1.01 OF GDIFF1'//)
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'               INPUT',ILUNI)
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'              OUTPUT',ILUNO)
C---
 
C	.GET SHOT NUMBER.
      CALL URSHOT('GDIFF1','ENTER "Q" TO QUIT OR "D" TO CHANGE NAMES',
     1              'QD', ISHOT, IANS)
      IF (IANS .GT. 0)  GO TO (900,10) IANS
      IF (ISHOT .EQ. 0) GO TO 900
 
C  CREATE TEMPORARY FILE TO RECORD SCALARS MODIFICATIONS, OTHER REMARKS
 
      IDCUT=0
      CALL UFOPCF(ILUNT,IER)
      WRITE(ILUNT,7001)
 7001 FORMAT('  ')
C---
C
      CALL UFOPRD(ILUNI,ISHOT,IER)
      IF(IER.NE.0) THEN
        CALL UCLEAR
        CALL UERMSG('%ERROR', ' FROM CALL UFOPRD ', IER)
        GO TO 50
      ENDIF
C
      CALL UF1DRD(ILUNI,IDEV,ZSDATE,
     >   X,Y,JDSIZ,NRET,IPROC,
     >   XLAB,YLAB,MAXSC,NUMSC,XTRVAL,XTRLAB,IER)
C
      YLABN(1) = YLAB(1)
      YLABN(2)= YLAB(2)
      YLABN(3)= YLAB(3)
C                                       ! SET NEW LABEL = OLD
C
      ZXUN00=XLAB(3)
      ZYUN00=YLAB(3)
      IPROCP=IPROC
      IF((IPROC.EQ.0).OR.(IPROC.EQ.1)) GO TO 32
      IF(IPROC.GT.3) GO TO 34
      CALL UERMSG('% INPUT DATA HAS ALREADY BEEN SMOOTH',' ',2)
      GO TO 34
C
 32   CONTINUE
C
 34   CONTINUE
C
      IF(IER.NE.0) THEN
        CALL UCLEAR
        GO TO 290
      ENDIF
C
C  COPY UNDIFFERENTIATED DATA INTO OUTPUT BUFFER FOR NOW ...
C
C  REENTRY LINE 35 - DO NOT REREAD ERROR BAR DATA
      IFLREB=0
 35   CONTINUE
      CALL COPYY(Y,1.0,YF,NRET)
C
C
 50   CONTINUE
C-------------------------------------------
C  DIFFERENTIATING CONTROL NODE
C
      CALL NEUPAG
 51   IF(LXOUT(0)) WRITE(LUNTRM,2000) NUMSC,CMPSTA(ICOMPR)
 2000 FORMAT(' GDIFF1 DATA OPTIONS:'/
     >'  A - GENERATE 40 POINTS OF TEST DATA IN Y ARRAY'/
     >'  D - DIFFERENTIATE THE DATA'/
     >'  E - EXAMINE/MODIFY ASSOCIATED SCALARS (NSC= ', I6,')'/
     >'  1 - PRESET PLOT SCALING/AXES DEFAULTS'/
     >'  G - GRAPH THE *RAW* DATA'/
     >'  H - GRAPH THE *DIFFERENTIATED/INTEGRATED* DATA'/
     >'  I - INTEGRATE Y ARRAY OVER X'/
     >'  L - CHANGE Y AXIS LABEL ON NEW Y ARRAY'/
     >'  P - COMPRESS- Toggle data output format flag, NOW "',A,'"'/
     >'  4 - *new* Ufile output format control menu'/
     >'  Q - QUIT (GET NEW SHOT WITHOUT WRITING OUTPUT FILE)'/
     >'  U - CHANGE THE UNITS OF THE DATA (F--> A*F+B TRANSFORM)'/
     >'  W - WRITE DATA (NEW DATA IF AVAILABLE) TO OUTPUT FILE'/
     >'  X - EXIT (STOP PROGRAM NOW)')
 
      CALL UREAD('GDIFF1: ENTER OPTION CODE:$')
      IANS=IXUOPC('1PICBEQDFUWXGHAL4$')
      CALL UCHKOP(IANS,0,1,100,-1,*51)
      GO TO (45,55,95,90,80,60,290,70,75,100,125,900,180,190,
C               1  P  I  C  B  E  Q   D  F  U   W   X   G   H
     1                                                 400,500,56) IANS
C                                                       A   L  4
 
 45   CONTINUE
      CALL GPRESET
      GO TO 50
C
 55   CONTINUE
      ICOMPR=ITOGGL-ICOMPR
      GO TO 50
C
 56   continue
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      go to 50
C
C  MODIFY SCALARS
 60   IF(NUMSC.GT.0)
     >     CALL UFSCLK(ILUNO,ISHOT,NUMSC,XTRVAL,XTRLAB,IORDER,1,ILUNT)
      GO TO 50
C
C  DIFFERENTIATE THE DATA
C
 70   CALL UDIFF1 (X,Y,NRET,YF)
      LINTEG = .FALSE.
      LDIFF  = .TRUE.			! FLAG DIFFERENTIATION
      IF (LXOUT(0))  WRITE (LUNTRM,2222)
 2222   FORMAT(/' Y ARRAY HAS BEEN DIFFERENTIATED'/
     1           /' USE OPTION L TO CHANGE Y LABEL'//)
      GO TO 50
 
C  ** UNDEFINED
 75   CONTINUE
      IF (LXOUT(0))  WRITE (LUNTRM,2002)
 2002   FORMAT(/' YOU HAVE REACHED AN UNDEFINED PLACE IN MAIN AT 75'/)
      GO TO 50
C
C
 80   CONTINUE
C  	NOW UNDEFINED
      GO TO 50
C
 90   CONTINUE
C	.UNDEFINED FUNCTION.
      GO TO 50
 
 
C	.INTEGRATE Y ARRAY OVER X STARTING AT CHOSEN X.
 95   CONTINUE
      CALL UINTEG (X, Y, NRET, LXOUT(0), LUNTRM, YF, XZERO)
      LINTEG = .TRUE.
      LDIFF  = .FALSE.	    ! FLAG INTEGRATION.
      IF (LXOUT(0))  WRITE (LUNTRM,2223)
 2223   FORMAT(/' INTEGRATION OF Y ARRAY COMPLETE '/
     1     /  ' USE OPTION L TO CHANGE Y LABEL'/)
      GO TO 50
 
 
C  UNITS TRANSFORM OPTION
 100  CONTINUE
C  X UNITS
      CALL UCHUNS(
     >'X    ',XLAB(3),IXUNTC,ZXUN00,X,NRET,ZXCONA,ZXCONB,1)
      IXUNOL=MAX0(IXUNOL,IXUNTC)
C
      IF((KTPPCE.EQ.1).AND.(IXUNTC.GT.0)) THEN
        DO 126 I=1,NPCE
          IF(IXUNTC.EQ.1) THEN
            ZFAC=ZXCONA
          ELSE
            ZFAC=ZXCONB
          ENDIF
          XPCE(I)=ZFAC*XPCE(I)
 126    CONTINUE
      ENDIF
C
C  Y UNITS
      CALL UCHUNS(
     >'Y    ',YLAB(3),IYUNTC,ZYUN00,YF,NRET,ZYCONA,ZYCONB,2)
      IYUNOL=MAX0(IYUNOL,IYUNTC)
C
      IF(IYUNTC.GT.0) THEN
C
      DO 127 I=1,NRET
C TRANSFORM OF BOTH DIFFERENTIATED AND UNDIFFERENTIATED
C                                              DATA REQUIRED
C  DIFFERENTIATED DATA DONE ABOVE IN UCHUNS CALL
        IF(IYUNTC.EQ.1) THEN
          Y(I)=ZYCONA*Y(I)+ZYCONB
        ELSE
          Y(I)=ZYCONB*ABS(Y(I))**ZYCONA
        ENDIF
 127  CONTINUE
C
      IF(KTPPCE.EQ.1) THEN
        DO 128 I=1,NPCE
          IF(IYUNTC.EQ.1) THEN
            ZFAC=ZXCONA
          ELSE
            ZFAC=ZXCONB
          ENDIF
          EPSPC(I)=ZFAC*EPSPC(I)
 128    CONTINUE
      ENDIF
C
      ENDIF
C  RECORD TRANSFORMATIONS IN COMMENTS FILE
      CALL UFAXCOM(ILUNT,IXUNTC,ZXCONA,ZXCONB,IYUNTC,ZYCONA,ZYCONB,
     >     0,0.0,0.0)
      GO TO 50
 
C  GRAPH THE RAW DATA
 180  CONTINUE
      CALL GRFUF1(X,Y,NRET,IPROCP,YLAB,XLAB,ISHOT,IDEV,ZSDATE,
     >              NUMSC,XTRVAL,XTRLAB)
      GO TO 50
 
C  GRAPH DIFFERENTIATED OR INTEGRATED DATA (IF ANY)
 190  CONTINUE
        IF (LXOUT(0)) THEN
            IF(LDIFF) THEN
             WRITE (LUNTRM,2332)
          ELSE
             WRITE (LUNTRM,3332)
          END IF  !LDIFF
        END IF    ! LXOUT(0)
 
 2332   FORMAT(/' GRAPH THE DIFFERENTIATED DATA'///)
 3332   FORMAT(/' GRAPH THE INTEGRATED DATA'///)
 
      CALL GRFUF1(X,YF,NRET,IPROC,YLABN,XLAB,ISHOT,IDEV,ZSDATE,
     >               NUMSC,XTRVAL,XTRLAB)
      GO TO 50
 
C *** WRITE THE NEW UFILE
 125  CONTINUE
C
C	.COPY INFORMATION INTO TEMPORARY VARIABLES
      NNUMSC = NUMSC
      DO  I=1,MAXSC
          XXTRVAL(I) = XTRVAL(I)
          DO  J=1,3
      	XXTRLAB(J,I) = XTRLAB(J,I)
          END  DO   ! J
      END DO  ! I
 
      IF (LINTEG)  THEN
C	    .IF OUTPUT IS FROM INTEGRATION - PUT OUT XZERO AS A SCALAR.
C
C	    .CHECK TO SEE IF XZERO IS ALREADY IN THE FILE AS A SCALAR.
          DO I=1,NNUMSC
      	IF ('XZERO:' .EQ. XXTRLAB(1,I))  THEN
      	    CALL UERMSG('XZERO:', '  IS ALREADY A SCALAR -'
     1                        // ' WILL OVERWRITE', I)
      	    XXTRVAL(I) = XZERO
      	    GO TO 140    ! JUMP OUT OF LOOP
      	END IF  ! XZERO
          END DO      ! I
 
          IF (NNUMSC+1 .GT. MAXSC)  THEN
      	CALL UERMSG ('ERROR', ' TOO MANY SCALARS ' //
     1			      '- DO NOT OVERWRITE XZERO', NNUMSC)
          ELSE
C		.PUT OUT XZERO INFO.
      	NNUMSC = NNUMSC + 1
      	XXTRVAL(NNUMSC)   = XZERO
      	XXTRLAB(1,NNUMSC) = 'XZERO:'
      	XXTRLAB(2,NNUMSC) = 'LOWR LIMIT'
      	XXTRLAB(3,NNUMSC) = XLAB(3)
          END IF   ! NNUMSC
 
  140 CONTINUE
      END IF     ! LINTEG
 
 
C  SET COMPRESSION OPTION
      CALL UFCMPR(ILUNO,ICOMPR)
      CALL UFOPWR(ILUNO,ISHOT,IER)
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 290
 
      CALL UF1DWR(ILUNO,IDEV,
     >     ZSDATE,X,YF,NRET,IPROC,XLAB,YLABN,NNUMSC,XXTRVAL,XXTRLAB,IER)
C
C  APPEND COMMENTS TO FILE
C
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 200
C
      CALL UFSNAM(ISHOT,ZFILE,IER,ILUNI)
      WRITE(ILUNT,4001) ZFILE
 4001 FORMAT('    PRODUCED BY PROGRAM GDIFF1 [TRANSP] '/
     >         '    FROM INPUT DATA FILE:  "',A,'"')
 
      IF (LDIFF)  THEN
          WRITE (ILUNT,2332)
      ELSE
          WRITE (ILUNT,3332)
      END IF  !LDIFF
C
      IF(IXUNOL.NE.0) WRITE(ILUNT,4011) ZXUN00,XLAB(3)
      IF(IYUNOL.NE.0) WRITE(ILUNT,4012) ZYUN00,YLABN(3)
 4011 FORMAT(' "X" UNITS WERE TRANSFORMED: "',A10,'" TO "',A10,'"')
 4012 FORMAT(' "Y" UNITS WERE TRANSFORMED: "',A10,'" TO "',A10,'"')
C
      IF (LINTEG)  THEN
C	.   WRITE OUT LOWER LIMIT OF INTEGRAL TO FILE.
          WRITE (ILUNT,4019) XZERO
 4019     FORMAT('LOWER LIMIT OF X FOR INTEGRAL = ', E15.5)
      END IF   ! LINTEG
 
C  GET USER COMMENTS TO APPEND TO END OF OUTPUT FILE
      CALL UFACOM(ILUNT)
C
      WRITE(ILUNT,4007) IPROCP,ZDATE
 4007 FORMAT(
     > /' =========================================================='/
     >  ' COMMENTS SPOOLED FROM FILE INPUT TO GDIFF1 [IPROC=',I1,']:'/
     >  ' ON VAX-11 ON DATE:  ',A10/)
C  SPOOL COMMENTS FROM INPUT FILE, SCALARS MODIFICATIONS RECORD FILE
C
      CALL UCSEND(ILUNT,ILUNO)
C
      CALL USPOOL(ILUNI,ILUNO)
C
 200  CONTINUE
      CALL UFCLOS(ILUNO)
 290  CONTINUE
      CALL UFCLOS(ILUNI)
      GO TO 20
 
 
C-------------------------------------------------------
C  NEW OPTION "A" - UNDEFINED
C  INPUT DATA
C
 400  CONTINUE
      NRET = 40
      DO I=1,NRET
          X(I) = I
          Y(I) = Y(I) + (X(I) * I * COS(X(I)))
      END DO
      GO TO 35
 
 500  YLABN(3) = 'JOULES/SEC'
      CALL UREADW('GDIFF1: ENTER UNITS OF DEPENDENT COORDINATE$$',
     1               YLABN(3) )
      CALL UREADL('GDIFF1: ENTER NEW YLABEL$$', C20 )
      YLABN(1) = C20(1:10)
      YLABN(2) = C20(11:20)
      GO TO 50
 
 
C-------------------------------------------------------
C  EXIT PROGRAM
C
 900  CONTINUE
      CALL UEXITA
      STOP
      	END
 
 
C******************** END FILE GDIFF1.FOR ; GROUP GDIFF1 ******************
