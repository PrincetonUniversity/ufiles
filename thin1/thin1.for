C******************** START FILE THIN1.FOR ; GROUP THNVRG ******************
C-----PROGRAM TO THIN DATA-----
C================================
C-----WRITTEN BY A. ERLICH 4-4-85
C================================
C================================
      PROGRAM THIN1
C================================
C================================
C     COMMENTS: THIN1: DATA THINNING UTILITY: MAIN PROGRAM
C     1.)INTERACTIVELY ACCEPTS SHOT NUMBER FROM USER. 2.)GIVES
C        USER OPTIONS TO:(A)-QUIT PROGRAM,(B)-GET NEW SHOT,
C        (C)-PLOT UNTHINNED DATA,(D)-PLOT THINNED DATA,(E)-THIN
C        SOME DATA,(F)-WRITE THINNED DATA TO OUTPUT FILE
C       OPTIONS (C),(D) ABOVE ARE ACHIEVED BY CALLS TO GRFUF1,
C       OPTION (E) IS ACHIEVED BY A CALL TO THINSET,OPTION(F)
C       IS ACHIEVED BY A CALL TO UF1DWR.
C================================
C
C================================
C-----IDENTIFICATION SECTION-----
C================================
C
      PARAMETER (MAXSC=100)
      PARAMETER (JDSIZ=81695)
C
      REAL X(JDSIZ),Y(JDSIZ),XT(JDSIZ),YT(JDSIZ),WK(JDSIZ,2)
      REAL XTRVAL(MAXSC)
C
      CHARACTER*10 ZSDATE,XLAB(3),YLAB(3),XTRLAB(3,MAXSC),ZSHID,ZDATE
      CHARACTER*64 ZFILE
      CHARACTER*4  IDEV
      CHARACTER*3  CMPSTA(2)
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C-----L.U.N. TEMP. COMMENTS FILE
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C-----L.U.N. 2NDARY TEMP. COMMENTS FILE
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
      PARAMETER (MAXN=24000)
C-----L.U.N. FOR DATA INPUT
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C-----L.U.N. FOR DATA OUTPUT
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LXOUT
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => THIN1                BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA CMPSTA/'OFF','ON '/
      DATA ICOMPR/2/  ! default:  compressed binary, portable
      DATA ILUNT/24/
      DATA ILUNT2/26/
      DATA ILUNI/21/
      DATA ILUNO/22/
C => END DATA BLOCK
C ====================
C
      call ufheader("thin1")
      CALL UINITG("THIN1")
      LUNTRM=LNOUT(0)
C
C=======================================
C-----INTERACTIVE SECTION OF CODE BEGINS
C=======================================
      CALL UAHEAD
      CALL URDEXT('ifi')
C
 10   CONTINUE
      IST=0
      CALL UFNTER(ILUNI,'1D INPUT FILES RAW')
      CALL UFNTER(ILUNO,'OUTPUT FILES THINNED')
C
 30   CONTINUE
      IF(IST.NE.1)GO TO 31
      CALL UFCLOS(ILUNI)
 31   CONTINUE
C
      IRET=0
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'               INPUT',ILUNI)
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'      THINNED OUTPUT',ILUNO)
      CALL URSHOT('THIN1',',0 OR Q TO QUIT, D TO CHANGE FILENAMES',
     >    'QD',ISHOT,IANS)
      IF (IANS.EQ.1) GO TO 20
      IF (IANS.EQ.2) GO TO 10
      IF(ISHOT.EQ.0) GO TO 20
      IST=1
C
C-----CREATE TEMP. FILE TO RECORD COMMENTS
      CALL UFOPCF(ILUNT,IER)
      WRITE(ILUNT,32)
 32   FORMAT('  ')
C-----
 33   CONTINUE
      CALL UFOPRD(ILUNI,ISHOT,IER)
      IF(IER.NE.0)THEN
        CALL UCLEAR
        GO TO 30
      ENDIF
C
      CALL UF1DRD(ILUNI,IDEV,ZSDATE,X,Y,JDSIZ,NRET,
     >     IPROC,XLAB,YLAB,MAXSC,NUMSC,XTRVAL,XTRLAB,
     >     IER)
C
      IF(IER.NE.0)THEN
        CALL UCLEAR
        GO TO 30
      ENDIF
C
      NCLEAR=0
C
 35   CONTINUE
C
      IF(LXOUT(0)) THEN
        CALL NEUPAG
        WRITE(LUNTRM,37) IRET
 37   FORMAT(/' CURRENT # OF F(X) POINTS IN FILE = ',I10/)
C
        WRITE(LUNTRM,1000)
 1000 FORMAT(' THIN1 OPTIONS:'/
     >	' Q - QUIT PROGRAM NOW:'/
     >  ' S - GET NEW SHOT/ INPUT FILE:'/
     >  ' P - PLOT DATA (UNTHINED):'/
     >  ' T - PLOT DATA (THINNED):'/
     >  ' A - DEFINE THINNING OPERATION AND THIN THE DATA'/
     >  ' 4 - check/set output file format'/
     >  ' W - WRITE DATA(THINNED) TO OUTPUT FILE:')
C
      ENDIF
C
      CALL UREAD(' THIN1: ENTER OPT. CODE:$')
      IANS=IXUOPC ('QSPTAW4$')
      IF(IANS.GT.0) GO TO (20,30,40,50,60,70,68)IANS
C
C
C-----PLOT UNTHINED DATA
 40   CONTINUE
      CALL GRFUF1(X,Y,NRET,IPROCP,YLAB,XLAB,ISHOT,IDEV,ZSDATE,
     >              NUMSC,XTRVAL,XTRLAB)
      GO TO 35
C-----PLOT THINNED DATA
 50    CONTINUE
      IF(IRET.EQ.0) GO TO 51
      CALL GRFUF1(XT,YT,IRET,IPROC,YLAB,XLAB,ISHOT,IDEV,ZSDATE,
     >              NUMSC,XTRVAL,XTRLAB)
      GO TO 35
 51   CONTINUE
      WRITE(LUNTRM,55)
 55   FORMAT(' % DATA MUST BE THINNED FIRST')
      GO TO 35
C-----PROCEED WITH OPTION TO THIN
 60   CONTINUE
      CALL THINSET(ISHOT,X,XT,NRET,ZDUM1,ZDUM2,1,Y,YT,NRET,WK,JDSIZ,
     >    IRET,IDUM,1)
      GO TO 35
C
C-----FORMAT CHECK
 68   continue
      call ufmtsel(icompr)
      go to 35
C-----WRITE THINNED DATA
 70   CONTINUE
      IF(IRET.EQ.0) GO TO 51
C--SET DATA COMPRESSION OPTION
      CALL UFCMPR(ILUNO,ICOMPR)
      CALL UFOPWR(ILUNO,ISHOT,IER)
      IF(IER.NE.0) THEN
        CALL UCLEAR
        GO TO 290
      ENDIF
C
      IPROC=IPROCP
C
 116  CONTINUE
C
      CALL UF1DWR(ILUNO,IDEV,ZSDATE,XT,YT,IRET,IPROC,XLAB,YLAB,
     >	   NUMSC,XTRVAL,XTRLAB,IER)
C
C-----APPEND COMMENTS
      IF(IER.NE.0)CALL UCLEAR
      IF(IER.NE.0) GO TO 280
      CALL UFSNAM(ISHOT,ZFILE,IER,ILUNI)
      WRITE(ILUNT,4001) ZFILE
 4001 FORMAT(' PRODUCED BY PROGRAM THIN1 [TRANSP]'/
     >         ' FROM INPUT FILE: "',A,'"')
C
C-----GET USER COMMENTS
      CALL UFACOM(ILUNT)
      CALL UCSEND(ILUNT,ILUNO)
      CALL USPOOL(ILUNI,ILUNO)
 280  CONTINUE
      CALL UFCLOS(ILUNO)
 290  CONTINUE
      GO TO 30
C
C
C-----EXIT PROGRAM NOW
C
 20   CONTINUE
      CALL UEXITA
      STOP
      END
C******************** END FILE THIN1.FOR ; GROUP THNVRG ******************
