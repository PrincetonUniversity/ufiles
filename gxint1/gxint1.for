C******************** START FILE GXINT1.FOR ; GROUP GXINT1 ******************
C------------------------------------------------------------
C  GXINT1
C
C  INTERPOLATE DATA
C  A "TARGET" FILE IS READ WHICH CONTAINS THE X VALUES TO WHICH
C  TO INTERPOLATE
C
C  THEN EACH INPUT FILE IS READ AND ITS DATA INTERPOLATED TO THE
C  SEQUENCE OF X VALUES DEFINED BY THE "TARGET" FILE
C
C  WARNING ERRORS-- UNITS LABELS OF X ARRAYS OF TARGET AND INPUT
C   FILES DO NOT AGREE, OR, SOME EXTRAPOLATION REQUIRED
C
C  FATAL ERROR-- INTERSECTION OF RANGE COVERED BY TARGET AND INPUT
C   X VECTORS IS NULL SET
C
      PROGRAM GXINT1
C
C  MAX NUMBER ASSOCIATED KEYWORD SCALAR QUANTITIES
C
      PARAMETER (MAXSC=100)
C  MAX NUMBER OF PTS IN DATA
      PARAMETER (JDSIZ=102400)
C
      REAL XTARG(JDSIZ),XIN(JDSIZ),YIN(JDSIZ),YOUT(JDSIZ)
      INTEGER IORDER(MAXSC)
      CHARACTER*10 ZSDATE,XLAB(3),YLAB(3),XTRLAB(3,MAXSC,3),
     >     ZSHID,ZDATE,ZTUNS
C
      CHARACTER*40 ZFILE,ZFILET
      CHARACTER*4 IDEV
      REAL XTRVAL(MAXSC,3)
C-----------------------------
C  PROGRAM MOD APR 1984 DMC-- DEAL WITH VAX COMPRESSED UFILES DATA
C   FORMATTED COMMENTS FOR THE OUTPUT FILE ARE PUT IN A TEMPORARY FILE
C   WHICH IS SPOOLED TO THE PERMANENT FILE WHICH IS OPTIONALLY BINARY-
C   COMPRESSED.
C  USER MAY SELECT COMPRESSED OR UNCOMPRESSED DATA OUTPUT
C
      CHARACTER*7 CMPSTA(0:4)
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  COMPRESSED DATA OUTPUT DEFAULT FLAG, =1 FOR COMPRESSION ON
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  L.U.N. FOR TEMPORARY COMMENTS FILE
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C-------------------------------
C
C  LUN FOR TARGET DATA INPUT
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  LUN FOR INPUT DATA
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  LUN FOR OUTPUT DATA
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  LUN FOR TEMPORARY COMMENTS FILE
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  DATA BUFFER SIZE--
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR,lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => GXINT1               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA CMPSTA/'ascii','????','binary','HDF','NetCDF'/
      data icompr/2/  ! default:  portable binary
      DATA ILUNTC/99/
      DATA ILUNTA/21/
      DATA ILUNI/22/
      DATA ILUNO/23/
      DATA ILUNC/24/
C => END DATA BLOCK
C ====================
C
      itoggl=icompr
C
      MAXD=JDSIZ
C
      call ufheader("gxint1")
      call date_and_time(DATE=zdate)
      CALL UINITG("GXINT1")
CC	CALL USINIT
CC	CALL UAHEAD
      call urdext('ifi')
      ITARG=0
      ZFILET='            *** UNDEFINED ***          '
      IINP=0
      luntrm=lnout(0)
C
 10   CONTINUE
      CALL UFNTER(ILUNI,'INPUT-UNINTERPOLATED')
      CALL UFNTER(ILUNO,'OUTPUT- INTERPOLATED')
C
 15   CONTINUE
C  TOP NODE--
      CALL NEUPAG
 16   CONTINUE
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'UNINTERPOLATED INPUT',ILUNI)
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,' INTERPOLATED OUTPUT',ILUNO)
      IF(LXOUT(0).AND.(IINP.GT.0)) WRITE(LUNTRM,1003) ISHOT
 1003 FORMAT('     [ INPUT DATA SHOT:  ',I6,']')
      IF(LXOUT(0)) WRITE(LUNTRM,1001) ZFILET
 1001 FORMAT(' ==> SOURCE FILE FOR INTERPOLATION TARGET X VALUES: '/
     >     10X,A)
      IF(LXOUT(0).AND.(ITARG.EQ.0)) WRITE(LUNTRM,1000)
 1000 FORMAT(
     >  '  ** DEFINE SOURCE FILE FOR INTERPOLATION TARGET FIRST **'/
     >  '     USE OPTION T')
      IF(LXOUT(0).AND.(ITARG.EQ.1)) WRITE(LUNTRM,1300) ZTUNS,
     >     NTARG,XTARG(1),XTARG(NTARG)
      IF(LXOUT(0).AND.(IINP.EQ.1)) WRITE(LUNTRM,1301) XLAB(3),
     >     NIN,XIN(1),XIN(NIN)
      IF(LXOUT(0).AND.(ITARG.EQ.1).AND.(IINP.EQ.0)) 
     >   WRITE(LUNTRM,1004)
 1004 FORMAT('  ... USE OPTION I TO READ AND INTERPOLATE DATA')
      IF(LXOUT(0)) WRITE(LUNTRM,1002) CMPSTA(ICOMPR)
 1002 FORMAT(/' GXINT1 TOP NODE OPTIONS:'/
     >  ' C - TOGGLE DATA OUTPUT FORMAT FLAG (CURRENTLY "',A,'")'/
     >  ' 4 - *new* Ufile output format control menu'/
     >  ' G - PLOT UNINTERPOLATED DATA'/
     >  ' I - READ AND INTERPOLATE DATA'/
     >  ' P - PLOT INTERPOLATED DATA'/
     >  ' D - DISPLAY/MODIFY KEYWORD SCALAR DATA'/
     >  ' R - RESET INPUT AND OUTPUT FILENAMES'/
     >  ' T - (RE)DEFINE *TARGET* FILE'/
     >  ' W - WRITE THE OUTPUT FILE'/
     >  ' X - EXIT - STOP GXINT1'/)
      CALL UREAD('GXINT1:  ENTER OPCODE (G/I/P/D/R/T/W/X/Q):$$')
C
      IOP=IXUOPC('C4GIPDRTWXQ$')
      CALL UCHKOP(IOP,0,1,100,-1,*16)
      GO TO (18,19,100,300,200,50,10,20,500,900,900) IOP
C              C  4  G   I   P   D  R  T  W   X    Q
C
C  TOGGLE COMPRESSED OUTPUT DATA FLAG
C
 18   CONTINUE
      ICOMPR=ITOGGL-ICOMPR
      GO TO 15
C
 19   continue
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      go to 15
C
C  DEFINE TARGET FILE
C
 20   CONTINUE
      IF(IINP.GT.0) CALL CLOSC(ILUNI,ILUNC)
      IINP=0
      CALL UFNTER(ILUNTA,'X-PTS TARGET FILE   ')
 21   CALL UREAD(
     >   'GXINT1: ENTER SHOT NUMBER FOR TARGET DATA FILE'//
     >   ', "0" TO ABORT:$$')
      ISTARG=IDCOD(IERT)
      IF(LCHAR('Q')) GOTO 15
      IF(IERT.NE.0) GO TO 21
      IF(ISTARG.EQ.0) GO TO 15
C  GET DATA
      CALL UFOPRD(ILUNTA,ISTARG,IER)
      IF(IER.NE.0) THEN
        CALL UCLEAR
        GO TO 21
      ENDIF
C  READ DATA
      CALL UF1DRD(ILUNTA,IDEV,ZSDATE,XTARG,YIN,JDSIZ,NTARG,IPROC,
     >     XLAB,YLAB,MAXSC,NUMSC,XTRVAL,XTRLAB,IER)
C
      IF(IER.NE.0) GO TO 29
C  CHECK FOR MONOTONICITY
      INM1=NTARG-1
      IF(INM1.LE.0) THEN
        WRITE(LUNTRM,9021)
 9021 FORMAT(' ? TARGET FILE CONTAINS TOO FEW POINTS IN X ARRAY')
        IER=1
        CALL UERJMP(1,*29)
      ENDIF
      DO 24 I=1,INM1
      IP1=I+1
      IF(XTARG(I).GE.XTARG(IP1)) THEN
        WRITE(LUNTRM,9024)
 9024 FORMAT(' ? TARGET FILE X ARRAY IS NOT MONOTONIC')
        IER=1
        CALL UERJMP(1,*29)
      ENDIF
 24   CONTINUE
C
C  SET FLAG AND COPY UNITS-- NOTE THAT ONLY "XTARG" AND "NTARG" ARE
C  SAVED PERMANENTLY
      ITARG=1
      ZTUNS=XLAB(3)
C  TARGET FILENAME
      CALL UFSNAM(ISTARG,ZFILET,IERTMP,ILUNTA)
C
 29   CONTINUE
      IF(IER.NE.0) THEN
        CALL UCLEAR
        ITARG=0
        IINP=0
      ENDIF
      CALL UFCLOS(ILUNTA)
      GO TO 15
C-----------------------
C  EXAMINE/MODIFY SCALARS
C
 50   CONTINUE
      IF(IINP.EQ.0) GO TO 991
      IF(NUMSC.EQ.0) THEN
        WRITE(LUNTRM,1005)
 1005   FORMAT(' % NO SCALAR DATA IN FILE')
        CALL UPAUST(0)
                     ELSE
        CALL UFSCLK(ILUNO,ISHOT,NUMSC,XTRVAL,XTRLAB,IORDER,1,ILUNC)
      ENDIF
      GO TO 15
C----------------------
C  GRAPH INPUT DATA
C
 100  CONTINUE
      IF(IINP.EQ.0) GO TO 991
      CALL GRFUF1(XIN,YIN,NIN,IPROC,YLAB,XLAB,ISHOT,IDEV,ZSDATE,
     >     NUMSC,XTRVAL,XTRLAB)
      GO TO 15
C-------------------------
C  GRAPH INTERPOLATED OUTPUT DATA
C
 200  CONTINUE
      IF(IINP.EQ.0) GO TO 991
      CALL GRFUF1(XTARG,YOUT,NTARG,IPROC,YLAB,XLAB,ISHOT,IDEV,
     >     ZSDATE,NUMSC,XTRVAL,XTRLAB)
      GO TO 15
C---------------------------
C  ** READ AND INTERPOLATE DATA **
C
 300  CONTINUE
      IF(IINP.GT.0) CALL CLOSC(ILUNI,ILUNC)
      IINP=0
      CALL NEUPAG
      IF(ITARG.EQ.0) GO TO 992
C  GET SHOT NUMBER
 301  CALL UREAD('GXINT1:  ENTER SHOT NUMBER:$$')
      ISHOT=IDCOD(IERT)
      IF(LCHAR('Q')) GOTO 15
      IF(IERT.NE.0) GO TO 301
C  OPEN INPUT FILE
      CALL UFOPRD(ILUNI,ISHOT,IER)
      IF(IER.NE.0) THEN
        CALL UCLEAR
        GO TO 15
      ENDIF
C  READ INPUT DATA
      CALL UF1DRD(ILUNI,IDEV,ZSDATE,XIN,YIN,JDSIZ,NIN,IPROC,
     >     XLAB,YLAB,MAXSC,NUMSC,XTRVAL,XTRLAB,IER)
      IF(IER.NE.0) THEN
        CALL UCLEAR
        CALL UFCLOS(ILUNI)
        GO TO 15
      ENDIF
C  OPEN TEMPORARY FILE FOR COMMENTS
      OPEN(UNIT=ILUNC,FILE='ZZUSPL.DAT',status='UNKNOWN')
      WRITE(ILUNC,7001)
 7001 FORMAT('   ')
C  CHECK INPUT DATA -- MONOTONICITY -- X ARRAY UNITS AND
C    IF EXTRAPOLATION IS NECESSARY
C
      IF(NIN.LT.2) THEN
        CALL UERMSG('? TOO FEW POINTS IN DATA FILE',' ',1)
        CALL CLOSC(ILUNI,ILUNC)
        GO TO 15
      ENDIF
      INM1=NIN-1
      DO 310 I=1,INM1
      IP1=I+1
      IF(XIN(IP1).LE.XIN(I)) THEN
        CALL UERMSG('? INPUT DATA X ARRAY NON-MONOTONIC',' ',1)
        CALL CLOSC(ILUNI,ILUNC)
        GO TO 15
      ENDIF
 310  CONTINUE
C
 1300 FORMAT(/
     >  ' X TARGET ("',A,'"):  NPTS=',I6,' MIN,MAX = ',2(1PE10.3,1X))
 1301 FORMAT(/
     >' X INPUT DATA ("',A,'"):  NPTS=',I6,' MIN,MAX = ',2(1PE10.3,1X))
C
      IF((XTARG(1).GE.XIN(NIN)).OR.(XTARG(NTARG).LE.XIN(1))) THEN
      WRITE(LUNTRM,1300) ZTUNS,NTARG,XTARG(1),XTARG(NTARG)
      WRITE(LUNTRM,1301) XLAB(3),NIN,XIN(1),XIN(NIN)
        CALL UERMSG('? X DOMAINS DO NOT INTERSECT',' ',1)
        CALL CLOSC(ILUNI,ILUNC)
        GO TO 15
      ENDIF
      IWARN=0
      IF(ZTUNS.NE.XLAB(3)) THEN
      WRITE(LUNTRM,1300) ZTUNS,NTARG,XTARG(1),XTARG(NTARG)
      WRITE(LUNTRM,1301) XLAB(3),NIN,XIN(1),XIN(NIN)
        WRITE(LUNTRM,9310)
 9310   FORMAT(' % X DATA UNITS DO NOT MATCH EXACTLY')
        IWARN=1
      ENDIF
C
      IF((XIN(1).NE.XTARG(1)).OR.(XIN(NIN).NE.XTARG(NTARG))) THEN
      WRITE(LUNTRM,1300) ZTUNS,NTARG,XTARG(1),XTARG(NTARG)
      WRITE(LUNTRM,1301) XLAB(3),NIN,XIN(1),XIN(NIN)
        WRITE(LUNTRM,9320)
 9320   FORMAT(' % X DATA ENDPOINTS DO NOT MATCH EXACTLY')
        IWARN=1
      ENDIF
C  DATA ACCEPTED
      IF(IWARN.EQ.1) CALL UPAUST(0)
      IINP=1
C  DO INTERPOLATION
C    EXTRAPOLATIONS FIRST -- FLAT EXTRAPOLATION
      DO 330 I=1,NTARG
      IF(XTARG(I).LE.XIN(1)) YOUT(I)=YIN(1)
      IF(XTARG(I).GE.XIN(NIN)) YOUT(I)=YIN(NIN)
 330  CONTINUE
C    INTERPOLATIONS
      IST=1
      DO 340 I=1,NTARG
      IF((XTARG(I).LE.XIN(1)).OR.(XTARG(I).GE.XIN(NIN))) GO TO 340
      DO 335 J=IST,INM1
      JP1=J+1
      IF((XTARG(I).GT.XIN(J)).AND.(XTARG(I).LE.XIN(JP1))) GO TO 336
 335  CONTINUE
C  PROGRAM ERROR
      STOP 10
 336  CONTINUE
      IST=J
      YOUT(I)=YIN(J)+(YIN(JP1)-YIN(J))*(XTARG(I)-XIN(J))/
     >             (XIN(JP1)-XIN(J))
 340  CONTINUE
      GO TO 15
C------------------------
C  WRITE OUTPUT FILE
 500  CONTINUE
      IF(IINP.EQ.0) GO TO 991
      CALL UFCMPR(ILUNO,ICOMPR)
      CALL UFOPWR(ILUNO,ISHOT,IER)
      IF(IER.NE.0) GO TO 599
C
      CALL UF1DWR(ILUNO,IDEV,ZSDATE,XTARG,YOUT,NTARG,IPROC,
     >     XLAB,YLAB,NUMSC,XTRVAL,XTRLAB,IER)
      IF(IER.NE.0) THEN
        CALL UFCLOS(ILUNO)
        GO TO 599
      ENDIF
C
C  APPEND COMMENTS TO OUTPUT FILE
C
      CALL UFSNAM(ISHOT,ZFILE,IERTMP,ILUNI)
C
      CALL UFOPCF(ILUNTC,IER)
      WRITE(ILUNTC,4001) ZFILE,ZFILET
 4001 FORMAT('  ... PRODUCED BY PROGRAM GXINT1 [TRANSP] '/
     >   ' INTERPOLATED DATA FROM FILE "',A,'"'/
     >   ' TO X ARRAY POSITIONS IN FILE "',A,'"')
C  USER COMMENTS
      CALL UFACOM(ILUNTC)
C  SPOOLED COMMENTS
      REWIND ILUNC
      CALL USPOOL(ILUNC,ILUNTC)
C
      WRITE(ILUNTC,4008) ZDATE
 4008 FORMAT(/
     >  ' ==========================================================='/
     >  ' COMMENTS SPOOLED FROM FILE INPUT TO GXINT1 [TRANSP - PPL]'/
     >  ' ON VAX-780 ON DATE:  ',A10/)
      CALL USPOOL(ILUNI,ILUNTC)
      CALL UCSEND(ILUNTC,ILUNO)
C
C  CLOSE INPUT FILE AND CLEAR FLAG
C
      CALL UFCLOS(ILUNO)
      CALL CLOSC(ILUNI,ILUNC)
      IINP=0
      GO TO 15
C-----------
C  ERROR DURING WRITE - FLUSH INPUT
 599  CONTINUE
      IINP=0
      CALL UCLEAR
      CALL CLOSC(ILUNI,ILUNC)
      GO TO 15
C-----------------------------
C  ERRORS-- COMMANDS OUT OF ORDER
C
 991  CONTINUE
      CALL UERMSG('? DEFINE TARGET/ READ INPUT DATA FIRST',' ',-1)
      GO TO 16
 992  CONTINUE
      CALL UERMSG('? DEFINE X-TARGET ARRAY SOURCE FILE FIRST',' ',-1)
      GO TO 16
C--------------------
C  PROGRAM EXIT
 900  CONTINUE
      CALL NEUPAG
      CALL UEXITA(0)
      STOP
      	END
C******************** END FILE GXINT1.FOR ; GROUP GXINT1 ******************


C******************** START FILE CLOSC.FOR ; GROUP GXINT1 ******************
C------------------------------
C  CLOSC
C
C  CLOSE INPUT AND TEMPORARY FILES
C
      SUBROUTINE CLOSC(ILUNI,ILUNC)
C
      CLOSE(UNIT=ILUNC,status='DELETE')
      CALL UFCLOS(ILUNI)
      RETURN
      END
C******************** END FILE CLOSC.FOR ; GROUP GXINT1 ******************
