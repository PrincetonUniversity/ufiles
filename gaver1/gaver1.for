C******************** START FILE GAVER1.FOR ; GROUP GAVER1 ******************
C-----------------------------------------------------------
C  GAVER1
C  PROGRAM TO AVERAGE DATA INPUT FROM UFILES DATA FILE
C
      PROGRAM GAVER1
C
C  MAXIMUM NUMBER OF ASSOCIATED KEYWORD SCALAR QUANTITIES--
      PARAMETER (MAXSC=100)
C MAX NUMBER OF SHOTS AVERAGED TOGETHER
      PARAMETER (JLSHO=50)
C  MAX NUMBER OF POINTS IN DATA
      PARAMETER (JDSIZ=102400)
C
C  DATA BUFFERS AND LABELS
      REAL X(JDSIZ,2),Y(JDSIZ,2),XTRVAL(MAXSC,3)
      CHARACTER*10 ZSDATE,XLAB(3),YLAB(3),
     >     XTRLAB(3,MAXSC,3),ZSHID,ZDATE
      CHARACTER*64 ZFILE(JLSHO)
      REAL ZWGHT(JLSHO)
      CHARACTER*10 ZZDATE,ZXLAB(3),ZYLAB(3)
      CHARACTER*4 IDEV(2)
      INTEGER LSHOT(JLSHO),IORDER(MAXSC,3),NUMSC(3)
      LOGICAL IORDRX(2)
C
      REAL XRANGE(2,JLSHO),XTRAP(JLSHO)
      LOGICAL INTERP,IVFILE,IWGHT,ISUM
C-----------------------------
C  DMC 15 JULY 1986 - NEW FEATURES:  VARY AVERAGING WEIGHT
C  VARY INPUT FILENAME (DEFAULT-- FALSE)
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C-----------------------------
C  MOD DMC JUNE 1986-- ADDED INTERPOLATION CAPABILITY
C   IF INPUT FILES DO NOT HAVE PRECISELY MATCHING INPUT COORDINATES
C   USE THE 1ST INPUT FILE AS "MASTER", INTERPOLATE SUBSEQUENT INPUT
C   FILES TO ITS INDEP. COORDINATES BEFORE AVERAGING
C   EXTRA COMMENT OUTPUT ADDED TO UFILE TO DOCUMENT
C
C-----------------------------
C  PROGRAM MOD APR 1984 DMC-- DEAL WITH VAX COMPRESSED UFILES DATA
C   FORMATTED COMMENTS FOR THE OUTPUT FILE ARE PUT IN A TEMPORARY FILE
C   WHICH IS SPOOLED TO THE PERMANENT FILE WHICH IS OPTIONALLY BINARY-
C   COMPRESSED.
C  USER MAY SELECT COMPRESSED OR UNCOMPRESSED DATA OUTPUT
C
      CHARACTER*7 CMPSTA(0:4)
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  COMPRESSED DATA OUTPUT DEFAULT FLAG, =1 FOR COMPRESSION ON
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  L.U.N. FOR TEMPORARY COMMENTS FILE
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C-------------------------------
C
C  L.U.N FOR DATA INPUT
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  L.U.N FOR DATA OUPUT
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  L.U.N. FOR TEMPORARY FILE-- COMMENT SPOOLING
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  DATA BUFFER SIZE--
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL I1ORDER
      LOGICAL LARCMP
      LOGICAL LBLCMP
      LOGICAL LCHAR
      LOGICAL LYES
      LOGICAL LYESC
      logical lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => GAVER1               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA ISUM/.FALSE./
      DATA IWGHT/.FALSE./
      DATA IVFILE/.FALSE./
      DATA CMPSTA/'ascii','????','binary','HDF','NetCDF'/
C
      DATA ICOMPR/2/  ! default:  portable binary
C
      DATA ILUNC/99/
      DATA ILUNI/21/
      DATA ILUNO/22/
      DATA ILUNT/23/
C => END DATA BLOCK
C ====================
C
      itoggl=icompr
C
      MAXD=JDSIZ
C  MAX NUMBER OF SHOTS IN AVERAGE
      MAXSHO=JLSHO
C
      call date_and_time(DATE=zdate)
      CALL UINITG("GAVER1")
      luntrm=lnout(0)
C
      call urdext('ifi')
C
 10   CONTINUE
C
      CALL UFNTER(ILUNI,'1D INPUT FILES - RAW')
C
      CALL UFNTER(ILUNO,'OUTPUT FILE- AVERAGE')
C
C  CLEAR NUMBER OF SHOTS--
C
 12   CONTINUE
      NSHOTS=0
      INTERP=.FALSE.
      NUMSC(1)=0
C
C  CLEAR AVERAGED DATA (SUMMED ARRAY)
C
      DO 13 I=1,MAXD
        Y(I,1)=0.0
 13   CONTINUE
C
C---
C  TOP NODE-- AVG MORE DATA, WRITE OUTPUT FILE, START OVER, QUIT
 15   CONTINUE
      IMENU=1
      CALL NEUPAG
C
 16   IF(LXOUT(0)) THEN
        CALL UFSNMD(LUNTRM,'               INPUT',ILUNI)
        CALL UFSNMD(LUNTRM,'              OUTPUT',ILUNO)
        WRITE(LUNTRM,1010) NSHOTS,INTERP,NUMSC(1),
     >      CMPSTA(ICOMPR)
C
 1010 FORMAT(/
     >' CURRENTLY ',I2,' SHOTS IN AVERAGE; INTERPOLATION FLAG = ',L1/
     >' CURRENTLY ',I3,' KEYWORD SCALARS IN AVERAGED DATA LIST'/
     >' GAVER1 TOP NODE OPTIONS:'/
     >'   A - AVERAGE - AVERAGE/SUM MORE DATA'/
     >'   C - COMPRESS- TOGGLE OUTPUT DATA FORMAT FLAG, NOW "',A,'"'/
     >'   4 - FORMAT  - *new* Ufile output format control menu'/
     >'   D - DISPLAY - DISPLAY/MODIFY AVERAGED KEYWORD SCALAR DATA'/
     >'   L - LIST    - LIST SHOTS AVERAGED OR SUMMED'/
     >'   1 - PRESET  - PRESET PLOT SCALING/AXES DEFAULTS'/
     >'   P - PLOT    - PLOT THE AVERAGED/SUMMED DATA'/
     >'   R - RESET   - RESET INPUT AND OUTPUT FILENAMES'/
     >'   S - START   - START OVER: SET # OF SHOTS AVERAGED TO 0'/
     >'   W - WRITE   - WRITE THE OUTPUT AVERAGED/SUMMED DATA FILE'/
     >'   X - EXIT    - STOP'/)
C
      ENDIF
C
      CALL UREAD('GAVER1: ENTER OPCODE (A/D/L/P/R/S/W/X/Q):$')
      IOP=IXUOPC('1AC4DLPRSWXQ$')
      CALL UCHKOP(IOP,0,1,100,-1,*16)
      GO TO (17,20,18,14,600,350,300,10,12,200,19,19) IOP
C
 17   CONTINUE
      CALL GPRESET
      GO TO 15
C
 14   CONTINUE
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      go to 15
C
 18   CONTINUE
      ICOMPR=ITOGGL-ICOMPR
      GO TO 15
C
 19   CONTINUE
      CALL NEUPAG
      CALL UEXITA(0)
      STOP
C---------
C
 20   CONTINUE
C
C  INPUT LOOP - DATA TO AVERAGE
C
      IMENU=2
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,1020) IWGHT,ISUM,IVFILE,NSHOTS
 1020   FORMAT(/' NEW INPUT FILE OPTIONS :'/
     >'  ENTER "W" TO SET/CANCEL VARIABLE AVG WEIGHTING (=',L1,')'/
     >'    POSITIVE WEIGHTING FACTORS REQUIRED'/
     >'  ENTER "S" FOR VARIABLE WEIGHTED ',
     >     'SUMMING/DIFFERENCING OPTION (=',L1,')'/
     >'    NEGATIVE WEIGHTING FACTORS ALLOWED, BUT SUMMED DATA'/
     >'    WILL NOT HAVE SUM OF WEIGHTS DIVIDED OUT-- ** NO AVERAGE **'/
     >'  ENTER "F" TO SET/CANCEL VARIABLE FILENAME FORM (=',L1,')'/
     >'  ENTER "L" TO LIST SHOTS SUMMED SO FAR (NSHOTS=',I2,')'/
     >'  ENTER "P" TO PLOT DATA SUMMED/AVERAGED SO FAR'/)
C
      CALL UREAD(
     >'GAVER1: ENTER 5 DIGIT INPUT SHOT # OR "X" TO EXIT INPUT LOOP:$')
C
C  CHECK LETTER OPTIONS
C
      IF(LCHAR('X')) GO TO 15
      IF(LCHAR('Q')) GO TO 15
      IF(LCHAR('P')) GO TO 300
      IF(LCHAR('L')) GO TO 350
C
      IF(LCHAR('F')) THEN
        IVFILE=.NOT.IVFILE
        GO TO 20
      ELSE IF(LCHAR('W')) THEN
        IWGHT=.NOT.IWGHT
        IF(IWGHT) ISUM=.FALSE.
        GO TO 20
      ELSE IF(LCHAR('S')) THEN
        ISUM=.NOT.ISUM
        IF(ISUM) IWGHT=.FALSE.
        GO TO 20
      ENDIF
C
C  NOT A LETTER OPTION - GET SHOT NUMBER
C
      ISHOT=IDCOD(IERT)
      IF(IERT.NE.0) GO TO 20
C
      IF(IVFILE) CALL UFNTER(ILUNI,'2D INPUT FILES - RAW')
C
      CALL UFOPRD(ILUNI,ISHOT,IER)
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 20
C
      ISP=MIN0(2,(NSHOTS+1))
      CALL UF1DRD(ILUNI,IDEV(ISP),ZZDATE,
     >   X(1,ISP),Y(1,2),JDSIZ,IRET,JPROC,
     >   ZXLAB,ZYLAB,
     >   MAXSC,NUMSC(2),XTRVAL(1,2),XTRLAB(1,1,2),IER)
C
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 190
C  CHECK THE DATA
      IF(ISP.EQ.2) GO TO 50
      IER2=0
C  FIRST SHOT
      IPROC=JPROC
      IF((IPROC.EQ.0).OR.(IPROC.EQ.2)) GO TO 30
      IF(IPROC.GT.3) GO TO 30
      IER2=1
      WRITE(LUNTRM,9091)
 9091 FORMAT(' % DATA IN INPUT FILE ALREADY AVERAGED.')
 30   CONTINUE
C
      NRET=IRET
C
      ZSDATE=ZZDATE
C
      DO 33 I=1,3
          XLAB(I)=ZXLAB(I)
          YLAB(I)=ZYLAB(I)
 33   CONTINUE
C
      IORDRX(1)=I1ORDER(X(1,1),NRET,XRANGE(1,1))
C
      GO TO 100
C----------
C  NOT THE FIRST SHOT.  CHECK FOR DISCREPANCIES
 50   CONTINUE
C
      IORDRX(2)=I1ORDER(X(1,2),IRET,XRANGE(1,NSHOTS+1))
C
      IER2=0
      IF(.NOT.INTERP) THEN
C  CHECK FOR DIFFERENT X ARRAY, REQUIRING INTERPOLATION
        ZABS=0.0
        ZREL=0.005
        IF(LARCMP(X(1,1),NRET,X(1,2),IRET,ZABS,ZREL,IPT)) GO TO 52
        WRITE(LUNTRM,9051) LSHOT(1),ISHOT,XLAB(1),XLAB(2),XLAB(3)
 9051   FORMAT(/' ** WARNING: DATA CANNOT BE AVERAGED DIRECTLY'/
     >	  '   THE "X" ARRAYS FOR SHOTS ',I6,' AND ',I6,' ARE NOT'/
     >	  '   CONSISTANT  (X LABEL:  ',2A10,1X,A10,')')
        IF(IPT.EQ.0) WRITE(LUNTRM,9052) LSHOT(1),NRET,ISHOT,IRET
 9052   FORMAT('  SHOT ',I6,' X ARRAY HAS ',I6,' POINTS'/
     >		 '  SHOT ',I6,' X ARRAY HAS ',I6,' POINTS')
        IF(IPT.GT.0) WRITE(LUNTRM,9053)
     >	    IPT,LSHOT(1),X(IPT,1),ISHOT,X(IPT,2),ZABS,ZREL
 9053   FORMAT(
     >    '  POINT X(J), J= ',I6,' DOES NOT AGREE FOR THE 2 SHOTS'/
     >	  '  SHOT ',I6,':  X(J)= ',1PE11.4/
     >	  '  SHOT ',I6,':  X(J)= ',1PE11.4/
     >	  '  FAILED ABSOLUTE DIFFERENCE TEST (MAX DIFF = ',1PE11.4,')'/
     >	  '  FAILED RELATIVE DIFFERENCE TEST (MAX DIFF = ',1PE11.4,')'/)
          IER2=2
C
C  INTERPOLATION REQUIRED
C  CHECK ORDER CONSTRAINT
        IF(.NOT.IORDRX(1)) THEN
          IER2=3
          WRITE(LUNTRM,9054) LSHOT(1)
 9054 FORMAT(' ? X ARRAY FOR SHOT ',I6,' NOT ORDERED;'/
     >      '   DATA CANNOT BE INTERPOLATED.  NO AVERAGING POSSIBLE')
        ENDIF
C
        IF(.NOT.IORDRX(2)) THEN
          IER2=3
          WRITE(LUNTRM,9054) ISHOT
        ENDIF
C
      ELSE
C  INTERPOLATION IN EFFECT ALREADY.  CHECK ORDER ON NEW SHOT ONLY.
        IF(.NOT.IORDRX(2)) THEN
          IER2=3
          WRITE(LUNTRM,9054) ISHOT
        ENDIF
      ENDIF
C
C  CANNOT AVERAGE BECAUSE INTERPOLATION ON UNORDERED X REQUIRED
      IF(IER2.EQ.3) THEN
        CALL URSTOP(2)
        GO TO 190
      ELSE IF(IER2.EQ.2) THEN
C
C  TURN ON INTERPOLATION
        INTERP=.TRUE.
      ENDIF
C-----
 52   CONTINUE
      IF(IDEV(1).EQ.IDEV(2)) GO TO 55
      WRITE(LUNTRM,9057) IDEV(1),IDEV(2)
 9057 FORMAT(' % DATA TO BE AVERAGED FROM DIFFERENT TOKAMAKS:'/
     >  '   ORIGINAL SHOT DATA FROM:  "',A4,'"'/
     >  '   CURRENT SHOT DATA FROM:   "',A4,'"'/)
      IER2=MAX0(IER2,1)
C-----
 55   CONTINUE
      IF(ZZDATE.EQ.ZSDATE) GO TO 65
      WRITE(LUNTRM,9060) LSHOT(1),ZSDATE,ISHOT,ZZDATE
 9060 FORMAT(' % INPUT DATA HAS DIFFERENT SHOT DATE:'/
     >  '  SHOT ',I6,' DATE:  ',A10/
     >  '  SHOT ',I6,' DATE:  ',A10)
      IER2=MAX0(IER2,1)
C---
 65   CONTINUE
      IF(LBLCMP(XLAB,ZXLAB)) GO TO 70
      WRITE(LUNTRM,9062) LSHOT(1),(XLAB(IJ),IJ=1,3)
     >    ,ISHOT,(ZXLAB(IJ),IJ=1,3)
 9062 FORMAT(' % INPUT DATA HAS DIFFERENT X AXIS LABEL:'/
     >  '  SHOT ',I6,':  X LABEL = ',3A10/
     >  '  SHOT ',I6,':  X LABEL = ',3A10)
      IER2=MAX0(IER2,1)
C---
 70   CONTINUE
      IF(LBLCMP(YLAB,ZYLAB)) GO TO 75
      WRITE(LUNTRM,9063) LSHOT(1),(YLAB(IJ),IJ=1,3)
     >    ,ISHOT,(ZYLAB(IJ),IJ=1,3)
 9063 FORMAT(' % INPUT DATA HAS DIFFERENT Y AYIS LABEL:'/
     >  '  SHOT ',I6,':  Y LABEL = ',3A10/
     >  '  SHOT ',I6,':  Y LABEL = ',3A10)
      IER2=MAX0(IER2,1)
C---
 75   CONTINUE
      IF((JPROC.EQ.0).OR.(JPROC.EQ.2)) GO TO 80
      IF(JPROC.GT.3) GO TO 80
      WRITE(LUNTRM,9091)
      IER2=MAX0(IER2,1)
C--
 80   CONTINUE
C  CHECK AGAINST DUPLICATION OF SHOTS
      DO 85 I=1,NSHOTS
      IF(LSHOT(I).EQ.ISHOT) GO TO 86
 85   CONTINUE
      GO TO 100
C
 86   CONTINUE
      WRITE(LUNTRM,9095) ISHOT
 9095 FORMAT(' % SHOT ',I6,' HAS ALREADY BEEN AVERAGED')
      IER2=MAX0(IER2,1)
C
 100  CONTINUE
      IF(IER2.NE.0) CALL URSTOP(2)
C  COMPARE THE KEYWORD SCALARS
      CALL UFSCMP(XTRLAB,XTRVAL,IORDER,MAXSC,NUMSC,NSHOTS,ISHOT,IDIFS)
C
C  GRAPH THE DATA
      CALL UREAD('GAVER1:  ENTER "P" TO PLOT INPUT DATA:$')
      IF(.NOT.LYESC('P')) GO TO 110
      CALL GRFUF1(X(1,ISP),Y(1,2),IRET,JPROC,
     >    ZYLAB,ZXLAB,ISHOT,IDEV(ISP),ZZDATE,NUMSC(2),
     >    XTRVAL(1,2),XTRLAB(1,1,2))
C
C  AVERAGE THE DATA
C
 110  CONTINUE
      IF(IER2.NE.0) WRITE(LUNTRM,9081)
 9081 FORMAT(' % DISCREPANCY WARNINGS WERE ISSUED'/
     >  '   THE LABELS, ETC. FOR THE AVERAGED OUTPUT FILE'/
     >  '   ARE TAKEN FROM THE *FIRST* INPUT FILE'/)
      IF((IDIFS.NE.0).AND.(NSHOTS.GT.0)) WRITE(LUNTRM,9082)
 9082 FORMAT(' % NEWLY READ DATA FILE CONTAINS KEYWORD SCALARS'/
     >  '   AT VARIANCE WITH PREVIOUSLY AVERAGED DATA'/
     >  '   IF THIS DATA IS AVERAGED ANY NEW KEYWORDS WILL BE'/
     >  '   INSERTED IN THE AVERAGED DATA LIST, AND THE SCALAR'/
     >  '   VALUES IN THE NEW DATA LIST WILL BE AVERAGED WITH'/
     >  '   THOSE ALREADY IN THE AVERAGED DATA LIST.  LABELS IN'/
     >  '   THE AVERAGED SCALAR DATA LIST WILL NOT BE CHANGED'/)
      IF(INTERP) WRITE(LUNTRM,9083) LSHOT(1)
 9083 FORMAT(
     >' % DATA WILL BE INTERPOLATED TO SHOT ',I6,' X GRID BEFORE AVG')
      CALL UREAD('GAVER1:  AVERAGE THIS SHOT? (Y/N):$')
C
      IF(.NOT.LYES(0)) THEN
        IF(IER2.EQ.2) INTERP=.FALSE.  ! DATA REJECTED, CLEAR INTERP
        GO TO 190
      ENDIF
C
      NSHOTS=NSHOTS+1
      LSHOT(NSHOTS)=ISHOT
        CALL UFSNAM(LSHOT(NSHOTS),ZFILE(NSHOTS),IER,ILUNI)
C
C  CHECK FOR VARIABLE WEIGHTING FACTOR
      ZWGHT(NSHOTS)=1.0
      IF(IWGHT.OR.ISUM) THEN
 115    CONTINUE
        CALL UREADF('GAVER1:  SPECIFY WEIGHTING FACTOR FOR DATA:$',
     >	      ZWGHT(NSHOTS))
        IF(IWGHT.AND.(ZWGHT(NSHOTS).LE.0.0)) THEN
          CALL UERMSF(' % POSITIVE WEIGHT REQUIRED FOR AVERAGING',
     >	      ZWGHT(NSHOTS),1)
          GO TO 115
CX	  ELSE IF(ZWGHT(NSHOTS).EQ.0.0) THEN
CX	    CALL UERMSF(' % NON-ZERO WEIGHT REQUIRED FOR AVERAGING',
CX     >	      ZWGHT(NSHOTS),1)
CX	    GO TO 115
        ENDIF
      ENDIF
C
      IF(NSHOTS.EQ.1) THEN
        ZWGTOT=0.0
      ENDIF
C
C  AVERAGE THE SCALARS
C
      CALL UFSCAV(XTRLAB,XTRVAL,IORDER,NUMSC(1),
     >     XTRLAB(1,1,2),XTRVAL(1,2),IORDER(1,2),NUMSC(2),
     >	   ZWGTOT,ABS(ZWGHT(NSHOTS)),MAXSC)
C
C AVERAGE THE 2D DATA
C
      ZWGTOT=ZWGTOT+ABS(ZWGHT(NSHOTS))
C
      ITRAP=0
      DO 120 I=1,NRET
        IF(INTERP) THEN
          ZY=XINTR0(X(I,1),X(1,2),Y(1,2),IRET,IEX)
          IF(IEX.NE.0) ITRAP=ITRAP+1
        ELSE
          ZY=Y(I,2)
        ENDIF
        Y(I,1)=Y(I,1)+ZY*ZWGHT(NSHOTS)
 120  CONTINUE
      IF(INTERP) THEN
        ITRAP2=0
        DO 125 I=1,IRET
          ZY=XINTR0(X(I,2),X(1,1),Y(1,1),NRET,IEX)
          IF(IEX.NE.0) ITRAP2=ITRAP2+1
 125    CONTINUE
        XTRAP(NSHOTS)=100.0*
     >      AMAX1(FLOAT(ITRAP)/NRET,FLOAT(ITRAP2)/IRET)
        WRITE(LUNTRM,9085) LSHOT(NSHOTS),XTRAP(NSHOTS)
 9085 FORMAT(' % EXTRAPOLATION PERCENTAGE FOR SHOT ',I6,': ',F5.2)
        CALL UPAUST(0)
      ELSE
        XTRAP(NSHOTS)=0.0
      ENDIF
C  SPOOL COMMENTS TO OUTPUT FILE; OPEN IF ON FIRST SHOT
      IF(NSHOTS.EQ.1) THEN
        CALL UFOPCF(ILUNT,IER)
      ENDIF
      WRITE(ILUNT,7001) IPROC,ISHOT,ZDATE
 7001 FORMAT(
     >  ' =========================================================='/
     >  ' COMMENTS SPOOLED FROM FILE INPUT TO GAVER1 [IPROC=',
     >  I1,' SHOT=',I6,']:'/' ON VAX-11 ON DATE:  ',A10/)
      CALL USPOOL(ILUNI,ILUNT)
      WRITE(ILUNT,7002)
 7002 FORMAT(
     >  ' ----------------------------------------------------------')
C ---
C  BRANCH HERE ON ERROR OR NO AVERAGE:
C
 190  CONTINUE
      CALL UFCLOS(ILUNI)
      GO TO 20
C---------
 200  CONTINUE
      IF(NSHOTS.EQ.0) GO TO 15
C
      CALL UREAD(
     >	  'GAVER1:  ENTER 5 DIGIT SHOT NUMBER TO NAME OUTPUT FILE:$')
      IF(LCHAR('Q')) GO TO 15
C
      CALL NEUPAG
      ISHOT=IDCOD(IERT)
      IF(IERT.NE.0) GO TO 200
C  COMPRESS?
      CALL UFCMPR(ILUNO,ICOMPR)
      CALL UFOPWR(ILUNO,ISHOT,IER)
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 15
C
      IF(.NOT.ISUM) THEN
        DO 209 IS=1,NSHOTS
          ZWGHT(IS)=ZWGHT(IS)/ZWGTOT
 209    CONTINUE
C
        DO 210 I=1,NRET
          Y(I,1)=Y(I,1)/ZWGTOT
 210    CONTINUE
      ENDIF
C
      IF((IPROC.EQ.0).OR.(IPROC.EQ.2)) IPROC=IPROC+1
C
      CALL UF1DWR(ILUNO,IDEV(1),
     >   ZSDATE,X,Y,NRET,IPROC,XLAB,YLAB,NUMSC(1),XTRVAL,XTRLAB,IER)
C
C  APPEND COMMENTS TO FILE-- VIA TEMPORARY FILE
C
      CALL UFOPCF(ILUNC,IER)
C
      IF(IER.NE.0) GO TO 400
C
      WRITE(ILUNC,4001) NSHOTS
 4001 FORMAT(' >> AVERAGED/SUMMED DATA FROM ',I2,' INPUT FILES:'/
     >' ## WEIGHT      *  FILENAME'/
     >' -- ----------  ------------------')
      DO 395 IJ=1,NSHOTS
        WRITE(ILUNC,4002) IJ,ZWGHT(IJ),ZFILE(IJ)
 4002   FORMAT(1X,I2,1X,1PE10.3,2X,A)
C
        IF(INTERP) WRITE(ILUNC,4011)
     >      XRANGE(1,IJ),XRANGE(2,IJ),XLAB(3),XTRAP(IJ)
 4011 FORMAT('     X RANGE ',1PE11.4,' TO ',1PE11.4,1X,A/
     >         '     EXTRAPOLATION PERCENTAGE:  ',0PF5.2)
C
 395  CONTINUE
C
      WRITE(ILUNC,4005)
 4005 FORMAT('  AVERAGING PROGRAM NAME:  GAVER1 [TRANSP]'/)
C
C  GET USER COMMENTS
      CALL UFACOM(ILUNC)
C
C  SPOOL COMMENTS TO OUTPUT FILE-- NEW COMMENTS PLUS OLD COMMENTS FROM
C  THE INPUT FILES.
C
      CALL UCSEND(ILUNC,ILUNO)
      CALL UCSEND(ILUNT,ILUNO)
C  DONE.
      CALL UFCLOS(ILUNO)
C
      GO TO 12
C  CLOSE OUTPUT FILE ON WRITE ERROR
 400  CONTINUE
      CALL UFCLOS(ILUNO)
      GO TO 315
C-----------------------------
C  PLOT DATA AVERAGED SO FAR
C
 300  CONTINUE
      IF(NSHOTS.EQ.0) GO TO (15,20) IMENU
C
      IF(.NOT.ISUM) THEN
        DO 310 I=1,NRET
          Y(I,1)=Y(I,1)/ZWGTOT
 310    CONTINUE
      ENDIF
C
      IJPROC=IPROC
      IF((IPROC.EQ.0).OR.(IPROC.EQ.2)) IJPROC=IPROC+1
      CALL GRFUF1(X,Y,NRET,IJPROC,
     >   YLAB,XLAB,LSHOT(1),IDEV(1),ZSDATE,1,XTRVAL,XTRLAB)
 315  CONTINUE
C  UN-AVERAGE THE DATA
      IF(.NOT.ISUM) THEN
        DO 320 I=1,NRET
          Y(I,1)=Y(I,1)*ZWGTOT
 320    CONTINUE
      ENDIF
C
      GO TO (15,20) IMENU
C----------
C  LIST SHOTS IN AVERAGE
 350  CONTINUE
      IF(NSHOTS.EQ.0) GO TO (15,20) IMENU
C
      IF(.NOT.ISUM) THEN
        DO 309 IS=1,NSHOTS
          ZWGHT(IS)=ZWGHT(IS)/ZWGTOT
 309    CONTINUE
      ENDIF
C
      CALL NEUPAG
      WRITE(LUNTRM,3000)
