C******************** START FILE UFJMSG.FOR ; GROUP UFILS0 ******************
C--------------------------------------------------------------------
C  UFJMSG
C   RETRIEVE INFORMATIVE AND ERROR MESSAGE OUTPUT LEVELS
C    SEE ROUTINES UFEMSG AND UFIMSG
C
C   *THIS ROUTINE HAS NO AFFECT ON OUTPUT OF ERROR MESSAGES*
C   *THIS ROUTINE HAS NO AFFECT ON OUTPUT OF INFORMATIVE MESSAGES*
C
C   IT JUST RETURNS THE CURRENTLY STORED MESSAGE LEVEL FLAGS
C   IN FORM THAT THEY MAY BE PASSED BACK INTO UFIMSG AND UFEMSG
C   ROUTINES AS ARGUMENTS
C
      SUBROUTINE UFJMSG(IILEV,IELEV)
C
C  OUTPUTS:
C   IILEV - INFORMATIONAL MSG LEVEL (CF ARGUMENT TO UFIMSG)
C   IELEV - ERROR MESSAGE LEVEL (CF ARGUMENT TO UFEMSG)
C
      USE UFILES
C
      CALL UFINIT
C
C  ONES DIGIT OF UFILEV IS INFORMATIONAL MESSAGE FLAG
C  TENS DIGIT OF UFILEV IS ERROR MESSAGE FLAG
C
      IELEV=UFILEV/10
      IILEV=UFILEV-10*IELEV
C
      RETURN
      END
C******************** END FILE UFJMSG.FOR ; GROUP UFILS0 ******************
