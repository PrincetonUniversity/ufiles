C******************** START FILE THIN2.FOR ; GROUP THNVRG ******************
C-----PROGRAM TO THIN DATA-----
C================================
C-----WRITTEN BY A. ERLICH 4-4-85
C================================
C================================
      PROGRAM THIN2
C================================
C
C  DMC - CONVERTED FROM THIN2 SOURCE, 6 OCT 1986
C
C================================
C     COMMENTS: THIN2: DATA THINNING UTILITY: MAIN PROGRAM
C     1.)INTERACTIVELY ACCEPTS SHOT NUMBER FROM USER. 2.)GIVES
C        USER OPTIONS TO:(A)-QUIT PROGRAM,(B)-GET NEW SHOT,
C        (C)-PLOT UNTHINNED DATA,(D)-PLOT THINNED DATA,(E)-THIN
C        SOME DATA,(F)-WRITE THINNED DATA TO OUTPUT FILE
C       OPTIONS (C),(D) ABOVE ARE ACHIEVED BY CALLS TO GRFUF1,
C       OPTION (E) IS ACHIEVED BY A CALL TO THINSET,OPTION(F)
C       IS ACHIEVED BY A CALL TO UF1DWR.
C================================
C
C================================
C-----IDENTIFICATION SECTION-----
C================================
C
      PARAMETER (MAXSC=100)
      PARAMETER (JXSIZ=81695)
      PARAMETER (JDSIZ=1045696)
C
      REAL X(JXSIZ),Y(JXSIZ),XT(JXSIZ),YT(JXSIZ),WK(JXSIZ,2)
C
      REAL XTRVAL(MAXSC)
      REAL F(JDSIZ),FT(JDSIZ)
C
      CHARACTER*10 ZSDATE,XLAB(3),YLAB(3),FLAB(3),
     >	  XTRLAB(3,MAXSC),ZSHID,ZDATE,ZTITLE(3)
C
      CHARACTER*64 ZFILE
      CHARACTER*4  IDEV
      CHARACTER*3  CMPSTA(2)
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C-----L.U.N. TEMP. COMMENTS FILE
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C-----L.U.N. 2NDARY TEMP. COMMENTS FILE
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
      PARAMETER (MAXN=24000)
C-----L.U.N. FOR DATA INPUT
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C-----L.U.N. FOR DATA OUTPUT
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LXOUT
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => THIN2                BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA CMPSTA/'OFF','ON '/
      DATA ICOMPR/2/  ! default:  compressed binary, portable
      DATA ILUNT/24/
      DATA ILUNT2/26/
      DATA ILUNI/21/
      DATA ILUNO/22/
C => END DATA BLOCK
C ====================
C
      CALL UINITG("THIN2")
      LUNTRM=LNOUT(0)
      CALL UAHEAD
      CALL URDEXT('ifi')
C
C=======================================
C-----INTERACTIVE SECTION OF CODE BEGINS
C=======================================
C
 10   CONTINUE
      IST=0
      CALL UFNTER(ILUNI,'2D INPUT FILES RAW')
      CALL UFNTER(ILUNO,'OUTPUT FILES THINNED')
C
 30   CONTINUE
C
      IF(IST.NE.1)GO TO 31
      CALL UFCLOS(ILUNI)
C
 31   CONTINUE
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'               INPUT',ILUNI)
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'      THINNED OUTPUT',ILUNO)
C
      IRETX=0
      IRETY=0
      CALL URSHOT('THIN2',',0 OR Q TO QUIT, D TO CHANGE FILENAMES',
     >    'QD',ISHOT,IANS)
      IF (IANS.EQ.1) GO TO 20
      IF (IANS.EQ.2) GO TO 10
      IF(ISHOT.EQ.0) GO TO 20
      IST=1
C
C-----CREATE TEMP. FILE TO RECORD COMMENTS
      CALL UFOPCF(ILUNT,IER)
      WRITE(ILUNT,32)
 32   FORMAT('  ')
C-----
 33   CONTINUE
      CALL UFOPRD(ILUNI,ISHOT,IER)
      IF(IER.NE.0)THEN
        CALL UCLEAR
        GO TO 30
      ENDIF
C
      INF1=JDSIZ/JXSIZ
      CALL UF2DRD(ILUNI,IDEV,ZSDATE,F,INF1,X,JXSIZ,Y,JXSIZ,
     >     IPROC,NRETX,NRETY,1,
     >	   FLAB,XLAB,YLAB,MAXSC,NUMSC,XTRVAL,XTRLAB,
     >     IER)
C
      ISAVE=0
C
      ZTITLE(1)='SHOTDATE: '
      ZTITLE(2)=ZSDATE
C
      IF(IER.NE.0)THEN
        CALL UCLEAR
        GO TO 30
      ENDIF
C
      NCLEAR=0
C
 35   CONTINUE
C
      IF(LXOUT(0)) THEN
        CALL NEUPAG
        WRITE(LUNTRM,37) NRETX,IRETX,NRETY,IRETY,
     >	    (FLAB(IJ),IJ=1,3),
     >	    (XLAB(IJ),IJ=1,3),X(1),X(NRETX),
     >	    (YLAB(IJ),IJ=1,3),Y(1),Y(NRETY)
 37   FORMAT(/' F(X,Y) : NO. OF X PTS: ',I6,' (ORIG.), ',I6,' (CUR.)'/
     >'        : NO. OF Y PTS: ',I6,' (ORIG.), ',I6,' (CUR.)'/
     >' DATA LABELS: F = ',2A10,1X,A10/
     >'        : X = ',2A10,1X,A10,' RANGE ',1PE11.4,' TO ',1PE11.4/
     >'        : Y = ',2A10,1X,A10,' RANGE ',1PE11.4,' TO ',1PE11.4/
     >)
      IF(ISAVE.EQ.0) THEN
        WRITE(LUNTRM,3701)
      ELSE
        WRITE(LUNTRM,3702) ISAVE
      ENDIF
 3701   FORMAT(' >>> READY TO THIN:  UFILE IMAGE DATA')
 3702   FORMAT(
     >' >>> READY TO THIN DATA, ALREADY THINNED ',I1,' TIME(S).')
C
        WRITE(LUNTRM,1000)
 1000 FORMAT(' THIN2 OPTIONS:'/
     >	' Q - QUIT PROGRAM NOW:'/
     >  ' S - GET NEW SHOT/ INPUT FILE:'/
     >  ' P - PLOT DATA (UNTHINED):'/
     >  ' T - PLOT DATA (THINNED):'/
     >  ' X - DEFINE THINNING OPERATION *ON X* AND THIN THE DATA'/
     >  ' Y - DEFINE THINNING OPERATION *ON Y* AND THIN THE DATA'/
     >  ' Z - **SAVE** LAST THINNING OPERATION RESULTS'/
     >  '   USE OPTION Z BEFORE THINNING ALREADY THINNED DATA'/
     >  ' 4 - check/set format of output file'/
     >  ' W - WRITE DATA(AS JUST THINNED) TO OUTPUT FILE:')
C
      ENDIF
C
      CALL UREAD(' THIN2: ENTER OPT. CODE:$')
      IANS=IXUOPC ('QSPTXYWZ4$')
      IF(IANS.GT.0) GO TO (20,30,40,50,60,60,70,100,68) IANS
C
C
C-----PLOT UNTHINED DATA
 40   CONTINUE
      ZTITLE(3)=' ORIG.DATA'
      CALL GRF3(X,F,Y,WK,NRETX,NRETY,NRETX,
     >	  XLAB,YLAB,FLAB,XLAB(3),YLAB(3),FLAB(3),
     >	  ZTITLE,1,0,0,IDEV,ISHOT,0,ISHOT,1,0)
      GO TO 35
C-----PLOT THINNED DATA
 50    CONTINUE
      IF(IRETX.EQ.0) GO TO 51
      ZTITLE(3)=' THINNED  '
      CALL GRF3(XT,FT,YT,WK,IRETX,IRETY,NRETX,
     >	  XLAB,YLAB,FLAB,XLAB(3),YLAB(3),FLAB(3),
     >	  ZTITLE,1,0,0,IDEV,ISHOT,0,ISHOT,1,0)
      GO TO 35
 51   CONTINUE
      WRITE(LUNTRM,55)
 55   FORMAT(' % DATA MUST BE THINNED FIRST')
      GO TO 35
C-----PROCEED WITH OPTION TO THIN
 60   CONTINUE
C
      IAXIS=IANS-4
      CALL THINSET(ISHOT,X,XT,NRETX,Y,YT,NRETY,F,FT,NRETX,WK,JXSIZ,
     >	  IRETX,IRETY,IAXIS)
      GO TO 35
C-----FORMAT CHECK
 68   continue
      call ufmtsel(icompr)
      go to 35
C
C-----WRITE THINNED DATA
 70   CONTINUE
      IF(IRETX.EQ.0) GO TO 51
C--SET DATA COMPRESSION OPTION
      CALL UFCMPR(ILUNO,ICOMPR)
      CALL UFOPWR(ILUNO,ISHOT,IER)
      IF(IER.NE.0) THEN
        CALL UCLEAR
        GO TO 290
      ENDIF
C
 116  CONTINUE
C
      CALL UF2DWR(ILUNO,IDEV,ZSDATE,FT,NRETX,XT,IRETX,YT,IRETY,IPROC,
     >	  FLAB,XLAB,YLAB,NUMSC,XTRVAL,XTRLAB,IER)
C
C-----APPEND COMMENTS
      IF(IER.NE.0)CALL UCLEAR
      IF(IER.NE.0) GO TO 280
      CALL UFSNAM(ISHOT,ZFILE,IER,ILUNI)
      WRITE(ILUNT,4001) ZFILE
 4001 FORMAT(' PRODUCED BY PROGRAM THIN2 [TRANSP]'/
     >         ' FROM INPUT FILE: "',A,'"')
C
C-----GET USER COMMENTS
      CALL UFACOM(ILUNT)
      CALL UCSEND(ILUNT,ILUNO)
      CALL USPOOL(ILUNI,ILUNO)
 280  CONTINUE
      CALL UFCLOS(ILUNO)
 290  CONTINUE
      GO TO 30
C
C
C-----EXIT PROGRAM NOW
C
 20   CONTINUE
      CALL UEXITA
      STOP
C
C-----------/SAVE
 100  CONTINUE
C
      IA0=1-IRETX
      IA1=1-NRETX
      DO 110 IY=1,IRETY
        IA0=IA0+IRETX
        IA1=IA1+NRETX
        CALL COPYY(FT(IA1),1.0,F(IA0),IRETX)
 110  CONTINUE
C
      NRETX=IRETX
      NRETY=IRETY
      CALL COPYY(XT,1.0,X,NRETX)
      CALL COPYY(YT,1.0,Y,NRETY)
C
      IXY=IRETX*IRETY
      CALL COPYY(F,1.0,FT,IXY)
C
      IRETX=0
      IRETY=0
C
      ISAVE=ISAVE+1
      GO TO 35
C
      END
C******************** END FILE THIN2.FOR ; GROUP THNVRG ******************
