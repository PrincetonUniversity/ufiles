! CONCAT COMMON BLOCKS   D. MC CUNE MAY 82
! REBUILD DMC 20 MAR 1984-- TO SUPPORT VARIATION OVER FILENAME
! EXTENSION RATHER THAN SHOT NUMBER FOR CONCAT INPUT PHASE.
! ALSO ADDING ARRAY CAPACITY
!
module concat_mod
    
  integer, PARAMETER :: NIMAX=6553600
  integer, PARAMETER :: NXMAX=65536
  integer, PARAMETER :: NYMAX=65536
  integer, PARAMETER :: NSMAX=1000
  integer, PARAMETER :: NSCMAX=30
  !
  ! NIMAX-- BUFFER SIZE (MAX # SHOTS * # PTS. PER SHOT FILE)
  ! NXMAX-- MAX NUMBER OF PTS IN 1D INPUT FILES
  ! NYMAX-- MAX NUMBER OF DIMENSION-OF-CONCATENATION PTS IN OUTPUT FILE
  ! NSMAX-- MAX NUMBER OF INPUT PROFILES (BETWEEN-PROFILE INTERPOLATION
  !  MAKES IT POSSIBLE TO HAVE MORE Y PTS THEN INPUT PROFILES)
  ! NSCMAX-- MAX NUMBER OF ASSOCIATED SCALARS IN INPUT OR OUTPUT FILE
  !
  !
  ! INPUT BUFFER
  !  CAPACITY NIMAX WORDS  (==> NIMAX=NIMAX)
  !  FIN(NIMAX)  WILL HOLD MANY PROFILES SIMULTANEOUSLY
  !  XIN(NXMAX)   WILL HOLD X PTS FOR LAST INPUT PROFILE
  !               CAPACITY 200 PTS ==>NXMAX=200
  !  NX  --ASSUMED CONSTANT AFTER FIRST PROFILE IS READ IN--
  !      # OF X PTS IN EACH INPUT PROFILE
  !  NS-- # OF SHOTS (PROFILES) READ IN
  !            (NS*NX < NIMAX MUST BE MAINTAINED)
  !  ISHOTS(NSMAX)  LIST OF SHOT NUMBERS OF PROFILES READ IN
  !    THE JTH PROFILE IS EXPECTED TO HAVE THE SAME X PTS AS
  !    THE 1ST PROFILE, AND IS STORED IN FIN( (J-1)*NX+1 ... J*NX)
  !  YSHOTS(NSMAX)  ASSOCIATED Y VALUES OF PROFILES READ IN
  !    EXTRACTED FROM INPUT FILE KEYWORD SCALAR DATA
  !  XSHOTX(NSMAX)  ASSOCIATED FILENAME EXTENSIONS
  !  MODEI - MODE OF INPUT
  !   MODEI = 1:  SHOT LIST-- FILENAME EXTENSION FIXED
  !   MODEI = 2:  FILENAME EXTENSION LIST -- SHOT NO. FIXED
  !
  !
  ! NUMSC(NSMAX) -- NUMBER OF ASSOCIATED SCALARS IN INPUT FILE
  !  SCVALI(NSCMAX,NSMAX) -- VALUES OF KEYWORD SCALARS ASSOCIATED
  !  WITH EACH INPUT FILE
  !  SCLABI(3,NSCMAX,NSMAX) -- (30 CHAR) KEYWORD/LABEL/UNITS OF EACH
  !  SCALAR ASSOCIATED WITH EACH INPUT FILE
  !
  !  XLABI,YLABI,FLABI:  30 CHAR LABELS FROM INPUT FILE
  !
  !  IDEV -- TOKAMAK DEVICE OF INPUT FILE
  !  YKEY -- 10 CHAR KEYWORD OF SCALAR WHICH SHOULD CONTAIN Y VALUE
  !   ASSOCIATED WITH INPUT FILE *** MUST BE PRESENT IN SCALAR LIST
  !   OF EACH INPUT FILE
  ! LUNI-- LUN OF INPUT FILES
  ! LUNC-- LUN OF TEMPORARY COMMENT FILES
  ! LUNT-- ANOTHER LUN OF TEMPORARY COMMENTS
  !
  !  CFILID -- 2 CHAR IDS OF FILES TO WHICH INPUT FILE COMMENTS WERE
  !   SPOOLED (TEMPORARY FILES, LEFT TO BE DELETED BY PROCEDURE
  !   CONTROLLING CONCAT *** NAMES OF FORM ZCNC__.TMP WHERE __ IS
  !   REPLACED BY THE CONTENTS OF CFILID(J) FOR JTH INPUT FILE)
  !
  ! Y2(1...NY2) 2D INPUT FILE Y AXIS TO CONCATENATE INTO...
  !
  !COMMON/TVTINP/ FIN(NIMAX),XIN(NXMAX) &
  !     ,ISHOTS(NSMAX),YSHOT0(NSMAX),YSHOTS(NSMAX),Y2(NXMAX) &
  !     ,NX,NS,NY2,NITOT,SCVALI(NSCMAX,NSMAX) &
  !     ,LUNI,LUN2,LUNC,IPROCI,NUMSC(NSMAX) &
  !     ,MODEI,LJUNKDIR
  !
  REAL, DIMENSION(NIMAX) :: FIN
  REAL, DIMENSION(NXMAX) :: XIN
  INTEGER, DIMENSION(NSMAX) :: ISHOTS
  REAL, DIMENSION(NSMAX) :: YSHOT0
  REAL, DIMENSION(NSMAX) :: YSHOTS
  REAL, DIMENSION(NSMAX) :: Y2
  INTEGER :: NX, NS, NY2, NITOT
  REAL, DIMENSION(NSCMAX,NSMAX) :: SCVALI
  INTEGER :: LUN1, LUN2, LUNC
  INTEGER :: IPROCI
  INTEGER, DIMENSION(NSMAX) :: NUMSC
  INTEGER :: MODEI
  INTEGER :: LJUNKDIR
  !
  !COMMON/TVTINC/ XLABI(3),YLABI(3),FLABI(3),YKEY, &
  !     SCLABI(3,NSCMAX,NSMAX),IDEVI,CFILID(NSMAX),CFILNM, &
  !     ZSDATI,XSHOTX(NSMAX),CJUNKDIR
  !
  CHARACTER*10, DIMENSION(3) :: XLABI,YLABI,FLABI
  CHARACTER*10 :: YKEY,ZSDATI
  CHARACTER*10, DIMENSION(3,NSCMAX,NSMAX) :: SCLABI
  CHARACTER*20 :: cfilnm
  CHARACTER*4 :: IDEVI
  CHARACTER*2, DIMENSION(NSMAX) :: CFILID
  CHARACTER*10, DIMENSION(NSMAX) :: XSHOTX
  !
  CHARACTER*120 :: cjunkdir
  !
  ! OUTPUT ARRAY
  !
  ! F(NXO,NYO)  2D ARRAY FCN OF X AND Y FORMED BY JOINING
  !       OF INPUT PROFILES
  ! F2  SAME AS F WITH INDICES REVERSED
  ! NYO:  # OF Y PTS USED TO FORM OUTPUT ARRAY IN ITS CURRENT FORM
  !   (PROFILES READ IN + INTERPOLATIONS)
  ! NXO=NX=# OF X PTS FROM FIRST INPUT PROFILE
  ! X=XIN= X VECTOR FROM FIRST INPUT PROFILE.
  ! DIFFERENT ARRAYS ALLOW CHECK OF SUCCESSIVE INPUT FILES
  ! ISHOTX(NYMAX) SHOTS USED IN FORMING F
  ! YSHOTX(NYMAX) Y PTS OF SHOTS USED IN FORMING F
  ! Y  VECTOR USED IN DEFINING F
  !
  ! SCLAB,SCVAL -- KEYWORD LABEL AND VALUES LIST FOR OUTPUT FILE
  !  NUMSCO -- NUMBER OF SCALARS FOR OUTPUT FILE
  !  AVERAGED FROM INPUT DATA
  !
  ! LSHOT2,YSHOT2,WSHOT2 -- DATA ON INTERPOLATIONS BETWEEN PROFILES
  !
  ! XLAB,YLAB,FLAB -- OUTPUT DATA LABELS
  ! LUNO - LUN OF OUTPUT FILE
  ! NSHOTO -- SHOT NUMBER FOR NAMING OUTPUT FILE
  !
  ! ICOMPR -- OUTPUT DATA COMPRESSION FLAG, .gt. 0 FOR COMPRESSED OUTPUT
  ! ITOGGL -- toggle format btw ascii and ITOGGL
  !
  ! CMPSTA -- CHARACTER LABEL TO INDICATE COMPRESSION STATUS
  !
  ! NSHOT2 -- SHOT NUMBER OF INPUT 2D FILE (IF ANY) OR ZERO
  !
  !COMMON/TVTOUT/ F(NIMAX),F2(NIMAX),X(NXMAX),Y(NYMAX) &
  !   >     ,NFTOT,NXO,NYO,NSO,SCVAL(NSCMAX),LUNO,LUNT,NUMSCO &
  !   >     ,LSHOT2(2,NYMAX),YSHOT2(NYMAX),WSHOT2(NYMAX) &
  !   >     ,ISHOTX(NSMAX),YSHOTX(NSMAX),LSHOTX(NSMAX),IPROC &
  !   >     ,NSHOTO,ICOMPR,ITOGGL,NSHOT2
  REAL, DIMENSION(NIMAX) :: F, F2
  REAL, DIMENSION(NXMAX) :: X
  REAL, DIMENSION(NYMAX) :: Y
  INTEGER :: NFTOT,NXO,NYO,NSO,LUNO,LUNT,NUMSCO
  REAL, DIMENSION(NSCMAX) :: SCVAL
  INTEGER, DIMENSION(2,NYMAX) :: LSHOT2
  REAL, DIMENSION(NYMAX) :: YSHOT2, WSHOT2
  INTEGER, DIMENSION(NSMAX) :: ISHOTX, LSHOTX
  REAL, DIMENSION(NSMAX) :: YSHOTX
  INTEGER :: IPROC,NSHOTO,ICOMPR,ITOGGL,NSHOT2
  !
  !COMMON/TVTOUC/ SCLAB(3,NSCMAX),XLAB(3),YLAB(3),FLAB(3) &
  !     ,IDEV,ZSDATE,CMPSTA(0:4)
  CHARACTER*10, DIMENSION(3,NSCMAX) :: SCLAB
  CHARACTER*10, DIMENSION(NXMAX) :: XLAB,YLAB,FLAB
  CHARACTER*10 :: ZSDATE
  CHARACTER*4 :: IDEV
  CHARACTER*7 :: CMPSTA(0:4)
  !
end module CONCAT_MOD
