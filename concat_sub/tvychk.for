C----------------------------------------------------------------------
C  TVYCHK - CHECK Y (SCALAR KEY) VALUE OF CONCAT INPUT PROFILE
C
      SUBROUTINE TVYCHK(ZY,IXTRA,IER)
C
C  CHECK Y VALUE INPUT
C
      USE CONCAT_MOD
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      LUNTRM=LNOUT(0)
C
C  CHECK 2D INPUT Y VALUES THEN CHECK 1D PROFILE INPUT Y VALUES
C
 275  CONTINUE
      IF(NSHOT2.GT.0) THEN
        ZYMAX=ABS(Y2(1))
        ZYDIF=ABS(Y2(1)-ZY)
      ELSE
        ZYMAX=ABS(YSHOTS(1))
        ZYDIF=ABS(YSHOTS(1)-ZY)
      ENDIF
C
      ZYMAX=AMAX1(1.E-30,ZYMAX)
C
      IF(NSHOT2.GT.0) THEN
        IST=2
        DO IY=1,NY2
          ZYMAX=AMAX1(ZYMAX,ABS(Y2(IY)))
          ZYDIF=AMIN1(ZYDIF,ABS(Y2(IY)-ZY))
        ENDDO
      ELSE
        IST=1
      ENDIF
C
      DO IY=IST,NS
        ZYMAX=AMAX1(ZYMAX,ABS(YSHOTS(IY)))
        ZYDIF=AMIN1(ZYDIF,ABS(YSHOTS(IY)-ZY))
      ENDDO
C
      IF(IXTRA.GT.0) THEN
        DO IY=1,IXTRA
          ZYMAX=AMAX1(ZYMAX,ABS(YSHOT2(IY)))
          ZYDIF=AMIN1(ZYDIF,ABS(YSHOT2(IY)-ZY))
        ENDDO
      ENDIF
C
      IYERR=0
      IF(ZYDIF.EQ.0.0) THEN
        IYERR=1
      ELSE
        ZYREL=ZYDIF/ZYMAX
        IF(ZYREL.LT.0.333E-4) IYERR=1
      ENDIF
C
      IF(IYERR.EQ.1) THEN
        WRITE(LUNTRM,9017) YKEY,ZY
 9017   FORMAT(
     >' ?CONCAT -- INPUT KEY (Y) VALUE "',A,'" = ',1PE11.4,' INVALID:'/
     >'   VALUE ALREADY IN USE')
        CALL UCLEAR
        CALL UREAD(
     >'TVYCHK(CONCAT):  ENTER NEW KEY VALUE OR "Q" TO QUIT/BACKUP:$')
        IF(LCHAR('Q')) GO TO 295
        Z=FDCOD(IERT)
        IF(IERT.NE.0) GO TO 275
        ZY=Z
      ENDIF
C
C  NORMAL EXIT
      IER=0
      GO TO 300
C
C  ABORT EXIT
 295  CONTINUE
      IER=1
C
 300  CONTINUE
      RETURN
C
      END
