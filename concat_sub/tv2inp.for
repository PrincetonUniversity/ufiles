C-------------------------------------------------------------------
C  TV2INP  READ A 2D UFILE AT START OF CONCAT SESSION
C    ADDL PROFILES MAY BE INSERTED INTO THE 2D FILE SEQUENCE
C
      SUBROUTINE TV2INP(ZXMAX,IOFF)
C
      USE CONCAT_MOD
C
C  SET FILENAME FORM, SHOT NO. AND READ 2D INPUT FILE
C
      CHARACTER*40 ZFILE
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LYES
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      LUNTRM=LNOUT(0)
C
 10   CONTINUE
      CALL UFNTER(LUN2,'CONCAT 2D INPUT FILE')
      CALL UFSNMD(LUNTRM,'CONCAT 2D INPUT FILE',LUN2)
      NSHOT2=NSHOTO
 20   CONTINUE
      CALL URSHOT('CONCAT',', "Q" TO QUIT, "D" TO CHANGE NAMES','QD',
     >	  NSHOT2,IANS)
C
      IF(IANS.EQ.1) THEN
C  QUIT/ABORT
        NSHOT2=0
        RETURN
      ENDIF
C  CHANGE FILENAMING
      IF(IANS.EQ.2) GO TO 10
C
C  OPEN FILE
      CALL UFOPRD(LUN2,NSHOT2,IER)
      IF(IER.NE.0) THEN
        CALL UCLEAR
        GO TO 20
      ENDIF
C
C  READ FILE
      INF1=NIMAX/NXMAX
      CALL UF2DRD(LUN2,IDEV,ZSDATE,
     >    FIN,INF1,X,NXMAX,Y2,NYMAX,
     >    IPROC,NX,NY2,1,
     >    FLAB,XLAB,YLAB,
     >    NSCMAX,NUMSC(1),SCVALI(1,1),SCLABI(1,1,1),IER)
C
      IF(IER.NE.0) THEN
        CALL UFCLOS(LUN2)
        CALL UCLEAR
        GO TO 20
      ENDIF
C
      NS=1  ! SHOT READ IN
      ISHOTS(1)=0
      XSHOTX(1)='_2D'
C  SPOOL COMMENTS TO TEMPORARY OUTPUT FILE
      CALL CFNXID(CFILID(NS),1)
      CFILNM(5:6)=CFILID(NS)
      OPEN(UNIT=LUNC,FILE=CJUNKDIR(1:LJUNKDIR)//CFILNM,status='unknown')
      CALL UFSNAM(NSHOT2,ZFILE,IER,LUN2)
      WRITE(LUNC,3001) ZFILE,NSHOT2,IDEV,ZSDATE,IPROC
 3001 FORMAT(
     > ' ----------------------------------------------'/
     > '   **CONCAT 2D INPUT FILE**'/
     > ' ----------------------------------------------'/
     > ' COMMENTS SPOOLED BY "CONCAT" FROM FILE: '/'     "',A,'"'/
     > ' SHOT ',I6,1X,A4,1X,A10,' IPROC = ',I1,':'/)
      CALL USPOOL(LUN2,LUNC)
      CLOSE(UNIT=LUNC)
      CALL UFCLOS(LUN2)
C
      WRITE(LUNTRM,4001) (XLAB(IJ),IJ=1,3),(YLAB(IJ),IJ=1,3),YKEY
 4001   FORMAT(/
     >' 2D INPUT FILE X AXIS LABEL:  ',3A10/
     >' 2D INPUT FILE Y AXIS LABEL:  ',3A10/
     >'  ... CONCATENATION KEY = ',A10/
     >' CONCATENATION KEY MUST MATCH "Y" AXIS OF 2D INPUT FILE:')
C
      CALL UREAD(
     >'TV2INP:  ENTER "Y" TO SWAP X/Y AXES OF 2D INPUT FILE:$$')
C
      INUM=NX*NY2
      IF(LYES(0)) CALL UFSWXY(FIN,F2,INUM,X,NX,Y2,NY2,XLAB,YLAB)
C
      ZXMAX=0.0
      DO 120 I=1,NX
        ZXMAX=AMAX1(ZXMAX,ABS(X(I)))
 120  CONTINUE
C
      IOFF=(NY2-1)*NX
C
      RETURN
      END
