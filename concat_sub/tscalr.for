C******************** START FILE TSCALR.FOR ; GROUP CONCAT *************
C--------------------------------------------------------------
C  TSCALR
C  LOOK AT / COMPARE / MODIFY SCALAR LISTS FROM INPUT FILES
C
      SUBROUTINE TSCALR
C
      USE CONCAT_MOD
C
      INTEGER IORDER(NSCMAX,3),INUMSC(3),ICSHOT(3)
      REAL ZVAL(NSCMAX,3)
      CHARACTER*10  ZLAB(3,NSCMAX,3)
      logical lxout
C
      luntrm=lnout(0)
C
 10   CONTINUE
      CALL NEUPAG
 11   IF(LXOUT(0)) WRITE(LUNTRM,2001)
 2001 FORMAT(' TSCALR OPTIONS --'/
     >  ' L:LIST:   LIST INPUT FILENAMES W. SHOT NO.'/
     >  ' D:DISPLAY: DISPLAY OR MODIFY SCALARS FROM A PARTICULAR SHOT'/
     >  ' C:COMPARE: COMPARE SCALAR LISTS OF 2 INPUT SHOTS'/
     >  ' A:ALL:     COMPARE SCALAR LISTS OF ALL INPUT SHOTS'/
     >  '            TO THE LIST IN A PARTICULAR INPUT SHOT'/
     >  ' Q:QUIT:    EXIT THIS ROUTINE'/)
      CALL UREAD('TSCALR: ENTER OPCODE (L/D/C/A/Q):$')
      IOPT=IXUOPC('LDCAQ$')
      CALL UCHKOP(IOPT,0,1,100,-1,*11)
      GO TO (100,200,300,400,500) IOPT
C  LIST
 100  CONTINUE
      CALL XSHOTS(1)
      GO TO 10
C  DISPLAY/MODIFY
 200  CONTINUE
      CALL TSCGSH(ICSHOT(1),IND,IER)
      CFILNM(5:6)=CFILID(IND)
      IF(IER.EQ.1) GO TO 200
      IF(NUMSC(IND).EQ.0) GO TO 900
      OPEN(UNIT=LUNC,FILE=CJUNKDIR(1:LJUNKDIR)//CFILNM,
     >    STATUS='OLD',Position='APPEND')
      CALL UFSCLK(LUNI,ISHOTS(IND),NUMSC(IND),SCVALI(1,IND),
     >     SCLABI(1,1,IND),IORDER,1,LUNC)
      CLOSE(UNIT=LUNC)
      GO TO 10
C
 300  CONTINUE
      CALL TSCGSH(ICSHOT(1),IND1,IER)
      IF(IER.EQ.1) GO TO 200
      IF(NUMSC(IND1).EQ.0) GO TO 900
      CALL TSCGSH(ICSHOT(2),IND2,IER)
      IF(IER.EQ.1) GO TO 200
      IF(NUMSC(IND2).EQ.0) GO TO 900
      MAXSC=MAX0(NUMSC(IND1),NUMSC(IND2))
      INUMSC(1)=NUMSC(IND1)
      INUMSC(2)=NUMSC(IND2)
      DO 310 I=1,MAXSC
      ZVAL(I,1)=SCVALI(I,IND1)
      ZVAL(I,2)=SCVALI(I,IND2)
      DO 310 J=1,3
      ZLAB(J,I,1)=SCLABI(J,I,IND1)
      ZLAB(J,I,2)=SCLABI(J,I,IND2)
 310  CONTINUE
C
      CALL UFSCM2(ZLAB,ZVAL,IORDER,NSCMAX,INUMSC,ICSHOT,ID)
      GO TO 10
C
 400  CONTINUE
      CALL TSCGSH(ICSHOT(1),IND1,IER)
      IF(IER.EQ.1) GO TO 200
      INUMSC(1)=NUMSC(IND1)
      IF(INUMSC(1).EQ.0) GO TO 900
      DO 410 I=1,INUMSC(1)
      ZVAL(I,1)=SCVALI(I,IND1)
      DO 410 J=1,3
      ZLAB(J,I,1)=SCLABI(J,I,IND1)
 410  CONTINUE
C
      DO 420 IS2=1,NSO
      IND2=LSHOTX(IS2)
      IF(IND1.EQ.IND2) GO TO 420
      ICSHOT(2)=ISHOTS(IND2)
      INUMSC(2)=NUMSC(IND2)
      IF(INUMSC(2).EQ.0) GO TO 420
      DO 415 I=1,INUMSC(2)
      ZVAL(I,2)=SCVALI(I,IND2)
      DO 415 J=1,3
      ZLAB(J,I,2)=SCLABI(J,I,IND2)
 415  CONTINUE
C
      CALL UFSCM2(ZLAB,ZVAL,IORDER,NSCMAX,INUMSC,ICSHOT,ID)
C
 420  CONTINUE
      GO TO 10
C
 500  CONTINUE
      RETURN
C
 900  CONTINUE
      WRITE(LUNTRM,9001)
 9001 FORMAT(' % NO SCALARS IN SPECIFIED SHOT (FILE)')
      CALL URSTOP(1)
      GO TO 10
      END
C******************** END FILE TSCALR.FOR ; GROUP CONCAT ***************
