C******************** START FILE TVTINS.FOR ; GROUP CONCAT ******************
C============================================================
C  TVTINS
C
C  INSERT  EXTRA PROFILE(S) IN OUTPUT ARRAY
C
C  EXTRA PROFILES ARE WEIGHTED AVERAGES OF TWO CONSECUTIVE
C  LASER DATA PROFILES.  USER SUPPLIES WEIGHT W FOR 1ST PROFILE,
C  0 .LE. W .LE. 1, AND W' = 1-W IS WEIGHT FOR 2ND PROFILE, S.Y.
C    PROFILE = W*{1ST PROFILE} + W'*{2ND PROFILE}
C
      SUBROUTINE TVTINS
C
      USE CONCAT_MOD
C
      CHARACTER*3 ZEXT1,ZEXT2
C
      logical lxout
C
C  INITIAL--
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      IF(NSO.GT.0) GO TO 5
      IF(NSHOT2.GT.0) GO TO 5
C
      luntrm=lnout(0)
      WRITE(LUNTRM,9001)
 9001 FORMAT(' ? INSUFFICIENT INPUT DATA TO DEFINE EXTRA PROFILES'/
     >  '   FOR OUTPUT ARRAY.  MINIMUM OF ONE INPUT PROFILE'/)
      CALL UPAUST(1)
      RETURN
C---
 5    CONTINUE
C
 10   CONTINUE
C
      IF(NSHOT2.EQ.0) THEN
        IOFF=0
        IXTRA=NYO-NSO
      ELSE
        IOFF=(NY2-1)*NX
        IXTRA=NYO-NY2-NSO
      ENDIF
      CALL NEUPAG
 11   IF(LXOUT(0)) WRITE(LUNTRM,2001)
 2001 FORMAT(/
     >  '  "EXTRA PROFILES" ARE USER-SPECIFIED WEIGHTED AVERAGES'/
     >  '  OF TWO CONSECUTIVELY CONCATENATED INPUT DATA PROFILES'//
     >  '  EXTRAPOLATIONS ARE ALLOWED'//
     >  '  OPTIONS:'/
     >  ' I:INSERT:  INSERT (OR EXTRAPOLATE) AN EXTRA PROFILE'/
     >  ' D:DELETE:  DELETE PREVIOUSLY DEFINED EXTRA PROFILE'/
     >  ' G:GRAPH:   GRAPH THE 2D OUTPUT ARRAY AS CURRENTLY DEFINED'/
     >  ' L:LIST:    LIST PROFILES IN 2D OUTPUT ARRAY'/
     >  ' X:EXIT:    RETURN TO TOP NODE'/)
C
 15   CALL UREAD('TVTINS:  ENTER OPCODE:$')
      IOP=IXUOPC('IDGLXQ$')
      CALL UCHKOP(IOP,0,1,100,-1,*11)
C
      GO TO (50,200,400,500,600,600) IOP
C
C----
C  INSERT AN EXTRA PROFILE
C
 50   CONTINUE
      IF(LXOUT(0)) WRITE(LUNTRM,2002) YLAB(1),YLAB(3)
 2002 FORMAT(' CONCATENATION VARIABLE:  Y= ',A10,1X,A10/)
      CALL UREAD(
     >  'TVTINS:  ENTER Y VALUE FOR EXTRA PROFILE: (E10 FORMAT):$')
      ZTIME=FDCOD(IERT)
      IF(LCHAR('Q')) GOTO 10
      IF(IERT.NE.0) GO TO 50
C  CHECK LEGALITY OF SPECIFIED TIME
      CALL TVYCHK(ZTIME,IXTRA,IER)
      IF(IER.NE.0) GO TO 10
C---
C  TIME OK.  SET UP TO INSERT EXTRA PROFILE
C
 60   CONTINUE
C   INSERT TIME IN EXTRA PROFILES LIST
      IXP1=IXTRA+1
      IF(IXP1.EQ.1) GO TO 70
      IF(ZTIME.GT.YSHOT2(IXTRA)) GO TO 70
C
      DO 65 I=IXTRA,1,-1
      IF(ZTIME.LT.YSHOT2(I)) IXP1=I
 65   CONTINUE
C
 70   CONTINUE
      IXTRA=IXTRA+1
      IF(IXTRA.EQ.IXP1) GO TO 80
C
      IXPP1=IXP1+1
      DO 75 I=IXTRA,IXPP1,-1
      IM1=I-1
      LSHOT2(1,I)=LSHOT2(1,IM1)
      LSHOT2(2,I)=LSHOT2(2,IM1)
      YSHOT2(I)=YSHOT2(IM1)
      WSHOT2(I)=WSHOT2(IM1)
 75   CONTINUE
 80   CONTINUE
      YSHOT2(IXP1)=ZTIME
C
C  FIND SHOTS BETWEEN WHICH
C  INTERPOLATION IS TO BE PERFORMED
C
C  CHECK FOR EXTRAPOLATION-- PAST ENDS OF DATA
      IF(NSO.EQ.0) THEN
        I=0
        IP1=0
      ELSE
        CALL TVYINS(ZTIME,YSHOTX,NSO,I,IP1)
      ENDIF
C
      IF(NSHOT2.EQ.0) THEN
C  INTERPOLATION/EXTRAPOLATION FROM 1D PROFILE DATA ONLY...
        LX1=0
        LX2=0
        IF(I.GT.0) THEN
          LX1=LSHOTX(I)
        ENDIF
        IF(IP1.GT.0) THEN
          LX2=LSHOTX(IP1)
        ENDIF
      ELSE
C  INTERPOLATION/EXTRAPOLATION FROM 1D AND/OR 2D PROFILE DATA
        CALL TVYINS(ZTIME,Y2,NY2,IY,IYP1)
C
        IF((I.EQ.0).AND.(IY.EQ.0)) THEN
C  EXTRAPOLATION
          LX1=0
        ELSE IF((I.EQ.0).OR.(IY.EQ.0)) THEN
C  FIND IF GLB COMES FROM 1D (I) OR 2D (IY) DATA
          IF(I.EQ.0) THEN
            LX1=-IY
          ELSE IF(IY.EQ.0) THEN
            LX1=LSHOTX(I)
          ENDIF
        ELSE
          IF(Y2(IY).GT.YSHOTX(I)) THEN
            LX1=-IY
          ELSE
            LX1=LSHOTX(I)
          ENDIF
        ENDIF
C
        IF((IP1.EQ.0).AND.(IYP1.EQ.0)) THEN
C  EXTRAPOLATION
          LX2=0
        ELSE IF((IP1.EQ.0).OR.(IYP1.EQ.0)) THEN
C  FIND IF GLB COMES FROM 1D (IP1) OR 2D (IYP1) DATA
          IF(IP1.EQ.0) THEN
            LX2=-IYP1
          ELSE IF(IYP1.EQ.0) THEN
            LX2=LSHOTX(IP1)
          ENDIF
        ELSE
          IF(Y2(IYP1).LT.YSHOTX(IP1)) THEN
            LX2=-IYP1
          ELSE
            LX2=LSHOTX(IP1)
          ENDIF
        ENDIF
C
      ENDIF
C
      LSHOT2(1,IXP1)=LX1
      LSHOT2(2,IXP1)=LX2
C
      YSH1=0.0
      YSH2=0.0
      ISH1=0
      ISH2=0
      ZEXT1='---'
      ZEXT2='---'
      IF(LX1.GT.0) THEN
        ISH1=ISHOTS(LX1)
        YSH1=YSHOTS(LX1)
        ZEXT1=XSHOTX(LX1)
      ELSE IF(LX1.LT.0) THEN
        ISH1=NSHOT2
        YSH1=Y2(-LX1)
        ZEXT1='*2D'
      ENDIF
      IF(LX2.GT.0) THEN
        ISH2=ISHOTS(LX2)
        YSH2=YSHOTS(LX2)
        ZEXT2=XSHOTX(LX2)
      ELSE IF(LX2.LT.0) THEN
        ISH2=NSHOT2
        YSH2=Y2(-LX2)
        ZEXT2='*2D'
      ENDIF
      IF(LXOUT(0)) WRITE(LUNTRM,2003) ISH1,ZEXT1,YSH1,ISH2,ZEXT2,YSH2
 2003 FORMAT(/
     >  '   INTERPOLATING BETWEEN TWO INPUT PROFILES:'/
     >  '      ..."*2D" INDICATES PROFILE FROM 2D INPUT DATA'/
     >  '      (A) [SHOT ',I6,', .EXT ',A,'] Y = ',1PE10.3/
     >  '      (B) [SHOT ',I6,', .EXT ',A,'] Y = ',1PE10.3//
     >  '   (NEW PROFILE) = (1-W) * (PROFILE A) + W * (PROFILE B)'//
     >  '   INCREASED W ==> INCREASED WEIGHT ON PROFILE B'/
     >  '   "SHOT     0" INDICATES "EXTRAPOLATION":'/
     >  '   TREATED AS INTERPOLATION BETWEEN THE NAMED'/
     >  '   SHOT AND A PROFILE WHICH IS IDENTICALLY 0.0')
 105  CALL UREAD(
     >  'TVTINS:  ENTER WEIGHTING FACTOR W (BETWEEN 0 AND 1):$')
      ZWT=FDCOD(IERT)
      IF(IERT.NE.0) GO TO 105
      IF(ZWT.LT.0.0) GO TO 105
      IF(ZWT.GT.1.0) GO TO 105
C
      WSHOT2(IXP1)=1.0-ZWT
C
C  CALCULATE AND INSERT NEW PROFILE
C
C  CHECK FOR EXTRAPOLATION PAST TIME ENDPOINTS
      CALL TVYINS(ZTIME,Y,NYO,I,IP1)
      IF(IP1.EQ.0) IP1=NYO+1
C
      IEXTR=IP1
      IEXTP1=IEXTR+1
      NYO=NYO+1
      IF(NYO.EQ.IEXTR) GO TO 145
C
C  MAKE ROOM
      DO 140 I=NYO,IEXTP1,-1
        IM1=I-1
        Y(I)=Y(IM1)
        IP1M=(IM1-1)*NXO
        IP1P=IP1M+NXO
        DO 140 J=1,NXO
          F(IP1P+J)=F(IP1M+J)
 140  CONTINUE
C
 145  CONTINUE
      Y(IEXTR)=ZTIME
C
      IP=(IEXTR-1)*NXO
      IF(LX1.GT.0) THEN
        IPX1=(LX1-1)*NX + IOFF
      ELSE IF(LX1.LT.0) THEN
        IPX1=(-LX1-1)*NX
      ENDIF
C
      IF(LX2.GT.0) THEN
        IPX2=(LX2-1)*NX + IOFF
      ELSE IF(LX2.LT.0) THEN
        IPX2=(-LX2-1)*NX
      ENDIF
C
      DO 150 J=1,NX
        IF((LX1.NE.0).AND.(LX2.NE.0))
     >	    F(IP+J)=(1.0-ZWT)*FIN(IPX1+J)+ZWT*FIN(IPX2+J)
        IF(LX1.EQ.0) F(IP+J)=ZWT*FIN(IPX2+J)
        IF(LX2.EQ.0) F(IP+J)=(1.0-ZWT)*FIN(IPX1+J)
 150  CONTINUE
C
C  THATS ALL
C
      GO TO 10
C
C  DELETE AN EXTRA PROFILE
C
 200  CONTINUE
      CALL NEUPAG
      IF(LXOUT(0))WRITE(LUNTRM,2008)
 2008 FORMAT(/' ENTER THE NUMBER N OF THE "EXTRA" PROFILE'/
     >  ' TO DELETE, OR "L" TO GENERATE A LIST'//
     >  ' FILE INPUT DATA PROFILES MAY NOT BE DELETED HERE'/
     >  ' NUMBER N REFERS TO NTH NON-DATA PROFILE IN OUTPUT ARRAY'/)
 205  CALL UREAD('TVTINS:  ENTER PROFILE NUMBER OR "L":$')
      IOP=IXUOPC('L$')
      IF(LCHAR('Q')) GOTO 10
      IF(IOP.EQ.1) GO TO 500
      IDEL=IDCOD(IERT)
      IF(IERT.NE.0) GO TO 205
C
      IF(NSHOT2.EQ.0) THEN
        IXTRA=NYO-NSO
      ELSE
        IXTRA=NYO-NY2-NSO
      ENDIF
C
      IF((IDEL.GE.1).AND.(IDEL.LE.IXTRA)) GO TO 210
      WRITE(LUNTRM,9008)
 9008 FORMAT(/' ? NOT A VALID PROFILE NUMBER'/)
      CALL URSTOP(1)
      GO TO 10
C
 210  CONTINUE
      ZTIME=YSHOT2(IDEL)
C
C  DELETE EXTRA PROFILE
C
      NYO=NYO-1
      IF(IDEL.EQ.IXTRA) GO TO 240
      IDP1=IDEL+1
      DO 220 I=IDP1,IXTRA
      IM1=I-1
      YSHOT2(IM1)=YSHOT2(I)
      WSHOT2(IM1)=WSHOT2(I)
      DO 220 I2=1,2
      LSHOT2(I2,IM1)=LSHOT2(I2,I)
 220  CONTINUE
C
C
 240  CONTINUE
C  LOCATE IN OUTPUT ARRAY IF NECESSARY
      IF(ZTIME.GT.Y(NYO)) GO TO 10
C  CHECK FOR DELETION OF FIRST PROFILE (EXTRAPOLATION)
      I=1
      IF(Y(1).EQ.ZTIME) GO TO 260
C
      DO 250 I=2,NYO
C  NOTE NYO HAS BEEN DECREMENTED
      IF(Y(I).EQ.ZTIME) GO TO 260
 250  CONTINUE
C
 260  CONTINUE
      IX=I
      DO 270 I=IX,NYO
      IP1=I+1
      Y(I)=Y(IP1)
      JPP=NXO*I
      JPM=JPP-NXO
      DO 270 J=1,NXO
      F(JPM+J)=F(JPP+J)
 270  CONTINUE
      GO TO 10
C
C  GRAPH RESULTS SO FAR
C
 400  CONTINUE
      CALL TV2GRF
      GO TO 10
C
C  LIST PROFILES IN OUTPUT ARRAY
C
 500  CONTINUE
      CALL XSHOTS(1)
      GO TO 10
C
C  QUIT
C
 600  CONTINUE
      RETURN
      END
C******************** END FILE TVTINS.FOR ; GROUP CONCAT ******************
