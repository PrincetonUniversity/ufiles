C******************** START FILE TV2OUT.FOR ; GROUP CONCAT *************
C=================================================================
C  TV2OUT
C
C
C  OUTPUT 2D CONCATENED DATA FILE
C
C  INVERT ARRAY SO THAT TIME SEQUENCES ARE CONTIGUOUS, AS RE-
C  QUIRED BY TRANSP
C
C  ZF0-- OUTPUT ARRAY WITH RADIAL SEQUENCES CONTIGUOUS, PASSED
C        TO THIS SUBROUTINE
C  KX    # OF RADIAL PTS
C  KY    # OF TIME PTS
C  ZFF-- OUTPT ARRAY WITH TIME SEQUENCES CONTIGUOUS, DEFINED HERE
C        FROM ZF0
C
C
      SUBROUTINE TV2OUT(ZF0,KX,KY,ZFF)
C
      USE CONCAT_MOD
C
      DIMENSION ZF0(KX,KY),ZFF(KY,KX)
      DIMENSION ZBUFF(20)
      INTEGER IORDER(NSCMAX,3)
      CHARACTER*10 ZDATE
      LOGICAL DBUGR,lxout
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  CHECK THAT SUFFICIENT DATA IS PROVIDED
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => TV2OUT               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA DBUGR/.FALSE./
C => END DATA BLOCK
C ====================
C
      luntrm=lnout(0)
C
      IF(KY.GE.2) GO TO 10
        WRITE(LUNTRM,9001)
 9001   FORMAT(/' ? INSUFFICIENT DATA FOR 2D WRITE'/)
        CALL URSTOP(2)
        RETURN
C
 10   CONTINUE
C
      DO 20 IX=1,KX
        DO 20 IY=1,KY
          ZFF(IY,IX)=ZF0(IX,IY)
 20   CONTINUE
C
C  AVERAGE ALL SCALAR LISTS INTO OUTPUT LIST
C
      IF(NSHOT2.GT.0) THEN
        WRITE(LUNTRM,1999)
 1999   FORMAT(/' % SCALARS RETAINED FROM 2D INPUT FILE')
        NUMSCO=NUMSC(1)
        DO 25 IS=1,NUMSCO
          DO 24 I3=1,3
            SCLAB(I3,IS)=SCLABI(I3,IS,1)
 24       CONTINUE
          SCVAL(IS)=SCVALI(IS,1)
 25     CONTINUE
      ELSE
        WRITE(LUNTRM,2000)
 2000   FORMAT(/' % SCALARS AVERAGED FROM 1D INPUT FILES')
        NUMSCO=0
        DO 30 I=1,NSO
          IP=LSHOTX(I)
          CALL UFSCAV(SCLAB,SCVAL,IORDER,NUMSCO,
     >	       SCLABI(1,1,IP),SCVALI(1,IP),IORDER(1,2),NUMSC(IP),
     >	       FLOAT(I-1),1.0,NSCMAX)
 30     CONTINUE
      ENDIF
C
      CALL UFCMPR(LUNO,ICOMPR)
      CALL UFOPWR(LUNO,NSHOTO,IER)
      IF(IER.NE.0) RETURN
C
 40   IF(LXOUT(0)) WRITE(LUNTRM,2001) XLAB(1),YLAB(1)
 2001 FORMAT(
     >  ' OPTIONS:'/
     >  '  1 - WRITE DATA WITH "',A10,'" DIMENSION CONTIGUOUS'/
     >  '  2 - WRITE DATA WITH "',A10,'" DIMENSION CONTIGUOUS'/)
      CALL UREAD('TV2OUT:  ENTER 1 OR 2 DIMENSION ORDER SELECT:$')
      IOPT=IXUOPC('12$')
      IF(LCHAR('Q')) RETURN
      CALL UCHKOP(IOPT,0,1,100,-1,*40)
      IF(IOPT.EQ.1) CALL UF2DWR(LUNO,IDEV,ZSDATE,ZF0,
     >     KX,X,KX,Y,KY,IPROC,FLAB,XLAB,YLAB,NUMSCO,SCVAL,SCLAB,IER)
      IF(IOPT.EQ.2) CALL UF2DWR(LUNO,IDEV,ZSDATE,ZFF,
     >     KY,Y,KY,X,KX,IPROC,FLAB,YLAB,XLAB,NUMSCO,SCVAL,SCLAB,IER)
      IF(IER.NE.0) GO TO 290
C  INSERT COMMENTS
      CALL UFOPCF(LUNT,IER)
      WRITE(LUNT,3000)
 3000 FORMAT(/' COMMENTS GENERATED BY CONCATENATOR PROGRAM'/
     >  ' [TRANSP]CONCAT.FOR VSN 3.0 MAY 1987'//
     >  ' DATA IS 2D CONCATENATION OF THE FOLLOWING PROFILES:'/)
      CALL XSHOTS(2)
C  USER COMMENTS
      CALL UFACOM(LUNT)
C  COMMENTS SPOOLED FROM INPUT FILE
      WRITE(LUNT,3001)
 3001 FORMAT(
     >  ' ============================================================'/
     >  ' COMMENTS SPOOLED FROM INPUT FILES:')
C
      CALL UCSEND(LUNT,LUNO)
C
      IF(NSHOT2.GT.0) THEN
        CFILNM(5:6)=CFILID(1)
        OPEN(UNIT=LUNC,FILE=CJUNKDIR(1:LJUNKDIR)//CFILNM,
     >      status='OLD')
        CALL USPOOL(LUNC,LUNO)
        CLOSE(UNIT=LUNC)
      ENDIF
C
      DO 100 IF=1,NSO
        CFILNM(5:6)=CFILID(LSHOTX(IF))
        OPEN(UNIT=LUNC,FILE=CJUNKDIR(1:LJUNKDIR)//CFILNM,
     >      status='OLD')
        CALL USPOOL(LUNC,LUNO)
        CLOSE(UNIT=LUNC)
 100  CONTINUE
C
C  CLOSE FILE - BRANCH HERE AFTER ERROR
C
 290  CONTINUE
      CALL UFCLOS(LUNO)
      RETURN
      END
C******************** END FILE TV2OUT.FOR ; GROUP CONCAT ***************
