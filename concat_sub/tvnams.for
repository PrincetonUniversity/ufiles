C******************** START FILE TVNAMS.FOR ; GROUP CONCAT *************
C----------------------------------
C  TVNAMS
C
C  SET UP INPUT DEFAULTS FOR NAMING INPUT FILES
C  SELECT KEYWORD OF VARIABLE OF CONCATENATION
C
      SUBROUTINE TVNAMS(INIT)
C
      USE CONCAT_MOD
C
      logical lxout
C
      luntrm=lnout(0)
      INIT=1
C  SET NAMING RULES FOR INPUT FILES
      CALL UFNTER(LUNI,'INPUT 1D PROFILES   ')
C  SELECT KEYWORD OF VARIABLE OF CONCATENATION
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,1000)
 1000 FORMAT(/
     >  ' ENTER KEYWORD IDENTIFYING VARIABLE OF CONCATENATION (Y)'/
     >  ' I.E. THAT QUANTITY OTHER THAN THE INDEPENDENT VARIABLE (X)'/
     >  ' OF THE 1D INPUT FILES Fj(X), THAT WILL BECOME AN INDEPENDENT'/
     >  ' VARIABLE OF THE 2D OUTPUT FILE DATA F(X,Y).'//
     >  ' EXAMPLE-- "T0" IS THE KEYWORD FOR LASER FIRING TIME FOR PLT'/
     >  ' AND PDX THOMPSON SCATTERING TE,NE PROFILE DATA.'//
     >  ' THE SPECIFIED KEYWORD MUST NAME SCALAR DATA IN THE INPUT 1D'/
     >  ' UFILES.  IF NO SUCH SCALAR DATA EXISTS, ENTER "USER"; YOU'/
     >  ' WILL BE PROMPTED FOR "Y" VALUES FROM THE TERMINAL'/)
      CALL UFGKEY(YKEY)
C
      RETURN
      END
C******************** END FILE TVNAMS.FOR ; GROUP CONCAT ***************
