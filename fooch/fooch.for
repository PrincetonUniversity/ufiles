C----------------------------------------------------------------------
C  FOOCH - STRAIGHT LINE PROJECTOR PLOTTER
C
C   INTERACTIVELY INPUT R,Y,THETA,PHI, STARTING COORDINATES FOR A
C   STRAIGHT LINE TRACK AS USED IN TRANSP/TRKRB
C
C   SPECIFY A TARGET "PLASMA" SURFACE AND A VACUUM VESSEL SURFACE
C   MAY CHOOSE TO VIEW POLOIDAL OR MIDPLANE PROJECTION OF SPECIFIED
C   TRACK
C
      PROGRAM FOOCH
C
      PARAMETER (NRES=256)
C
      REAL VVX(NRES,3)  ! VV BDY 1-POLOIDAL, 2 MIDPLANE INNER
      REAL VVY(NRES,3)  !  3: MIDPLANE OUTER
      REAL PLX(NRES,3)  ! PLASMA BDY; 1,2,3 AS ABOVE
      REAL PLY(NRES,3)
C
      REAL TRAJ3(NRES,3) ! 3 SPACE TRAJECTORY
      REAL TRAJ2(NRES,2) ! 2 SPACE POLOIDAL PROJECTION
C
      REAL XBUF(NRES,5),YBUF(NRES,5),ZBUF(5)
C
      INTEGER INC(5),ISEL(5)
C
      CHARACTER*60 MNLAB(3)
      CHARACTER*17 KYLAB(5)
      CHARACTER*10 LBCON(5),RUN,YUN
C
C-----------------------------------------------------------------------
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
      LOGICAL LXOUT
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      CALL UINITG("FOOCH")
C
      LUNTRM=LNOUT(0)
C
      RVV=265.0
      AVV=109.0
C
      RPL=250.0
      APL=80.0
C
 10   CONTINUE
C
      ICALC=0
C
      CALL UREADF('FOOCH:  VACUUM VESSEL MAJOR RADIUS (CM):$$',RVV)
C
      CALL UREADF('FOOCH:  VACUUM VESSEL MINOR RADIUS:$$',AVV)
C
      CALL UREADF('FOOCH:  PLASMA SURFACE MAJOR RADIUS:$$',RPL)
C
      CALL UREADF('FOOCH:  PLASMA SURFACE MINOR RADIUS:$$',APL)
C
      CALL UREADF('FOOCH:  TRAJECTORY STARTING RADIUS:$$',RTRAJ)
C
      CALL UREADF('FOOCH:  TRAJECTORY STARTING ELEVATION:$$',YTRAJ)
C
      CALL UREADF('FOOCH:  THETA AIMING ANGLE (DEGREES):$$',ZTHETA)
      CALL UREADF('FOOCH:  PHI   AIMING ANGLE (DEGREES):$$',ZPHI)
C
      ZL0=SQRT(RTRAJ**2+YTRAJ**2)
      ZL=2.0*ZL0
      CALL UREADF('FOOCH:  TRAJECTORY SEGMENT LENGTH FOR PLOTTING:$$',
     >    ZL)
C
 20   CONTINUE
      IF(LXOUT(0)) WRITE(LUNTRM,1001) RVV,AVV,RPL,APL,
     >     RTRAJ,YTRAJ,ZTHETA,ZPHI,ZL
 1001   FORMAT(/
     >' VACUUM VESSEL  R,a: ',2(1X,1PE11.4)/
     >' PLASMA SURFACE R,a: ',2(1X,1PE11.4)/
     >'  TRAJECTORY STARTING PT (R,Y): ',2(1X,1PE11.4)/
     >'  AIMING ANGLES (THETA,PHI) DG: ',2(1X,1PE11.4)/
     >'    TRAJECTORY PLOT SEGMENT LENGTH:  ',1PE11.4//
     >' OPTIONS:'/
     >'  M - MIDPLANE PROJECTION PLOT'/
     >'  P - POLOIDAL PROJECTION PLOT'/
     >'  R - RESPECIFY SOME OR ALL OF THE ABOVE COORDINATES'/
     >'  Q - QUIT PROGRAM NOW')
C
      CALL UREAD('FOOCH:  ENTER CONTROL OPTION CODE:$$')
C
      IPLOT=0
      IF(LCHAR('Q')) THEN
        CALL UEXITA(0)
      ELSE IF(LCHAR('R')) THEN
        GO TO 10
      ELSE IF(LCHAR('M')) THEN
        IPLOT=1
      ELSE IF(LCHAR('P')) THEN
        IPLOT=2
      ELSE
        CALL UERMSG('%FOOCH - UNRECOGNIZED OPCODE',' ',0)
      ENDIF
C
      IF(IPLOT.EQ.0) GO TO 20
C
      IF(ICALC.EQ.0) THEN
C
C  COMPUTE ALL CONTOURS
C
        ICALC=1
C
        ZPI=3.141593
C
C VV AND PLASMA REFERENCE CONTOURS
        DO ITH=1,NRES
          ZF=FLOAT(ITH-1)/FLOAT(NRES-1)
          ZALPH=ZF*2.0*ZPI
          ZCOSA=COS(ZALPH)
          ZSINA=SIN(ZALPH)
C
          VVX(ITH,1)=RVV+AVV*ZCOSA
          VVY(ITH,1)=AVV*ZSINA
C
          PLX(ITH,1)=RPL+APL*ZCOSA
          PLY(ITH,1)=APL*ZSINA
C
          VVX(ITH,2)=ZCOSA*(RVV-AVV)
          VVY(ITH,2)=ZSINA*(RVV-AVV)
C
          PLX(ITH,2)=ZCOSA*(RPL-APL)
          PLY(ITH,2)=ZSINA*(RPL-APL)
C
          VVX(ITH,3)=ZCOSA*(RVV+AVV)
          VVY(ITH,3)=ZSINA*(RVV+AVV)
C
          PLX(ITH,3)=ZCOSA*(RPL+APL)
          PLY(ITH,3)=ZSINA*(RPL+APL)
C
        ENDDO
C
        ZZTHET=ZTHETA*ZPI/180.0
        ZZPHI=ZPHI*ZPI/180.0
C
        ZCOSPH=COS(ZZPHI)
        ZSINPH=SIN(ZZPHI)
C
        ZCOSTH=COS(ZZTHET)
        ZSINTH=SIN(ZZTHET)
C
        ZDLA=ZL0*2.0E-2
C
C  START PT
        TRAJ3(1,1)=RTRAJ
        TRAJ3(1,2)=YTRAJ
        TRAJ3(1,3)=0.0
C
        DO IC=2,10
          DO IDIR=1,3
            TRAJ3(IC,IDIR)=TRAJ3(1,IDIR)
          ENDDO
        ENDDO
C
C  START SYMBOL
C
        TRAJ3(2,1)=TRAJ3(1,1)+ZDLA
        TRAJ3(3,1)=TRAJ3(1,1)-ZDLA
C
        TRAJ3(5,2)=TRAJ3(1,2)+ZDLA
        TRAJ3(6,2)=TRAJ3(1,2)-ZDLA
C
        TRAJ3(8,3)=TRAJ3(1,3)+ZDLA
        TRAJ3(9,3)=TRAJ3(1,3)-ZDLA
C
        IRES=NRES-10
        ZDL=ZL/FLOAT(IRES)
C
C  3 SPACE TRAJECTORY
        ZL=0.0
        DO IL=1,IRES
          ZL=ZL+ZDL
          TRAJ3(10+IL,1)=RTRAJ-ZL*ZCOSTH*ZCOSPH
          TRAJ3(10+IL,2)=YTRAJ+ZL*ZSINTH
          TRAJ3(10+IL,3)=ZL*ZCOSTH*ZSINPH
        ENDDO
C
        DO IL=1,NRES
C  2 SPACE PROJECTION
          TRAJ2(IL,1)=SQRT(TRAJ3(IL,1)**2+TRAJ3(IL,3)**2)
          TRAJ2(IL,2)=TRAJ3(IL,2)
        ENDDO
      ENDIF
C
C  MAKE THE PLOTS
C
      IF(IPLOT.EQ.1) THEN
        WRITE(MNLAB(1),2001)
 2001   FORMAT('TRAJECTORY PLOT - MIDPLANE PROJECTION',23X)
      ELSE
        WRITE(MNLAB(1),2002)
 2002   FORMAT('TRAJECTORY PLOT - POLOIDAL PROJECTION',23X)
      ENDIF
      WRITE(MNLAB(2),2003) RTRAJ,YTRAJ
 2003   FORMAT('STARTING R,Y = ',2(1X,1PE11.4),' CM',18X)
      WRITE(MNLAB(3),2004) ZTHETA,ZPHI
 2004   FORMAT('STARTING THETA,PHI = ',2(1X,1PE11.4),' DEGREES',7X)
C
      RUN='CM        '
      YUN='CM        '
C
      WRITE(KYLAB(1),2009)
 2009   FORMAT('CONTOUR LABELS   ')
      WRITE(KYLAB(3),2010)
        INZ=5
 2010   FORMAT(' 1:  TRAJECTORY  ')
      IF(IPLOT.EQ.1) THEN
        WRITE(KYLAB(4),2011)
 2011   FORMAT(' 2,3: VAC.VESSEL ')
        WRITE(KYLAB(5),2012)
 2012   FORMAT(' 4,5: PLAS.SURF. ')
      ELSE
        WRITE(KYLAB(4),2021)
 2021   FORMAT('2: VACUUM VESSEL ')
        WRITE(KYLAB(5),2022)
 2022   FORMAT('3: PLASMA SURFACE')
C
      ENDIF
C
      DO I5=1,5
        WRITE(LBCON(I5),2030) I5
 2030   FORMAT(' NO. ',I1,'    ')
        ZBUF(I5)=FLOAT(I5)
        INC(I5)=NRES
        ISEL(I5)=I5
      ENDDO
C
      IF(IPLOT.EQ.1) THEN
        INZ=5
        DO IRES=1,NRES
          XBUF(IRES,1)=TRAJ3(IRES,1)
          XBUF(IRES,2)=VVX(IRES,2)
          XBUF(IRES,3)=VVX(IRES,3)
          XBUF(IRES,4)=PLX(IRES,2)
          XBUF(IRES,5)=PLX(IRES,3)
          YBUF(IRES,1)=TRAJ3(IRES,3)
          YBUF(IRES,2)=VVY(IRES,2)
          YBUF(IRES,3)=VVY(IRES,3)
          YBUF(IRES,4)=PLY(IRES,2)
          YBUF(IRES,5)=PLY(IRES,3)
        ENDDO
      ELSE
        INZ=3
        DO IRES=1,NRES
          XBUF(IRES,1)=TRAJ2(IRES,1)
          XBUF(IRES,2)=VVX(IRES,1)
          XBUF(IRES,3)=PLX(IRES,1)
          YBUF(IRES,1)=TRAJ2(IRES,2)
          YBUF(IRES,2)=VVY(IRES,1)
          YBUF(IRES,3)=PLY(IRES,1)
        ENDDO
      ENDIF
C
      CALL GRFMM1(XBUF,YBUF,NRES,INC,1,ZBUF,INZ,ISEL,INZ,
     >    RUN,YUN,MNLAB,KYLAB,LBCON)
      GO TO 20
C
      END
