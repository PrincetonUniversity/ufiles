C******************** START FILE EXTRK2.FOR ; GROUP EXSUBS ******************
C---------------------------------------------------------------------
C  EXTRK2
C
C  EXTRACT ALL SLICES FROM THE 2D DATA FOR OUTPUT TO 1D UFILES
C
C  OPTIONS INCLUDE PLOTTING THE 2D INPUT DATA
C  AND CHOOSING THE SLICE TYPE (VS. 1ST OR 2ND INDEPENDENT COORDINATE)
C
      SUBROUTINE EXTRK2
C
      USE EXTRAC_MOD
      USE UFILES
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LYES,lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C-----------------------
C
      luntrm=lnout(0)
C
 10   CONTINUE
C
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,1001) (FLAB(IJ),IJ=1,3),
     >     (XLAB(IJ),IJ=1,3),(YLAB(IJ),IJ=1,3),CMPSTA(ICOMPR)
 1001 FORMAT(/
     >' EXTRK2 PERFORMS MASS EXTRACTIONS OF *ALL* DATA SLICES'//
     >' EXTRK2 OPTIONS:'/
     >'  G - GRAPH THE 2D INPUT DATA F(X,Y)'/
     >'      F IS ',3A10/
     >'      X IS ',3A10/
     >'      Y IS ',3A10/
     >'  A - EXTRACT ALL SLICES OF F VS. X AT EVERY FIXED Y'/
     >'  B - EXTRACT ALL SLICES OF F VS. Y AT EVERY FIXED X'/
     >'  I - SET EXTRACTION INTERPOLATION/EXTRAPOLATION OPTIONS'/
     >'  C - COMPRESS- TOGGLE OUTPUT DATA FORMAT FLAG, NOW "',A,'"'/
     >'  4 - FORMAT  - *new* Ufile output format control menu'/
     >'  Q - QUIT THIS ROUTINE')
      CALL UREAD('EXTRK2:  ENTER CONTROL OPTION G/A/B/Q:$')
      IANS=IXUOPC('GAB4CQI$')
      CALL UCHKOP(IANS,0,1,100,-1,*10)
C
      GO TO (100,200,300,48,50,400,450) IANS
C
 48   continue
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      go to 10
C
 50   CONTINUE
      ICOMPR=ITOGGL-ICOMPR
      GO TO 10
C
 100  CONTINUE
C
      CALL GRF3(X,F,Y,ZWK,NXACT,NYACT,NXACT,
     >   XLAB,YLAB,FLAB,XLAB(3),YLAB(3),FLAB(3),
     >   ZTITLE,1,0,0,IDEV,ISHOT,0,JSHOT,1,ISMOO)
C
      GO TO 10
C
 200  CONTINUE
      IF(NYACT.GT.99) CALL EXPERR(
     >   '? TOO MANY Y PTS. (MAX=99) NO MASS EXTRACTION ALLOWED',*10)
      INUM=NYACT
      IXSEL=1
      CALL EXSCLB(YLAB,INSC1,INSC2)
      GO TO 500
C
 300  CONTINUE
      IF(NXACT.GT.99) CALL EXPERR(
     >'? TOO MANY X PTS. (MAX=99) NO MASS EXTRACTION ALLOWED',*10)
      INUM=NXACT
      IXSEL=2
      CALL EXSCLB(XLAB,INSC1,INSC2)
      GO TO 500
C
C  USER EXIT
C
 400  CONTINUE
      RETURN
C
C  INTERPOLATION/EXTRAPOLATION OPTIONS
C
 450  CONTINUE
      CALL EXINTX
      GO TO 10
C
 500  CONTINUE
      WRITE(LUNTRM,1002) INUM
 1002 FORMAT(
     >' % ALL ',I2,' SLICES OF THE 2D DATA WILL BE WRITTEN INTO'/
     >'   1D UFILES'/
     >' % THE INDEX NUMBER OF THE EXTRACTED 1D SLICE WILL BE'/
     >'   ENCODED INTO THE LAST 2 CHARACTERS OF THE UFILES FILENAME'/
     >'   EXTENSION-- THUS ONLY THE 1ST CHARACTER OF THE EXTENSION'/
     >'   IS UNDER USER CONTROL'/
     >)
      CALL UREAD('EXTRK2: ENTER "Y" TO VERIFY MASS EXTRACTION:$')
      IF(.NOT.LYES(0)) GO TO 10
C
      CALL UFNTER(ILUNO,'OUTPUT SLICE FILES  ')
C
C  FETCH UFILES CHANNEL NUMBER FROM UFILES COMMON (SUCCESS GUARANTEED
C  BY UFNTER)
C
      CALL UFLCHK(ILUNO,'EXTRK2    ',ICHAN,IER)
C
C  LOOP OVER INDEX OF FIXED PTS OF EXTRACTION
C
      CALL NEUPAG
C
      DO 550 I=1,INUM
C  FILENAME EXTENSION
        IDIG1=I/10
        IDIG2=I-10*IDIG1
        IF(IDIG2.EQ.0) CALL NEUPAG
        WRITE(UEXTND(ICHAN)(2:3),5001) IDIG1,IDIG2
 5001   FORMAT(2I1)
C  RECORD FIXED PT. AND  EXTRACT THE DATA
        IF(IXSEL.EQ.1) THEN
          SCV(1)=Y(I)
          CALL EXPGET(F,NXACT,NYACT,IXSEL,I,I,-1.0,ZWK,ZWK1,MAXIND,
     >           X,XTARG,NXTARG,LXTRAP,XTRAP,IER)
        ELSE
          SCV(1)=X(I)
          CALL EXPGET(F,NXACT,NYACT,IXSEL,I,I,-1.0,ZWK,ZWK1,MAXIND,
     >           Y,YTARG,NYTARG,LYTRAP,YTRAP,IER)
        ENDIF
C  WRITE THE DATA (UNCONDITIONAL)
        CALL UFCMPR(ILUNO,ICOMPR)
        CALL UFOPWR(ILUNO,ISHOT,IER)
        IF(IER.EQ.0) THEN
C---------------------------------------
        INSC=NUMSC+1
        IF(IXSEL.EQ.1) THEN
          CALL UF1DWR(ILUNO,IDEV,ZSDATE,XTARG,ZWK1,NXTARG,IPROC,
     >                  XLAB,FLAB,INSC,SCV,SCLAB,IERW)
        ELSE
          CALL UF1DWR(ILUNO,IDEV,ZSDATE,YTARG,ZWK1,NYTARG,IPROC,
     >                  YLAB,FLAB,INSC,SCV,SCLAB,IERW)
        ENDIF
C  WRITE COMMENT HEADER ONLY
        CALL UFOPCF(ILUNC,IER)
        CALL EXCHED(ILUNI,ILUNC)
        IF((IXSEL.EQ.1).AND.(LXTRAP.GT.0)) THEN
          WRITE(ILUNC,4001)
 4001 FORMAT('  *** DATA INTERPOLATED AND/OR EXTRAPOLATED ***')
          CALL UFSNMD(ILUNC,'X - TARGET DATA FILE',ILUNX)
        ENDIF
        IF((IXSEL.EQ.2).AND.(LYTRAP.GT.0)) THEN
          WRITE(ILUNC,4001)
          CALL UFSNMD(ILUNC,'X - TARGET DATA FILE',ILUNY)
        ENDIF
        CALL UCSEND(ILUNC,ILUNO)
C
        ENDIF
C---------------------------------------
        CALL UFCLOS(ILUNO)
C
 550  CONTINUE
C
      RETURN
      END
C******************** END FILE EXTRK2.FOR ; GROUP EXSUBS ******************
