C******************** START FILE EXBLOK.FOR ; GROUP EXBLOK ******************
C---------------------------------------------------------------------
C  EXBLOK
C
C  SPECIFY A SUB-BLOCK OF A 2D DATA ARRAY AND OUTPUT TO UFILES
C
C  USE RNGSEL SUBROUTINE TO PERMIT WEEDING OUT OF ANY SUBSEQUENCE OF
C  INDICES OF EITHER INDEPENDENT DIMENSION OF THE DATA
C
C  SUBROUTINE OF EXTRAC UTILITY
C
      SUBROUTINE EXBLOK
C
      USE EXTRAC
C
      LOGICAL ITRUE,IFALSE,lxout
C
      DATA ITRUE/.TRUE./
      DATA IFALSE/.FALSE./
C
C  INITIAL SELECTION-- ALL OF THE DATA
C
      luntrm=lnout(0)
C
      CALL RNGSL0(LX,NXACT,ITRUE)
      CALL RNGSL0(LY,NYACT,ITRUE)
      INX=NXACT
      INY=NYACT
C
 10   CONTINUE
      CALL NEUPAG
 11   CONTINUE
C
      IF(LXOUT(0)) WRITE(LUNTRM,1001) (FLAB(IJ),IJ=1,3),
     >     (XLAB(IJ),IJ=1,3),NXACT,(YLAB(IJ),IJ=1,3),NYACT,INX,INY,
     >     CMPSTA(ICOMPR)
C
 1001 FORMAT(/
     >' EXBLOK PERMITS USER TO WRITE A TRUNCATED VERSION OF THE 2D'/
     >' INPUT DATA WITH SELECTED X AND Y ROWS AND COLUMNS DELETED'/
     >' EXBLOK OPTIONS:'/
     >'  G - GRAPH THE 2D INPUT DATA F(X,Y)'/
     >'      F IS ',3A10/
     >'      X IS ',3A10,' NX = ',I6/
     >'      Y IS ',3A10,' NY = ',I6/
     >'  X - MODIFY X AXIS SEQUENCE (CURRENTLY ',I6,' PTS REMAIN)'/
     >'  Y - MODIFY Y AXIS SEQUENCE (CURRENTLY ',I6,' PTS REMAIN)'/
     >'  P - PLOT THE OUTPUT DATA (WITH X AND Y MODIFIED)'/
     >'  C - COMPRESS- TOGGLE OUTPUT DATA FORMAT FLAG, NOW "',A,'"'/
     >'  4 - FORMAT  - *new* Ufile output format control menu'/
     >'  W - WRITE THE OUTPUT DATA (X AND Y MODIFIED)'/
     >'  Q - QUIT (ABORT) THIS ROUTINE'/)
C
      CALL UREAD('EXBLOK: ENTER OPCODE G/X/Y/P/W/Q:$')
C
      IOP=IXUOPC('GXYP4CWQ$')
C
      CALL UCHKOP(IOP,0,1,100,-1,*11)
C
      GO TO (100,200,300,400,48,50,500,900) IOP
C
 48   continue
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      go to 10
C
 50   CONTINUE
      ICOMPR=ITOGGL-ICOMPR
      GO TO 10
C
 100  CONTINUE
C  PLOT INPUT DATA
      CALL GRF3(X,F,Y,ZWK,NXACT,NYACT,NXACT,
     >   XLAB,YLAB,FLAB,XLAB(3),YLAB(3),FLAB(3),
     >   ZTITLE,1,0,0,IDEV,ISHOT,0,JSHOT,1,ISMOO)
C
      GO TO 10
C
C  MODIFY X
C
 200  CONTINUE
      CALL RNGSEL(XLAB,X,LX,NXACT)
      INX=0
      DO 210 IX=1,NXACT
      IF(LX(IX)) INX=INX+1
 210  CONTINUE
C
      GO TO 10
C
C
C  MODIFY Y
C
 300  CONTINUE
      CALL RNGSEL(YLAB,Y,LY,NYACT)
      INY=0
      DO 310 IY=1,NYACT
      IF(LY(IY)) INY=INY+1
 310  CONTINUE
C
      GO TO 10
C
 400  CONTINUE
      IF((INX.LE.1).OR.(INY.LE.1)) CALL EXPERR(
     >'? *** TOO FEW X OR Y PTS FOR 2D OUTPUT DATA',*10)
C  PLOT INPUT DATA
      CALL EXBLKD(FB,XB,YB,INX,INY)
C
      CALL GRF3(XB,FB,YB,ZWK,INX,INY,INX,
     >   XLAB,YLAB,FLAB,XLAB(3),YLAB(3),FLAB(3),
     >   ZTITLE,1,0,0,IDEV,ISHOT,0,JSHOT,1,ISMOO)
C
      GO TO 10
C
C  WRITE OUTPUT DATA
C
 500  CONTINUE
      IF((INX.LE.1).OR.(INY.LE.1)) CALL EXPERR(
     >'? *** TOO FEW X OR Y PTS FOR 2D OUTPUT DATA',*10)
C
      CALL EXBLKD(FB,XB,YB,INX,INY)
C
      CALL UFNTER(ILUNO,'2D OUTPUT FILE      ')
      CALL UFCMPR(ILUNO,ICOMPR)
      CALL UFOPWR(ILUNO,ISHOT,IER)
      IF(IER.EQ.0) THEN
C----------------------------------
      CALL UF2DWR(ILUNO,IDEV,ZSDATE,FB,INX,XB,INX,YB,INY,IPROC,
     >     FLAB,XLAB,YLAB,NUMSC,SCV(2),SCLAB(1,2),IER)
      CALL UFOPCF(ILUNC,IER)
      WRITE(ILUNC,3001) ISHOT
 3001 FORMAT(' X AND/OR Y AXIS MODIFIED DATA FOR SHOT #####=',I6/
     >' FROM FILE:')
      CALL UFSNMD(ILUNC,'2D ORIGINAL DATA    ',ILUNI)
C
      CALL RNGSPR(ILUNC,LX,XLAB,X,NXACT,ITRUE)
      CALL RNGSPR(ILUNC,LX,XLAB,X,NXACT,IFALSE)
C
      CALL RNGSPR(ILUNC,LY,YLAB,Y,NYACT,ITRUE)
      CALL RNGSPR(ILUNC,LY,YLAB,Y,NYACT,IFALSE)
C
      CALL UFACOM(ILUNC)
C
      CALL UCSEND(ILUNC,ILUNO)
C  SPOOLED COMMENTS
      OPEN(UNIT=ILUNT,status='OLD',FILE='ZEXTRC.MMT')
      CALL USPOOL(ILUNT,ILUNO)
      CLOSE(UNIT=ILUNT)
C----------------------------------
      ENDIF
C
      CALL UFCLOS(ILUNO)
C
C  EXIT
C
 900  CONTINUE
      RETURN
      END
C******************** END FILE EXBLOK.FOR ; GROUP EXBLOK ******************
