C******************** START FILE EXINT0.FOR ; GROUP EXSUBS ******************
C---------------------------------------------------------------
C
      SUBROUTINE EXINT0(ILUN,ZXLAB,ZX,INX,ZXO,INXO,LXO,ZXTRAP)
C
C  READ UFILE TO DEFINE INTERPOLATION OR EXTRAPOLATION ALONG AXIS
C  PASSED THRU CALLING ARGUMENTS
C
C  CHECK THAT THE UFILE DATA UNITS AGREE WITH THE PASSED LABEL AND
C  THAT COVERAGE OF THE ORIGINAL DATA BY THE NEW DATA X RANGE IS
C  GOOD.  ALSO REQUIRE BOTH X VECTORS TO BE MONOTONIC
C
      USE EXTRAC_MOD
C
      REAL ZX(INX), ZXO(MAXIND), ZXTRAP(3,2)
      CHARACTER*10 ZXLAB(3)
C
C  ILUN - LUN TO READ TARGET COORDINATES
C  ZXLAB - LABEL OF ORIGINAL COORD FROM 2D INPUT FILE
C  ZX(INX) - ORIGINAL X COORD
C  ZXO(INXO) - TARGET X COORD READ IN ** BOTH ZXO AND INXO ARE
C    OUTPUT.
C  LXO - OUTPUT 0 IF ZXO RESET TO EQUAL ORIGINAL COORD
C        OUTPUT 1 IF ZXO WAS READ IN FROM FILE
C  ZXTRAP - EXTRAPOLATION PARAMETERS (IF NEEDED USER IS PROMPTED)
C        OUTPUT
C-----------------------
C  LOCAL:
C
      CHARACTER*10 ZZXLAB(3),ZZWLAB(3),ZZDATE
      CHARACTER*4 ZTOK
      CHARACTER*10 ZSCLAB(3,100)
      REAL ZSCVAL(100)
C
C  CHECK MONOTONICITY OF INPUT X
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LYES
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      INXM1=INX-1
      DO 10 IX=1,INXM1
        IXP=IX+1
        IF(ZX(IXP).LE.ZX(IX)) THEN
          CALL UERMSI(
     >' 2D INPUT DATA INDEP. COOORD NOT MONOTONIC, PT.',IX,2)
          RETURN
        ENDIF
 10   CONTINUE
C
 15   CONTINUE
      CALL NEUPAG
 16   CONTINUE
      CALL UREAD(
     >'EXINT0: TYPE "A" TO RESTORE ORIGINAL, "B" FOR NEW TARGET X:$')
      IANS=IXUOPC('AB$')
      IF(IANS.EQ.0) THEN
        CALL UCLEAR
        GO TO 16
      ENDIF
C
C  RESTORE ORIGINAL DATA
C
      IF(IANS.EQ.0) THEN
        LXO=0
        INXO=INX
        DO 20 IX=1,INX
          ZXO(IX)=ZX(IX)
 20     CONTINUE
        RETURN
      ENDIF
C
C  NEW TARGET X - READ 1D UFILE
C
      CALL UFNTER(ILUN,'1D TARGET COORD DATA')
C
      CALL UFOPRD(ILUN,ISHOT,IER)
C
      IF(IER.NE.0) GO TO 15
C
      CALL UF1DRD(ILUN,ZTOK,ZZDATE,ZXO,ZWK,MAXIND,INXO,JPROC,
     >     ZZXLAB,ZZWLAB,100,INSC,ZSCVAL,ZSCLAB,IER)
C
      CALL UFCLOS(ILUN)
C
C  CHECK MONOTONICITY
C
C
      INXM1=INXO-1
      DO 40 IX=1,INXM1
        IXP=IX+1
        IF(ZXO(IXP).LE.ZXO(IX)) THEN
          CALL UERMSI(
     >' NEW INPUT DATA INDEP. COOORD NOT MONOTONIC, PT.',IX,2)
          GO TO 15
        ENDIF
 40   CONTINUE
	
C
      ILUNT=LNOUT(0)
C
 50   CONTINUE
      CALL NEUPAG
C
      WRITE(ILUNT,1001) (ZXLAB(IJ),IJ=1,3),(ZZXLAB(IJ),IJ=1,3),
     >     ZX(1),ZX(INX),ZXO(1),ZXO(INXO)
C
 1001 FORMAT(/
     >'  2D INPUT DATA COORDINATE LABEL:  ',2A10,1X,A10,' *RETAINED*'/
     >'  1D INPUT DATA COORDINATE LABEL:  ',2A10,1X,A10/
     >'   *RANGE OF 2D INPUT DATA COORDINATE:  ',1PE11.4,' TO ',1PE11.4/
     >'   *RANGE OF 1D TARGET DATA COORDINATE: ',1PE11.4,' TO ',1PE11.4/
     >/'  ALL EXTRAPOLATIONS ARE FLAT FROM ENDPT OF INPUT DATA')
C
      CALL UREAD('EXINT0:  PLOT THE TARGET COORDINATE DATA? (Y/N):$')
      IF(LYES(0)) THEN
        CALL GRFUF1(ZXO,ZWK,INXO,JPROC,ZZWLAB,ZZXLAB,ISHOT,ZTOK,
     >     ZZDATE,INSC,ZSCVAL,ZSCLAB)
      ENDIF
C
      CALL UREAD('EXINT0:  USE TARGET COORDINATE DATA? (Y/N):$')
      IF(LYES(0)) THEN
        LXO=1
        RETURN
      ELSE
        GO TO 15
      ENDIF
C
      END
C******************** END FILE EXINT0.FOR ; GROUP EXSUBS ******************
