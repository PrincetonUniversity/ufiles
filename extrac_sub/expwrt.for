C******************** START FILE EXPWRT.FOR ; GROUP EXSUBS *************
C---------------------------------------------------------------
C  EXPWRT
C
C  OFFER OPTIONS TO PLOT AND WRITE THE EXTRACTED PROFILE
C
C  **MODIF DMC SEPT 1987**
C  OUTPUT BACK TO COMMON INSTEAD OF UFILE, IF ILUNO .LE. 0
C  TO SUPPORT RPLOT/EXTRAC SUBROUTINE INTERFACE
C
      SUBROUTINE EXPWRT(ZX,ZF,INX,ZXLAB,INSC)
C
      USE EXTRAC
C
      REAL ZX(INX),ZF(INX)
      CHARACTER*10 ZXLAB(3)
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LYES
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      CALL NEUPAG
C
      CALL UREAD('EXPWRT:  PLOT THE EXTRACTED PROFILE? (Y/N):$')
      IF(LYES(0)) THEN
        IF(INSC.GT.NUMSC) THEN
          IXLBL=1
        ELSE
          IXLBL=0
        ENDIF
        CALL GRFUF1(ZX,ZF,INX,IPROC,FLAB,ZXLAB,ISHOT,IDEV,
     >         ZSDATE,IXLBL,SCV,SCLAB)
      ENDIF
C
      IF(ILUNO.GT.0) THEN
C  UFILES OUTPUT
        CALL UREAD(
     >	'EXPWRT:  WRITE EXTRACTED PROFILE TO 1D UFILES FILE? (Y/N):$')
        IF(LYES(0)) THEN
          CALL UFNTER(ILUNO,'OUTPUT 1D DATA SLICE')
          CALL UFCMPR(ILUNO,ICOMPR)
          CALL UFOPWR(ILUNO,ISHOT,IER)
          IF(IER.EQ.0) THEN
            IF(INSC.GT.NUMSC) THEN
      	CALL UF1DWR(ILUNO,IDEV,ZSDATE,ZX,ZF,INX,IPROC,
     >		   ZXLAB,FLAB,INSC,SCV,SCLAB,IERW)
            ELSE
      	CALL UF1DWR(ILUNO,IDEV,ZSDATE,ZX,ZF,INX,IPROC,
     >		   ZXLAB,FLAB,INSC,SCV(2),SCLAB(1,2),IERW)
            ENDIF
C  USER COMMENTS
            CALL UFOPCF(ILUNC,IER)
            CALL UFACOM(ILUNC)
            CALL UCSEND(ILUNC,ILUNO)
C  SPOOLED COMMENTS FILE
            OPEN(UNIT=ILUNT,status='OLD',FILE='ZEXTRC.MMT')
            CALL USPOOL(ILUNT,ILUNO)
C
            CLOSE(UNIT=ILUNT)
          ENDIF
          CALL UFCLOS(ILUNO)
        ENDIF
      ELSE
C  COMMON OUTPUT
        ICOMPR=INX
        DO 100 IX=1,INX
          ZWK(IX)=ZX(IX)
          ZWK1(IX)=ZF(IX)
 100    CONTINUE
      ENDIF
C
      RETURN
      END
C******************** END FILE EXPWRT.FOR ; GROUP EXSUBS ***************
