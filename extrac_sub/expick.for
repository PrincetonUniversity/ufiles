C******************** START FILE EXPICK.FOR ; GROUP EXSUBS ******************
C-----------------------------------------------------------------
C
C  EXPICK
C
C  PICK FIXED VALUE INDEPENDENT VARIABLE AND RANGE TO AVG OVER.
C
      SUBROUTINE EXPICK(ZXLAB,ZX,NZX,IZX1,IZX2,INSC,ZINTRP,IER)
C
      USE EXTRAC_MOD
C
      CHARACTER*10 ZXLAB(3)
      REAL ZX(NZX)
C
C INPUTS:
C  ZXLAB - LABEL OF INDEPENDENT VARIABLE
C  ZX(NZX) INDEPENDENT VARIABLE VALUES
C
C  EQUAL TO EITHER X OR Y IN THE COMMON BLOCK
C
C OUTPUTS:
C  IZX1 TO IZX2 -- INDEX RANGE OF TO BE AVERAGED OVER IN CALCULATING
C   OUTPUT PROFILE.  IF NO AVERAGING IS TO BE DONE, IZX1=IZX2 ON OUTPUT
C  INSC -- TOTAL NUMBER OF SCALARS TO WRITE IN OUTPUT FILE =
C   ORIGINAL NUMBER OF SCALARS +1 IF NO AVERAGING IS DONE, +3 IF
C   AVERAGING IS DONE
C  IER - SET TO ZERO IF A SLICE OR AVG IS SUCCESSFULLY PICKED
C
C  ERROR FLAG INTITIALLY SET ON
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LYES,lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
      IER=1
C
      luntrm=lnout(0)
C
      ZINTRP=-1.0  ! default:  no interpolation in ZX coordinate dir.
C
C  SET UP ADDL SCALAR LABELS FOR OUTPUT FILE
C
      CALL EXSCLB(ZXLAB,INSC1,INSC2)
C
C  USER CONTROL LOOP
C
 10   CONTINUE
      CALL NEUPAG
C
      IF(LXOUT(0)) WRITE(LUNTRM,1001) (ZXLAB(IJ),IJ=1,3),
     >    NZX,ZX(1),ZX(NZX),SCLAB(1,1)
C
 1001 FORMAT(/' EXPICK - CHOOSE FIXED ',3A10/
     >'  (NPTS=',I5,' RANGE OF VALUES ',1PE11.4,' TO ',1PE11.4,')'/
     >'  SCALAR KEY NAME FOR 1D OUTPUT FILE:  "',A,'"'//
     >'  OPTIONS:'/
     >'   A - AVG - SPECIFY AVERAGING RANGE.  OUTPUT SLICE WILL BE'/
     >'             AVERAGE OF ALL INPUT DATA SLICES W/IN THE RANGE'/
     >'   S - SNGL- SPECIFY SINGLE VALUE-- NEAREST SLICE IN THE'/
     >'             INPUT DATA WILL BE EXTRACTED FOR 1D OUTPUT FILE'/
     >'   P - INTRP-SPECIFY SINGLE VALUE-- INPUT DATA WILL BE'/
     >'             LINEARLY INTERPOLATED TO THIS POINT'/
     >'   I - IND - SPECIFY INDEX OF SLICE TO EXTRACT FOR OUTPUT'/
     >'   K - KEY - CHANGE FIXED X SCALAR KEYWORD NAME'/
     >'   Q - QUIT- ABORT THIS NODE'/)
      CALL UREAD('EXPICK:  ENTER DATA EXTRACTION OPTION A/S/I/Q:$')
      IANS=IXUOPC('ASIKQP$')
C
      CALL UCHKOP(IANS,0,1,100,-1,*10)
C
      GO TO (100,200,300,350,400,250) IANS
C
 100  CONTINUE
C
      CALL EXPMCK(ZX,NZX,*10)
      CALL UREADF('EXPICK: ENTER AVG LOWER LIMIT:$',Z1)
      CALL UREADF('EXPICK: ENTER AVG UPPER LIMIT:$',Z2)
C
      CALL EXPCKI(ZX,NZX,2,Z1,Z2,IZX1,IZX2)
      IF(IZX1.EQ.0) CALL EXPERR(
     >'? NULL OR INVALID AVERAGING RANGE',*10)
C
C  VALID RANGE
C
      SCV(1)=0.5*(ZX(IZX1)+ZX(IZX2))
      SCV(INSC1)=ZX(IZX1)
      SCV(INSC2)=ZX(IZX2)
      INSC=INSC2
      GO TO 1000
C
C  A SINGLE SLICE
C
 200  CONTINUE
      CALL UREADF('EXPICK: SPECIFY SINGLE FIXED VALUE:$',Z0)
      CALL EXPCKI(ZX,NZX,1,Z0,ZDUM,IZX0,IDUM)
      ZPICK=ZX(IZX0)
      GO TO 500
C
C  A SINGLE SLICE (INTERPOLATION)
C
 250  CONTINUE
      CALL UREADF('EXPICK: SPECIFY SINGLE FIXED VALUE:$',Z0)
      IF((Z0.LT.ZX(1)).OR.(Z0.GT.ZX(NZX))) THEN
         call uermsf('%expick:  interpolation target out of range',
     >                 z0,0)
         go to 10
      ENDIF
      CALL EXPCKI(ZX,NZX,3,Z0,ZDUM,IZX1,IZX2)
      ZINTRP=(ZX(IZX2)-Z0)/(ZX(IZX2)-ZX(IZX1))
      ZPICK=Z0
      SCV(INSC1)=ZX(IZX1)
      SCV(INSC2)=ZX(IZX2)
      GO TO 500
C
C  SPECIFY SINGLE INDEX
C
 300  CONTINUE
      CALL UREADI('EXPICK: SPECIFY SLICE INDEX (1 TO NPTS):$',IND)
      IF((IND.LT.1).OR.(IND.GT.NZX))
     >    CALL EXPERR('? SPECIFIED INDEX OUT OF BOUNDS',*10)
C
      IZX0=IND
C
      GO TO 500
C
C  SET KEYNAME
C
 350  CONTINUE
      CALL UFGKEY(SCLAB(1,1))
C
      GO TO 10
C
C-----------------------------------
C  EXIT
C
 400  CONTINUE
      RETURN
C
C-----------------------------------
C
C  SINGLE SLICE-- SET SCALAR VALUES
C
 500  CONTINUE
      SCV(1)=ZPICK
      INSC=NUMSC+1
C
      IF(ZINTRP.LT.0.0) then
         IZX1=IZX0
         IZX2=IZX0
      endif
C
C  VERIFICATION
C
 1000 CONTINUE
      IF(ZINTRP.LT.0.0) then
         WRITE(LUNTRM,2001)
 2001    FORMAT(' EXTRACTION FIXED POINT DATA:')
      else
         WRITE(LUNTRM,2011)
 2011    FORMAT(' EXTRACTION FIXED POINT DATA (interpolation):')
      endif
      WRITE(LUNTRM,2002) (SCLAB(IJ,1),IJ=1,3),SCV(1)
      IF(IZX1.NE.IZX2) THEN
        WRITE(LUNTRM,2002) (SCLAB(IJ,INSC1),IJ=1,3),SCV(INSC1)
        WRITE(LUNTRM,2002) (SCLAB(IJ,INSC2),IJ=1,3),SCV(INSC2)
      ENDIF
 2002 FORMAT(2X,A10,1X,A10,1X,'(',A10,'):  ',1PE11.4)
      CALL UREAD('EXPICK: ENTER "Y" TO VERIFY:$')
      IF(LYES(0)) THEN
        IER=0
        GO TO 400
      ENDIF
      GO TO 10
      END
C******************** END FILE EXPICK.FOR ; GROUP EXSUBS ******************
