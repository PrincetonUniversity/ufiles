C******************** START FILE EXTRK1.FOR ; GROUP EXSUBS *************
C---------------------------------------------------------------------
C  EXTRK1
C
C  EXTRACT A SLICE FROM THE 2D DATA FOR OUTPUT TO 1D UFILES
C
C  **MODIF DMC SEPT 1987** EXTRACTED OUTPUT MAY BE INTENDED FOR
C  RPLOT SCALAR MULTIPLOT DATA INSTEAD
C  **IF SO THE OUTPUT LUN ILUNO IS ZERO ON ENTRY TO THIS ROUTINE
C  **UFILES-SPECIFIC OPTIONS DISABLED IN THAT CASE...
C
C  OPTIONS INCLUDE PLOTTING THE 2D INPUT DATA, PLOT AND VERIFY THE
C  OUTPUT 1D DATA, AVERAGING OF MULTIPLE SLICES TO DEFINE THE OUTPUT
C  SLICE.
C
      SUBROUTINE EXTRK1
C
      USE EXTRAC_MOD
C
      CHARACTER*10 ZFLAB(3)
C
      logical lxout
C
C-----------------------------------------------------------------------
C
      luntrm=lnout(0)
      DO I=1,3
        ZFLAB(I)=FLAB(I)
      ENDDO
C
      IF(ILUNO.LE.0) ICOMPR=0
 10   CONTINUE
      CALL NEUPAG
      IF(LXOUT(0)) WRITE(LUNTRM,1001) (FLAB(IJ),IJ=1,3),
     >     (XLAB(IJ),IJ=1,3),(YLAB(IJ),IJ=1,3)
 1001 FORMAT(/' EXTRK1 OPTIONS:'/
     >'  G - GRAPH THE 2D INPUT DATA F(X,Y)'/
     >'      F IS ',3A10/
     >'      X IS ',3A10/
     >'      Y IS ',3A10/
     >'  A - EXTRACT A SLICE OF F VS. X AT FIXED Y'/
     >'  B - EXTRACT A SLICE OF F VS. Y AT FIXED X'/
     >'  M - *NEW* - extract max[over all Y](F) vs. X'/
     >'  N - *NEW* - extract max[over all X](F) vs. Y'/
     >'  Q - QUIT THIS ROUTINE')
      IF(LXOUT(0).AND.(ILUNO.GT.0)) WRITE(LUNTRM,1002)
     >         CMPSTA(ICOMPR)
 1002 FORMAT(
     >'  I - SET EXTRACTION INTERPOLATION/EXTRAPOLATION OPTIONS'/
     >'  C - COMPRESS- TOGGLE OUTPUT DATA FORMAT FLAG, NOW "',A,'"'/
     >'  4 - FORMAT  - *new* Ufile output format control menu')
C
      CALL UREAD('EXTRK1:  ENTER CONTROL OPTION G/A/B/Q:$')
      IF(ILUNO.GT.0) THEN
        IANS=IXUOPC('GABC4QIMN$')
      ELSE
        IANS=IXUOPC('GABGGQGMN$')  ! 1ST "G" TAKEN, OTHERS PLACEHOLDERS
      ENDIF
      CALL UCHKOP(IANS,0,1,100,-1,*10)
C
      GO TO (100,200,300,50,48,400,450,600,700) IANS
C
 48   continue
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      go to 10
C
 50   CONTINUE
      ICOMPR=ITOGGL-ICOMPR
      GO TO 10
C
 100  CONTINUE
C
      CALL GRF3(X,F,Y,ZWK,NXACT,NYACT,NXACT,
     >   XLAB,YLAB,FLAB,XLAB(3),YLAB(3),FLAB(3),
     >   ZTITLE,1,0,0,IDEV,ISHOT,0,JSHOT,1,ISMOO)
C
      GO TO 10
C
 200  CONTINUE
      IXSEL=1
      CALL EXPICK(YLAB,Y,NYACT,IY1,IY2,INSC,ZINTRP,IER)
      IF(IER.NE.0) GO TO 10
      CALL EXPGET(F,NXACT,NYACT,IXSEL,IY1,IY2,ZINTRP,ZWK,ZWK1,MAXIND,
     >            X,XTARG,NXTARG,LXTRAP,XTRAP,IER)
      CALL EXPWRT(XTARG,ZWK1,NXTARG,XLAB,INSC)
      IF(ILUNO.LE.0) RETURN
      GO TO 10
C
 300  CONTINUE
      IXSEL=2
      CALL EXPICK(XLAB,X,NXACT,IX1,IX2,INSC,ZINTRP,IER)
      IF(IER.NE.0) GO TO 10
      CALL EXPGET(F,NXACT,NYACT,IXSEL,IX1,IX2,ZINTRP,ZWK,ZWK1,MAXIND,
     >            Y,YTARG,NYTARG,LYTRAP,YTRAP,IER)
      CALL EXPWRT(YTARG,ZWK1,NYTARG,YLAB,INSC)
      IF(ILUNO.LE.0) RETURN
      GO TO 10
C
 400  CONTINUE
      RETURN
C
C  INTERPOLATION/EXTRAPOLATION OPTIONS
C
 450  CONTINUE
      CALL EXINTX
      GO TO 10
C
C-------------------------------------
C new options -- dmc 18 Aug 1992
C
 600  CONTINUE
      IF(MAX(NXTARG,NXACT).GT.MAXIND) THEN
        CALL UERMSI('?EXTRK1 -- INSUFFICIENT ARRAY SPACE, MAXIND',
     >      MAXIND,0)
        GO TO 10
      ENDIF
C
      FLAB(1)='MAX: '//ZFLAB(1)(1:5)
      FLAB(2)=ZFLAB(1)(6:10)//ZFLAB(2)(1:5)
      FLAB(3)=ZFLAB(2)(6:10)//ZFLAB(3)(1:5)
C
      DO IX=1,NXACT
        IADR=IX
        ZWK(IX)=F(IADR)
        DO IY=2,NYACT
          IADR=(IY-1)*NXACT+IX
          ZWK(IX)=MAX(ZWK(IX),F(IADR))
        ENDDO
      ENDDO
C
      CALL EXPINT(X,ZWK,NXACT,XTARG,ZWK1,NXTARG,LXTRAP,XTRAP)
      CALL EXPWRT(XTARG,ZWK1,NXTARG,XLAB,NUMSC)
      GO TO 900
C
 700  CONTINUE
      IF(MAX(NYTARG,NYACT).GT.MAXIND) THEN
        CALL UERMSI('?EXTRK1 -- INSUFFICIENT ARRAY SPACE, MAXIND',
     >      MAXIND,0)
        GO TO 10
      ENDIF
C
      FLAB(1)='MAX: '//ZFLAB(1)(1:5)
      FLAB(2)=ZFLAB(1)(6:10)//ZFLAB(2)(1:5)
      FLAB(3)=ZFLAB(2)(6:10)//ZFLAB(3)(1:5)
C
      DO IY=1,NYACT
        IADR=(IY-1)*NXACT+1
        ZWK(IY)=F(IADR)
        DO IX=2,NXACT
          IADR=(IY-1)*NXACT+IX
          ZWK(IY)=MAX(ZWK(IY),F(IADR))
        ENDDO
      ENDDO
C
      CALL EXPINT(Y,ZWK,NYACT,YTARG,ZWK1,NYTARG,LYTRAP,YTRAP)
      CALL EXPWRT(YTARG,ZWK1,NYTARG,YLAB,NUMSC)
      GO TO 900
C
 900  CONTINUE
      DO I=1,3
        FLAB(I)=ZFLAB(I)
      ENDDO
      GO TO 10
C
      END
C******************** END FILE EXTRK1.FOR ; GROUP EXSUBS ***************
