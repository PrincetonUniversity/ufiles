C******************** START FILE EXINTX.FOR ; GROUP EXSUBS ******************
C---------------------------------------------------------------------
C  EXINTX
C
C  SUPPLY OPTIONS FOR DATA INTERPOLATION OR EXTRAPOLATION
C
C  EXTRACTED PROFILES DEFAULT TO HAVING THE SAME INDEPENDENT X AXIS
C  AS THE PARENT 2D DATA; BUT THROUGH THIS ROUTINE AN OPTION TO
C  SUPPLY X FROM AN INDEPENDENT SOURCE (1D UFILE) IS SUPPLIED.
C    THE UNITS OF THE 2ND X AND THE DEGREE OF OVERLAP WITH THE ORIGINAL
C  DATA X ARE CHECKED
C
      SUBROUTINE EXINTX
C
      USE EXTRAC_MOD
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LXOUT
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
 10   CALL NEUPAG
      IF(LXOUT(0)) WRITE(LNOUT(0),1000) (XLAB(IJ),IJ=1,3),
     >     (YLAB(IJ),IJ=1,3)
C
 1000 FORMAT(/'  X IS ',2A10,1X,A10/'  Y IS ',2A10,1X,A10/
     >'  ENTER X TO MODIFY X INTERPOLATION; Y TO MODIFY Y ',
     >'  INTERPOLATION; Q TO QUIT')
C
      CALL UREAD('EXINTX:  AXIS SELECTION:$')
      IANS=IXUOPC('XYQ$')
C
      IF(IANS.EQ.0) THEN
        CALL UERMSG(' ILLEGAL OPCODE',' ',1)
        GO TO 10
      ENDIF
C
      IF(IANS.EQ.3) RETURN
C
      IF(IANS.EQ.1) THEN
        CALL EXINT0(ILUNX,XLAB,X,NXACT,XTARG,NXTARG,LXTRAP,XTRAP)
      ELSE IF(IANS.EQ.2) THEN
        CALL EXINT0(ILUNY,YLAB,Y,NYACT,YTARG,NYTARG,LYTRAP,YTRAP)
      ENDIF
C
      RETURN
      END
C******************** END FILE EXINTX.FOR ; GROUP EXSUBS ******************
