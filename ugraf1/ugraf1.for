C******************** START FILE UGRAF1.FOR ; GROUP UGRAF1 ************
C--------------------------------------------------------------
C  UGRAF1  PROGRAM TO GRAPH CONTENTS OF 1D USER DATA FILE (UFILE)
C
      PROGRAM UGRAF1
C  MAX NUMBER OF ASSOC. SCALAR QUANTITIES HANDLED:
      PARAMETER (MAXSC=200)
C  MAX NUMBER OF PTS IN FUNCTION
      PARAMETER (MAXN=200000)
C
C  DATA BUFFERS AND LABELS
      REAL X(MAXN),Y(MAXN),XTRVAL(MAXSC)
      INTEGER IORDSC(MAXSC)
      CHARACTER*10 ZSDATE,XLAB(3),YLAB(3),XTRLAB(3,MAXSC),ZKEY
      CHARACTER*4 IDEV
C
      logical lxout
C
C  L.U.N FOR DATA INPUT
C
      DATA ILUN/21/
C
C  TEMPORARY COMMENTS FILE
C
      DATA ILUNC/22/
      DATA ICOPN/0/
C
C  DEFAULT KEYWORD SCALAR FOR DISPLAY
C
      DATA ZKEY/'??????????'/
C
CCC	CALL USINIT
CCC	CALL UAHEAD
      CALL UINITG("UGRAF1")
      call urdext('ifi')
      luntrm=lnout(0)
C
 10   CONTINUE
      CALL UFNTER(ILUN,'1D INPUT FILES      ')
C
 20   CONTINUE
      CALL NEUPAG
 21   IF(LXOUT(0)) WRITE(LUNTRM,2002)
 2002 FORMAT(/
     >' ENTER "D" TO CHANGE FILE NAMING CONVENTION'/
     >' ENTER "L" TO SPECIFY KEYWORD SCALAR TO DISPLAY IN 1D PLOT'/
     >)
      CALL URSHOT('UGRAF1',', "Q" TO QUIT','QDL',ISHOT,IOP)
      IF(IOP.EQ.1) GO TO 900
      IF(IOP.EQ.2) GO TO 10
      IF(IOP.EQ.3) THEN
        CALL UFGKEY(ZKEY)
        GO TO 20
      ENDIF
      IF(ISHOT.EQ.0) GO TO 900
C
      CALL NEUPAG
      CALL UFOPRD(ILUN,ISHOT,IER)
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 21
C
      CALL UF1DRD(ILUN,IDEV,ZSDATE,
     >   X,Y,MAXN,NRET,IPROC,
     >   XLAB,YLAB,MAXSC,NUMSC,XTRVAL,XTRLAB,IER)
C
      IF(IER.NE.0) THEN
        CALL UCLEAR
        CALL UFCLOS(ILUN)
        GO TO 20
      ENDIF
C
C  SPOOL COMMENTS TO TEMPORARY FILE
      IF(ICOPN.EQ.1) CLOSE(UNIT=ILUNC,STATUS='DELETE')
C	OPEN(UNIT=ILUNC,FILE='ZUFCMMTS.TMP',TYPE='SCRATCH',
      OPEN(UNIT=ILUNC,STATUS='SCRATCH',
     >       ACCESS='SEQUENTIAL')
      ICOPN=1
C
      CALL USPOOL(ILUN,ILUNC)
      CALL UFCLOS(ILUN)
C
      GO TO 31
 30   CONTINUE
      CALL NEUPAG
 31   CONTINUE
C
      WRITE(LUNTRM,3001) NUMSC
 3001 FORMAT(' NUMBER OF ASSOCIATED SCALARS IN FILE:  ',I3)
      IF(LXOUT(0)) WRITE(LUNTRM,3003)
 3003 FORMAT(/' ** UGRAF1 OPTIONS:'/
     >'  1 - PRESET PLOT SCALING/AXES DEFAULTS'/
     >'  P - PLOT THE DATA'/
     >'  L - LIST THE ASSOCIATED SCALAR QUANTITIES'/
     >'  C - SPOOL FILE COMMENTS TO TTY (USE CTRL(Q), CTRL(S))'/
     >'  S - GET NEW SHOT'/
     >'  D - CHANGE FILENAMING CONVENTION'/
     >'  Q - QUIT UGRAF1')
      CALL UREAD('UGRAF1:  ENTER CONTROL CODE:$')
      IOP=IXUOPC('1PLCSDQ$')
      CALL UCHKOP(IOP,0,1,100,-1,*31)
      GO TO (35,100,50,40,20,10,900) IOP
C
 35   CONTINUE
      CALL GPRESET
      GO TO 30
C  SPOOL COMMENTS TO TTY
 40   CONTINUE
      REWIND ILUNC
      CALL NEUPAG
      CALL USPOOL(ILUNC,LUNTRM)
      CALL UPAUST(1)
      GO TO 30
C
 50   CONTINUE
      IF(NUMSC.GT.0) THEN
        CALL UFSCLK(ILUN,ISHOT,NUMSC,XTRVAL,XTRLAB,IORDSC,0,0)
      ELSE
        CALL UERMSG(' % NO SCALARS IN FILE',' ',-1)
        GO TO 31
      ENDIF
C
      GO TO 30
C
 100  CONTINUE
      IF(NUMSC.GT.0) THEN
        INUM0=1
        IND=MAX0(1,IUFKEY(ZKEY,XTRLAB,NUMSC))
      ELSE
        INUM0=0
        IND=1
      ENDIF
      CALL GRFUF1(X,Y,NRET,IPROC,
     >     YLAB,XLAB,ISHOT,IDEV,ZSDATE,INUM0,XTRVAL(IND),XTRLAB(1,IND))
C
      GO TO 30
C  EXIT
 900  CONTINUE
        CALL NEUPAG
        CALL UEXITA(0)
        STOP
C
      	END
C******************** END FILE UGRAF1.FOR ; GROUP UGRAF1 ******************
