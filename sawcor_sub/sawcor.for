C******************** START FILE SAWCOR.FOR ; GROUP SAWCOR *************
C-----------------------------------------------------------------
C  SAWCOR
C
C  COMPUTE SAWTOOTH CORRELATION FUNCTION FOR INPUT TIME SERIES
C
C  USE USMOO1 AS A SUBROUTINE TO DEFINE
C   (A) TIMESCALE FOR SAWTEETH = SMOOTHING DELTA
C   (B) VARIABLE BASELINE FOR SAWTOOTH CORRELATION INTEGRAL (THE
C       SMOOTHED TIMETRACE = THE BASELINE)
C
      SUBROUTINE SAWCOR(X,Y,N,YS,DEL,EPS,S1,S2,XSAW,YSAW,SSAW,NSAW,
     >     XLAB,YLAB,XUN,YUN,DATID,PROGID,ISHOT,IDEV,ZSDATE)
C
C  ORIG. AND SMOOTHED DATA (CF USMOO1 SUBROUTINE):
      REAL X(N),Y(N),YS(N),DEL(N),EPS(N)
C
C  SAWTOOTH CORRELATION FUNCTIONS
C
      REAL S1(N)  ! MINIMUM CORRELATION
      REAL S2(N)  ! NORMALIZED CORRELATION
C
C  "ACCEPTED SAWTEETH" OUTPUT
C
      REAL XSAW(N)  ! SELECTED SAWTOOTH TIMES
      REAL SSAW(N)  ! NORMALIZED CORRELATION VALUE OF EVENT
C
C  PIECEWISE ENTERED MINIMUM CORRELATION CRITERION
C
      PARAMETER (IPIECE=50)
      REAL XPC(IPIECE),SPC(IPIECE)
C
C   NSAW (OUTPUT) = NUMBER OF SELECTED SAWTOOTH EVENTS
C
C  LABELS (PASSED, CF. USMOO1, GRFUF1 SUBROUTINES)
C
      CHARACTER*10 XLAB,YLAB(2),XUN,YUN,DATID,PROGID
C
      CHARACTER*4 IDEV
      CHARACTER*10 ZSDATE
C
C  LOCAL LABELS
C
      CHARACTER*30 ZXL,ZYL,ZRL,ZS1,ZS2,ZSAW,ZSLMIN
C
      CHARACTER*6 ZZWORD
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C-----------------------------------
C
C  LABEL SET UP
C
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
      LOGICAL LXOUT
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => SAWCOR               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA ZDFAC/0.5/
      DATA ZSEP/0.2/
C => END DATA BLOCK
C ====================
C
      ZXL=XLAB//'          '//XUN
      ZYL=YLAB(1)//YLAB(2)//YUN
C
      ZRL='SMOOTHING RESIDUE   '//YUN
C
      ZS1='ABSOLUTE CORRELATION'//YUN
      ZS2='NORMAL. CORRELATION           '
      ZSLMIN='MINIMUM CORRELATION           '
C
      ZSAW='OUTPUT SAWTOOTH DATA          '
C
      LUNTTY=LNOUT(0)
C
C-----------------------------------
C
C  INTERACTIVE DATA SMOOTH FOR TIMESCALE/BASELINE INFO
C
      CALL USMOO1(X,Y,N,YS,DEL,EPS,ZEND1,ZEND2,ZBASE,NBASE,
     >              ZDROP,NDROP,XLAB,YLAB,XUN,YUN,DATID,PROGID)
C
C-----------------------------------
C
C  EVALUATE CORRELATION FUNCTIONS
C
C  "RESIDUE" OF SMOOTHING-- "UNSMOOTH PART" - HI-PASS
C
      DO 10 J=1,N
        YS(J)=Y(J)-YS(J)
 10   CONTINUE
C
 12   CONTINUE
      CALL UREADF(
     >'SAWCOR:  ENTER MULTIPLICATIVE FACTOR FOR DELTA:$$',ZDFAC)
C
      ZDFAC=AMAX1(0.01,ZDFAC)
C
      ZDMAX=0.0
      DO 20 J=1,N
        ZDMAX=AMAX1(ZDMAX,DEL(J))
        DEL(J)=ZDFAC*DEL(J)
 20   CONTINUE
C
      ZDMIN=0.1*ZDMAX
      CALL UREADF(
     >'SAWCOR:  ENTER MINIMUM CORRELATION DELTA (seconds):$$',ZDMIN)
C
      DO 30 J=1,N
        IF(DEL(J).GE.ZDMIN) THEN
          CALL SAWCRL(X,YS,DEL,N,J,S2(J),ZEND1,ZEND2)
        ELSE
          S2(J)=0.0
        ENDIF
 30   CONTINUE
C
      DO 40 J=1,N
        DEL(J)=DEL(J)/ZDFAC
 40   CONTINUE
C
C-----------------------------------
C
C  USER OPTIONS
C
      NSAW=0
C
 50   CONTINUE
      CALL NEUPAG
C
      IF(LXOUT(0)) WRITE(LUNTTY,2001) ZDFAC
 2001 FORMAT(/
     >' USER OPTIONS:'/
     >'  1 - PLOT ORIGINAL TIMETRACE DATA'/
     >'  2 - PLOT UNSMOOTHED RESIDUE OF TIMETRACE DATA'/
     >'  4 - PLOT COMPUTED NORMALIZED SAWTOOTH CORRELATION DATA'/
     >'  C - CALCULATE CORRELATION DATA WITH NEW RESCALED DELTA '/
     >'      FUNCTION [DELTA(CORR) = ',1PE11.4,' * DELTA(SMOOTH) ]'/
     >'  S - SELECT SAWTOOTH TIMES FROM CORRELATION DATA'/
     >'  H - ADD/DELETE SAWTOOTH TIMES BY HAND'/
     >'  P - PLOT SELECTED SAWTEETH'/
     >'  Q - QUIT (ABORT) RETURN NO DATA'/
     >'  R - RETURN SAVED SAWTOOTH SEQUENCE'/
     >)
C
      CALL UREAD('SAWCOR:  SPECIFY DATA/PLOT OPTION:$')
C
      IF(LCHAR('1')) THEN
        CALL GRFUF1(X,Y,N,0,
     >     ZYL,ZXL,ISHOT,IDEV,ZSDATE,0,ZDUMMY,ZXL)
C
      ELSE IF(LCHAR('2')) THEN
        CALL GRFUF1(X,YS,N,0,
     >     ZRL,ZXL,ISHOT,IDEV,ZSDATE,0,ZDUMMY,ZXL)
C
      ELSE IF(LCHAR('4')) THEN
        CALL GRFUF1(X,S2,N,0,
     >     ZS2,ZXL,ISHOT,IDEV,ZSDATE,0,ZDUMMY,ZXL)
C
      ELSE IF(LCHAR('Q')) THEN
        NSAW=0
        RETURN
C
      ELSE IF(LCHAR('S')) THEN
        CALL PCIDEF(X,S1,N,XPC,SPC,IPC,IPIECE,
     >                ZXL,ZSLMIN,ZXL(21:30),ZSLMIN(21:30))
        ZSEP=0.2
        CALL UREADF(
     >'SAWCOR:  ENTER MINIMUM EVENT SEPERATION FACTOR (* DELTA(SM)):$$',
     >           ZSEP)
C
        CALL CORLIS(X,Y,YS,S1,S2,DEL,N,ZSEP,XSAW,YSAW,SSAW,NSAW)
C
      ELSE IF(LCHAR('P')) THEN
C  GRAPH THE UNSMOOTHED DATA
        IF(NSAW.GT.0) THEN
          CALL GRFFIT(X,Y,N,0,ZYL,ZXL,ISHOT,IDEV,ZSDATE,
     >              0,XTRVAL,XTRLAB,NSAW,XSAW,YSAW)
        ELSE
          CALL GRFUF1(X,Y,N,0,ZYL,ZXL,ISHOT,IDEV,ZSDATE,
     >              0,XTRVAL,XTRLAB)
        ENDIF
C
      ELSE IF(LCHAR('H')) THEN
        CALL INORDU(XSAW,YSAW,N,NSAW,'SAWTOOTH TIMES',0)
        IF(NSAW.GT.0) CALL FSNORD(X,Y,YS,S2,N,XSAW,NSAW,YSAW,SSAW)
C
      ELSE IF(LCHAR('R')) THEN
        IF(NSAW.EQ.0) THEN
          CALL UERMSG(' ?SAWCOR:  NO SAWTOOTH SEQUENCE DEFINED',' ',1)
        ELSE
          RETURN
        ENDIF
C
      ELSE IF(LCHAR('C')) THEN
        GO TO 12
      ELSE
        CALL CDCOD(ZZWORD)
        CALL UERMSG(' %SAWCOR:  UNKNOWN OPTION',ZZWORD,1)
      ENDIF
C
      GO TO 50
      END
C******************** END FILE SAWCOR.FOR ; GROUP SAWCOR ***************
