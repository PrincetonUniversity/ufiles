C******************** START FILE CORLIS.FOR ; GROUP SAWCOR ******************
C------------------------------------------------------------------
C  CORLIS
C  DMC NOV 1985
C
C  SELECT SAWTOOTH TIMES FROM SAWTOOTH CORRELATION TRACE
C
      SUBROUTINE CORLIS(X,Y,YS,SMIN,SACT,DEL,N,FDMIN,
     >                    XSAW,YSAW,SSAW,NSAW)
C
C  ** INPUT DATA **
C
      REAL X(N)  ! DATA TIMES
      REAL Y(N)  ! ORIG. DATA
      REAL YS(N) ! RESIDUE; Y(SMOOTHED)(J) = Y(J)-YS(J)
C
      REAL SMIN(N)	! MINIMUM CORRELATION TO QUALIFY AS SAWTOOTH
      REAL SACT(N)	! ACTUAL CORRELATION (ALREADY CALCULATED)
C
      REAL DEL(N)	! TIME DELTA FCN USED FOR SMOOTHING, CORRELATION
C
      REAL FDMIN	! FDMIN*DEL(N) = MINIMUM SEPERATION BTW. EVENTS
C
C  ** OUTPUT DATA **
C
      INTEGER NSAW	! NUMBER OF SAWTOOTH EVENTS FOUND
C
      REAL XSAW(N)	! TIME OF EVENTS
      REAL YSAW(N)	! Y(SMOOTHED) AT TIME OF EVENT
      REAL SSAW(N)	! SAWTOOTH CORRELATION VALUE AT TIME OF EVENT
C
C
C  ALGORITHM:  IN EACH CONTIGUOUS REGION {J} WHERE SACT(J).GE.SMIN(J),
C   THE EVENT TIME IS X(K), WHERE K IN {J} MAXIMIZES SACT(J)-SMIN(J).
C
C  IF THE RESULTING CONSECUTIVE MAXIMA DO NOT SATISFY THE MINIMUM
C   TIME SEPERATION CRITERION, THEY ARE COMBINED AND THE GREATEST MAXIMA
C   IS CHOSEN.
C
C-----------------
C
C  EXECRABLE CODE
C
      NSAW=0
      ISAW=0
      ISTART=0
C
 10   CONTINUE
C  FIND NEXT MAXIMA
      ISAWP=ISAW
C  ISTART = SCAN START ON INPUT
      CALL FNSMAX(SMIN,SACT,N,ISTART,ISAW)
C  ISTART = SCAN END = START OF NEXT SCAN ON OUTPUT
C  ISAW = 0 OR LOCATION OF NEXT MAXIMA
      IF(ISAW.EQ.0) GO TO 100
C
C  CHECK SEPERATION CRITERIA
C
      IF(ISAWP.EQ.0) GO TO 50
C
      ZTMIN=FDMIN*AMAX1(DEL(ISAW),DEL(ISAWP))
C
      IF((X(ISAW)-X(ISAWP)).GT.ZTMIN) GO TO 50
C
C  EVENTS TOO CLOSE: SAVE ONLY THE BETTER MAXIMA
C
      IF((SACT(ISAWP)-SMIN(ISAWP)).GT.(SACT(ISAW)-SMIN(ISAW))) THEN
        ISAW=ISAWP
      ELSE
C  REPLACE MAXIMA
        XSAW(NSAW)=X(ISAW)
        SSAW(NSAW)=SACT(ISAW)
        YSAW(NSAW)=Y(ISAW)-YS(ISAW)
      ENDIF
C
      GO TO 10
C
C  NEW MAXIMA ACCEPTED
C
 50   CONTINUE
      NSAW=NSAW+1
        XSAW(NSAW)=X(ISAW)
        SSAW(NSAW)=SACT(ISAW)
        YSAW(NSAW)=Y(ISAW)-YS(ISAW)
C
      GO TO 10
C
C  EXIT
C
 100  CONTINUE
      RETURN
      END
C******************** END FILE CORLIS.FOR ; GROUP SAWCOR ******************
