C******************** START FILE FSNORD.FOR ; GROUP SAWCOR ******************
C-------------------------------------------------------------------
C  FSNORD
C  GIVEN ORDERED SAWTOOTH EVENT TIMES, EVALUATE CORRELATION AND
C  SMOOTHED DATA FCN AT EACH EVENT TIME
C
      SUBROUTINE FSNORD(X,Y,YS,S,N,XSAW,NSAW,YSAW,SSAW)
C
C  INPUT
      REAL X(N)	! ORIG DATA TIMES
      REAL Y(N)	! ORIG DATA
      REAL YS(N)	! SMOOTHING RESIDUE Y(SMOOTHED)(J)=Y(J)-YS(J)
      REAL S(N)	! CORRELATION FUNCTION
C
      REAL XSAW(NSAW) ! EVENT TIMES
C
C  OUTPUT
      REAL YSAW(NSAW) ! INTERPOLATED SMOOTHED FCN AT EVENT TIMES
      REAL SSAW(NSAW) ! INTERPOLATED CORRELATION AT EVENT TIMES
C
C  ASSUME X,XSAW ARE ORDERED
C----
C
      ISRCH=0
      ISAW=1
C
      IF(XSAW(1).LT.X(1)) THEN
        CALL UERMSF('%EVENT TIME(S) PRECEDE FIRST DATA TIME',X(1),1)
 10     CONTINUE
          YSAW(ISAW)=0.0
          SSAW(ISAW)=0.0
          ISAW=ISAW+1
          IF(ISAW.GT.NSAW) GO TO 100  ! ***
          IF(XSAW(ISAW).LT.X(1)) GO TO 10
      ENDIF
C
 20   CONTINUE
      ISRCHP=ISRCH
      ISRCH=ISRCH+1
      IF(ISRCH.GT.N) GO TO 100
C
      IF(X(ISRCH).LE.XSAW(ISAW)) GO TO 20
C
C  FOUND ONE
C
      ZI=(X(ISRCH)-XSAW(ISAW))/(X(ISRCH)-X(ISRCHP))
      ZIP=1.0-ZI
C
      YSM=Y(ISRCH)-YS(ISRCH)
      YSMP=Y(ISRCHP)-YS(ISRCHP)
C
      YSAW(ISAW)=YSM*ZIP+YSMP*ZI
      SSAW(ISAW)=S(ISRCH)*ZIP+S(ISRCHP)*ZI
C
      ISAW=ISAW+1
      IF(ISAW.GT.NSAW) GO TO 100
C
      ISRCH=ISRCH-1  ! MIGHT BE IN SAME INTERVAL
C
      GO TO 20
C
C  ANY LEFT?
C
 100  CONTINUE
      IF(ISAW.LE.NSAW) THEN
        CALL UERMSF('%EVENT TIME(S) AFTER LAST DATA TIME',X(N),1)
 150    CONTINUE
          YSAW(ISAW)=0.0
          SSAW(ISAW)=0.0
          ISAW=ISAW+1
          IF(ISAW.GT.NSAW) GO TO 200  ! ***
          GO TO 150
      ENDIF
C
 200  CONTINUE
      RETURN
      END
C******************** END FILE FSNORD.FOR ; GROUP SAWCOR ******************
