C******************** START FILE SAWCRL.FOR ; GROUP SAWCOR ******************
C-------------------------------------------------------
C  SAWCRL
C
C  COMPUTE AND NORMALIZE SAWTOOTH CORRELATION INTEGRAL
C   USE FILFCN CALL - JUST A SUBTLE TWIST ON THE SMOOTHING
C   INTEGRAL
C
      SUBROUTINE SAWCRL(X,YS,DEL,N,J0,CORR2,ZENDA,ZENDB)
C
C  X(N),YS(N) - FCN PART OF CORRELATION INTEGRAND
C   INTEGRAL = CONVOLUTION OF FCN WITH "SAWTOOTH WEIGHTING FCN":
C
C           *
C          *|
C         * |
C        *  |
C W =   *-------*  OF NORMALIZED AREA 1
C           |  *
C           | *
C           |*
C           *
C
C   THIS IS JUST AN "ANTISYMMETRIC" VERSION OF THE SMOOTHING TRIANGLE
C   WEIGHTING FCN; THE SAME SUBROUTINE FILFN6, SLIGHTLY MODIFIED
C   DMC NOV. 1985, IS USED TO COMPUTE THE INTEGRAL.
C
C   DEL(N) GIVES (AS A FCN OF J0) GIVES THE WIDTH OF THE BASE OF THE
C   CONVOLUTION (I.E. INTEGRATE FROM X(J0)-DEL(J0) TO X(J0)+DEL(J0)
C
C   J0 IS THE CTR OF THE CONVOLUTION FINITE INTEGRAL
C
C   ZENDA,ZENDB -- FILFN6 END CONDITIONS
C     SAME AS IN USMOO1/FILTR6 SMOOTHING STUFF
C
C   THE OUTPUTS ARE ***
C
C   CORR1 = INTEGRAL RESULT * 3/2
C   CORR2 = CORR1 / (MAX(ABS(YS(J))) WHERE ABS(X(J)-X(J0)) .LT. DEL(J0)
C
      REAL X(N),YS(N),DEL(N)
C
      CORR1=0.0
      CORR2=0.0
      IF(DEL(J0).LE.0.0) RETURN
C
      ZMAX=0.0
C
      DO 10 J=J0,1,-1
        IF(ABS(X(J0)-X(J)).LT.DEL(J0)) THEN
          ZMAX=AMAX1(ZMAX,ABS(YS(J)))
        ELSE
          GO TO 12
        ENDIF
 10   CONTINUE
C
 12   CONTINUE
C
      DO 20 J=J0,N
        IF(ABS(X(J0)-X(J)).LT.DEL(J0)) THEN
          ZMAX=AMAX1(ZMAX,ABS(YS(J)))
        ELSE
          GO TO 22
        ENDIF
 20   CONTINUE
C
 22   CONTINUE
C
      IF(ZMAX.EQ.0.0) RETURN
C
      ZCORR=FILFN6(X,YS,N,J0,DEL,ZENDA,ZENDB,2)
C
      CORR1=1.5*ZCORR
C
      CORR2=CORR1/ZMAX
C
      RETURN
      END
C******************** END FILE SAWCRL.FOR ; GROUP SAWCOR ******************
