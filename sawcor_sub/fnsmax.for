C******************** START FILE FNSMAX.FOR ; GROUP SAWCOR ******************
C---------------------------------------------------------------
C  FNSMAX
C  FIND NEXT SAWTOOTH MAXIMUM
C
      SUBROUTINE FNSMAX(SMIN,SACT,N,ISTART,ISAW)
C
      REAL SMIN(N)	! MINIMUM CORRELATION VALUE OF INTEREST
      REAL SACT(N)	! ACTUAL CORRELATION FUNCTION
C
      INTEGER ISTART  ! SEARCH START INDEX INPUT
C
      INTEGER ISAW	! LOCATED MAXIMUM INDEX OUTPUT
C
C---------
C
      ISAW=0
 10   CONTINUE
      ISTART=ISTART+1
      IF(ISTART.GT.N) RETURN
C
C  LOOKING FOR FIRST ACCEPTABLE CORRELATION VALUE
C
      IF(SACT(ISTART).LT.SMIN(ISTART)) GO TO 10
C
C  FOUND START OF ACCEPTABLE CORRELATION REGION
C
      IMAX=ISTART
      SDIF=SACT(ISTART)-SMIN(ISTART)
C
 20   CONTINUE
      ISTART=ISTART+1
C
C  LOOKING FOR END OF ACCEPTABLE REGION
C
      IF(ISTART.GT.N) GO TO 100
      SDIFNW=SACT(ISTART)-SMIN(ISTART)
      IF(SDIFNW.LT.0.0) GO TO 100
C
      IF(SDIFNW.GT.SDIF) THEN
        IMAX=ISTART
        SDIF=SDIFNW
      ENDIF
C
      GO TO 20
C
C  EXIT
C
 100  CONTINUE
      ISAW=IMAX
      RETURN
      END
C******************** END FILE FNSMAX.FOR ; GROUP SAWCOR ******************
