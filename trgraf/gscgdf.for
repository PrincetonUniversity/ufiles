C******************** START FILE GSCGDF.FOR ; GROUP GSCALE ******************
C-------------
C  GSCGDF
C   NON-INTERACTIVE FETCH OF SCALING DEFAULTS
C
C  IAX=1:  X-AXIS SCALING;  IAX=2:  Y-AXIS SCALING
C   ISEL:  1,2,3,4, OR 5 TO SELECT OPTION AS IN SUBROUTINE GSCDEF
C    IF ISEL=3, ZARG1 AND ZARG2 ARE THE LOWER AND UPPER FIXED LIMITS
C    IF ISEL=4 OR 5, ZARG1 IS THE MULTIPLIER
C   FOR OTHER VALUES OF ISEL ZARG1 AND ZARG2 ARE IGNNORED
C
      SUBROUTINE GSCGDF(IAX,ISEL,ZARG1,ZARG2)
C
      use gscale_blk
C
      IF(IGSINI.EQ.0) CALL GSCINI
C
      GO TO (100,200) IAX
C  X AXIS
 100  CONTINUE
      ISEL=NOPTX
      GO TO (500,500,110,120,120) ISEL
C
 110  CONTINUE
      ZARG1=XMIN00
      ZARG2=XMAX00
      GO TO 500
C
 120  CONTINUE
      ZARG1=XRAT00
      GO TO 500
C  Y AXIS
 200  CONTINUE
      ISEL=NOPTY
      GO TO (500,500,210,220,220) ISEL
C
 210  CONTINUE
      ZARG1=YMIN00
      ZARG2=YMAX00
      GO TO 500
C
 220  CONTINUE
      ZARG1=YRAT00
      GO TO 500
C----
C EXIT
 500  CONTINUE
      RETURN
      END
C******************** END FILE GSCGDF.FOR ; GROUP GSCALE ******************
