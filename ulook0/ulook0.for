C******************** START FILE ULOOK0.FOR ; GROUP ULOOK0 ******************
C--------------------------------------------------------------
C  ULOOK0
C  PROGRAM TO LOOK AT CONTENTS OF 0D USER DATA FILE
C
      PROGRAM ULOOK0
C  MAX NUMBER OF ASSOC. SCALAR QUANTITIES HANDLED:
      PARAMETER (MAXSC=100)
C
C  DATA BUFFERS AND LABELS
      REAL XTRVAL(MAXSC)
      INTEGER IORDSC(MAXSC)
      CHARACTER*10 ZSDATE,XTRLAB(3,MAXSC)
      CHARACTER*4 IDEV
C
C  L.U.N FOR DATA INPUT
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
CC	CALL USINIT
CC	CALL UAHEAD
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR,lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => ULOOK0               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA ILUN/21/
C => END DATA BLOCK
C ====================
C
      CALL UINITG("ULOOK0")
      call urdext('ifi')
      luntrm=lnout(0)
C
 10   CONTINUE
      CALL UFNTER(ILUN,'0D INPUT FILE       ')
C
 20   CONTINUE
      CALL NEUPAG
 21   CALL UREAD(
     >'ULOOK0: ENTER 5 DIGIT SHOT #, "0" TO QUIT, "D" TO CHANGE NAMES$')
      IF(LCHAR('Q')) GO TO 100
      IF(LCHAR('D')) GO TO 10
      ISHOT=IDCOD(IERT)
      IF(ISHOT.EQ.0) GO TO 100
      IF(IERT.NE.0) GO TO 21
C
      CALL UFOPRD(ILUN,ISHOT,IER)
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 21
C
      CALL UF0DRD(ILUN,IDEV,ZSDATE,XTRVAL,XTRLAB,MAXSC,NUMSC,IER)
C
      CALL UFCLOS(ILUN)
C
      IF(IER.NE.0 .OR. NUMSC<=0) CALL UCLEAR
      IF(IER.NE.0 .OR. NUMSC<=0) GO TO 20
C
      IF(NUMSC.LE.0) THEN
        WRITE(LUNTRM,3001) NUMSC
        CALL UPAUST(1)
                     ELSE
        CALL UFSCLK(ILUN,ISHOT,NUMSC,XTRVAL,XTRLAB,IORDSC,0,0)
      ENDIF
 3001 FORMAT(' NUMBER OF ASSOCIATED SCALARS IN FILE:  ',I3)
      GO TO 20
C EXIT
 100  CONTINUE
        CALL NEUPAG
        CALL UEXITA(0)
        STOP
C
      	END
C******************** END FILE ULOOK0.FOR ; GROUP ULOOK0 ******************
