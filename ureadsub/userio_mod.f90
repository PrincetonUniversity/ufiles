!   SOFT CODED COMMAND CHARACTERS
!    E.G. MFILI (DFLT "@") INDIRECT INPUT FILE CHARACTER
!
!   OUTPUT LUN STACK FOR MULTIPLE SIMULTANEOUS INDIRECT FILES
!    OPEN FOR OUTPUT-- RECORDING OF PROMPTS/INSTRUCTIONS.
!
!   TYPEAHEAD BUFFER STACK TO ALLOW TYPEAHEAD PAST INDIRECT
!    INPUT FILENAMES
!
!  character buffers:  size:
!
