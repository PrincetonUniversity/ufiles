C     INTO UREAD PROGRAMS FROM DCL
C        SOFT-CODED UREAD COMMANDS THAT CAN BE TURNED OFF;
C     MAKE IT POSSIBLE TO TURN OFF UPPERCASE CONVERSION OF INPUT
C       >>TYPEAHEAD BUFFER STACK TO SUPPORT TYPEAHEAD THRU
C         MULTIPLE LEVELS OF COMMAND INPUT
C       >>OUTPUT LUN STACK SO THAT MULTIPLE LEVELS OF COMMAND
C         OUTPUT FILES MAY BE CREATED SIMULTANEOUSLY
