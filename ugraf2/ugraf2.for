C******************** START FILE UGRAF2.FOR ; GROUP UGRAF2 ************
C--------------------------------------------------------------
C  UGRAF2
C  PROGRAM TO GRAPH CONTENTS OF 1D USER DATA FILE
C
      PROGRAM UGRAF2
C
      parameter (maxind=200000)
      parameter (maxtot=5000000)
      PARAMETER (MAXSC=200)
C  DATA BUFFERS AND LABELS
      REAL X(MAXIND),Y(MAXIND),ZWK(MAXIND),F(MAXTOT),SCV(MAXSC)
      REAL FF(MAXTOT)
      CHARACTER*10 ZSDATE,XLAB(3),YLAB(3),FLAB(3)
      CHARACTER*15 ZTITLE(3)
      CHARACTER*4 IDEV
      CHARACTER*10 LYABL(5),SCLAB(3,MAXSC)
      INTEGER IORDSC(MAXSC)
C
      logical lxout
C
      DATA LYABL/'          ',' AVERAGED.',' SMOOTHED.',
     >             ' AVG+SM''D.',' SPECIAL. '/
C
C  L.U.N FOR DATA INPUT
C
      DATA ILUN/21/
C
C  TEMPORARY COMMENTS FILE
C
      DATA ILUNC/22/
      DATA ICOPN/0/
C
      NUMD=MAXTOT
C
      call ufheader("ugraf2")
      CALL UINITG("UGRAF2")
CC	CALL USINIT
CC	CALL UAHEAD
      call urdext('ifi')
      luntrm=lnout(0)
C
 10   CONTINUE
      CALL UFNTER(ILUN,'2D INPUT FILES      ')
C
 20   CONTINUE
      CALL NEUPAG
 21   CONTINUE
      CALL URSHOT('UGRAF2',', "0" TO QUIT, "D" TO CHANGE NAMES','QD',
     >	  ISHOT,IOP)
C
      IF(IOP.EQ.1) GO TO 900
      IF(IOP.EQ.2) GO TO 10
      IF(ISHOT.EQ.0) GO TO 900
C
      ier=0
      CALL UFOPRD(ILUN,ISHOT,IER)
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 21
C
      IX1MAX=MAXTOT/MAXIND
      CALL UF2DRD(ILUN,IDEV,ZSDATE,
     >   F,IX1MAX,X,MAXIND,Y,MAXIND,IPROC,
     >   NXACT,NYACT,1,
     >   FLAB,XLAB,YLAB,MAXSC,NUMSC,SCV,SCLAB,IER)
C
      IF(IER.NE.0) THEN
        CALL UCLEAR
        CALL UFCLOS(ILUN)
        GO TO 20
      ENDIF
C
      call ufmds_inf(ilun,ZTITLE(1),-1,ier)  ! MDS+ ?
      if (ier .eq. -77) then
         ZTITLE(1)='SHOTDATE: '
      endif
      ZTITLE(2)=ZSDATE
      IND=MIN0(5,(IPROC+1))
      ZTITLE(3)=LYABL(IND)
C
C  SPOOL COMMENTS TO TEMPORARY FILE
      IF(ICOPN.EQ.1) CLOSE(UNIT=ILUNC,STATUS='DELETE')
C	OPEN(UNIT=ILUNC,FILE='ZUFCMMTS.TMP',TYPE='SCRATCH',
      OPEN(UNIT=ILUNC,STATUS='SCRATCH',
     >       ACCESS='SEQUENTIAL')
      ICOPN=1
C
      CALL USPOOL(ILUN,ILUNC)
      CALL UFCLOS(ILUN)
C
C  EXAMINE SCALARS
C
      GO TO 31
 30   CONTINUE
      CALL NEUPAG
 31   CONTINUE
C
      WRITE(LUNTRM,3001) NUMSC
 3001 FORMAT(' NUMBER OF ASSOCIATED SCALARS IN FILE:  ',I3)
      IF(LXOUT(0)) WRITE(LUNTRM,3003)
 3003 FORMAT(/' ** UGRAF2 OPTIONS:'/
     >'  1 - PRESET PLOT SCALING/AXES DEFAULTS (2D PLOTS ONLY)'/
     >'  P - PLOT THE DATA'/
     >'  I - INTERCHANGE X AND Y AXES (FOR 3D PLOT VIEW)'/
     >'  L - LIST THE ASSOCIATED SCALAR QUANTITIES'/
     >'  C - SPOOL FILE COMMENTS TO TTY (USE CTRL(Q), CTRL(S))'/
     >'  S - GET NEW SHOT'/
     >'  D - CHANGE FILENAMING CONVENTION'/
     >'  Q - QUIT UGRAF2')
      CALL UREAD('UGRAF2:  ENTER CONTROL CODE:$')
      IOP=IXUOPC('1PILCSDQ$')
      CALL UCHKOP(IOP,0,1,100,-1,*31)
      GO TO (35,100,90,50,40,20,10,900) IOP
C
 35   CONTINUE
      CALL GPRESET
      GO TO 30
C
C  SPOOL COMMENTS TO TTY
 40   CONTINUE
      REWIND ILUNC
      CALL NEUPAG
      CALL USPOOL(ILUNC,LUNTRM)
      CALL UPAUST(1)
      GO TO 30
C
 50   CONTINUE
      IF(NUMSC.GT.0)
     >     CALL UFSCLK(ILUN,ISHOT,NUMSC,SCV,SCLAB,IORDSC,0,0)
      GO TO 30
C
C------
 90   CONTINUE
C  INTERCHANGE DATA DIMENSIONS
      CALL UFSWXY(F,FF,NUMD,X,NXACT,Y,NYACT,XLAB,YLAB)
      GO TO 30
C
C------
 100  CONTINUE
      ISMOO=0
      CALL GRF3(X,F,Y,ZWK,NXACT,NYACT,NXACT,
     >   XLAB,YLAB,FLAB,XLAB(3),YLAB(3),FLAB(3),
     >   ZTITLE,1,0,0,IDEV,ISHOT,0,ISHOT,1,ISMOO)
C
      GO TO 30
C  EXIT
 900  CONTINUE
        CALL NEUPAG
        CALL UEXITA(0)
        STOP
C
      	END
C******************** END FILE UGRAF2.FOR ; GROUP UGRAF2 ***************
