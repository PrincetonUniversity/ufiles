C******************** START FILE CONCAT.FOR ; GROUP CONCAT *************
C----------------------------------------------------------------------
C >>> CONCAT    MAY 1982 D. MC CUNE
C
C  MOD DMC 3 OCT 1990 -- PERMIT INPUT OF FILES THAT LACK SCALAR DATA--
C  PROMPT USER FOR SCALAR VALUES TO SUBSTITUTE
C
C  INITIAL VERSION UFILES-BASED GENERALIZED CONCATENATOR PROGRAM
C  CONCATENATE UP TO 50 DATA FILES CONTAINING DATA OF FORM
C  F(X) @FIXED Y, TO FORM A SINGLE FILE CONTAINING DATA OF FORM
C  F(Y,X).
C  BASED ON OLD SPECIAL PURPOSE PROGRAM [TRANSP.PDX]TVTCAT
C  WHICH WAS FOR PDX TVTS DATA ONLY.  SOME OF THE OLD NOMENCLATURE
C  HAS BEEN RETAINED-- THE FIXED Y MAY BE REFERRED TO AS "TIME" BUT
C  MAY IN FACT BE SOME OTHER QUANTITY.  FOR TVTS DATA CONCATENATION,
C  Y IS TIME.  ALSO SUBROUTINE NAMES BEGIN IN "TV" REFERRING TO TVTS
C -----
C  TVTCAT       MAY 81 D. MC CUNE
C  CONCATENATE TVT DATA
C  IE ASSEMBLE F(X,Y) FROM INDIVIDUAL LASER PROFILES F(X)
C
C  2D GRAPHS FOR PROFILES
C  2+3D GRAPHS OF F(X,Y)
C
C  ARBITRARY FILENAMEING ALLOWED FOR INPUT AND OUTPUT FILES
C  INPUT FILES MUST BE 1D UFILES ON CONSISTANT X-GRID AND MUST
C  EACH CONTAIN A KEYWORD SCALAR FOR THAT PROFILE'S FIXED Y
C  VALUE (E.G. TVTS LASER TIME).
C  OUTPUT FILES ARE 2D VS. X AND Y.
C
C
C  READ IN 1D LASER PROFILES
C  WRITE OUT 1D+TIME LASER PROFILE EVOLUTIONS
C
C  SORT INPUT PROFILES BY SHOT #
C  READ AS MANY AS YOU LIKE (UP TO 50)
C  GRAPH 'EM ANY WAY YOU LIKE
C
C  ASSEMBLE A SINGLE 2D OUTPUT PROFILE EVOLUTION ARRAY
C
C  ALLOW USER SELECTION OF TIMES BUT DEFAULT IS TO USE
C  LASER FIRING TIMES FROM FILE
C
C  PROGRAM-GENERATED COMMENTS IN OUTPUT FILE
C
C  UREAD FOR USER INTERFACE
C
C  IF NEEDED INSTALL OPTION TO DEFINE ADDL PROFILES VIA
C  LINEAR INTERPOLATION ON ANY TWO INPUT PROFILES USER
C  SUPPLIES WEIGHTS, INSERT PROFILE IN OUTPUT ARRAY
C
C  COMMENCE CODING
C
C-------------------------------------
C  MODIF DMC MAR 1984--
C   ADDED CONCAT COMMON ARRAY XSHOTX = FILENAME EXTENSION
C  LIST, AND MODEI = INPUT MODE
C   MODEI=1:  FILENAME FORM IS FIXED, SHOT NUMBER VARIES
C    FOR 1D INPUT FILES (I.E. OLD STYLE OPERATION OF CONCAT)
C   MODEI=2:  SHOT NUMBER OF INPUT 1D DATA FILES IS FIXED,
C    BUT FILENAME EXTENSION VARIES (NEW MODE OF OPERATION ADDED
C    WITH THIS REV)
C
C   MODEI=2 ALLOWS REJOINING OF SELECTED EXTRACTED PROFILES OR
C    TIMETRACES FROM THE NEW (FEB 1984) UFILES EXTRAC UTILITY
C    -DMC
C-------------------------------------
C
      PROGRAM CONCAT
C  COMMON BLOCKS
C
      USE CONCAT_MOD
C
C
C  INITIALIZE GRAPHICS
C
      LOGICAL LCHAR
      logical lxout
C
      CALL UFHEADER("CONCAT")
C
      CALL UINITG("CONCAT")
C
      luntrm=lnout(0)
C
C  INITIALIZE INPUT
C
      LUNI=25
      LUNC=26
      LUNT=28
      LUN2=29
      NS=0
      INIT=0
      CFILNM='ZCNC__X'
C
      cjunkdir='tmp/'
      ljunkdir=4
c     call tempfile(cfilnm,cjunkdir,ilcj)
c     do ic=ilcj,1,-1
c        if((cjunkdir(ic:ic).eq.'/').or.(cjunkdir(ic:ic).eq.':').or.
c    >      (cjunkdir(ic:ic).eq.']').or.(cjunkdir(ic:ic).eq.'>')) then
c           LJUNKDIR=ic
c           cfilnm=cjunkdir(ic+1:)
c           cjunkdir(ic+1:)=' '
c           go to 5
c        endif
c     enddo
c     call ufbad_exit(
c    >   '?concat -- temporary files directory not found.')
c5    continue
C
C  INITIALIZE OUTPUT - COMPRESSION OF DATA IS "ON"
C
      ICOMPR=2
      ITOGGL=ICOMPR
      CMPSTA(0)='ascii'
      CMPSTA(1)='?????'
      CMPSTA(2)='binary'
      CMPSTA(3)='HDF'
      CMPSTA(4)='NetCDF'
C
      LUNO=27
      NYO=0
      NSO=0
C
C  TOP NODE
C
 10   CONTINUE
C
      CALL NEUPAG
      IF(INIT.EQ.1) GO TO 11
      IF(LXOUT(0)) WRITE(LUNTRM,1999)
 1999 FORMAT(' *USE OPTION "R" FIRST*')
      GO TO 12
C
 11   CONTINUE
      IF(LXOUT(0)) THEN
        WRITE(LUNTRM,2000) YKEY,NSHOTO
 2000 FORMAT(/' *KEY TO VARIABLE OF CONCATENATION:  "',A10,'"'/
     >         ' *SHOT NUMBER FOR OUTPUT FILE:  ',I6/)
        CALL UFSNMD(LUNTRM,'...INPUT 1D PROFILES',LUNI)
        CALL UFSNMD(LUNTRM,'...2D CONCAT. OUTPUT',LUNO)
        IF(MODEI.EQ.1) THEN
          WRITE(LUNTRM,2011)
        ELSE
          WRITE(LUNTRM,2012)
        ENDIF
      ENDIF
 2011 FORMAT(' *INPUT MODE:  VARIABLE SHOT NUMBER')
 2012 FORMAT(' *INPUT MODE:  VARIABLE FILENAME EXTENSION')
C
 12   CONTINUE
      IF(LXOUT(0)) WRITE(LUNTRM,2001) CMPSTA(ICOMPR)
 2001 FORMAT(/' CONCAT TOP NODE OPTIONS:'/
     >  ' R:RESET:  CLEAR INPUT PROFILE COUNT, RESET INPUT FILENAMES'/
     >  '    RESET CONCATENATION KEY, OUTPUT FILENAME AND SHOT NUMBER'/
     >' K:QKRESET:CLEAR INPUT PROFILE COUNT, SET OUTPUT SHOT NO. ONLY'/
     >  ' F:FETCH:  FETCH (OR DELETE) INPUT PROFILE(S)'/
     >  '           2D INPUT FILE FETCH OPTION PROVIDED'/
     >  ' G:GRAPH:  GRAPH INPUT PROFILE(S)'/
     >  ' I:INSERT: INSERT EXTRA PROFILE(S) IN OUTPUT ARRAY'/
     >  ' L:LIST:   LIST PROFILES IN OUTPUT ARRAY'/
     >  ' P:PLOT:   PLOT 2D OUTPUT ARRAY'/
     >  ' S:SCALARS:DISPLAY/COMPARE/MODIFY SCALARS FROM INPUT FILES'/
     >  '   OUTPUT FILE WILL CONTAIN SCALARS AVERAGED FROM INPUT FILES'/
     >  ' C:COMPRS: TOGGLE OUTPUT DATA FORMAT FLAG (NOW "',A,'")'/
     >  ' 4:FORMAT: *new* Ufile output format control menu'/
     >  ' W:WRITE:  WRITE THE 2D OUTPUT ARRAY TO DISK'/
     >  ' X:EXIT:   QUIT '/
     >  ' ======> ENTER 1 LETTER OPTION CODE'/)
 15   CALL UREAD('CONCAT TOP NODE: ENTER OPCODE$')
      IOP=IXUOPC('RKFGILPSC4WXQ$')
      CALL UCHKOP(IOP,0,1,100,2,*10)
C
C  BRANCH
C
      GO TO (100,90,200,300,400,450,500,550,80,78,600,700,700) IOP
C
C  SET FILE ID DEFAULTS
C
 78   continue
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      go to 10
C
 80   CONTINUE
C  TOGGLE COMPRESSION SWITCH
      ICOMPR=ITOGGL-ICOMPR  ! loss free compression ... or ... ascii
      GO TO 10
C
 90   CONTINUE
      IF(INIT.NE.0) GO TO 100
      WRITE(LUNTRM,9001)
 9001 FORMAT(' ? FULL RESET (OPTION "R") REQUIRED FIRST.')
      CALL UPAUST(1)
      GO TO 10
C
 100  CONTINUE
      NS=0
      NSHOT2=0
      NY2=0
      NSO=0
      NYO=0
      IF(IOP.EQ.2) GO TO 35
C  SELECT INPUT MODE
      CALL NEUPAG
 105  CONTINUE
      IF(LXOUT(0)) WRITE(LUNTRM,2002)
 2002 FORMAT(/
     >' TWO MODES OF SPECIFICATION OF INPUT 1D DATA ARE AVAILABLE:'/
     >'  (1)  1D INPUT FILES HAVE FIXED FILENAME FOR Pnnnnn.EXT BUT'/
     >'       THE SHOT NUMBER nnnnn VARIES'/
     >'  (2)  1D INPUT FILES HAVE FIXED SHOT NUMBER nnnnn BUT THE'/
     >'       FILENAME EXTENSION .EXT VARIES'/
     >)
      CALL UREAD('CONCAT: SELECT MODE OF INPUT (1 OR 2):$')
      IANS=IXUOPC('12Q$')
      CALL UCHKOP(IANS,0,1,100,2,*105)
      IF(IANS.EQ.3) GO TO 10
      IF(IANS.EQ.1) THEN
        MODEI=1
      ELSE IF(IANS.EQ.2) THEN
        MODEI=2
      ENDIF
      CALL TVNAMS(INIT)
C  GET OUTPUT FILENAME
      CALL UFNTER(LUNO,'2D CONCAT **OUTPUT** ')
 35   CONTINUE
C  GET SHOT NUMBER FOR NAMING OUTPUT FILE
      IF(MODEI.EQ.1) THEN
        CALL UREAD(
     >  'TV2OUT:  ENTER 5 DIGIT SHOT # FOR NAMING OUTPUT FILE:$')
      ELSE
        CALL UREAD(
     >  'TV2OUT:  ENTER 5 DIGIT SHOT # FOR NAMING DATA FILES:$')
      ENDIF
      NSHOTO=IDCOD(IERT)
      IF(LCHAR('Q')) GOTO 35
      IF((IERT.NE.0).OR.(NSHOTO.LT.1).OR.(NSHOTO.GT.999999)) THEN
        CALL UERMSG('% ILLEGAL SHOT NUMBER',' ',0)
        GO TO 35
      ENDIF
C  RESET COMMENT FILE ID CODES
      CALL CFNXID(CFILID,0)
C
      GO TO 10
C
C  GET PROFILES
C
 200  CONTINUE
      CALL TVGETM(INIT)
C  ASSEMBLE INPUT PROFILES INTO INITIAL FORM OF OUTPUT ARRAY
      CALL TVMAK2
      GO TO 10
C
C  GRAPH ONE OR MORE PROFILE
C
 300  CONTINUE
      CALL TV1GRF
      GO TO 10
C
C  INSERT 1D PROFILES IN 2D OUTPUT ARRAY
C
 400  CONTINUE
      CALL TVTINS
      GO TO 10
C
C LIST PROFILES CURRENTLY IN OUTPUT ARRAY
C
 450  CONTINUE
      CALL XSHOTS(1)
      GO TO 10
C
C  PLOT 2D OUTPUT ARRAY
C
 500  CONTINUE
      CALL TV2GRF
      GO TO 10
C
C  LOOK AT/ COMPARE/ MODIFY SCALARS FROM INPUT FILES
C
 550  CONTINUE
      CALL TSCALR
      GO TO 10
C
C  WRITE OUTPUT FILE
C
 600  CONTINUE
      CALL TV2OUT(F,NXO,NYO,F2)
      GO TO 10
C
C  QUIT
C
 700  CONTINUE
      CALL NEUPAG
      CALL UEXITA(0)
      STOP
C---
      END
C******************** END FILE CONCAT.FOR ; GROUP CONCAT ***************
