C******************** START FILE GAVER0.FOR ; GROUP GAVER0 ******************
C-----------------------------------------------------------
C  GAVER0
C  PROGRAM TO AVERAGE DATA INPUT FROM UFILES DATA FILE
C
      PROGRAM GAVER0
C
C  MAXIMUM NUMBER OF ASSOCIATED KEYWORD SCALAR QUANTITIES--
      PARAMETER (MAXSC=300)
C MAX NUMBER OF SHOTS AVERAGED TOGETHER
      PARAMETER (JLSHO=50)
C  MAX NUMBER OF POINTS IN DATA
      PARAMETER (JDSIZ=10000)
C
C  DATA BUFFERS AND LABELS
      REAL XTRVAL(MAXSC,3)
      CHARACTER*10 ZSDATE,
     >     XTRLAB(3,MAXSC,3),ZDATE
      CHARACTER*40 ZFILE
      CHARACTER*10 ZZDATE
      CHARACTER*4 IDEV(2)
      INTEGER LSHOT(JLSHO),IORDER(MAXSC,3),NUMSC(3)
C-----------------------------
C  PROGRAM MOD APR 1984 DMC-- DEAL WITH VAX COMPRESSED UFILES DATA
C   FORMATTED COMMENTS FOR THE OUTPUT FILE ARE PUT IN A TEMPORARY FILE
C   WHICH IS SPOOLED TO THE PERMANENT FILE WHICH IS OPTIONALLY BINARY-
C   COMPRESSED.
C  USER MAY SELECT COMPRESSED OR UNCOMPRESSED DATA OUTPUT
C
      CHARACTER*7 CMPSTA(0:4)
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  COMPRESSED DATA OUTPUT DEFAULT FLAG, =1 FOR COMPRESSION ON
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  L.U.N. FOR TEMPORARY COMMENTS FILE
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C-------------------------------
C
C  L.U.N FOR DATA INPUT
C
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  L.U.N FOR DATA OUPUT
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C  L.U.N. FOR TEMPORARY FILE-- COMMENT SPOOLING
C *LISMAK* DATA SATEMENT MOVED 12-APR-88
C
C  DATA BUFFER SIZE--
C
C *LISMAK* 12-APR-88  GENERATED LOGICAL DECLARATIONS
      LOGICAL LCHAR
      LOGICAL LYES
      logical lxout
C *LISMAK* END OF GENERATED LOGICAL DECLARATIONS
C
C => GAVER0               BEGIN DATA BLOCK
C => LISMAK 12-APR-88  MOVED DATA STATEMENTS
      DATA CMPSTA/'ascii','????','binary','HDF','NetCDF'/
      DATA ICOMPR/0/
      DATA ILUNC/99/
      DATA ILUNI/21/
      DATA ILUNO/22/
      DATA ILUNT/23/
C => END DATA BLOCK
C ====================
C
      itoggl=max(2,icompr)
C
      MAXD=JDSIZ
C  MAX NUMBER OF SHOTS IN AVERAGE
      MAXSHO=JLSHO
C
      call ufheader("gaver0")
      call date_and_time(DATE=zdate)
      CALL UINITG("GAVER0")
      luntrm=lnout(0)
CC	CALL USINIT
CC	CALL UAHEAD
      call urdext('ifi')
 10   CONTINUE
      CALL UFNTER(ILUNI,'0D INPUT FILES - RAW')
      CALL UFNTER(ILUNO,'OUTPUT FILE- AVERAGE')
C  CLEAR NUMBER OF SHOTS--
 12   NSHOTS=0
      NUMSC(1)=0
C
C---
C  TOP NODE-- AVG MORE DATA, WRITE OUTPUT FILE, START OVER, QUIT
 15   CONTINUE
      CALL NEUPAG
 16   IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'               INPUT',ILUNI)
      IF(LXOUT(0)) CALL UFSNMD(LUNTRM,'              OUTPUT',ILUNO)
      IF(LXOUT(0)) WRITE(LUNTRM,1010) NSHOTS,NUMSC(1),
     >    CMPSTA(ICOMPR)
 1010 FORMAT(/' CURRENTLY ',I2,' SHOTS IN AVERAGE'/
     >  ' CURRENTLY ',I3,' KEYWORD SCALARS IN AVERAGED DATA LIST'/
     >  ' GAVER0 TOP NODE OPTIONS:'/
     >  '   A - AVERAGE - AVERAGE MORE DATA'/
     >  '   C - COMPRESS- TOGGLE OUTPUT FORMAT FLAG, NOW "',A,'"'/
     >  '   4 - FORMAT  - *new* Ufile output format control menu'/
     >  '   D - DISPLAY - DISPLAY/MODIFY AVERAGED KEYWORD SCALAR DATA'/
     >  '   L - LIST    - LIST SHOTS IN AVERAGE'/
     >  '   R - RESET   - RESET INPUT AND OUTPUT FILENAMES'/
     >  '   S - START   - START OVER: SET # OF SHOTS AVERAGED TO 0'/
     >  '   W - WRITE   - WRITE THE OUTPUT AVERAGED DATA FILE'/
     >  '   X - EXIT    - STOP'/)
C
      CALL UREAD('GAVER0:  ENTER OPCODE (A/D/L/R/S/W/X/Q):$')
      IOP=IXUOPC('A4CDLRSWXQ$')
      CALL UCHKOP(IOP,0,1,100,-1,*16)
      GO TO (20,17,18,600,350,10,12,200,19,19) IOP
C
 17   continue
      call ufmtsel(icompr)
      if(icompr.gt.0) itoggl=icompr
      go to 15
C
 18   CONTINUE
      ICOMPR=ITOGGL-ICOMPR
      GO TO 15
C
 19   CONTINUE
      CALL NEUPAG
      CALL UEXITA(0)
      STOP
C---------
C
 20   CONTINUE
      CALL NEUPAG
 21   CALL UREAD(
     >'GAVER0: ENTER 5 DIGIT INPUT SHOT # OR "X" TO EXIT INPUT LOOP:$')
      IF(LCHAR('X').OR.LCHAR('Q')) GO TO 15
      ISHOT=IDCOD(IERT)
      IF(IERT.NE.0) GO TO 21
C
      CALL UFOPRD(ILUNI,ISHOT,IER)
      IF(IER.NE.0) THEN
        CALL UCLEAR
        GO TO 21
      ENDIF
C
      ISP=MIN0(2,(NSHOTS+1))
      CALL UF0DRD(ILUNI,IDEV(ISP),ZZDATE,
     >   XTRVAL(1,2),XTRLAB(1,1,2),MAXSC,NUMSC(2),IER)
C
      IF(IER.NE.0 .OR. NUMSC(2)<=0) CALL UCLEAR
      IF(IER.NE.0 .OR. NUMSC(2)<=0) GO TO 190
C  CHECK THE DATA
      IF(ISP.EQ.2) GO TO 50
      IER2=0
C  FIRST SHOT
C
      ZSDATE=ZZDATE
C
C
      GO TO 100
C----------
C  NOT THE FIRST SHOT.  CHECK FOR DISCREPANCIES
 50   CONTINUE
      IER2=0
      IF(IDEV(1).EQ.IDEV(2)) GO TO 55
      WRITE(LUNTRM,9057) IDEV(1),IDEV(2)
 9057 FORMAT(' % DATA TO BE AVERAGED FROM DIFFERENT TOKAMAKS:'/
     >  '   ORIGINAL SHOT DATA FROM:  "',A4,'"'/
     >  '   CURRENT SHOT DATA FROM:   "',A4,'"'/)
      IER2=1
C-----
 55   CONTINUE
      IF(ZZDATE.EQ.ZSDATE) GO TO 65
      WRITE(LUNTRM,9060) LSHOT(1),ZSDATE,ISHOT,ZZDATE
 9060 FORMAT(' % INPUT DATA HAS DIFFERENT SHOT DATE:'/
     >  '  SHOT ',I6,' DATE:  ',A10/
     >  '  SHOT ',I6,' DATE:  ',A10)
      IER2=1
C---
 65   CONTINUE
C  CHECK AGAINST DUPLICATION OF SHOTS
      DO 85 I=1,NSHOTS
      IF(LSHOT(I).EQ.ISHOT) GO TO 86
 85   CONTINUE
      GO TO 100
C
 86   CONTINUE
      WRITE(LUNTRM,9095) ISHOT
 9095 FORMAT(' % SHOT ',I6,' HAS ALREADY BEEN AVERAGED')
      IER2=1
C
 100  CONTINUE
      IF(IER2.NE.0) CALL UPAUST(1)
C  COMPARE THE KEYWORD SCALARS
      CALL UFSCMP(XTRLAB,XTRVAL,IORDER,MAXSC,NUMSC,NSHOTS,ISHOT,IDIFS)
C
C  AVERAGE THE DATA
C
 110  CONTINUE
      IF(IER2.NE.0) WRITE(LUNTRM,9081)
 9081 FORMAT(' % DISCREPANCY WARNINGS WERE ISSUED'/
     >  '   THE LABELS, ETC. FOR THE AVERAGED OUTPUT FILE'/
     >  '   ARE TAKEN FROM THE *FIRST* INPUT FILE'/)
      IF(IER2.NE.0) CALL UCLEAR
      CALL UREAD('GAVER0:  AVERAGE THIS SHOT? (Y/N):$')
      IF(.NOT.LYES(0)) GO TO 190
C
C  AVERAGE THE SCALAR LISTS
      CALL UFSCAV(XTRLAB,XTRVAL,IORDER,NUMSC(1),
     >     XTRLAB(1,1,2),XTRVAL(1,2),IORDER(1,2),NUMSC(2),
     >     FLOAT(NSHOTS),1.0,MAXSC)
      NSHOTS=NSHOTS+1
      LSHOT(NSHOTS)=ISHOT
C  SPOOL COMMENTS TO OUTPUT FILE; OPEN IF ON FIRST SHOT
      IF(NSHOTS.EQ.1) THEN
        CALL UFOPCF(ILUNT,IER)
      ENDIF
      WRITE(ILUNT,7001) ISHOT,ZDATE
 7001 FORMAT(
     >  ' =========================================================='/
     >  ' COMMENTS SPOOLED FROM FILE INPUT TO GAVER0 [',
     >  'SHOT=',I6,']:'/' ON VAX-11 ON DATE:  ',A10/)
      CALL USPOOL(ILUNI,ILUNT)
      WRITE(ILUNT,7002)
 7002 FORMAT(
     >  ' ----------------------------------------------------------')
C ---
C  BRANCH HERE ON ERROR OR NO AVERAGE:
C
 190  CONTINUE
      CALL UFCLOS(ILUNI)
      GO TO 20
C---------
 200  CONTINUE
      IF(NSHOTS.EQ.0) GO TO 15
C
      CALL UREAD(
     >  'GAVER0:  ENTER 5 DIGIT SHOT NUMBER TO NAME OUTPUT FILE:$')
      ISHOT=IDCOD(IERT)
      IF(LCHAR('Q')) GOTO 19
      IF(IERT.NE.0) GO TO 200
C  COMPRESS?
      CALL UFCMPR(ILUNO,ICOMPR)
      CALL UFOPWR(ILUNO,ISHOT,IER)
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 15
C
      CALL UF0DWR(ILUNO,IDEV(1),
     >   ZSDATE,XTRVAL,XTRLAB,NUMSC(1),IER)
C
C  APPEND COMMENTS TO FILE
C
      IF(IER.NE.0) CALL UCLEAR
      IF(IER.NE.0) GO TO 400
C
      CALL UFOPCF(ILUNC,IER)
      WRITE(ILUNC,4001) NSHOTS
 4001 FORMAT(' >> AVERAGED DATA FROM ',I2,' INPUT FILES:'/)
      DO 395 IJ=1,NSHOTS
      CALL UFSNAM(LSHOT(IJ),ZFILE,IER,ILUNI)
      WRITE(ILUNC,4002) IJ,ZFILE
 4002 FORMAT('  >> #',I2,':  FILE "',A,'"')
 395  CONTINUE
C
      WRITE(ILUNC,4005)
 4005 FORMAT('  AVERAGING PROGRAM NAME:  GAVER0 [TRANSP]'/)
C
C  GET USER COMMENTS
      CALL UFACOM(ILUNC)
C
C  SPOOL COMMENTS TO OUTPUT FILE
C
      CALL UCSEND(ILUNC,ILUNO)
      CALL UCSEND(ILUNT,ILUNO)
C
      CALL UFCLOS(ILUNO)
C
      GO TO 12
C  CLOSE OUTPUT FILE ON WRITE ERROR
 400  CONTINUE
      CALL UFCLOS(ILUNO)
      GO TO 15
C-----------------------------
C  LIST SHOTS IN AVERAGE
 350  CONTINUE
      IF(NSHOTS.EQ.0) GO TO 15
      CALL NEUPAG
      WRITE(LUNTRM,3000)
 3000 FORMAT(/' >> LIST OF SHOTS AVERAGED SO FAR:')
      DO 360 I=1,NSHOTS
      WRITE(LUNTRM,3001) I,LSHOT(I)
 3001 FORMAT(' SHOT # ',I2,':  ',I6)
 360  CONTINUE
      CALL UPAUST(1)
      GO TO 15
C---------------------------------------------------------
 600  CONTINUE
C  CALL ROUTINE TO LOOK AT AVERAGED SCALARS
      IF(NUMSC(1).GT.0) CALL UFSCLK(
     >     ILUNO,LSHOT(1),NUMSC(1),XTRVAL,XTRLAB,IORDER,1,ILUNT)
      GO TO 15
      	END
C******************** END FILE GAVER0.FOR ; GROUP GAVER0 ******************
